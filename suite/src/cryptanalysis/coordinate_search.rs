/// How the involution's invariants are formed from the per-point value `u`.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum InvariantRule {
    /// `w = u²`, `s = Π u_i` (sign frame).
    Sign,
    /// `w = u² + u`, `s = Σ u_i` (additive frame).
    Additive,
    /// `w = u + g(u)` (or `u·g(u)` when that is constant), `s` the sum over
    /// even-weight orbit representatives — works for any involution.
    Generic,
}

/// A coordinate system on the relation tuple: a frame on the `x`-line,
/// optionally an involution to quotient by, optionally the elementary
/// symmetric functions of the summands.
#[derive(Clone, Debug)]
pub struct CoordinateSystem {
    pub name: String,
    pub frame: Mobius,
    /// The involution written in the frame (already conjugated).
    pub involution: Option<Mobius>,
    pub rule: InvariantRule,
    /// Replace `(w_1, …, w_m)` by `e_1, …, e_m` — valid because the
    /// summands are interchangeable.
    pub symmetric: bool,
}

impl CoordinateSystem {
    pub fn plain(frame: &Frame, symmetric: bool) -> Self {
        CoordinateSystem {
            name: format!("{}{}", frame.name, if symmetric { ", e_k" } else { "" }),
            frame: frame.mob,
            involution: None,
            rule: InvariantRule::Generic,
            symmetric,
        }
    }

    /// Quotient by the involution `g_x` (given on the `x`-line) in `frame`.
    pub fn with_involution(f: &Gf, frame: &Frame, g_x: &Mobius, symmetric: bool) -> Self {
        let g = g_x.conjugate_by(f, &frame.mob);
        let rule = match frame.kind {
            FrameKind::Sign => InvariantRule::Sign,
            FrameKind::Additive => InvariantRule::Additive,
            _ => InvariantRule::Generic,
        };
        let inv_name = match rule {
            InvariantRule::Sign => "w = u², s = Πu",
            InvariantRule::Additive => "w = u² + u, s = Σu",
            InvariantRule::Generic => "w = u + g(u), s = σ_even",
        };
        CoordinateSystem {
            name: format!(
                "{} / {}{}",
                frame.name,
                inv_name,
                if symmetric { ", e_k" } else { "" }
            ),
            frame: frame.mob,
            involution: Some(g),
            rule,
            symmetric,
        }
    }

    /// Per-point coordinate: `u`, or the involution invariant `w` of `u`.
    pub fn point_value(&self, f: &Gf, p: Pt) -> u64 {
        let u = self.frame.apply(f, p.x());
        if u == INF {
            return INF;
        }
        match (&self.involution, self.rule) {
            (None, _) => u,
            (Some(_), InvariantRule::Sign) => f.mul(u, u),
            (Some(_), InvariantRule::Additive) => f.add(f.mul(u, u), u),
            (Some(g), InvariantRule::Generic) => {
                let gu = g.apply(f, u);
                if gu == INF {
                    return INF;
                }
                if self.generic_uses_product(f) {
                    f.mul(u, gu)
                } else {
                    f.add(u, gu)
                }
            }
        }
    }

    fn generic_uses_product(&self, f: &Gf) -> bool {
        // `u + g(u)` is constant exactly when g(u) = c − u.
        let g = self.involution.as_ref().unwrap();
        let vals: Vec<u64> = [0u64, 1, 2 % f.q]
            .iter()
            .filter_map(|&t| {
                let gt = g.apply(f, t);
                (gt != INF).then(|| f.add(t, gt))
            })
            .collect();
        vals.len() >= 2 && vals.iter().all(|&v| v == vals[0])
    }

    /// The extra invariant `s` of the even-weight subgroup.
    fn extra_invariant(&self, f: &Gf, us: &[u64]) -> Option<u64> {
        let g = self.involution.as_ref()?;
        Some(match self.rule {
            InvariantRule::Sign => us.iter().fold(1, |acc, &u| f.mul(acc, u)),
            InvariantRule::Additive => us.iter().fold(0, |acc, &u| f.add(acc, u)),
            InvariantRule::Generic => {
                let n = us.len();
                let gus: Vec<u64> = us.iter().map(|&u| g.apply(f, u)).collect();
                if gus.contains(&INF) {
                    return None;
                }
                let mut total = 0;
                for mask in 0..(1u32 << n) {
                    if mask.count_ones() % 2 != 0 {
                        continue;
                    }
                    let mut prod = 1;
                    for i in 0..n {
                        prod = f.mul(prod, if (mask >> i) & 1 == 1 { gus[i] } else { us[i] });
                    }
                    total = f.add(total, prod);
                }
                total
            }
        })
    }

    pub fn var_names(&self, m: usize) -> Vec<String> {
        let base = if self.involution.is_some() { "w" } else { "u" };
        let mut names = Vec::new();
        if self.symmetric {
            for k in 1..=m {
                names.push(format!("e{k}"));
            }
        } else {
            for i in 1..=m {
                names.push(format!("{base}{i}"));
            }
        }
        names.push(format!("{base}R"));
        if self.involution.is_some() {
            names.push("s".to_string());
        }
        names
    }

    /// Per-variable degree bounds for the summation polynomial of `m + 1`
    /// points: `2^{m−1}` in a degree-2 coordinate, halved by the involution.
    pub fn bounds(&self, m: usize) -> Vec<u32> {
        let base = if self.involution.is_some() {
            1u32 << (m - 2)
        } else {
            1u32 << (m - 1)
        };
        let mut b = Vec::new();
        b.extend(std::iter::repeat_n(base, m));
        b.push(base);
        if self.involution.is_some() {
            b.push(if self.rule == InvariantRule::Generic {
                2
            } else {
                1
            });
        }
        b
    }

    /// Admissible exponent vectors: within the bounds, and for the
    /// symmetric variables `e_k` (of degree `k`) also of bounded total and
    /// weighted degree so that the degree in each hidden `w_i` stays within
    /// the bound.
    pub fn monomials(&self, m: usize) -> Vec<Vec<u32>> {
        let bounds = self.bounds(m);
        let all = enumerate_monomials(&bounds);
        if !self.symmetric {
            return all;
        }
        let base = bounds[0];
        all.into_iter()
            .filter(|e| {
                let total: u32 = e[..m].iter().sum();
                total <= base
            })
            .collect()
    }

    /// Coordinates of a relation tuple, `None` if any coordinate is `∞`.
    pub fn evaluate(&self, f: &Gf, tuple: &[Pt]) -> Option<Vec<u64>> {
        let m = tuple.len() - 1;
        let us: Vec<u64> = tuple.iter().map(|&p| self.frame.apply(f, p.x())).collect();
        if us.contains(&INF) {
            return None;
        }
        let ws: Vec<u64> = tuple.iter().map(|&p| self.point_value(f, p)).collect();
        if ws.contains(&INF) {
            return None;
        }
        let mut vals = Vec::new();
        if self.symmetric {
            vals.extend(elementary_symmetric_values(f, &ws[..m]));
        } else {
            vals.extend_from_slice(&ws[..m]);
        }
        vals.push(ws[m]);
        if self.involution.is_some() {
            vals.push(self.extra_invariant(f, &us)?);
        }
        Some(vals)
    }
}

fn elementary_symmetric_values(f: &Gf, xs: &[u64]) -> Vec<u64> {
    let m = xs.len();
    // e[k] after processing each x: e_k ← e_k + x·e_{k−1}
    let mut e = vec![0u64; m + 1];
    e[0] = 1;
    for &x in xs {
        for k in (1..=m).rev() {
            e[k] = f.add(e[k], f.mul(x, e[k - 1]));
        }
    }
    e[1..].to_vec()
}

/// All exponent vectors `0 ≤ e_i ≤ bounds[i]`.
pub fn enumerate_monomials(bounds: &[u32]) -> Vec<Vec<u32>> {
    let mut out = vec![vec![]];
    for &b in bounds {
        let mut next = Vec::new();
        for e in &out {
            for k in 0..=b {
                let mut e2 = e.clone();
                e2.push(k);
                next.push(e2);
            }
        }
        out = next;
    }
    out
}

