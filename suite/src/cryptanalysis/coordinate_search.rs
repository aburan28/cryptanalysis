/// What a frame does to the involution it was built for.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum FrameKind {
    /// The Weierstrass `x`-line itself.
    Weierstrass,
    /// The involution becomes `t ↦ −t` (odd characteristic, rational fixed
    /// points).
    Sign,
    /// The involution becomes `t ↦ t + 1` (characteristic 2).
    Additive,
    /// No rational linearising frame exists; the involution is used as is,
    /// through its trace and norm invariants.
    Trace,
}

/// A Möbius change of coordinate on the `x`-line together with what it
/// achieves.
#[derive(Clone, Debug)]
pub struct Frame {
    pub name: String,
    pub mob: Mobius,
    pub kind: FrameKind,
}

impl Frame {
    pub fn weierstrass() -> Self {
        Frame {
            name: "x".to_string(),
            mob: Mobius::identity(),
            kind: FrameKind::Weierstrass,
        }
    }
}

/// The frame in which the involution `g` of `P¹` acts linearly: `t ↦ −t`
/// over odd characteristic, `t ↦ t + 1` in characteristic 2.  Returns a
/// [`FrameKind::Trace`] identity frame when the fixed points are not
/// rational, since then no such frame exists over `K`.
pub fn linearising_frame(f: &Gf, g: &Mobius) -> Frame {
    let fps = g.fixed_points(f);
    // Möbius map sending t ↦ ∞ for a given point.
    let send_to_inf = |t: u64| -> Mobius {
        if t == INF {
            Mobius::identity()
        } else {
            // 1 / (t − t₀)
            Mobius {
                a: 0,
                b: 1,
                c: 1,
                d: f.neg(t),
            }
        }
    };
    if f.p == 2 {
        // unipotent: exactly one fixed point
        let Some(&t0) = fps.first() else {
            return Frame {
                name: "x (no rational fixed point)".to_string(),
                mob: Mobius::identity(),
                kind: FrameKind::Trace,
            };
        };
        let n0 = send_to_inf(t0);
        let g1 = g.conjugate_by(f, &n0);
        if let MobiusKind::Translation(c) = g1.kind(f) {
            // rescale so the translation is by 1
            let scale = Mobius {
                a: f.inv(c),
                b: 0,
                c: 0,
                d: 1,
            };
            let n = scale.compose(f, &n0);
            debug_assert_eq!(g.conjugate_by(f, &n).kind(f), MobiusKind::Translation(1));
            return Frame {
                name: format!("u = {}", n.describe(f)),
                mob: n,
                kind: FrameKind::Additive,
            };
        }
        Frame {
            name: "x (involution not unipotent?)".to_string(),
            mob: Mobius::identity(),
            kind: FrameKind::Trace,
        }
    } else {
        let mut distinct = fps.clone();
        distinct.dedup();
        if distinct.len() < 2 {
            return Frame {
                name: "x (fixed points irrational)".to_string(),
                mob: Mobius::identity(),
                kind: FrameKind::Trace,
            };
        }
        let (f1, f2) = (distinct[0], distinct[1]);
        // t ↦ (t − f1)/(t − f2), with the ∞ conventions
        let n = match (f1 == INF, f2 == INF) {
            (false, false) => Mobius {
                a: 1,
                b: f.neg(f1),
                c: 1,
                d: f.neg(f2),
            },
            (true, false) => Mobius {
                a: 0,
                b: 1,
                c: 1,
                d: f.neg(f2),
            },
            (false, true) => Mobius {
                a: 1,
                b: f.neg(f1),
                c: 0,
                d: 1,
            },
            (true, true) => unreachable!(),
        };
        let g1 = g.conjugate_by(f, &n);
        if g1.kind(f) == MobiusKind::Scaling(f.neg(1)) {
            Frame {
                name: format!("u = {}", n.describe(f)),
                mob: n,
                kind: FrameKind::Sign,
            }
        } else {
            Frame {
                name: "x (involution not diagonalisable?)".to_string(),
                mob: Mobius::identity(),
                kind: FrameKind::Trace,
            }
        }
    }
}

/// Brute-force scan of every frame with coefficients in `F_{p^d}`: which
/// of them turn `g` into a scaling, inversion or translation?  Only for
/// tiny subfields (`p^d ≤ 8`); this is the check that the constructive
/// frame is not missing anything a Frobenius-compatible frame could do.
pub fn scan_subfield_frames(f: &Gf, d: u32, g: &Mobius) -> Vec<(Mobius, MobiusKind)> {
    let elems = f.subfield_elements(d);
    assert!(elems.len() <= 8, "frame scan only for tiny subfields");
    let mut seen = std::collections::HashSet::new();
    let mut out = Vec::new();
    for &a in &elems {
        for &b in &elems {
            for &c in &elems {
                for &dd in &elems {
                    if f.sub(f.mul(a, dd), f.mul(b, c)) == 0 {
                        continue;
                    }
                    let n = Mobius { a, b, c, d: dd }.normalise(f);
                    if !seen.insert(n) {
                        continue;
                    }
                    let k = g.conjugate_by(f, &n).kind(f);
                    if !matches!(k, MobiusKind::General | MobiusKind::Identity) {
                        out.push((n, k));
                    }
                }
            }
        }
    }
    out
}

