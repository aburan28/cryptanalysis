// Weil-descent cost model
// ---------------------------------------------------------------------------

/// Size of the Boolean system a factor base cut out by an `F_2`-subspace of
/// dimension `l` would produce, for a binary field of degree `n`.
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct DescentModel {
    pub factor_base_dim: u32,
    pub unknowns: u32,
    pub equations: u32,
    /// Degree of the descended Boolean system, read off the interpolated
    /// polynomial: a monomial `Π v_i^{e_i}` has bit-degree `Σ popcount(e_i)`
    /// because `v ↦ v^{2^k}` is `F_2`-linear.
    ///
    /// Counted over **all `m + 1` arguments of the polynomial**, the target
    /// included — unlike [`Self::unknowns`], which excludes it, since the
    /// target is known when a decomposition is attempted.  The two fields are
    /// therefore on different conventions, and a system actually handed to a
    /// solver has degree one less than this for the polynomials measured here
    /// (`S₄` in `x`: 7 here, 6 solved; symmetrised: 5 here, 4 solved).  Compare
    /// only like with like; `semaev_leading_form::boolean_degree` takes the
    /// symbolic-variable count as an argument and gives the other convention.
    pub boolean_degree: u32,
}

/// Bit-degree of the descended polynomial: `Σ_i popcount(e_i)` maximised
/// over the monomials, since every `2^k`-th power is linear over `F_2`.
pub fn boolean_degree(poly: &RelationPolynomial) -> u32 {
    poly.terms
        .iter()
        .map(|(e, _)| e.iter().map(|k| k.count_ones()).sum::<u32>())
        .max()
        .unwrap_or(0)
}

/// The model behind the numbers in [`Candidate::descent`].  Without an
/// involution each summand coordinate carries `l` bits.  With the additive
/// involution and `1 ∈ V`, each `w_i = u_i² + u_i` lies in the image of `V`
/// under the Artin–Schreier map, which is `F_2`-linear with kernel `{0, 1}`,
/// so `w_i` carries `l − 1` bits; the extra invariant `s = Σ u_i` satisfies
/// `s² + s = Σ w_i`, again linear in the bits, so it contributes one free
/// bit after linear elimination.  (A solve that lands on `R + T` is the
/// same projected relation as one on `R`, since the cofactor kills `T`;
/// an earlier version counted it as a second target.)
pub fn descent_model(
    cs: &CoordinateSystem,
    poly: &RelationPolynomial,
    m: usize,
    n: u32,
    l: u32,
) -> DescentModel {
    let m32 = m as u32;
    if cs.involution.is_some() {
        DescentModel {
            factor_base_dim: l,
            unknowns: m32 * (l - 1) + 1,
            equations: n,
            boolean_degree: boolean_degree(poly),
        }
    } else {
        DescentModel {
            factor_base_dim: l,
            unknowns: m32 * l,
            equations: n,
            boolean_degree: boolean_degree(poly),
        }
    }
}

