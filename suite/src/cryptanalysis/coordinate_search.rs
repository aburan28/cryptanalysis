#[derive(Clone, Debug)]
pub struct SearchOptions {
    /// Number of summands.
    pub m: usize,
    pub seed: u64,
    /// Factor-base subspace dimension for the descent model (binary fields).
    pub factor_base_dim: Option<u32>,
    /// Relation samples for the collapse-factor measurement.
    pub collapse_samples: usize,
}

impl Default for SearchOptions {
    fn default() -> Self {
        SearchOptions {
            m: 3,
            seed: 0x5EED,
            factor_base_dim: None,
            collapse_samples: 16,
        }
    }
}

/// One coordinate system and everything measured about it.
#[derive(Clone, Debug)]
pub struct Candidate {
    pub system: CoordinateSystem,
    /// Which symmetry it quotients by, if any.
    pub symmetry: Option<String>,
    pub frame_kind: FrameKind,
    /// `coord(πP) = coord(P)^{p^d}` on every point (measured).
    pub frobenius_compatible: Option<bool>,
    pub result: Result<InterpolationResult, String>,
    pub collapse: Option<f64>,
    pub descent: Option<DescentModel>,
}

/// The whole search on one curve.
#[derive(Clone, Debug)]
pub struct SearchReport {
    pub curve: String,
    pub field: String,
    pub order: u64,
    pub j: Option<u64>,
    pub two_torsion: usize,
    pub aut_order: usize,
    pub subfield_degree: Option<u32>,
    pub m: usize,
    pub symmetries: Vec<Symmetry>,
    pub candidates: Vec<Candidate>,
}

fn frobenius_compatible(curve: &Curve, pts: &[Pt], cs: &CoordinateSystem) -> Option<bool> {
    let d = curve.subfield_degree()?;
    if d == curve.f.n {
        return None;
    }
    let f = &curve.f;
    Some(pts.iter().all(|&p| {
        let v = cs.point_value(f, p);
        let w = cs.point_value(f, curve.frobenius(p, d));
        v == INF || w == INF || w == f.frob_pow(v, d)
    }))
}

/// Run the search: detect symmetries, build frames, interpolate and measure
/// every candidate coordinate system.
pub fn search(curve: &Curve, opts: &SearchOptions) -> SearchReport {
    let f = &curve.f;
    let m = opts.m;
    assert!(m >= 2, "need at least two summands");
    let mut rng = Rng64::new(opts.seed);
    let pts = curve.affine_points();
    let symmetries = detect_symmetries(curve, &pts, &mut rng);
    let l = opts
        .factor_base_dim
        .unwrap_or_else(|| (f.n as usize).div_ceil(m).max(2) as u32);

    let mut systems: Vec<(CoordinateSystem, Option<String>, FrameKind)> = Vec::new();
    let wx = Frame::weierstrass();
    systems.push((
        CoordinateSystem::plain(&wx, false),
        None,
        FrameKind::Weierstrass,
    ));
    systems.push((
        CoordinateSystem::plain(&wx, true),
        None,
        FrameKind::Weierstrass,
    ));
    for s in &symmetries {
        let (Some(g), Scope::Pairwise) = (s.mobius, s.scope) else {
            continue;
        };
        let frame = linearising_frame(f, &g);
        let label = s.describe(f);
        if frame.kind != FrameKind::Trace {
            systems.push((CoordinateSystem::plain(&frame, false), None, frame.kind));
        }
        systems.push((
            CoordinateSystem::with_involution(f, &frame, &g, false),
            Some(label.clone()),
            frame.kind,
        ));
        systems.push((
            CoordinateSystem::with_involution(f, &frame, &g, true),
            Some(label),
            frame.kind,
        ));
    }

    let mut candidates = Vec::new();
    for (cs, symmetry, frame_kind) in systems {
        let result = interpolate_relation(curve, &pts, &cs, m, &mut rng);
        let collapse = result
            .as_ref()
            .ok()
            .filter(|_| !cs.symmetric)
            .map(|_| collapse_factor(curve, &pts, &cs, m, &mut rng, opts.collapse_samples));
        // The bit-degree model needs per-point variables; the elementary
        // symmetric functions are not linear in the bits.
        let descent = match (&result, f.is_binary(), cs.symmetric) {
            (Ok(res), true, false) => Some(descent_model(&cs, &res.poly, m, f.n, l)),
            _ => None,
        };
        candidates.push(Candidate {
            frobenius_compatible: frobenius_compatible(curve, &pts, &cs),
            symmetry,
            frame_kind,
            result,
            collapse,
            descent,
            system: cs,
        });
    }
    SearchReport {
        curve: curve.label.clone(),
        field: f.name(),
        order: pts.len() as u64 + 1,
        j: curve.j_invariant(),
        two_torsion: curve.two_torsion().len(),
        aut_order: curve.automorphisms().len(),
        subfield_degree: curve.subfield_degree(),
        m,
        symmetries,
        candidates,
    }
}

/// Plain-text rendering of a report.
pub fn format_report(f: &Gf, r: &SearchReport) -> String {
    let mut s = String::new();
    let _ = writeln!(
        s,
        "== {} over {}: #E = {}, j = {}, rational 2-torsion points = {}, |Aut| = {}, defined over {}",
        r.curve,
        r.field,
        r.order,
        r.j.map(|j| f.show(j)).unwrap_or_else(|| "singular".to_string()),
        r.two_torsion,
        r.aut_order,
        match r.subfield_degree {
            Some(d) => format!("F_{}^{}", f.p, d),
            None => r.field.clone(),
        }
    );
    let _ = writeln!(s, "   relation symmetries on the x-line (m = {}):", r.m);
    if r.symmetries.is_empty() {
        let _ = writeln!(s, "     (none beyond ±1)");
    }
    for sym in &r.symmetries {
        let _ = writeln!(s, "     - {}", sym.describe(f));
    }
    let _ = writeln!(
        s,
        "   {:<44} {:>5} {:>14} {:>6} {:>8} {:>5} {:>21}",
        "coordinates", "vars", "degrees", "terms", "collapse", "Frob", "descent unk/eq/bitdeg"
    );
    for c in &r.candidates {
        let (vars, degs, terms) = match &c.result {
            Ok(res) => (
                res.poly.var_names.len().to_string(),
                format!("{:?}", res.poly.degrees()),
                res.poly.n_terms().to_string(),
            ),
            Err(_) => ("-".into(), "-".into(), "-".into()),
        };
        let collapse = c
            .collapse
            .map(|v| format!("{v:.1}"))
            .unwrap_or_else(|| "-".to_string());
        let frob = match c.frobenius_compatible {
            Some(true) => "yes",
            Some(false) => "NO",
            None => "n/a",
        };
        let descent = c
            .descent
            .as_ref()
            .map(|d| format!("{}/{}/{}", d.unknowns, d.equations, d.boolean_degree))
            .unwrap_or_else(|| "-".to_string());
        let _ = writeln!(
            s,
            "   {:<44} {:>5} {:>14} {:>6} {:>8} {:>5} {:>21}",
            truncate(&c.system.name, 44),
            vars,
            degs,
            terms,
            collapse,
            frob,
            descent
        );
        if let Err(e) = &c.result {
            let _ = writeln!(s, "        ! {e}");
        }
    }
    s
}

fn truncate(s: &str, n: usize) -> String {
    if s.chars().count() <= n {
        s.to_string()
    } else {
        let t: String = s.chars().take(n - 1).collect();
        format!("{t}…")
    }
}

