/// xorshift64* — deterministic, seedable, dependency-free.
#[derive(Clone, Debug)]
pub struct Rng64(u64);

impl Rng64 {
    pub fn new(seed: u64) -> Self {
        Rng64(seed.wrapping_mul(0x9E37_79B9_7F4A_7C15) | 1)
    }
    pub fn next_u64(&mut self) -> u64 {
        let mut x = self.0;
        x ^= x >> 12;
        x ^= x << 25;
        x ^= x >> 27;
        self.0 = x;
        x.wrapping_mul(0x2545_F491_4F6C_DD1D)
    }
    pub fn below(&mut self, n: u64) -> u64 {
        self.next_u64() % n
    }
}

// ---------------------------------------------------------------------------
// Small finite fields: F_p (p odd prime) and F_{2^n}, elements as u64
// ---------------------------------------------------------------------------

/// A finite field of order `q = p^n` small enough to tabulate square roots:
/// either a prime field (`n = 1`) or a binary field `F_{2^n}` in polynomial
/// basis.  Elements are `u64` in `[0, q)`; for binary fields the integer is
/// the coefficient bit-vector.
#[derive(Clone, Debug)]
pub struct Gf {
    pub p: u64,
    pub n: u32,
    pub q: u64,
    poly: u64,
    sqrt_tab: Vec<u32>,
    as_tab: Vec<u32>,
    /// Binary and odd-extension fields: `log_tab[a] = k` with `g^k = a`,
    /// `exp_tab[k] = g^k` (doubled so that `exp_tab[i + j]` needs no
    /// reduction).
    log_tab: Vec<u32>,
    exp_tab: Vec<u32>,
    /// Odd-characteristic extension `F_{p^n} = F_p[t]/(f)`: the monic
    /// irreducible `f`'s coefficients `c_0 … c_{n−1}` (`t^n = −Σ c_i t^i`).
    /// Elements are digit vectors `Σ a_i p^i ↔ Σ a_i t^i`.
    ext_poly: Vec<u64>,
}

impl Gf {
    /// Prime field `F_p`, `p` an odd prime `< 2²²`.
    pub fn prime(p: u64) -> Self {
        assert!((5..(1 << 22)).contains(&p), "prime field out of toy range");
        assert!(is_prime_u64(p), "{p} is not prime");
        let mut sqrt_tab = vec![NONE32; p as usize];
        for a in 0..p {
            let sq = ((a as u128 * a as u128) % p as u128) as usize;
            if sqrt_tab[sq] == NONE32 {
                sqrt_tab[sq] = a as u32;
            }
        }
        Gf {
            p,
            n: 1,
            q: p,
            poly: 0,
            sqrt_tab,
            as_tab: Vec::new(),
            log_tab: Vec::new(),
            exp_tab: Vec::new(),
            ext_poly: Vec::new(),
        }
    }

    /// Odd-characteristic extension field `F_{p^k}`, `p^k < 2²²`, `k ≥ 2`,
    /// as `F_p[t]/(f)` for the lexicographically first monic irreducible
    /// `f` of degree `k`.  Elements are base-`p` digit vectors, so the
    /// digits of an element are its coordinates in the basis `1, t, …,
    /// t^{k−1}` — which is what a Weil descent to `F_p` reads off.
    pub fn extension(p: u64, k: u32) -> Self {
        assert!(p >= 3 && is_prime_u64(p), "{p} is not an odd prime");
        assert!(k >= 2, "use Gf::prime for k = 1");
        let q = p.pow(k);
        assert!(q < (1 << 22), "extension field out of toy range");
        let ext_poly = find_irreducible_fp(p, k).expect("an irreducible polynomial exists");
        let mut f = Gf {
            p,
            n: k,
            q,
            poly: 0,
            sqrt_tab: Vec::new(),
            as_tab: Vec::new(),
            log_tab: Vec::new(),
            exp_tab: Vec::new(),
            ext_poly,
        };
        let order = q - 1;
        let mut gen = p; // the element t
        loop {
            let mut exp_tab = vec![0u32; 2 * order as usize];
            let mut log_tab = vec![NONE32; q as usize];
            let mut v = 1u64;
            let mut ok = true;
            for kk in 0..order {
                if log_tab[v as usize] != NONE32 {
                    ok = false;
                    break;
                }
                log_tab[v as usize] = kk as u32;
                exp_tab[kk as usize] = v as u32;
                exp_tab[(kk + order) as usize] = v as u32;
                v = f.ext_mul_raw(v, gen);
            }
            if ok {
                f.log_tab = log_tab;
                f.exp_tab = exp_tab;
                break;
            }
            gen += 1;
            assert!(gen < q, "no generator found");
        }
        let mut sqrt_tab = vec![NONE32; q as usize];
        for a in 0..q {
            let sq = f.mul(a, a) as usize;
            if sqrt_tab[sq] == NONE32 {
                sqrt_tab[sq] = a as u32;
            }
        }
        f.sqrt_tab = sqrt_tab;
        f
    }

    /// Is this an odd-characteristic extension field?
    pub fn is_odd_extension(&self) -> bool {
        self.p != 2 && self.n > 1
    }

    /// Base-`p` digits of an element (coordinates in `1, t, …, t^{n−1}`).
    pub fn digits(&self, a: u64) -> Vec<u64> {
        let mut d = Vec::with_capacity(self.n as usize);
        let mut a = a;
        for _ in 0..self.n {
            d.push(a % self.p);
            a /= self.p;
        }
        d
    }

    /// Element from base-`p` digits.
    pub fn from_digits(&self, d: &[u64]) -> u64 {
        let mut a = 0u64;
        for &c in d.iter().rev() {
            a = a * self.p + (c % self.p);
        }
        a
    }

    /// Schoolbook product in `F_p[t]/(f)`, no tables.
    fn ext_mul_raw(&self, a: u64, b: u64) -> u64 {
        let n = self.n as usize;
        let p = self.p;
        let da = self.digits(a);
        let db = self.digits(b);
        let mut prod = vec![0u64; 2 * n - 1];
        for i in 0..n {
            if da[i] == 0 {
                continue;
            }
            for j in 0..n {
                prod[i + j] = (prod[i + j] + da[i] * db[j]) % p;
            }
        }
        // reduce: t^n = −Σ c_i t^i
        for deg in (n..2 * n - 1).rev() {
            let c = prod[deg];
            if c == 0 {
                continue;
            }
            prod[deg] = 0;
            for i in 0..n {
                let sub = (c * self.ext_poly[i]) % p;
                prod[deg - n + i] = (prod[deg - n + i] + p - sub) % p;
            }
        }
        self.from_digits(&prod[..n])
    }

    /// Binary field `F_{2^n}` with the same irreducible polynomial the
    /// Koblitz index-calculus module uses, so element encodings agree.
    pub fn binary(n: u32) -> Self {
        let irr = find_irreducible(n).expect("irreducible polynomial");
        Self::binary_with(&irr)
    }

    /// Binary field with an explicit irreducible polynomial.
    pub fn binary_with(irr: &IrreduciblePoly) -> Self {
        let n = irr.degree;
        assert!((2..=22).contains(&n), "binary field out of toy range");
        let mut poly = 1u64 << n;
        for &t in &irr.low_terms {
            poly |= 1 << t;
        }
        let q = 1u64 << n;
        let mut f = Gf {
            p: 2,
            n,
            q,
            poly,
            sqrt_tab: Vec::new(),
            as_tab: Vec::new(),
            log_tab: Vec::new(),
            exp_tab: Vec::new(),
            ext_poly: Vec::new(),
        };
        // Discrete-log tables from a generator of the multiplicative group.
        let order = q - 1;
        let mut gen = 2u64;
        loop {
            let mut exp_tab = vec![0u32; 2 * order as usize];
            let mut log_tab = vec![NONE32; q as usize];
            let mut v = 1u64;
            let mut ok = true;
            for k in 0..order {
                if log_tab[v as usize] != NONE32 {
                    ok = false;
                    break;
                }
                log_tab[v as usize] = k as u32;
                exp_tab[k as usize] = v as u32;
                exp_tab[(k + order) as usize] = v as u32;
                v = f.clmul_reduce(v, gen);
            }
            if ok {
                f.log_tab = log_tab;
                f.exp_tab = exp_tab;
                break;
            }
            gen += 1;
        }
        let mut sqrt_tab = vec![NONE32; q as usize];
        let mut as_tab = vec![NONE32; q as usize];
        for a in 0..q {
            let sq = f.mul(a, a);
            sqrt_tab[sq as usize] = a as u32;
            let asv = sq ^ a;
            if as_tab[asv as usize] == NONE32 {
                as_tab[asv as usize] = a as u32;
            }
        }
        f.sqrt_tab = sqrt_tab;
        f.as_tab = as_tab;
        f
    }

    pub fn is_binary(&self) -> bool {
        self.p == 2
    }

    pub fn add(&self, a: u64, b: u64) -> u64 {
        if self.p == 2 {
            a ^ b
        } else if self.n > 1 {
            let (da, db) = (self.digits(a), self.digits(b));
            let d: Vec<u64> = da.iter().zip(&db).map(|(x, y)| (x + y) % self.p).collect();
            self.from_digits(&d)
        } else {
            let s = a + b;
            if s >= self.q {
                s - self.q
            } else {
                s
            }
        }
    }
    pub fn sub(&self, a: u64, b: u64) -> u64 {
        if self.p == 2 {
            a ^ b
        } else if self.n > 1 {
            let (da, db) = (self.digits(a), self.digits(b));
            let d: Vec<u64> = da
                .iter()
                .zip(&db)
                .map(|(x, y)| (x + self.p - y) % self.p)
                .collect();
            self.from_digits(&d)
        } else if a >= b {
            a - b
        } else {
            a + self.q - b
        }
    }
    pub fn neg(&self, a: u64) -> u64 {
        if self.p == 2 || a == 0 {
            a
        } else if self.n > 1 {
            let d: Vec<u64> = self
                .digits(a)
                .iter()
                .map(|x| (self.p - x) % self.p)
                .collect();
            self.from_digits(&d)
        } else {
            self.q - a
        }
    }
    /// Carry-less product reduced modulo the field polynomial (no tables).
    fn clmul_reduce(&self, a: u64, b: u64) -> u64 {
        let mut r = 0u64;
        let mut x = a;
        let mut y = b;
        while y != 0 {
            if y & 1 == 1 {
                r ^= x;
            }
            x <<= 1;
            y >>= 1;
        }
        let n = self.n;
        for i in (n..2 * n).rev() {
            if (r >> i) & 1 == 1 {
                r ^= self.poly << (i - n);
            }
        }
        r
    }

    pub fn mul(&self, a: u64, b: u64) -> u64 {
        if self.n > 1 && self.p != 2 {
            if a == 0 || b == 0 {
                return 0;
            }
            if self.log_tab.is_empty() {
                return self.ext_mul_raw(a, b);
            }
            let k = self.log_tab[a as usize] as usize + self.log_tab[b as usize] as usize;
            return self.exp_tab[k] as u64;
        }
        if self.p == 2 {
            if a == 0 || b == 0 {
                return 0;
            }
            if !self.log_tab.is_empty() {
                let k = self.log_tab[a as usize] as usize + self.log_tab[b as usize] as usize;
                return self.exp_tab[k] as u64;
            }
            let mut r = 0u64;
            let mut x = a;
            let mut y = b;
            while y != 0 {
                if y & 1 == 1 {
                    r ^= x;
                }
                x <<= 1;
                y >>= 1;
            }
            let n = self.n;
            for i in (n..2 * n).rev() {
                if (r >> i) & 1 == 1 {
                    r ^= self.poly << (i - n);
                }
            }
            r
        } else {
            ((a as u128 * b as u128) % self.q as u128) as u64
        }
    }
    pub fn pow(&self, mut a: u64, mut e: u64) -> u64 {
        let mut r = 1u64;
        while e > 0 {
            if e & 1 == 1 {
                r = self.mul(r, a);
            }
            a = self.mul(a, a);
            e >>= 1;
        }
        r
    }
    pub fn inv(&self, a: u64) -> u64 {
        assert!(a != 0, "inverse of zero");
        if self.n > 1 && !self.log_tab.is_empty() {
            let order = (self.q - 1) as usize;
            let k = self.log_tab[a as usize] as usize;
            return self.exp_tab[(order - k) % order] as u64;
        }
        self.pow(a, self.q - 2)
    }
    pub fn div(&self, a: u64, b: u64) -> u64 {
        self.mul(a, self.inv(b))
    }
    /// A square root of `a`, if one exists.
    pub fn sqrt(&self, a: u64) -> Option<u64> {
        let v = self.sqrt_tab[a as usize];
        (v != NONE32).then_some(v as u64)
    }
    /// A solution `t` of `t² + t = c` (binary fields only).
    pub fn artin_schreier(&self, c: u64) -> Option<u64> {
        assert!(self.p == 2);
        let v = self.as_tab[c as usize];
        (v != NONE32).then_some(v as u64)
    }
    /// `a ↦ a^p`, the absolute Frobenius (identity on a prime field).
    pub fn frob(&self, a: u64) -> u64 {
        if self.p == 2 {
            self.mul(a, a)
        } else if self.n > 1 {
            self.pow(a, self.p)
        } else {
            a
        }
    }
    /// `a ↦ a^{p^d}`.
    pub fn frob_pow(&self, mut a: u64, d: u32) -> u64 {
        for _ in 0..d {
            a = self.frob(a);
        }
        a
    }
    /// Does `a` lie in the subfield `F_{p^d}`?
    pub fn in_subfield(&self, a: u64, d: u32) -> bool {
        self.frob_pow(a, d) == a
    }
    /// The elements of the subfield `F_{p^d}` (`d | n`).
    pub fn subfield_elements(&self, d: u32) -> Vec<u64> {
        (0..self.q).filter(|&a| self.in_subfield(a, d)).collect()
    }
    /// Uniformly random element.
    pub fn random(&self, rng: &mut Rng64) -> u64 {
        rng.below(self.q)
    }
    /// Display an element: decimal for prime fields, hex bit-vector for
    /// binary ones.
    pub fn show(&self, a: u64) -> String {
        if a == INF {
            "∞".to_string()
        } else if self.p == 2 {
            format!("0x{a:x}")
        } else if self.n > 1 {
            let d = self.digits(a);
            format!(
                "[{}]",
                d.iter()
                    .map(|c| c.to_string())
                    .collect::<Vec<_>>()
                    .join(",")
            )
        } else {
            a.to_string()
        }
    }
    pub fn name(&self) -> String {
        if self.p == 2 {
            format!("F_2^{}", self.n)
        } else if self.n > 1 {
            format!("F_{}^{}", self.p, self.n)
        } else {
            format!("F_{}", self.p)
        }
    }
}

/// Lexicographically first monic irreducible polynomial of degree `k`
/// over `F_p`, as `c_0 … c_{k−1}` (leading coefficient implicit), by trial
/// division by every monic polynomial of degree `1 … k/2`.
fn find_irreducible_fp(p: u64, k: u32) -> Option<Vec<u64>> {
    let k = k as usize;
    // polynomials as coefficient vectors, low to high, leading coeff 1
    fn rem_is_zero(p: u64, f: &[u64], g: &[u64]) -> bool {
        // f, g monic (leading coefficient 1 stored explicitly)
        let mut r: Vec<u64> = f.to_vec();
        let dg = g.len() - 1;
        while r.len() > dg && r.len() >= g.len() {
            let lead = r[r.len() - 1];
            if lead != 0 {
                let shift = r.len() - g.len();
                for (i, &gc) in g.iter().enumerate() {
                    r[shift + i] = (r[shift + i] + p * lead - (lead * gc) % p) % p;
                }
            }
            r.pop();
        }
        r.iter().all(|&c| c == 0)
    }
    let total = p.pow(k as u32);
    for code in 0..total {
        let mut f: Vec<u64> = (0..k).map(|i| (code / p.pow(i as u32)) % p).collect();
        if f[0] == 0 {
            continue; // divisible by t
        }
        f.push(1);
        let mut irreducible = true;
        'outer: for dg in 1..=k / 2 {
            for gcode in 0..p.pow(dg as u32) {
                let mut g: Vec<u64> = (0..dg).map(|i| (gcode / p.pow(i as u32)) % p).collect();
                g.push(1);
                if rem_is_zero(p, &f, &g) {
                    irreducible = false;
                    break 'outer;
                }
            }
        }
        if irreducible {
            f.pop();
            return Some(f);
        }
    }
    None
}

fn is_prime_u64(n: u64) -> bool {
    if n < 2 {
        return false;
    }
    let mut d = 2;
    while d * d <= n {
        if n.is_multiple_of(d) {
            return false;
        }
        d += 1;
    }
    true
}

// ---------------------------------------------------------------------------
// Curves in long Weierstrass form (any characteristic)
