/// What kind of map on `E` a symmetry comes from.
#[derive(Clone, Debug, PartialEq, Eq)]
pub enum SymmetryKind {
    /// Translation by a rational point of order 2.
    TwoTorsion(Pt),
    /// An automorphism other than `±1`.
    Automorphism(Auto),
    /// The `p^d`-power Frobenius of a curve defined over `F_{p^d}`.
    Frobenius(u32),
}

/// How the symmetry may be applied to a relation tuple without breaking it.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum Scope {
    /// To any even number of the points (translation type).  These lower
    /// the degree of the summation polynomial.
    Pairwise,
    /// Only to all points at once (automorphism / Frobenius type).  These
    /// collapse factor-base orbits but leave the polynomial alone.
    Global,
    /// Neither test passed.
    None,
}

/// A symmetry of the relation `P_1 + ⋯ + P_{m+1} = O` that descends to the
/// `x`-line.
#[derive(Clone, Debug)]
pub struct Symmetry {
    pub kind: SymmetryKind,
    /// Its action on `x`, when that action is a Möbius map (the Frobenius
    /// acts semilinearly, `x ↦ x^{p^d}`, and gets `None`).
    pub mobius: Option<Mobius>,
    pub scope: Scope,
}

impl Symmetry {
    pub fn describe(&self, f: &Gf) -> String {
        let what = match &self.kind {
            SymmetryKind::TwoTorsion(Pt::Aff(x, y)) => {
                format!("translation by T = ({}, {})", f.show(*x), f.show(*y))
            }
            SymmetryKind::TwoTorsion(Pt::Inf) => "translation by O".to_string(),
            SymmetryKind::Automorphism(Auto::Scale(u)) => {
                format!("automorphism (x,y) ↦ (u²x, u³y), u = {}", f.show(*u))
            }
            SymmetryKind::Automorphism(Auto::Neg) => "negation".to_string(),
            SymmetryKind::Frobenius(d) => format!("{}^{}-Frobenius", f.p, d),
        };
        let act = match self.mobius {
            Some(m) => format!("x ↦ {}", m.describe(f)),
            None => match self.kind {
                SymmetryKind::Frobenius(d) => format!("x ↦ x^{}", f.p.pow(d)),
                _ => "?".to_string(),
            },
        };
        format!("{what}; {act}; scope {:?}", self.scope)
    }
}

fn apply_symmetry(curve: &Curve, s: &Symmetry, p: Pt) -> Pt {
    match &s.kind {
        SymmetryKind::TwoTorsion(t) => curve.add(p, *t),
        SymmetryKind::Automorphism(a) => curve.apply_auto(*a, p),
        SymmetryKind::Frobenius(d) => curve.frobenius(p, *d),
    }
}

/// Fit the Möbius map with `x(γP) = M(x(P))` and verify it on every point.
fn mobius_of_map(curve: &Curve, pts: &[Pt], gamma: impl Fn(Pt) -> Pt) -> Option<Mobius> {
    let f = &curve.f;
    let mut pairs: Vec<(u64, u64)> = Vec::new();
    let mut seen = std::collections::HashSet::new();
    for &p in pts {
        let (t, s) = (p.x(), gamma(p).x());
        if t != INF && seen.insert(t) {
            pairs.push((t, s));
        }
        if pairs.len() == 3 {
            break;
        }
    }
    let m = Mobius::fit(f, &pairs)?;
    let ok = pts.iter().chain(std::iter::once(&Pt::Inf)).all(|&p| {
        let (t, s) = (p.x(), gamma(p).x());
        m.apply(f, t) == s
    });
    ok.then_some(m)
}

/// Random relation tuple `(P_1, …, P_{m+1})` with `Σ P_i = O`, all affine.
pub fn relation_tuple(curve: &Curve, pts: &[Pt], m: usize, rng: &mut Rng64) -> Vec<Pt> {
    loop {
        let mut tuple: Vec<Pt> = (0..m)
            .map(|_| pts[rng.below(pts.len() as u64) as usize])
            .collect();
        let sum = tuple.iter().fold(Pt::Inf, |acc, &p| curve.add(acc, p));
        let last = curve.neg(sum);
        if last != Pt::Inf {
            tuple.push(last);
            return tuple;
        }
    }
}

/// Is some signed combination `Σ ±Q_i` zero?  (The `x`-coordinate forgets
/// the sign, so this is the right notion of "still a relation".)
fn signed_relation(curve: &Curve, tuple: &[Pt]) -> bool {
    let n = tuple.len();
    for mask in 0..(1u32 << (n - 1)) {
        let mut sum = Pt::Inf;
        for (i, &q) in tuple.iter().enumerate() {
            let q = if i > 0 && (mask >> (i - 1)) & 1 == 1 {
                curve.neg(q)
            } else {
                q
            };
            sum = curve.add(sum, q);
        }
        if sum == Pt::Inf {
            return true;
        }
    }
    false
}

fn scope_of(curve: &Curve, pts: &[Pt], s: &Symmetry, rng: &mut Rng64) -> Scope {
    let trials = 24;
    let mut pairwise = true;
    let mut global = true;
    for _ in 0..trials {
        let tuple = relation_tuple(curve, pts, 2, rng);
        let mut pair = tuple.clone();
        pair[0] = apply_symmetry(curve, s, pair[0]);
        pair[1] = apply_symmetry(curve, s, pair[1]);
        if !signed_relation(curve, &pair) {
            pairwise = false;
        }
        let all: Vec<Pt> = tuple.iter().map(|&p| apply_symmetry(curve, s, p)).collect();
        if !signed_relation(curve, &all) {
            global = false;
        }
        if !pairwise && !global {
            break;
        }
    }
    if pairwise {
        Scope::Pairwise
    } else if global {
        Scope::Global
    } else {
        Scope::None
    }
}

/// Every symmetry of the relation that descends to the `x`-line, each one
/// fitted from data and verified on all points, with its scope measured.
pub fn detect_symmetries(curve: &Curve, pts: &[Pt], rng: &mut Rng64) -> Vec<Symmetry> {
    let mut out = Vec::new();
    for t in curve.two_torsion() {
        let mobius = mobius_of_map(curve, pts, |p| curve.add(p, t));
        let mut s = Symmetry {
            kind: SymmetryKind::TwoTorsion(t),
            mobius,
            scope: Scope::None,
        };
        s.scope = scope_of(curve, pts, &s, rng);
        out.push(s);
    }
    for a in curve.automorphisms() {
        if matches!(a, Auto::Neg | Auto::Scale(1)) {
            continue;
        }
        let mobius = mobius_of_map(curve, pts, |p| curve.apply_auto(a, p));
        let mut s = Symmetry {
            kind: SymmetryKind::Automorphism(a),
            mobius,
            scope: Scope::None,
        };
        s.scope = scope_of(curve, pts, &s, rng);
        out.push(s);
    }
    if let Some(d) = curve.subfield_degree() {
        if d < curve.f.n {
            let mut s = Symmetry {
                kind: SymmetryKind::Frobenius(d),
                mobius: None,
                scope: Scope::None,
            };
            s.scope = scope_of(curve, pts, &s, rng);
            out.push(s);
        }
    }
    out
}

