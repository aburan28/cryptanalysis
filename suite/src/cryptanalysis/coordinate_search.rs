/// Basis of `{v : M v = 0}` for the row-major matrix `rows` with `ncols`
/// columns, by reduced row echelon form.
pub fn kernel(f: &Gf, mut rows: Vec<Vec<u64>>, ncols: usize) -> Vec<Vec<u64>> {
    let nrows = rows.len();
    let mut pivots: Vec<usize> = Vec::new();
    let mut r = 0;
    for c in 0..ncols {
        if r == nrows {
            break;
        }
        let Some(pi) = (r..nrows).find(|&i| rows[i][c] != 0) else {
            continue;
        };
        rows.swap(r, pi);
        let inv = f.inv(rows[r][c]);
        for cc in c..ncols {
            rows[r][cc] = f.mul(rows[r][cc], inv);
        }
        let pivot_row = rows[r].clone();
        for (i, row) in rows.iter_mut().enumerate() {
            if i == r || row[c] == 0 {
                continue;
            }
            let factor = row[c];
            for cc in c..ncols {
                if pivot_row[cc] != 0 {
                    row[cc] = f.sub(row[cc], f.mul(factor, pivot_row[cc]));
                }
            }
        }
        pivots.push(c);
        r += 1;
    }
    let mut is_pivot = vec![false; ncols];
    for &c in &pivots {
        is_pivot[c] = true;
    }
    let mut basis = Vec::new();
    for fc in 0..ncols {
        if is_pivot[fc] {
            continue;
        }
        let mut v = vec![0u64; ncols];
        v[fc] = 1;
        for (i, &pc) in pivots.iter().enumerate() {
            v[pc] = f.neg(rows[i][fc]);
        }
        basis.push(v);
    }
    basis
}

