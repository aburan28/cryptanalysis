/// A polynomial over `Gf` in named variables, sparse.
#[derive(Clone, Debug)]
pub struct RelationPolynomial {
    pub var_names: Vec<String>,
    pub terms: Vec<(Vec<u32>, u64)>,
}

impl RelationPolynomial {
    pub fn n_terms(&self) -> usize {
        self.terms.len()
    }
    pub fn degrees(&self) -> Vec<u32> {
        let n = self.var_names.len();
        (0..n)
            .map(|i| self.terms.iter().map(|(e, _)| e[i]).max().unwrap_or(0))
            .collect()
    }
    pub fn total_degree(&self) -> u32 {
        self.terms
            .iter()
            .map(|(e, _)| e.iter().sum::<u32>())
            .max()
            .unwrap_or(0)
    }
    pub fn eval(&self, f: &Gf, vals: &[u64]) -> u64 {
        let mut acc = 0;
        for (e, c) in &self.terms {
            let mut t = *c;
            for (i, &k) in e.iter().enumerate() {
                if k > 0 {
                    t = f.mul(t, f.pow(vals[i], k as u64));
                }
            }
            acc = f.add(acc, t);
        }
        acc
    }
    /// Human-readable, monomials sorted by degree.
    pub fn render(&self, f: &Gf, max_terms: usize) -> String {
        let mut terms = self.terms.clone();
        terms.sort_by(|a, b| {
            let da: u32 = a.0.iter().sum();
            let db: u32 = b.0.iter().sum();
            db.cmp(&da).then(b.0.cmp(&a.0))
        });
        let mut parts = Vec::new();
        for (e, c) in terms.iter().take(max_terms) {
            let mut mono = String::new();
            for (i, &k) in e.iter().enumerate() {
                if k == 1 {
                    let _ = write!(mono, "·{}", self.var_names[i]);
                } else if k > 1 {
                    let _ = write!(mono, "·{}^{}", self.var_names[i], k);
                }
            }
            let coef = if *c == 1 && !mono.is_empty() {
                String::new()
            } else {
                f.show(*c)
            };
            parts.push(format!("{coef}{mono}").trim_start_matches('·').to_string());
        }
        let mut s = parts.join(" + ");
        if terms.len() > max_terms {
            let _ = write!(s, " + … ({} more)", terms.len() - max_terms);
        }
        s
    }
}

/// Outcome of interpolating one coordinate system.
#[derive(Clone, Debug)]
pub struct InterpolationResult {
    pub poly: RelationPolynomial,
    /// Kernel dimension at the final degree box (1 = unique polynomial).
    pub kernel_dim: usize,
    pub samples: usize,
    /// Fresh relation tuples the polynomial vanished on.
    pub verified_on: usize,
    /// Fraction of random non-relation tuples it also vanished on (should
    /// be about `deg/q`).
    pub false_positive_rate: f64,
}

fn build_rows(f: &Gf, samples: &[Vec<u64>], monos: &[Vec<u32>]) -> Vec<Vec<u64>> {
    samples
        .iter()
        .map(|vals| {
            monos
                .iter()
                .map(|e| {
                    let mut t = 1;
                    for (i, &k) in e.iter().enumerate() {
                        if k > 0 {
                            t = f.mul(t, f.pow(vals[i], k as u64));
                        }
                    }
                    t
                })
                .collect()
        })
        .collect()
}

/// Interpolate the summation polynomial of `m + 1` points in the given
/// coordinates, from random relation tuples, and verify it.
pub fn interpolate_relation(
    curve: &Curve,
    pts: &[Pt],
    cs: &CoordinateSystem,
    m: usize,
    rng: &mut Rng64,
) -> Result<InterpolationResult, String> {
    let f = &curve.f;
    let monos = cs.monomials(m);
    let need = monos.len() + monos.len() / 4 + 40;
    let mut samples: Vec<Vec<u64>> = Vec::new();
    let mut attempts = 0;
    while samples.len() < need {
        attempts += 1;
        if attempts > 50 * need {
            return Err("could not sample enough finite relation tuples".to_string());
        }
        let tuple = relation_tuple(curve, pts, m, rng);
        if let Some(v) = cs.evaluate(f, &tuple) {
            samples.push(v);
        }
    }
    let rows = build_rows(f, &samples, &monos);
    let ker = kernel(f, rows, monos.len());
    if ker.is_empty() {
        return Err(format!(
            "no polynomial within the degree box {:?} vanishes on the relation samples",
            cs.bounds(m)
        ));
    }
    // If the kernel is not one-dimensional the box is loose: shrink it
    // variable by variable while a solution survives.
    let mut chosen_monos = monos.clone();
    let mut chosen_ker = ker;
    if chosen_ker.len() > 1 {
        let mut bounds = cs.bounds(m);
        loop {
            let mut improved = false;
            for i in 0..bounds.len() {
                if bounds[i] == 0 {
                    continue;
                }
                let mut trial = bounds.clone();
                trial[i] -= 1;
                let tmonos: Vec<Vec<u32>> = monos
                    .iter()
                    .filter(|e| e.iter().zip(&trial).all(|(&k, &b)| k <= b))
                    .cloned()
                    .collect();
                if tmonos.is_empty() {
                    continue;
                }
                let rows = build_rows(f, &samples, &tmonos);
                let k = kernel(f, rows, tmonos.len());
                if !k.is_empty() {
                    bounds = trial;
                    chosen_monos = tmonos;
                    chosen_ker = k;
                    improved = true;
                    if chosen_ker.len() == 1 {
                        break;
                    }
                }
            }
            if !improved || chosen_ker.len() == 1 {
                break;
            }
        }
    }
    let kernel_dim = chosen_ker.len();
    let v = &chosen_ker[0];
    let mut terms: Vec<(Vec<u32>, u64)> = chosen_monos
        .iter()
        .zip(v.iter())
        .filter(|(_, &c)| c != 0)
        .map(|(e, &c)| (e.clone(), c))
        .collect();
    // normalise leading coefficient to 1 (last monomial in the list order)
    if let Some(&(_, lead)) = terms.last() {
        let inv = f.inv(lead);
        for (_, c) in terms.iter_mut() {
            *c = f.mul(*c, inv);
        }
    }
    let poly = RelationPolynomial {
        var_names: cs.var_names(m),
        terms,
    };
    // Verification on fresh relations and on random non-relations.
    let mut verified_on = 0;
    let mut checked = 0;
    while verified_on < 200 && checked < 4000 {
        checked += 1;
        let tuple = relation_tuple(curve, pts, m, rng);
        if let Some(vals) = cs.evaluate(f, &tuple) {
            if poly.eval(f, &vals) != 0 {
                return Err(format!(
                    "interpolated polynomial does not vanish on a fresh relation ({})",
                    cs.name
                ));
            }
            verified_on += 1;
        }
    }
    let mut fp = 0;
    let mut tested = 0;
    while tested < 300 {
        let mut tuple: Vec<Pt> = (0..=m)
            .map(|_| pts[rng.below(pts.len() as u64) as usize])
            .collect();
        // make sure it is not accidentally a relation
        if signed_relation(curve, &tuple) {
            continue;
        }
        tuple.truncate(m + 1);
        if let Some(vals) = cs.evaluate(f, &tuple) {
            tested += 1;
            if poly.eval(f, &vals) == 0 {
                fp += 1;
            }
        }
    }
    Ok(InterpolationResult {
        poly,
        kernel_dim,
        samples: samples.len(),
        verified_on,
        false_positive_rate: fp as f64 / tested as f64,
    })
}

// ---------------------------------------------------------------------------
// Collapse factor: how many relation tuples share one coordinate vector
// ---------------------------------------------------------------------------

/// Generic number of relation tuples `(P_1, …, P_{m+1})`, `Σ P_i = O`, that
/// map to the same coordinate vector: the median over random samples of
/// the fibre size, computed by enumerating the fibre of the per-point
/// coordinate on the curve.  It is the effective symmetry the coordinates
/// quotient out, measured rather than counted from a group; the median
/// rather than the mean because a sample through a 2-torsion point or a
/// fixed point of the involution has a smaller fibre.  Permutations of the
/// summands are not included (multiply by `m!` for a symmetric system).
pub fn collapse_factor(
    curve: &Curve,
    pts: &[Pt],
    cs: &CoordinateSystem,
    m: usize,
    rng: &mut Rng64,
    samples: usize,
) -> f64 {
    let f = &curve.f;
    // fibre table: coordinate value → points
    let mut fibre: HashMap<u64, Vec<Pt>> = HashMap::new();
    for &p in pts {
        let v = cs.point_value(f, p);
        if v != INF {
            fibre.entry(v).or_default().push(p);
        }
    }
    let mut sizes: Vec<usize> = Vec::new();
    while sizes.len() < samples {
        let tuple = relation_tuple(curve, pts, m, rng);
        let Some(vals) = cs.evaluate(f, &tuple) else {
            continue;
        };
        let per_point: Vec<&Vec<Pt>> = tuple
            .iter()
            .map(|&p| &fibre[&cs.point_value(f, p)])
            .collect();
        let size: usize = per_point.iter().map(|v| v.len()).product();
        if size > 1 << 16 {
            continue;
        }
        // enumerate the product
        let mut hits = 0;
        let mut idx = vec![0usize; m + 1];
        loop {
            let cand: Vec<Pt> = (0..=m).map(|i| per_point[i][idx[i]]).collect();
            let sum = cand.iter().fold(Pt::Inf, |acc, &p| curve.add(acc, p));
            if sum == Pt::Inf {
                if let Some(cv) = cs.evaluate(f, &cand) {
                    if cv == vals {
                        hits += 1;
                    }
                }
            }
            // increment
            let mut i = 0;
            loop {
                if i > m {
                    break;
                }
                idx[i] += 1;
                if idx[i] < per_point[i].len() {
                    break;
                }
                idx[i] = 0;
                i += 1;
            }
            if i > m {
                break;
            }
        }
        sizes.push(hits);
    }
    sizes.sort_unstable();
    sizes[sizes.len() / 2] as f64
}

