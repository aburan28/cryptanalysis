    #[test]
    fn additive_frame_factor_base_needs_the_x_minus_1_factor() {
        // The symmetrised system needs a factor base closed under
        // u ↦ u + 1, i.e. 1 ∈ V.  For the repo's Frobenius-invariant bases
        // V = roots of a linearised divisor of x^n − 1, and 1 is a root iff
        // the divisor contains the factor x − 1.
        use crate::cryptanalysis::koblitz_index_calculus::{
            all_factors_of_x_n_minus_1, subspace_basis_for_divisor,
        };
        let n = 7;
        let irr = find_irreducible(n).unwrap();
        let f = Gf::binary_with(&irr);
        let factors = all_factors_of_x_n_minus_1(n);
        let x_minus_1 = factors
            .iter()
            .position(|&p| p == 0b11)
            .expect("x − 1 factor");
        let other = (0..factors.len()).find(|&i| i != x_minus_1).unwrap();
        let to_u64 = |e: &F2mElement| e.to_biguint().to_u64_digits().first().copied().unwrap_or(0);
        let contains_one = |idx: &[usize]| {
            let basis = subspace_basis_for_divisor(n, idx, &irr).unwrap();
            let elems: Vec<u64> = basis.iter().map(to_u64).collect();
            // span contains 1?
            (0..(1u32 << elems.len())).any(|mask| {
                let v = (0..elems.len())
                    .filter(|&i| (mask >> i) & 1 == 1)
                    .fold(0u64, |acc, i| f.add(acc, elems[i]));
                v == 1
            })
        };
        assert!(
            !contains_one(&[other]),
            "a base without x − 1 must not contain 1"
        );
        assert!(contains_one(&[x_minus_1, other]), "with x − 1 it must");
    }

