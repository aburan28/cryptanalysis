/// `t ↦ (a t + b) / (c t + d)`.
#[derive(Clone, Copy, Debug, PartialEq, Eq, Hash)]
pub struct Mobius {
    pub a: u64,
    pub b: u64,
    pub c: u64,
    pub d: u64,
}

/// The shape of a Möbius map, up to the frame it is written in.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum MobiusKind {
    Identity,
    /// `t ↦ c t`.
    Scaling(u64),
    /// `t ↦ c / t`.
    Inversion(u64),
    /// `t ↦ t + c`.
    Translation(u64),
    General,
}

impl Mobius {
    pub fn identity() -> Self {
        Mobius {
            a: 1,
            b: 0,
            c: 0,
            d: 1,
        }
    }

    pub fn apply(&self, f: &Gf, t: u64) -> u64 {
        if t == INF {
            if self.c == 0 {
                INF
            } else {
                f.div(self.a, self.c)
            }
        } else {
            let den = f.add(f.mul(self.c, t), self.d);
            if den == 0 {
                INF
            } else {
                f.div(f.add(f.mul(self.a, t), self.b), den)
            }
        }
    }

    /// `self ∘ other`.
    pub fn compose(&self, f: &Gf, other: &Mobius) -> Mobius {
        Mobius {
            a: f.add(f.mul(self.a, other.a), f.mul(self.b, other.c)),
            b: f.add(f.mul(self.a, other.b), f.mul(self.b, other.d)),
            c: f.add(f.mul(self.c, other.a), f.mul(self.d, other.c)),
            d: f.add(f.mul(self.c, other.b), f.mul(self.d, other.d)),
        }
        .normalise(f)
    }

    pub fn inverse(&self, f: &Gf) -> Mobius {
        Mobius {
            a: self.d,
            b: f.neg(self.b),
            c: f.neg(self.c),
            d: self.a,
        }
        .normalise(f)
    }

    /// `n ∘ self ∘ n⁻¹`: the same map written in the frame `n`.
    pub fn conjugate_by(&self, f: &Gf, n: &Mobius) -> Mobius {
        n.compose(f, self).compose(f, &n.inverse(f))
    }

    /// Scale so the first non-zero entry is `1`; makes projective equality
    /// plain equality.
    pub fn normalise(&self, f: &Gf) -> Mobius {
        let lead = [self.a, self.b, self.c, self.d]
            .into_iter()
            .find(|&v| v != 0)
            .expect("zero matrix");
        let inv = f.inv(lead);
        Mobius {
            a: f.mul(self.a, inv),
            b: f.mul(self.b, inv),
            c: f.mul(self.c, inv),
            d: f.mul(self.d, inv),
        }
    }

    pub fn is_identity(&self, f: &Gf) -> bool {
        let m = self.normalise(f);
        m.b == 0 && m.c == 0 && m.a == m.d
    }

    /// Multiplicative order, if it is at most `cap`.
    pub fn order(&self, f: &Gf, cap: u32) -> Option<u32> {
        let mut m = *self;
        for k in 1..=cap {
            if m.is_identity(f) {
                return Some(k);
            }
            m = m.compose(f, self);
        }
        None
    }

    /// The rational fixed points, solving `c t² + (d − a) t − b = 0`
    /// (and `∞` when `c = 0`).
    pub fn fixed_points(&self, f: &Gf) -> Vec<u64> {
        let mut out = Vec::new();
        if self.c == 0 {
            out.push(INF);
            // (d − a) t = b
            let k = f.sub(self.d, self.a);
            if k != 0 {
                out.push(f.div(self.b, k));
            }
            return out;
        }
        for t in 0..f.q {
            let v = f.sub(
                f.add(f.mul(f.mul(self.c, t), t), f.mul(f.sub(self.d, self.a), t)),
                self.b,
            );
            if v == 0 {
                out.push(t);
            }
        }
        out
    }

    pub fn kind(&self, f: &Gf) -> MobiusKind {
        let m = self.normalise(f);
        if m.is_identity(f) {
            MobiusKind::Identity
        } else if m.b == 0 && m.c == 0 {
            MobiusKind::Scaling(f.div(m.a, m.d))
        } else if m.a == 0 && m.d == 0 {
            MobiusKind::Inversion(f.div(m.b, m.c))
        } else if m.c == 0 && m.a == m.d {
            MobiusKind::Translation(f.div(m.b, m.d))
        } else {
            MobiusKind::General
        }
    }

    /// All four coefficients in `F_{p^d}`?
    pub fn in_subfield(&self, f: &Gf, d: u32) -> bool {
        let m = self.normalise(f);
        [m.a, m.b, m.c, m.d].iter().all(|&v| f.in_subfield(v, d))
    }

    /// Fit a Möbius map through `(t, s)` pairs; needs three in general
    /// position.  Returns `None` if the pairs are inconsistent or do not
    /// determine the map.
    pub fn fit(f: &Gf, pairs: &[(u64, u64)]) -> Option<Mobius> {
        let mut rows = Vec::new();
        for &(t, s) in pairs {
            let row = match (t == INF, s == INF) {
                (false, false) => vec![t, 1, f.neg(f.mul(s, t)), f.neg(s)],
                (true, false) => vec![1, 0, f.neg(s), 0],
                (false, true) => vec![0, 0, t, 1],
                (true, true) => vec![0, 0, 1, 0],
            };
            rows.push(row);
        }
        let ker = kernel(f, rows, 4);
        if ker.len() != 1 {
            return None;
        }
        let v = &ker[0];
        let m = Mobius {
            a: v[0],
            b: v[1],
            c: v[2],
            d: v[3],
        };
        let det = f.sub(f.mul(m.a, m.d), f.mul(m.b, m.c));
        (det != 0).then(|| m.normalise(f))
    }

    pub fn describe(&self, f: &Gf) -> String {
        let m = self.normalise(f);
        match m.kind(f) {
            MobiusKind::Identity => "t".to_string(),
            MobiusKind::Scaling(c) => format!("{}·t", f.show(c)),
            MobiusKind::Inversion(c) => format!("{}/t", f.show(c)),
            MobiusKind::Translation(c) => format!("t + {}", f.show(c)),
            MobiusKind::General => {
                let lin = |a: u64, b: u64| -> String {
                    match (a, b) {
                        (0, b) => f.show(b),
                        (1, 0) => "t".to_string(),
                        (a, 0) => format!("{}·t", f.show(a)),
                        (1, b) => format!("t + {}", f.show(b)),
                        (a, b) => format!("{}·t + {}", f.show(a), f.show(b)),
                    }
                };
                if m.c == 0 {
                    lin(f.div(m.a, m.d), f.div(m.b, m.d))
                } else {
                    format!("({})/({})", lin(m.a, m.b), lin(m.c, m.d))
                }
            }
        }
    }
}

