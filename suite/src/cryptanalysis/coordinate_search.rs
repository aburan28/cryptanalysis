//! # Coordinate search: an algorithmic hunt for point representations that
//! make decomposition relations cheaper.
//!
//! Index calculus on an elliptic curve spends its time on the *point
//! decomposition problem*: given `R`, find factor-base points with
//! `P_1 + ⋯ + P_m = R`.  Every solver in this repository asks that question
//! through Semaev's summation polynomial in the Weierstrass `x`-coordinate.
//! The `x`-coordinate is one function on the curve among many, and the
//! literature has a handful of others that were found by hand — the
//! `y`-coordinate of a twisted Edwards curve (Faugère–Gaudry–Huot–Renault),
//! the coordinates of Kohel's `μ₄`-normal form, `λ`-coordinates on binary
//! curves, Jacobi quartics, Huff and Hessian models.  This module replaces
//! the hand search with an algorithm.
//!
//! ## What the algorithm knows before it starts
//!
//! Two structural facts prune the search from "all rational functions on
//! `E`" to something finite, and both are checked numerically rather than
//! trusted.
//!
//! 1. **A degree-2 coordinate is a Möbius frame on the `x`-line.**  A
//!    separable degree-2 map `E → P¹` is the quotient by an involution
//!    `P ↦ T' − P`; conjugating by a translation moves `T'` to `O`, so every
//!    degree-2 coordinate is `N(x(P + S))` for a Möbius map `N ∈ PGL₂(K)`.
//!    The translation only shifts the factor base, so the search over
//!    coordinates of degree 2 *is* the search over frames `N`.
//! 2. **A coordinate invariant under a translation subgroup factors through
//!    an isogeny**, and the discrete logarithm is isogeny-invariant.  Being
//!    invariant under `E[ℓ]` buys exactly nothing beyond working on `E/E[ℓ]`.
//!    What buys something is a symmetry that acts *linearly* on a degree-2
//!    coordinate: then the summation polynomial is an invariant of a linear
//!    group action, and invariant theory lowers its degree.
//!
//! So the objects to enumerate are the symmetries of the relation
//! `P_1 + ⋯ + P_{m+1} = O` that descend to the `x`-line as Möbius maps:
//! translation by rational 2-torsion, the automorphisms of `E`, and — on a
//! subfield curve — the Frobenius.  Each is *detected* by fitting a Möbius
//! map to `(x(P), x(γP))` pairs and verifying it on every point.  Each is
//! then *classified by scope*, again by experiment: a translation by
//! 2-torsion may be applied to any even number of the points and the
//! relation survives (`Σ(P_i + k_i T) = ΣP_i + (Σk_i)T`); an automorphism
//! or the Frobenius must be applied to all of them at once.  Only the
//! pairwise ones lower the degree of the polynomial; the global ones
//! collapse factor-base orbits in the linear algebra, which
//! [`crate::cryptanalysis::koblitz_index_calculus`] already exploits.
//!
//! ## What it does
//!
//! For each pairwise symmetry `g` it computes the frame that makes `g`
//! linear: over odd characteristic an involution with rational fixed points
//! becomes `t ↦ −t` after sending the fixed points to `0` and `∞`; in
//! characteristic 2 an involution of `P¹` is unipotent with a single fixed
//! point, and sending it to `∞` gives `t ↦ t + 1`.  In that frame the
//! relation-preserving group acts on `(P¹)^{m+1}` by even-weight sign flips
//! or even-weight translations, whose invariant ring is generated by
//! `w_i = u_i²` and `Π u_i` (respectively `w_i = u_i² + u_i` and `Σ u_i`).
//! It then **interpolates** the summation polynomial in those invariants
//! from random relation tuples — no symbolic algebra, no formulas, just a
//! kernel computation over the field — and measures the result:
//!
//! - degree in each variable and number of monomials, against the same
//!   numbers for the plain Semaev polynomial in the same frame;
//! - the **collapse factor**: how many relation tuples map to one point of
//!   the invariant coordinates, computed by enumerating the fibre rather
//!   than by counting group elements;
//! - whether the coordinate commutes with the Frobenius, i.e. whether the
//!   factor base can stay Frobenius-invariant (the Koblitz constraint);
//! - a Weil-descent cost model for a factor base cut out by a subspace.
//!
//! Every interpolated polynomial is verified on fresh relation tuples and
//! checked to be non-zero on random non-relations before it is reported.
//!
//! ## Honest scope
//!
//! Toy fields only: `F_p` with `p < 2²²` and `F_{2^n}` with `n ≤ 22`.  The
//! polynomials are specialised to one curve, which is all the shape
//! measurements need.  Nothing here solves a decomposition; it produces the
//! system the solvers would have to solve and says how big it is.  See
//! `research/notes/index-calculus/RESEARCH_EXOTIC_COORDINATES.md` for the measurements and for what they
//! do and do not imply.
//!
//! ## References
//!
//! - I. Semaev, *Summation polynomials and the discrete logarithm problem
//!   on elliptic curves*, ePrint 2004/031.
//! - J.-C. Faugère, P. Gaudry, L. Huot, G. Renault, *Using symmetries in
//!   the index calculus for elliptic curves discrete logarithm*,
//!   J. Cryptology 27 (2014).
//! - J.-C. Faugère, L. Huot, A. Joux, G. Renault, V. Vitse, *Symmetrized
//!   summation polynomials: using small order torsion points to speed up
//!   elliptic curve index calculus*, EUROCRYPT 2014.
//! - S. D. Galbraith, S. W. Gebregiyorgis, *Summation polynomial algorithms
//!   for elliptic curves in characteristic two*, INDOCRYPT 2014.
//! - D. Kohel, *Efficient arithmetic on elliptic curves in characteristic
//!   2*, INDOCRYPT 2012 (the `μ₄`-normal form).

