/// A point on the curve.
#[derive(Clone, Copy, Debug, PartialEq, Eq, Hash)]
pub enum Pt {
    Inf,
    Aff(u64, u64),
}

impl Pt {
    /// `x(P)`, with `x(O) = ∞`.
    pub fn x(&self) -> u64 {
        match self {
            Pt::Inf => INF,
            Pt::Aff(x, _) => *x,
        }
    }
    /// `y(P)`, with `y(O) = ∞`.
    pub fn y(&self) -> u64 {
        match self {
            Pt::Inf => INF,
            Pt::Aff(_, y) => *y,
        }
    }
}

/// An automorphism of `E` fixing `O`, in the shapes that occur over the
/// fields handled here.
#[derive(Clone, Copy, Debug, PartialEq, Eq, Hash)]
pub enum Auto {
    /// `P ↦ −P`.
    Neg,
    /// `(x, y) ↦ (u² x, u³ y)` on a short Weierstrass curve.
    Scale(u64),
}

/// `E : y² + a₁xy + a₃y = x³ + a₂x² + a₄x + a₆` over [`Gf`].
#[derive(Clone, Debug)]
pub struct Curve {
    pub f: Gf,
    pub a1: u64,
    pub a2: u64,
    pub a3: u64,
    pub a4: u64,
    pub a6: u64,
    pub label: String,
}

impl Curve {
    /// `y² = x³ + a x + b` over an odd-characteristic field.
    pub fn short_weierstrass(f: Gf, a: u64, b: u64, label: &str) -> Self {
        assert!(f.p != 2);
        Curve {
            f,
            a1: 0,
            a2: 0,
            a3: 0,
            a4: a,
            a6: b,
            label: label.to_string(),
        }
    }

    /// `y² + xy = x³ + a₂x² + a₆` over a binary field.
    pub fn binary(f: Gf, a2: u64, a6: u64, label: &str) -> Self {
        assert!(f.p == 2);
        Curve {
            f,
            a1: 1,
            a2,
            a3: 0,
            a4: 0,
            a6,
            label: label.to_string(),
        }
    }

    /// The Koblitz curve `K_a : y² + xy = x³ + a x² + 1` over `F_{2^n}`.
    pub fn koblitz(a: u8, n: u32) -> Self {
        Self::binary(Gf::binary(n), a as u64, 1, &format!("K_{a}/F_2^{n}"))
    }

    pub fn is_on(&self, p: Pt) -> bool {
        match p {
            Pt::Inf => true,
            Pt::Aff(x, y) => {
                let f = &self.f;
                let lhs = f.add(
                    f.add(f.mul(y, y), f.mul(f.mul(self.a1, x), y)),
                    f.mul(self.a3, y),
                );
                let x2 = f.mul(x, x);
                let rhs = f.add(
                    f.add(f.mul(x2, x), f.mul(self.a2, x2)),
                    f.add(f.mul(self.a4, x), self.a6),
                );
                lhs == rhs
            }
        }
    }

    pub fn neg(&self, p: Pt) -> Pt {
        match p {
            Pt::Inf => Pt::Inf,
            Pt::Aff(x, y) => {
                let f = &self.f;
                Pt::Aff(x, f.neg(f.add(f.add(y, f.mul(self.a1, x)), self.a3)))
            }
        }
    }

    pub fn add(&self, p: Pt, q: Pt) -> Pt {
        let f = &self.f;
        let (x1, y1) = match p {
            Pt::Inf => return q,
            Pt::Aff(x, y) => (x, y),
        };
        let (x2, y2) = match q {
            Pt::Inf => return p,
            Pt::Aff(x, y) => (x, y),
        };
        let lambda = if x1 != x2 {
            f.div(f.sub(y2, y1), f.sub(x2, x1))
        } else {
            if self.neg(p) == q {
                return Pt::Inf;
            }
            // doubling: λ = (3x² + 2a₂x + a₄ − a₁y) / (2y + a₁x + a₃)
            let three = f.add(f.add(1, 1), 1);
            let two = f.add(1, 1);
            let num = f.sub(
                f.add(
                    f.add(f.mul(three, f.mul(x1, x1)), f.mul(f.mul(two, self.a2), x1)),
                    self.a4,
                ),
                f.mul(self.a1, y1),
            );
            let den = f.add(f.add(f.mul(two, y1), f.mul(self.a1, x1)), self.a3);
            if den == 0 {
                return Pt::Inf;
            }
            f.div(num, den)
        };
        let nu = f.sub(y1, f.mul(lambda, x1));
        let x3 = f.sub(
            f.sub(
                f.add(f.mul(lambda, lambda), f.mul(self.a1, lambda)),
                self.a2,
            ),
            f.add(x1, x2),
        );
        let y3 = f.sub(f.sub(f.neg(f.mul(f.add(lambda, self.a1), x3)), nu), self.a3);
        Pt::Aff(x3, y3)
    }

    pub fn sub(&self, p: Pt, q: Pt) -> Pt {
        self.add(p, self.neg(q))
    }

    pub fn mul(&self, p: Pt, mut k: u64) -> Pt {
        let mut r = Pt::Inf;
        let mut b = p;
        while k > 0 {
            if k & 1 == 1 {
                r = self.add(r, b);
            }
            b = self.add(b, b);
            k >>= 1;
        }
        r
    }

    /// The affine points with abscissa `x`.
    pub fn lift_x(&self, x: u64) -> Vec<Pt> {
        let f = &self.f;
        let x2 = f.mul(x, x);
        let rhs = f.add(
            f.add(f.mul(x2, x), f.mul(self.a2, x2)),
            f.add(f.mul(self.a4, x), self.a6),
        );
        // y² + B y − rhs = 0 with B = a₁x + a₃
        let bb = f.add(f.mul(self.a1, x), self.a3);
        if f.p == 2 {
            if bb == 0 {
                return vec![Pt::Aff(x, f.sqrt(rhs).expect("squaring is bijective"))];
            }
            // y = B t, t² + t = rhs / B²
            let c = f.div(rhs, f.mul(bb, bb));
            match f.artin_schreier(c) {
                Some(t) => vec![Pt::Aff(x, f.mul(bb, t)), Pt::Aff(x, f.mul(bb, t ^ 1))],
                None => vec![],
            }
        } else {
            let disc = f.add(f.mul(bb, bb), f.mul(f.add(f.add(1, 1), f.add(1, 1)), rhs));
            match f.sqrt(disc) {
                None => vec![],
                Some(s) => {
                    let inv2 = f.inv(f.add(1, 1));
                    let y1 = f.mul(f.sub(s, bb), inv2);
                    let y2 = f.mul(f.sub(f.neg(s), bb), inv2);
                    if y1 == y2 {
                        vec![Pt::Aff(x, y1)]
                    } else {
                        vec![Pt::Aff(x, y1), Pt::Aff(x, y2)]
                    }
                }
            }
        }
    }

    /// All affine points, in abscissa order.
    pub fn affine_points(&self) -> Vec<Pt> {
        (0..self.f.q).flat_map(|x| self.lift_x(x)).collect()
    }

    /// `#E(K)`.
    pub fn order(&self) -> u64 {
        self.affine_points().len() as u64 + 1
    }

    /// The non-trivial rational 2-torsion points.
    pub fn two_torsion(&self) -> Vec<Pt> {
        self.affine_points()
            .into_iter()
            .filter(|&p| self.neg(p) == p)
            .collect()
    }

    /// The `j`-invariant, or `None` for a singular curve.
    pub fn j_invariant(&self) -> Option<u64> {
        let f = &self.f;
        let (a1, a2, a3, a4, a6) = (self.a1, self.a2, self.a3, self.a4, self.a6);
        let c = |k: u64| f.pow(f.add(1, 1), 0).wrapping_mul(0) + (k % f.p); // small integer as field elt
        let int = |k: u64| -> u64 {
            let mut r = 0;
            for _ in 0..(k % f.p) {
                r = f.add(r, 1);
            }
            r
        };
        let _ = c;
        let b2 = f.add(f.mul(a1, a1), f.mul(int(4), a2));
        let b4 = f.add(f.mul(int(2), a4), f.mul(a1, a3));
        let b6 = f.add(f.mul(a3, a3), f.mul(int(4), a6));
        let b8 = f.sub(
            f.add(
                f.add(f.mul(f.mul(a1, a1), a6), f.mul(f.mul(int(4), a2), a6)),
                f.add(f.mul(f.mul(a2, a3), a3), f.neg(f.mul(f.mul(a1, a3), a4))),
            ),
            f.mul(a4, a4),
        );
        let c4 = f.sub(f.mul(b2, b2), f.mul(int(24), b4));
        let disc = f.sub(
            f.sub(
                f.add(
                    f.neg(f.mul(f.mul(b2, b2), b8)),
                    f.mul(f.mul(int(9), b2), f.mul(b4, b6)),
                ),
                f.mul(int(8), f.pow(b4, 3)),
            ),
            f.mul(int(27), f.mul(b6, b6)),
        );
        if disc == 0 {
            None
        } else {
            Some(f.div(f.pow(c4, 3), disc))
        }
    }

    /// The automorphisms of `E` fixing `O`, as far as this module's curve
    /// shapes go: `±1` always; `(x, y) ↦ (u²x, u³y)` for every `u` that
    /// preserves a short Weierstrass equation.
    pub fn automorphisms(&self) -> Vec<Auto> {
        let mut out = vec![Auto::Scale(1), Auto::Neg];
        if self.f.p != 2 && self.a1 == 0 && self.a2 == 0 && self.a3 == 0 {
            let f = &self.f;
            for u in 2..f.q {
                let u2 = f.mul(u, u);
                let u4 = f.mul(u2, u2);
                let u6 = f.mul(u4, u2);
                if u == f.neg(1) {
                    continue;
                }
                if f.mul(u4, self.a4) == self.a4 && f.mul(u6, self.a6) == self.a6 {
                    out.push(Auto::Scale(u));
                }
            }
        }
        out
    }

    pub fn apply_auto(&self, a: Auto, p: Pt) -> Pt {
        match (a, p) {
            (_, Pt::Inf) => Pt::Inf,
            (Auto::Neg, _) => self.neg(p),
            (Auto::Scale(u), Pt::Aff(x, y)) => {
                let f = &self.f;
                let u2 = f.mul(u, u);
                Pt::Aff(f.mul(u2, x), f.mul(f.mul(u2, u), y))
            }
        }
    }

    /// Smallest `d | n` with all coefficients in `F_{p^d}`, i.e. the degree
    /// of the field the curve is really defined over; `None` on a prime
    /// field, where there is no proper subfield to speak of.
    pub fn subfield_degree(&self) -> Option<u32> {
        if self.f.n == 1 {
            return None;
        }
        (1..=self.f.n)
            .filter(|d| self.f.n.is_multiple_of(*d))
            .find(|&d| {
                [self.a1, self.a2, self.a3, self.a4, self.a6]
                    .iter()
                    .all(|&a| self.f.in_subfield(a, d))
            })
    }

    /// `(x, y) ↦ (x^{p^d}, y^{p^d})`.
    pub fn frobenius(&self, p: Pt, d: u32) -> Pt {
        match p {
            Pt::Inf => Pt::Inf,
            Pt::Aff(x, y) => Pt::Aff(self.f.frob_pow(x, d), self.f.frob_pow(y, d)),
        }
    }
}

