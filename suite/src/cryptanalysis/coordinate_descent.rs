//! # Descent of quotient coordinates to `F_p`: the Klein invariants in
//! Gaudry's setting.
//!
//! §10.3 of `research/notes/index-calculus/RESEARCH_EXOTIC_COORDINATES.md` ended on "bits, not degrees":
//! the full 2-torsion group `E[2] ≅ (Z/2)²` quadruples the collapse but
//! does not halve the per-point degree twice, and whether its invariants
//! give a *cheaper system* is a question about the descended equations,
//! not about degrees in the field.  On a prime field there is no subspace
//! factor base to descend to.  Over `F_{p^k}` there is: Gaudry's base
//! `{P : x(P) ∈ F_p}`, and if the frame and the involutions are
//! `F_p`-rational then every invariant of a factor-base point is in `F_p`
//! too, so one `F_{p^k}`-equation in `F_p`-unknowns is `k` equations over
//! `F_p` — read off the digits of the coefficients — and the repo's `F_p`
//! Buchberger engine can solve it.
//!
//! ## Fixed-target quotients
//!
//! The decomposition problem fixes the target `R`.  The symmetries that
//! remain are the elements of the relation subgroup `Γ` whose last
//! component is the identity, `Γ₀ = Γ ∩ (G^m × {id})`; the seeds are
//! functions of the summands only (`u(P_i)`, `Σu`, `Πu` over the
//! summands); the invariants are the orbit-set symmetric functions under
//! `Γ₀`; and the relation is interpolated from pairs `(P_1, …, P_m)` with
//! `Σ P_i = R` for *that* `R`, with the identities among the invariants
//! quotiented out as in [`crate::cryptanalysis::coordinate_quotients`].
//! The polynomial's coefficients depend on `R`, which is fine: `R` is
//! known.
//!
//! ## What is compared
//!
//! On the same curve, same target, same base: (a) Gaudry's `x`-system,
//! `S_{m+1}` in `x_i ∈ F_p`; (b) the sign-symmetrised system in
//! `w_i = u_i²` and `s' = Π u_i` (one involution, `T`); (c) the Klein
//! system, `Γ₀` generated by all of `E[2]`.  For each: `F_p`-unknowns,
//! `F_p`-equations (`k` per field equation), degrees, monomials, and the
//! wall-clock of a reduced Gröbner basis by Buchberger.  Every invariant
//! is checked to be `F_p`-valued on the factor base before anything is
//! timed.
//!
//! ## Honest scope
//!
//! Toy `p^k ≲ 5000`, `m = 2`, and the repo's textbook Buchberger, which
//! is the right algorithm and the wrong constant; the numbers rank the
//! three systems against each other on the same engine, nothing more.

