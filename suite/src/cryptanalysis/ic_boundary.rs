/// What the shared loop returns.
pub struct PipelineOutcome {
    pub relations: PhaseCost,
    pub linear_algebra: PhaseCost,
    pub verify: PhaseCost,
    pub trials: u64,
    pub relations_found: u64,
    pub independent: u64,
    pub dependent: u64,
    pub rank: u64,
    pub recovered: Option<u64>,
    pub verified: bool,
    pub counters: OracleCounters,
}

/// **The relation matrix, as a plug point.**
///
/// The choice between a dense incremental elimination, a structured
/// Gaussian elimination and an iterative method (Wiedemann, Lanczos) is
/// one of the real levers of an index-calculus attack, and the one most
/// often left unpriced.  The relation loop takes any implementation, so
/// `ic_framework` can swap it without a second copy of the loop.
///
/// The trait lives here rather than in the framework because
/// [`IncrementalGauss`] is its canonical implementation and the loop
/// that drives it is here too.
pub trait RelationSolver {
    /// Add a relation row over `Z/rZ` with right-hand side `rhs`.
    fn add_row(&mut self, row: Vec<u64>, rhs: u64) -> RowStatus;
    /// The value of column `col`, once the matrix determines it.
    fn pinned(&self, col: usize) -> Option<u64>;
    fn rank(&self) -> usize;
    /// Rows that added nothing to the rank.
    fn dependent(&self) -> u64;
    /// The work done and what it is counted in: `row_ops` for an
    /// elimination, matrix-vector products for an iterative method.
    fn work(&self) -> (u64, &'static str);
}

impl RelationSolver for IncrementalGauss {
    fn add_row(&mut self, row: Vec<u64>, rhs: u64) -> RowStatus {
        IncrementalGauss::add_row(self, row, rhs)
    }
    fn pinned(&self, col: usize) -> Option<u64> {
        IncrementalGauss::pinned(self, col)
    }
    fn rank(&self) -> usize {
        IncrementalGauss::rank(self)
    }
    fn dependent(&self) -> u64 {
        self.dependent
    }
    fn work(&self) -> (u64, &'static str) {
        (self.row_ops, "row_ops")
    }
}

/// How the relation loop draws its targets.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum TargetSource {
    /// `R = [a]G + [b]Q` with fresh random `a, b` every trial: two
    /// scalar multiplications and one addition per target, and the guard
    /// below.
    Random,
    /// The same draw without the guard, so a target the run has already
    /// seen is decomposed again.  For the diagnostic of §10.2 only.
    RandomUnguarded,
    /// An r-adding walk `R ← R + J_{h(R)}` over 16 jumps
    /// `J_j = [a_j]G + [b_j]Q` with the coefficients tracked modulo `r`:
    /// one addition per target after the jumps are set up.  A restart
    /// adds one pooled offset and reshuffles which jump each hash value
    /// selects, so every segment has its own step function at no group
    /// cost; the guard below forces the restart.
    Walk,
    /// The walk as the Round-2 ladder first ran it: one jump table for
    /// every segment and no guard, so segments merge as rho's walks do.
    /// For the diagnostic of §10.2 only.
    WalkSharedJumps,
}

impl TargetSource {
    pub fn name(&self) -> &'static str {
        match self {
            TargetSource::Random => "random",
            TargetSource::RandomUnguarded => "random_unguarded",
            TargetSource::Walk => "walk",
            TargetSource::WalkSharedJumps => "walk_shared_jumps",
        }
    }
    pub fn is_walk(&self) -> bool {
        matches!(self, TargetSource::Walk | TargetSource::WalkSharedJumps)
    }
    /// **Whether a target the run has already decomposed is skipped.**
    ///
    /// Presenting one group element twice hands the elimination two rows
    /// with the same factor-base part and different `(a, b)`, which pins
    /// the logarithm by itself: `a₁ + b₁d = a₂ + b₂d`.  That is a generic
    /// collision resolved through the factor base, not a relation, and it
    /// arrives after about `√r` targets whatever the oracle costs — so a
    /// run that takes it is measuring rho with extra steps.  A repeat
    /// carries no relation information either (its factor-base part is
    /// one the matrix already holds), so skipping it costs the relation
    /// search nothing.  The guard is one hash insert per target, counted
    /// and priced as a lookup.
    pub fn is_guarded(&self) -> bool {
        matches!(self, TargetSource::Random | TargetSource::Walk)
    }
}

/// When the walk's restart offsets are drawn.
///
/// `Lazy` draws offset `i` the first time a restart reaches for it, so a
/// run that never restarts pays for none.  `Eager` draws all sixteen at
/// setup, which is what Rounds 3 and 4 did; it is kept as a
/// configuration rather than deleted so that the two can be run against
/// each other from one binary, on one host, in one ladder.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum RestartPool {
    Lazy,
    Eager,
}

/// Sixteen jumps `[a]G + [b]Q` with their coefficients, charged to `ops`.
fn draw_jumps<G: CountedGroup>(
    g: &G,
    generator: G::Elt,
    target: G::Elt,
    r: u64,
    rng: &mut StdRng,
    ops: &mut GroupOps,
    count: usize,
) -> Vec<(G::Elt, u64, u64)> {
    (0..count)
        .map(|_| {
            let aj = rng.gen_range(1..r);
            let bj = rng.gen_range(1..r);
            let ag = g.mul(ops, generator, aj);
            let bq = g.mul(ops, target, bj);
            (g.add(ops, ag, bq), aj, bj)
        })
        .collect()
}

/// One restart offset `[c]G + [d]Q`, charged to the run's ledger and,
/// for the report, to the pool's own ledger as well: `walk_pool_ops` is
/// then the exact number of group additions the offsets cost, which is
/// what the lazy and the eager arm differ by.
fn draw_pool_offset<G: CountedGroup>(
    g: &G,
    generator: G::Elt,
    target: G::Elt,
    r: u64,
    rng: &mut StdRng,
    ops: &mut GroupOps,
    pool_ops: &mut GroupOps,
) -> (G::Elt, u64, u64) {
    let mut local = GroupOps::default();
    let drawn = draw_jumps(g, generator, target, r, rng, &mut local, 1);
    ops.merge(local);
    pool_ops.merge(local);
    drawn[0]
}

/// A key for the column part of a row: the same for two relations with
/// the same summand columns and coefficients, whatever their target.
fn column_part_key(row: &[u64]) -> u64 {
    let mut acc = 0x9E37_79B9_7F4A_7C15u64;
    for (c, &v) in row.iter().enumerate() {
        if v != 0 {
            acc = mix(acc ^ mix((c as u64) << 32 ^ v));
        }
    }
    acc
}

/// Draw the targets (`[a]G + [b]Q` per trial, or a walk), ask the
/// oracle, turn a decomposition into a row, and stop the moment the
/// elimination pins the logarithm.
pub fn collect_and_solve<G: CountedGroup>(
    g: &G,
    generator: G::Elt,
    target: G::Elt,
    r: u64,
    h: u64,
    fb: &FactorBase<G::Elt>,
    seed: u64,
    max_trials: u64,
    targets: TargetSource,
    pool_mode: RestartPool,
    oracle: impl FnMut(&mut GroupOps, &mut OracleCounters, G::Elt) -> Option<Vec<usize>>,
) -> PipelineOutcome {
    let mut gauss = IncrementalGauss::new(fb.columns + 1, r);
    collect_and_solve_with(
        g, generator, target, r, h, fb, seed, max_trials, targets, pool_mode, &mut gauss, oracle,
    )
}

/// [`collect_and_solve`] over any [`RelationSolver`].
///
/// The relation loop, the target guard, the collision guards and the
/// verification are identical; only the matrix differs.  Sharing the
/// loop is what keeps a framework result comparable with the ledger's
/// instead of being a second implementation that drifts.
pub fn collect_and_solve_with<G: CountedGroup, L: RelationSolver + ?Sized>(
    g: &G,
    generator: G::Elt,
    target: G::Elt,
    r: u64,
    h: u64,
    fb: &FactorBase<G::Elt>,
    seed: u64,
    max_trials: u64,
    targets: TargetSource,
    pool_mode: RestartPool,
    matrix: &mut L,
    mut oracle: impl FnMut(&mut GroupOps, &mut OracleCounters, G::Elt) -> Option<Vec<usize>>,
) -> PipelineOutcome {
    let mut rng = StdRng::seed_from_u64(seed ^ 0x5245_4C41_5449_4F4E);
    let mut rel = PhaseCost::default();
    let mut la = PhaseCost::default();
    let mut ver = PhaseCost::default();
    let mut ctr = OracleCounters::default();
    let cols = fb.columns + 1;
    let d_col = fb.columns;
    let mut trials = 0u64;
    let mut found = 0u64;
    let mut recovered = None;
    let mut verified = false;
    let rel_start = Instant::now();
    let mut la_ns = 0u64;
    let h_mod = h % r;
    let mut direct_skipped = 0u64;
    let (mut single_column_rows, mut two_column_rows) = (0u64, 0u64);
    // Rows whose column part repeats an earlier row's: with different
    // coefficients `a, b` such a pair pins `d` by itself, which is what a
    // rho collision does.  Zero on an honest relation search.
    let mut column_parts: FastMap<()> = fast_map(64);
    let (mut repeated_column_rows, mut pinned_by_repeated_row) = (0u64, false);

    // The walk: jumps with known coefficients, the current point with
    // its coefficients.  The guard is shared by both target sources.
    //
    // A restart must break the segment without letting the next one
    // merge into the path this one walked.  Round 2 redrew all sixteen
    // jumps, at two scalar multiplications each — about 1,170 additions
    // on a 24-bit curve, which on the binary rungs cost more than every
    // walk step put together.  Instead, the walk jumps **once**, keeps a
    // small pool of offsets `[c]G + [d]Q` drawn with them, and restarts
    // by adding one pool offset to the current point (one addition, the
    // coefficients add) while **permuting** which jump each hash value
    // selects.  The restart then costs one group operation instead of
    // thirty-two scalar multiplications, and two segments still have
    // different step functions.
    //
    // The permutation is what makes that last clause true.  A rotation
    // would give only `jump_count` distinct index maps, so after enough
    // restarts two segments would share one and merge exactly as §10.2's
    // shared jump table let them — the guard catches the repeated target,
    // but the steps that reached it are wasted, and the waste was
    // measurable: on the Koblitz `m = 2` rungs a rotating restart roughly
    // doubled the walk steps per relation and multiplied the
    // guard-forced restarts by six.  Two *permutations* of the same
    // sixteen jumps agree on about one index in sixteen, so two segments
    // that do collide diverge again within a step or two.  Shuffling
    // sixteen indices costs no group operation at all.
    //
    // The pool is drawn **on first use**, one offset at a time (§13).
    // Rounds 3 and 4 drew all sixteen at setup, at two scalar
    // multiplications each, and 110 of the ladder's 204 walk rows then
    // restarted exactly once — that is, never took an offset at all —
    // so more than half the rows paid thirty-two scalar multiplications
    // for nothing, and on the smallest rungs that setup was most of the
    // relation phase.  Drawing lazily charges a row for exactly the
    // offsets it used.
    //
    // Two details make the lazy and the eager arm comparable rather than
    // merely similar.  The offsets come off a **stream of their own**,
    // so moving the draw cannot shift the walk's randomness; and a
    // restart takes offset `k mod 16` rather than a random one, so the
    // selection consumes no randomness either.  The two arms therefore
    // walk bit-identical trajectories and differ in exactly one thing:
    // the offsets they paid for.  `walk_pool_ops` reports that cost, so
    // the difference between the arms is checkable rather than argued.
    let jump_count = 16usize;
    let pool_count = 16usize;
    let shared_jumps = targets == TargetSource::WalkSharedJumps;
    let guarded = targets.is_guarded();
    let mut jumps: Vec<(G::Elt, u64, u64)> = Vec::new();
    let mut pool: Vec<(G::Elt, u64, u64)> = Vec::new();
    let mut pool_rng = StdRng::seed_from_u64(seed ^ 0x504F_4F4C_5F4F_4646);
    let mut pool_ops = GroupOps::default();
    let mut pool_taken = 0u64;
    let mut jump_perm: Vec<usize> = (0..jump_count).collect();
    let mut walk_point = g.identity();
    let (mut wa, mut wb) = (0u64, 0u64);
    let mut walk_fresh = true;
    let segment_cap = ((r as f64).sqrt() * 4.0) as u64 + 65_536;
    let mut segment_steps = 0u64;
    let mut seen: FastMap<()> = fast_map(if guarded { 1 << 12 } else { 0 });
    let (mut walk_steps, mut walk_restarts, mut repeats_skipped, mut guard_probes, mut walk_jumps) =
        (0u64, 0u64, 0u64, 0u64, 0u64);
    if targets.is_walk() {
        jumps = draw_jumps(
            g,
            generator,
            target,
            r,
            &mut rng,
            &mut rel.group_ops,
            jump_count,
        );
        walk_jumps += jump_count as u64;
        if !shared_jumps && pool_mode == RestartPool::Eager {
            for _ in 0..pool_count {
                let off = draw_pool_offset(
                    g,
                    generator,
                    target,
                    r,
                    &mut pool_rng,
                    &mut rel.group_ops,
                    &mut pool_ops,
                );
                pool.push(off);
            }
        }
    }

    while trials < max_trials {
        let (point, a, b) = match targets {
            TargetSource::Random | TargetSource::RandomUnguarded => {
                let a = rng.gen_range(1..r);
                let b = rng.gen_range(1..r);
                let ag = g.mul(&mut rel.group_ops, generator, a);
                let bq = g.mul(&mut rel.group_ops, target, b);
                let point = g.add(&mut rel.group_ops, ag, bq);
                if g.is_identity(&point) {
                    direct_skipped += 1;
                    continue;
                }
                (point, a, b)
            }
            TargetSource::Walk | TargetSource::WalkSharedJumps => {
                if walk_fresh || segment_steps >= segment_cap {
                    if walk_restarts == 0 || shared_jumps {
                        // The first segment, and every segment of the
                        // unguarded diagnostic, starts from a fresh
                        // `[a]G + [b]Q`.
                        wa = rng.gen_range(1..r);
                        wb = rng.gen_range(1..r);
                        let ag = g.mul(&mut rel.group_ops, generator, wa);
                        let bq = g.mul(&mut rel.group_ops, target, wb);
                        walk_point = g.add(&mut rel.group_ops, ag, bq);
                    } else {
                        // Offset `k mod 16` for the k-th restart, drawn
                        // here if this is the first restart to reach it.
                        let idx = (pool_taken as usize) % pool_count;
                        pool_taken += 1;
                        if idx == pool.len() {
                            let off = draw_pool_offset(
                                g,
                                generator,
                                target,
                                r,
                                &mut pool_rng,
                                &mut rel.group_ops,
                                &mut pool_ops,
                            );
                            pool.push(off);
                        }
                        let (op, oa, ob) = pool[idx];
                        walk_point = g.add(&mut rel.group_ops, walk_point, op);
                        wa = addmod(wa, oa, r);
                        wb = addmod(wb, ob, r);
                        // A fresh index map for the segment: Fisher–Yates
                        // over the sixteen jumps, no group operation.
                        for i in (1..jump_count).rev() {
                            jump_perm.swap(i, rng.gen_range(0..i + 1));
                        }
                    }
                    walk_fresh = false;
                    walk_restarts += 1;
                    segment_steps = 0;
                } else {
                    let hsh = mix(g.key(&walk_point));
                    let j = jump_perm[((hsh >> 24) as usize) % jump_count];
                    let (jp, aj, bj) = jumps[j];
                    walk_point = g.add(&mut rel.group_ops, walk_point, jp);
                    wa = addmod(wa, aj, r);
                    wb = addmod(wb, bj, r);
                    walk_steps += 1;
                    segment_steps += 1;
                }
                if g.is_identity(&walk_point) {
                    walk_fresh = true;
                    direct_skipped += 1;
                    continue;
                }
                (walk_point, wa, wb)
            }
        };
        trials += 1;
        // The guard: a target this run has already decomposed carries no
        // relation the matrix does not hold, and taking it again would
        // pin the logarithm by collision rather than by relation.
        if guarded {
            guard_probes += 1;
            if seen.insert(g.key(&point), ()).is_some() {
                repeats_skipped += 1;
                walk_fresh = true;
                continue;
            }
        }
        let Some(summands) = oracle(&mut rel.group_ops, &mut ctr, point) else {
            continue;
        };
        found += 1;
        let la_start = Instant::now();
        let mut row = vec![0u64; cols];
        for &i in &summands {
            let c = fb.col_of[i];
            row[c] = addmod(row[c], fb.coef_of[i], r);
        }
        // How many columns the row touches: with orbit columns a sum of
        // two points of one signed orbit is a single-column row, and two
        // of those on one column pin the logarithm by themselves.
        let support = row[..d_col].iter().filter(|&&c| c != 0).count();
        match support {
            1 => single_column_rows += 1,
            2 => two_column_rows += 1,
            _ => {}
        }
        let repeated = column_parts
            .insert(column_part_key(&row[..d_col]), ())
            .is_some();
        if repeated {
            repeated_column_rows += 1;
        }
        // h·a + h·b·d = Σ coef·x  ⇒  Σ coef·x − h·b·d = h·a
        row[d_col] = submod(0, mulmod(h_mod, b, r), r);
        let rhs = mulmod(h_mod, a, r);
        match matrix.add_row(row, rhs) {
            RowStatus::Inconsistent => {
                la_ns += la_start.elapsed().as_nanos() as u64;
                la.count("inconsistent", 1);
                break;
            }
            RowStatus::Dependent => {}
            RowStatus::Independent => {}
        }
        if let Some(d) = matrix.pinned(d_col) {
            pinned_by_repeated_row = repeated;
            la_ns += la_start.elapsed().as_nanos() as u64;
            let v_start = Instant::now();
            let check = g.mul(&mut ver.group_ops, generator, d);
            ver.wall_ns = v_start.elapsed().as_nanos() as u64;
            if check == target {
                recovered = Some(d);
                verified = true;
                break;
            }
            ver.count("verification_failures", 1);
            break;
        }
        la_ns += la_start.elapsed().as_nanos() as u64;
    }
    rel.wall_ns = rel_start.elapsed().as_nanos() as u64 - la_ns - ver.wall_ns;
    rel.count("trials", trials);
    rel.count("relations", found);
    rel.count("lookups", ctr.lookups);
    rel.count("sqrt_solves", ctr.sqrt_solves);
    rel.count("inversions", ctr.inversions);
    rel.count("s4_pairs", ctr.s4_pairs);
    rel.count("s4_hits", ctr.s4_hits);
    rel.count("lift_failures", ctr.lift_failures);
    rel.count("unliftable_systems", ctr.unliftable_systems);
    rel.count("canonicalisations", ctr.canonicalisations);
    rel.count("frobfold_mismatches", ctr.frobfold_mismatches);
    rel.count("direct_relations_skipped", direct_skipped);
    rel.count("repeated_targets_skipped", repeats_skipped);
    rel.count("target_guard_probes", guard_probes);
    if targets.is_walk() {
        rel.count("walk_jumps", walk_jumps + pool.len() as u64);
        rel.count("walk_pool_offsets", pool.len() as u64);
        rel.count("walk_pool_ops", pool_ops.adds + pool_ops.doubles);
        rel.count("walk_pool_restarts", pool_taken);
        rel.count("walk_steps", walk_steps);
        rel.count("walk_restarts", walk_restarts);
    }
    la.wall_ns = la_ns;
    let (work, work_unit) = matrix.work();
    la.count(work_unit, work);
    la.count("rows", found);
    la.count("single_column_rows", single_column_rows);
    la.count("two_column_rows", two_column_rows);
    la.count("repeated_column_rows", repeated_column_rows);
    la.count("pinned_by_repeated_row", u64::from(pinned_by_repeated_row));
    la.count("columns", cols as u64);
    la.count("rank", matrix.rank() as u64);
    PipelineOutcome {
        relations: rel,
        linear_algebra: la,
        verify: ver,
        trials,
        relations_found: found,
        independent: matrix.rank() as u64,
        dependent: matrix.dependent(),
        rank: matrix.rank() as u64,
        recovered,
        verified,
        counters: ctr,
    }
}

// ── Calibration ────────────────────────────────────────────────────

/// Measure this host's nanoseconds per group addition and doubling on
/// the instance's own points.
///
/// Public because `ic_framework` calibrates the same way the ledger
/// does; the pinned ratios of §12 then convert every other counter, so
/// only `ns_per_add` is ever host-dependent and it cancels.
pub fn calibrate_group<G: CountedGroup>(g: &G, points: &[G::Elt], calib: &mut Calibration) {
    let mut ops = GroupOps::default();
    let n = points.len();
    let samples = 200_000u64;
    let mut acc = points[0];
    let start = Instant::now();
    for i in 0..samples {
        acc = g.add(&mut ops, acc, points[(i as usize * 7 + 1) % n]);
        if g.is_identity(&acc) {
            acc = points[(i as usize + 3) % n];
        }
    }
    calib.ns_per_add = start.elapsed().as_nanos() as f64 / samples as f64;
    std::hint::black_box(acc);
    let mut acc = points[1];
    let start = Instant::now();
    for i in 0..samples {
        acc = g.double(&mut ops, acc);
        if g.is_identity(&acc) {
            acc = points[(i as usize + 5) % n];
        }
    }
    calib.ns_per_double = start.elapsed().as_nanos() as f64 / samples as f64;
    std::hint::black_box(acc);
}

/// Measure this host's nanoseconds per relation-matrix multiply-subtract.
pub fn calibrate_row_ops(modulus: u64, calib: &mut Calibration) {
    let mut rng = StdRng::seed_from_u64(11);
    let cols = 2048usize;
    let pivot: Vec<u64> = (0..cols).map(|_| rng.gen_range(0..modulus)).collect();
    let mut row: Vec<u64> = (0..cols).map(|_| rng.gen_range(0..modulus)).collect();
    let reps = 500u64;
    let start = Instant::now();
    for k in 0..reps {
        let f = (k + 3) % modulus;
        for j in 0..cols {
            row[j] = submod(row[j], mulmod(f, pivot[j], modulus), modulus);
        }
    }
    calib.ns_per_row_op = start.elapsed().as_nanos() as f64 / (reps * cols as u64) as f64;
    std::hint::black_box(&row);
}

/// A 64-bit word XOR of one row into another, the unit of the Boolean
/// Macaulay elimination.
pub fn calibrate_word_xor() -> f64 {
    let words = 4096usize;
    let mut a: Vec<u64> = (0..words as u64).map(mix).collect();
    let b: Vec<u64> = (0..words as u64).map(|i| mix(i + 77)).collect();
    let reps = 2000u64;
    let start = Instant::now();
    for k in 0..reps {
        let shift = (k % 7) as usize;
        for j in 0..words {
            a[j] ^= b[(j + shift) % words];
        }
    }
    let ns = start.elapsed().as_nanos() as f64 / (reps * words as u64) as f64;
    std::hint::black_box(&a);
    ns
}

// ── Pricing a run ──────────────────────────────────────────────────

/// Convert a phase's native counters into group-addition equivalents.
///
/// Public because `ic_framework` prices its phases with it: a second
/// conversion table would be free to drift from this one, which is the
/// defect §12 of the ledger note removed at the level of the factors
/// themselves.
pub fn price_phase(phase: &mut PhaseCost, calib: &Calibration) {
    let mut gae = phase.group_ops.gae();
    let conv = |name: &str, ns: Option<f64>| -> f64 {
        match ns {
            Some(ns) => calib.gae(phase.get(name), ns),
            None => 0.0,
        }
    };
    gae += conv("sqrt_solves", calib.ns_per_sqrt);
    gae += conv("as_solves", calib.ns_per_as_solve);
    gae += conv("s4_pairs", calib.ns_per_s4_pair);
    gae += conv("lookups", Some(calib.ns_per_lookup));
    gae += conv("row_ops", Some(calib.ns_per_row_op));
    gae += conv("legendre_symbols", calib.ns_per_legendre);
    gae += conv("inversions", calib.ns_per_inversion);
    gae += conv("frobenius_maps", calib.ns_per_frobenius);
    gae += conv("canonicalisations", calib.ns_per_canon);
    gae += conv("target_guard_probes", Some(calib.ns_per_lookup));
    phase.gae = gae;
}

/// The exact ceiling for one base and summand count, computed once and
/// handed to every variant on that base: `(classes, ceiling)`, or
/// `None` when the classes could not be enumerated.
pub type ExactCeiling = Option<(u64, f64)>;

fn assemble_variant(
    name: &str,
    oracle_name: String,
    summands: u32,
    targets: TargetSource,
    fb_cost: &PhaseCost,
    signed_points: u64,
    abscissae: u64,
    columns: u64,
    dimension: Option<u32>,
    table: Option<TableCost>,
    exact: ExactCeiling,
    outcome: PipelineOutcome,
    r: u64,
    space: f64,
    calib: &Calibration,
    rho_s: f64,
    floor_s: f64,
    table_fold: f64,
) -> VariantResult {
    let mut fb_phase = fb_cost.clone();
    let table_kind = match &table {
        Some(t) => t.kind,
        None => "none",
    };
    if let Some(t) = table {
        fb_phase.group_ops.merge(t.group_ops);
        fb_phase.wall_ns += t.wall_ns;
        fb_phase.count("pair_table_entries", t.entries);
        for (name, by) in t.native {
            fb_phase.count(name, by);
        }
    }
    price_phase(&mut fb_phase, calib);
    let mut rel = outcome.relations;
    price_phase(&mut rel, calib);
    let mut la = outcome.linear_algebra;
    price_phase(&mut la, calib);
    let mut ver = outcome.verify;
    price_phase(&mut ver, calib);
    let total_gae = fb_phase.gae + rel.gae + la.gae + ver.gae;
    let total_wall = fb_phase.wall_ns + rel.wall_ns + la.wall_ns + ver.wall_ns;
    let sqrt_r = (r as f64).sqrt();
    let s = total_gae / sqrt_r;
    let s_wall = if calib.ns_per_add > 0.0 {
        total_wall as f64 / calib.ns_per_add / sqrt_r
    } else {
        f64::NAN
    };
    let tf = trials_floor(columns, signed_points, summands, space);
    let p_ceiling = decomposition_probability_ceiling(signed_points, summands, space);
    let measured_yield = outcome.relations_found as f64 / outcome.trials.max(1) as f64;
    let (classes, p_exact) = exact.unwrap_or((0, p_ceiling));
    let tf_exact = (columns as f64 + 1.0) / p_exact;
    // The column fold is the base's own: `K = F/2k`.
    let column_fold = (signed_points as f64 / (2.0 * columns.max(1) as f64)).max(1.0);
    let fam = family_optimum_s(space, r as f64, table_fold, column_fold);
    let fam_base = family_optimum_base(space, table_fold, column_fold);
    VariantResult {
        name: name.to_string(),
        oracle: oracle_name,
        summands,
        table: table_kind.to_string(),
        targets: targets.name().to_string(),
        factor_base: fb_phase,
        signed_points,
        abscissae,
        columns,
        dimension,
        relations: rel,
        linear_algebra: la,
        verify: ver,
        trials: outcome.trials,
        relations_found: outcome.relations_found,
        independent: outcome.independent,
        dependent: outcome.dependent,
        rank: outcome.rank,
        trials_floor: tf,
        trials_over_floor: outcome.trials as f64 / tf,
        decomposition_probability_ceiling: p_ceiling,
        yield_over_ceiling: measured_yield / p_ceiling,
        cofactor_classes: classes,
        decomposition_probability_ceiling_exact: p_exact,
        yield_over_ceiling_exact: measured_yield / p_exact,
        trials_floor_exact: tf_exact,
        trials_over_floor_exact: outcome.trials as f64 / tf_exact,
        family_optimum_s: fam,
        family_optimum_base: fam_base,
        signed_points_over_family_optimum: signed_points as f64 / fam_base,
        ratio_to_family_optimum: s / fam,
        total_gae,
        total_wall_ns: total_wall,
        s,
        s_wall,
        ratio_to_rho: s / rho_s,
        ratio_to_floor: s / floor_s,
        recovered: outcome.recovered,
        verified: outcome.verified,
    }
}

// ── Configuration ──────────────────────────────────────────────────

/// What to run.
#[derive(Clone, Debug, Serialize)]
pub struct BoundaryConfig {
    pub seed: u64,
    /// Repeats per instance (fresh target each; rho and every variant
    /// see the same target within a repeat).
    pub repeats: usize,
    /// Rho walks per repeat on that target (different walk seeds).  The
    /// reference is cheap and its single-run spread is about half its
    /// mean, so it gets more samples than the variants.
    pub rho_repeats: usize,
    pub prime_bits: Vec<u32>,
    pub char2_degrees: Vec<u32>,
    pub koblitz_degrees: Vec<u32>,
    /// Cap on targets drawn per variant run.
    pub max_trials: u64,
    /// A run also stops after this multiple of the counting floor's
    /// trial count (never fewer than 4096 trials), so a base that cannot
    /// yield relations fails in bounded time instead of at the cap.
    pub trial_floor_multiple: f64,
    /// Largest Koblitz degree at which the un-folded control (one column
    /// per abscissa) is run; it needs `2n` times the relations.
    pub koblitz_no_fold_max_degree: u32,
    /// Largest degree at which the `S₄` pairs-and-solve oracle is run.
    pub s4_max_degree: u32,
    /// Largest base the pair table may hold (signed points).
    pub max_table_points: usize,
    /// Rho step cap as a multiple of the expected count.
    pub rho_cap_multiple: f64,
    /// Largest Frobenius-folded table (entries) the balanced Koblitz base
    /// may need; the base is sized to `1.2·(4#E)^{1/3}` signed points
    /// within it, and run only where that is at least half again the
    /// first-round base.
    pub max_folded_table_pairs: u64,
    /// Run a two-summand row on a binary base when it is admissible and
    /// its exact trials floor is at most `max_trials` over this divisor.
    pub m2_floor_divisor: u64,
    /// Run every row without the repeat guard, and the walk rows with one
    /// jump table for every segment: the targets as the ladder drew them
    /// before §10.2 of the note, for the diagnostic that measures what
    /// that cost.  The default guards both sources.
    pub unguarded_targets: bool,
    /// Draw all sixteen restart offsets at setup, as Rounds 3 and 4 did,
    /// instead of drawing each the first time a restart reaches for it.
    /// This is the baseline arm of §13's comparison; the default is
    /// lazy.  Nothing else about the walk changes with it, which is what
    /// makes the two arms comparable row by row.
    pub eager_restart_pool: bool,
}

