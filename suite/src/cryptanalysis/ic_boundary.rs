    /// A cyclic group `Z/N` as a counted group, for the class-counting
    /// test: the "curve" is the integers modulo `N`, the key the residue.
    struct Cyclic(u64);

    impl CountedGroup for Cyclic {
        type Elt = u64;
        fn identity(&self) -> u64 {
            0
        }
        fn is_identity(&self, p: &u64) -> bool {
            *p == 0
        }
        fn add(&self, ops: &mut GroupOps, p: u64, q: u64) -> u64 {
            ops.adds += 1;
            (p + q) % self.0
        }
        fn double(&self, ops: &mut GroupOps, p: u64) -> u64 {
            ops.doubles += 1;
            (2 * p) % self.0
        }
        fn neg(&self, p: u64) -> u64 {
            (self.0 - p) % self.0
        }
        fn key(&self, p: &u64) -> u64 {
            *p
        }
    }

    #[test]
    fn exact_ceiling_counts_the_multisets_whose_classes_cancel() {
        // Z/2018 = Z/2 × Z/1009: r = 1009, h = 2.  Even residues have
        // class 0 (they are the subgroup), odd residues class 1009.
        let g = Cyclic(2018);
        let r = 1009u64;
        let rf = r as f64;
        let evens: Vec<u64> = (1..=6).map(|k| 2 * k).collect();
        let odds: Vec<u64> = (0..5).map(|k| 2 * k + 1).collect();
        let c = |n: f64, k: u32| binomial_f64(n, k);
        // All in the subgroup: every multiset cancels, and the uniform
        // bound C(F+m−1, m)/#E is loose by the index 2.
        let (classes, p2) = exact_decomposition_ceiling(&g, &evens, r, 2).unwrap();
        assert_eq!(classes, 1);
        assert!((p2 - c(7.0, 2) / rf).abs() < 1e-12);
        assert!((p2 / decomposition_probability_ceiling(6, 2, 2.0 * rf) - 2.0).abs() < 1e-9);
        let (_, p3) = exact_decomposition_ceiling(&g, &evens, r, 3).unwrap();
        assert!((p3 - c(8.0, 3) / rf).abs() < 1e-12);
        // All odd: two odds cancel, three never do.
        let (classes, p2) = exact_decomposition_ceiling(&g, &odds, r, 2).unwrap();
        assert_eq!(classes, 1);
        assert!((p2 - c(6.0, 2) / rf).abs() < 1e-12);
        let (_, p3) = exact_decomposition_ceiling(&g, &odds, r, 3).unwrap();
        assert_eq!(p3, 0.0);
        // Mixed: pairs within a class; triples of three evens or one
        // even with two odds.
        let mut mixed = evens.clone();
        mixed.extend(&odds);
        let (classes, p2) = exact_decomposition_ceiling(&g, &mixed, r, 2).unwrap();
        assert_eq!(classes, 2);
        assert!((p2 - (c(7.0, 2) + c(6.0, 2)) / rf).abs() < 1e-12);
        let (_, p3) = exact_decomposition_ceiling(&g, &mixed, r, 3).unwrap();
        assert!((p3 - (c(8.0, 3) + 6.0 * c(6.0, 2)) / rf).abs() < 1e-12);
        // Spread evenly over the classes, exact and uniform agree to
        // within the multiset boundary terms.
        let uniform = decomposition_probability_ceiling(11, 2, 2.0 * rf);
        assert!(
            p2 / uniform > 0.9 && p2 / uniform < 1.2,
            "{p2} vs {uniform}"
        );
        // The ceiling is a probability: capped at one.
        let (_, capped) = exact_decomposition_ceiling(&Cyclic(202), &mixed, 101, 3).unwrap();
        assert_eq!(capped, 1.0, "146 multisets over r = 101");
        assert!(exact_decomposition_ceiling(&g, &mixed, r, 4).is_none());
    }

    #[test]
    fn negation_folded_table_finds_every_pair_sum_the_full_table_finds() {
        let inst = roster_prime_instance(14).unwrap();
        let curve = &inst.curve;
        let fb = prime_factor_base(&inst, 24);
        let full = PairTable::build(curve, &fb);
        let neg = PairTable::build_negation_folded(curve, &fb);
        assert_eq!(full.entries, neg.entries, "the key set is the same");
        assert!(neg.build_ops.adds * 2 <= full.build_ops.adds + 2 * fb.abscissae as u64);
        let mut ops = GroupOps::default();
        let n = fb.points.len();
        for i in 0..n {
            for j in i..n {
                let s = curve.add(&mut ops, fb.points[i], fb.points[j]);
                if s.infinity {
                    continue;
                }
                for table in [&full, &neg] {
                    let mut lookups = 0;
                    let (a, b) = table
                        .probe(curve, &fb, &mut ops, &mut lookups, s)
                        .expect("a stored sum");
                    assert_eq!(curve.add(&mut ops, fb.points[a], fb.points[b]), s);
                }
            }
        }
        // Random subgroup points: both tables agree on what decomposes.
        let g = inst.generator_point();
        let mut rng = StdRng::seed_from_u64(3);
        let mut ctr = OracleCounters::default();
        for _ in 0..2000 {
            let q = curve.mul(&mut ops, g, rng.gen_range(1..inst.r));
            let a = decompose_mitm(curve, &fb, &full, 2, &mut ops, &mut ctr, q);
            let b = decompose_mitm(curve, &fb, &neg, 2, &mut ops, &mut ctr, q);
            assert_eq!(a.is_some(), b.is_some());
            if let Some(w) = b {
                let s = curve.add(&mut ops, fb.points[w[0]], fb.points[w[1]]);
                assert_eq!(s, q);
            }
        }
    }

    #[test]
    fn frobenius_folded_table_agrees_with_the_full_table_on_every_probe() {
        let inst = koblitz_instance_best(17).expect("K_a / 2^17");
        let (frob, desc) = choose_koblitz_base(&inst, 1, 6000).expect("base");
        let folded =
            koblitz_factor_base(&inst, &frob, ColumnFold::SignedFrobeniusOrbit, desc).unwrap();
        let g = BinaryGroup(&inst.fast);
        let full = PairTable::build(&g, &folded);
        let table =
            FrobeniusPairTable::build(&inst, &folded).expect("a normal basis and a closed base");
        let f = folded.points.len() as u64;
        let n = inst.n as u64;
        assert!(
            table.entries * 2 * n <= full.entries * 3,
            "{} entries against {} full: the fold is 2n",
            table.entries,
            full.entries
        );
        // One representative per column against every point of a later
        // or equal column: at most K·|F| additions, against |F|²/2.
        assert!(table.build_ops.adds <= folded.columns as u64 * f);
        assert!(
            table.build_ops.adds * 4 <= full.build_ops.adds,
            "{} adds against {} full",
            table.build_ops.adds,
            full.build_ops.adds
        );
        let mut ops = GroupOps::default();
        let mut ctr = OracleCounters::default();
        // Every pair sum is found, and the pair returned sums to it.
        for i in 0..folded.points.len() {
            for j in i..folded.points.len() {
                let s = g.add(&mut ops, folded.points[i], folded.points[j]);
                if s.infinity {
                    continue;
                }
                let (a, b) = table
                    .probe(&g, &folded, &mut ops, &mut ctr, s)
                    .expect("every pair sum has an image in the table");
                assert_eq!(g.add(&mut ops, folded.points[a], folded.points[b]), s);
            }
        }
        assert_eq!(ctr.frobfold_mismatches, 0);
        // Random subgroup points: the two oracles agree at m = 2 and m = 3.
        let mut rng = StdRng::seed_from_u64(5);
        for m in [2u32, 3] {
            let (mut hits, mut checked) = (0, 0);
            for _ in 0..(if m == 2 { 2000 } else { 40 }) {
                let q = g.mul(&mut ops, inst.generator, rng.gen_range(1..inst.r));
                let a = decompose_mitm(&g, &folded, &full, m, &mut ops, &mut ctr, q);
                let b = decompose_mitm_frobenius(&g, &folded, &table, m, &mut ops, &mut ctr, q);
                assert_eq!(a.is_some(), b.is_some(), "m = {m}: full {a:?} folded {b:?}");
                if let Some(w) = b {
                    let mut s = g.identity();
                    for &k in &w {
                        s = g.add(&mut ops, s, folded.points[k]);
                    }
                    assert_eq!(s, q);
                    hits += 1;
                }
                checked += 1;
            }
            assert!(checked > 0);
            std::hint::black_box(hits);
        }
        assert_eq!(ctr.frobfold_mismatches, 0);
        assert!(table.calibrate_canon(10_000) > 0.0);
    }

