impl BoundaryConfig {
    /// The target source of the walk rows.
    pub fn walk_source(&self) -> TargetSource {
        if self.unguarded_targets {
            TargetSource::WalkSharedJumps
        } else {
            TargetSource::Walk
        }
    }

    /// When the walk rows draw their restart offsets.
    pub fn restart_pool(&self) -> RestartPool {
        if self.eager_restart_pool {
            RestartPool::Eager
        } else {
            RestartPool::Lazy
        }
    }

    /// The target source of the rows that draw `[a]G + [b]Q` per trial.
    pub fn random_source(&self) -> TargetSource {
        if self.unguarded_targets {
            TargetSource::RandomUnguarded
        } else {
            TargetSource::Random
        }
    }

    /// A configuration small enough for a unit test.
    pub fn quick() -> Self {
        Self {
            repeats: 1,
            rho_repeats: 2,
            prime_bits: vec![10, 12],
            char2_degrees: vec![12],
            koblitz_degrees: vec![11, 15],
            koblitz_no_fold_max_degree: 15,
            s4_max_degree: 15,
            ..Self::default()
        }
    }
}

impl TableCost {
    /// Group-addition equivalents of the build alone, for comparing
    /// tables on one base.
    pub fn gae(&self, calib: &Calibration) -> f64 {
        let mut phase = PhaseCost {
            group_ops: self.group_ops,
            ..PhaseCost::default()
        };
        for (name, by) in &self.native {
            phase.count(name, *by);
        }
        price_phase(&mut phase, calib);
        phase.gae
    }
}

/// The step cap a ladder rho run gets: `multiple` times the `A = 1` floor,
/// plus a margin for the tiny groups.
pub fn rho_cap(r: u64, multiple: f64) -> u64 {
    (generic_floor_ops(r as f64, 1.0) * multiple) as u64 + 4096
}

/// Trials a variant may draw: the configured multiple of the counting
/// floor, at least 4096, at most the absolute cap.
fn trial_budget<E>(cfg: &BoundaryConfig, fb: &FactorBase<E>, m: u32, space: f64) -> u64 {
    let floor = trials_floor(fb.columns as u64, fb.points.len() as u64, m, space);
    ((cfg.trial_floor_multiple * floor).ceil() as u64).clamp(4096, cfg.max_trials.max(4096))
}

// ── The prime regime ───────────────────────────────────────────────

/// Run every prime-field variant on one instance.
pub fn run_prime_instance(inst: &PrimeInstance, cfg: &BoundaryConfig) -> RegimeInstance {
    let curve = &inst.curve;
    let r = inst.r;
    let g = inst.generator_point();
    let mut calib = Calibration::default();
    let mut rng = StdRng::seed_from_u64(cfg.seed ^ r);

    // Calibration on random points of the subgroup.
    let mut ops = GroupOps::default();
    let pts: Vec<PrimePoint> = (0..64)
        .map(|_| curve.mul(&mut ops, g, rng.gen_range(1..r)))
        .collect();
    calibrate_group(curve, &pts, &mut calib);
    calibrate_row_ops(r, &mut calib);
    {
        let mut residues = Vec::new();
        while residues.len() < 2048 {
            let v = rng.gen_range(1..curve.p);
            if curve.legendre(v) == 1 {
                residues.push(v);
            }
        }
        let start = Instant::now();
        let mut acc = 0u64;
        for _ in 0..8 {
            for &v in &residues {
                acc ^= curve.sqrt(v).unwrap_or(0);
            }
        }
        calib.ns_per_sqrt = Some(start.elapsed().as_nanos() as f64 / (8 * residues.len()) as f64);
        std::hint::black_box(acc);
        let values: Vec<u64> = (0..2048).map(|_| rng.gen_range(1..curve.p)).collect();
        let start = Instant::now();
        let mut acc = 0i32;
        for _ in 0..8 {
            for &v in &values {
                acc += curve.legendre(v);
            }
        }
        calib.ns_per_legendre = Some(start.elapsed().as_nanos() as f64 / (8 * values.len()) as f64);
        std::hint::black_box(acc);
        let start = Instant::now();
        let mut acc = 0u64;
        for _ in 0..8 {
            for &v in &values {
                acc ^= invmod(v, curve.p).unwrap_or(0);
            }
        }
        calib.ns_per_inversion =
            Some(start.elapsed().as_nanos() as f64 / (8 * values.len()) as f64);
        std::hint::black_box(acc);
    }
    calib.ns_per_word_xor = Some(calibrate_word_xor());

    let bits = 64 - r.leading_zeros();
    let fb_size = 1usize << bits.div_ceil(3);
    let fb = prime_factor_base(inst, fb_size);
    let table = PairTable::build(curve, &fb);
    let table_neg = PairTable::build_negation_folded(curve, &fb);
    calib.ns_per_lookup = table.calibrate_lookup(1_000_000);
    let exact_m2 = exact_decomposition_ceiling(curve, &fb.points, r, 2);
    let exact_m3 = exact_decomposition_ceiling(curve, &fb.points, r, 3);
    // Round 3: the base the family's shape law asks for, `#E^{1/3}`
    // signed points, against the `2^{⌈bits/3⌉}` abscissae of the rule
    // above.  Its own rows, its own table; `None` when the two agree to
    // within a tenth so the ladder does not carry a duplicate.
    let balanced_abscissae = (family_optimum_base(inst.group_order as f64, 1.0, 1.0) / 2.0)
        .round()
        .max(4.0) as usize;
    let balanced = (balanced_abscissae as f64 / fb.abscissae.max(1) as f64)
        .max(fb.abscissae.max(1) as f64 / balanced_abscissae as f64)
        > 1.1;
    let fb_bal = balanced.then(|| prime_factor_base(inst, balanced_abscissae));
    let table_bal = fb_bal
        .as_ref()
        .map(|f| PairTable::build_negation_folded(curve, f));
    let exact_bal_m2 = fb_bal
        .as_ref()
        .and_then(|f| exact_decomposition_ceiling(curve, &f.points, r, 2));

    let floor_s = generic_floor_s(2.0);
    // The unit's conversion ratios come from the repository, not from
    // what this host happened to measure a moment ago; see
    // `PINNED_CALIBRATION`.  `priced` is what every phase below is
    // converted with, `calib` stays as the host note — which is why the
    // rebinding to `priced` happens *after* the instance is built, below:
    // shadowing it here made `calibration_measured` a second copy of the
    // pinned table, so every prime row claimed the host had measured
    // exactly what the repository pinned.
    let mut priced = calib.clone();
    let pinned = priced.pin("prime", inst.name.as_str());
    let mut out = RegimeInstance {
        regime: "prime".into(),
        curve: serde_json::json!({
            "name": inst.name, "p": curve.p, "a": curve.a, "b": curve.b,
            "group_order": inst.group_order, "subgroup_order": r, "cofactor": inst.cofactor,
            "generator": {"x": inst.generator.0, "y": inst.generator.1},
        }),
        r,
        log2_r: (r as f64).log2(),
        group_order: inst.group_order as f64,
        cofactor: inst.cofactor,
        automorphisms_generic: 2,
        floor_s,
        floor_ops: generic_floor_ops(r as f64, 2.0),
        calibration: priced.clone(),
        calibration_measured: calib.clone(),
        calibration_pinned: pinned.clone(),
        rho: Vec::new(),
        rho_s_mean: 0.0,
        rho_verified_all: true,
        variants: Vec::new(),
        seeds: Vec::new(),
        targets: Vec::new(),
    };
    let calib = &priced;
    out.curve["factor_base"] = serde_json::json!({
        "description": fb.description,
        "signed_points": fb.points.len(),
        "abscissae": fb.abscissae,
        "columns": fb.columns,
        "full_table_entries": table.entries,
        "negation_folded_table_entries": table_neg.entries,
        "cofactor_classes": exact_m2.map(|e| e.0),
        "ceiling_uniform_m2": decomposition_probability_ceiling(fb.points.len() as u64, 2, inst.group_order as f64),
        "ceiling_exact_m2": exact_m2.map(|e| e.1),
        "ceiling_uniform_m3": decomposition_probability_ceiling(fb.points.len() as u64, 3, inst.group_order as f64),
        "ceiling_exact_m3": exact_m3.map(|e| e.1),
        "family_optimum_base_signed_points": family_optimum_base(inst.group_order as f64, 1.0, 1.0),
        "family_optimum_s": family_optimum_s(inst.group_order as f64, r as f64, 1.0, 1.0),
    });
    if let (Some(f), Some(t)) = (&fb_bal, &table_bal) {
        out.curve["factor_base_balanced"] = serde_json::json!({
            "description": f.description,
            "signed_points": f.points.len(),
            "abscissae": f.abscissae,
            "columns": f.columns,
            "negation_folded_table_entries": t.entries,
            "ceiling_exact_m2": exact_bal_m2.map(|e| e.1),
        });
    }

    let space = inst.group_order as f64;
    for rep in 0..cfg.repeats {
        let seed = cfg.seed.wrapping_add(rep as u64 * 0x9E37);
        let d = rng.gen_range(1..r);
        let target = curve.mul(&mut ops, g, d);
        out.seeds.push(seed);
        out.targets.push(d);
        let mut rho_s = 0.0;
        for k in 0..cfg.rho_repeats.max(1) {
            // The matched reference (negation, `A = 2`), then the plain
            // walk every row was priced against through §17, kept as the
            // before mark.
            let rho_seed = seed ^ (k as u64 * 0x5EED);
            let matched = rho_reference_negation(
                curve,
                g,
                target,
                r,
                rho_seed,
                rho_cap(r, cfg.rho_cap_multiple),
            );
            out.rho_verified_all &= matched.verified && matched.recovered == Some(d);
            rho_s += matched.s / cfg.rho_repeats.max(1) as f64;
            out.rho.push(matched);
            let plain = rho_reference(
                curve,
                g,
                target,
                r,
                rho_seed,
                rho_cap(r, cfg.rho_cap_multiple),
            );
            out.rho_verified_all &= plain.verified && plain.recovered == Some(d);
            out.rho.push(plain);
        }

        let random = cfg.random_source();
        let walk = cfg.walk_source();
        let variants: Vec<(&str, Oracle, TargetSource)> = vec![
            ("semaev_s3_roots_m2", Oracle::SemaevS3Roots, random),
            ("direct_subtraction_m2", Oracle::Subtract, random),
            (
                "mitm_m2",
                Oracle::Mitm {
                    table: &table,
                    m: 2,
                },
                random,
            ),
            (
                "mitm_m3",
                Oracle::Mitm {
                    table: &table,
                    m: 3,
                },
                random,
            ),
            // Round 2: the negation-folded table, then walk targets on it.
            (
                "mitm_m2_negfold",
                Oracle::Mitm {
                    table: &table_neg,
                    m: 2,
                },
                random,
            ),
            (
                "mitm_m2_negfold_walk",
                Oracle::Mitm {
                    table: &table_neg,
                    m: 2,
                },
                walk,
            ),
            (
                "mitm_m3_negfold",
                Oracle::Mitm {
                    table: &table_neg,
                    m: 3,
                },
                random,
            ),
            (
                "mitm_m3_negfold_walk",
                Oracle::Mitm {
                    table: &table_neg,
                    m: 3,
                },
                walk,
            ),
        ];
        let mut variants = variants;
        if let Some(t) = &table_bal {
            variants.push((
                "mitm_m2_negfold_walk_balanced",
                Oracle::Mitm { table: t, m: 2 },
                walk,
            ));
        }
        for (name, oracle, targets) in variants {
            let fb = match name.ends_with("_balanced") {
                true => fb_bal.as_ref().unwrap_or(&fb),
                false => &fb,
            };
            let exact_m2 = if name.ends_with("_balanced") {
                exact_bal_m2
            } else {
                exact_m2
            };
            let budget = trial_budget(cfg, fb, oracle.summands(), space);
            let outcome = collect_and_solve(
                curve,
                g,
                target,
                r,
                inst.cofactor,
                fb,
                seed,
                budget,
                targets,
                cfg.restart_pool(),
                |ops, ctr, point| decompose_prime(curve, fb, &oracle, ops, ctr, point),
            );
            let exact = if oracle.summands() == 2 {
                exact_m2
            } else {
                exact_m3
            };
            let mut v = assemble_variant(
                name,
                oracle.name(),
                oracle.summands(),
                targets,
                &fb.cost,
                fb.points.len() as u64,
                fb.abscissae as u64,
                fb.columns as u64,
                None,
                oracle.table_cost(),
                exact,
                outcome,
                r,
                space,
                calib,
                rho_s,
                floor_s,
                1.0,
            );
            v.verified &= v.recovered == Some(d);
            out.variants.push(v);
        }
    }
    out.rho_s_mean = matched_rho_s_mean(&out);
    out
}

/// Mean `S` of the matched reference: the runs whose automorphism count
/// is the one the instance's generic algorithm may use (`2` on the
/// prime and random binary curves, `2n` on a Koblitz curve).  The other
/// runs are the before mark or a cross-regime comparison, and price
/// nothing.
pub fn matched_rho_s_mean(inst: &RegimeInstance) -> f64 {
    let matched: Vec<f64> = inst
        .rho
        .iter()
        .filter(|x| x.automorphisms == inst.automorphisms_generic)
        .map(|x| x.s)
        .collect();
    matched.iter().sum::<f64>() / matched.len().max(1) as f64
}

/// One binary-regime variant on one target: the relation loop, the
/// pricing, the check against the planted logarithm.
fn run_binary_variant(
    inst: &BinaryInstance,
    name: &str,
    fb: &FactorBase<FastPoint>,
    oracle: &Oracle,
    targets: TargetSource,
    exact: ExactCeiling,
    target: FastPoint,
    d: u64,
    seed: u64,
    cfg: &BoundaryConfig,
    calib: &Calibration,
    rho_s: f64,
    floor_s: f64,
    table_fold: f64,
) -> VariantResult {
    let g = BinaryGroup(&inst.fast);
    let space = inst.group_order as f64;
    let budget = trial_budget(cfg, fb, oracle.summands(), space);
    let outcome = collect_and_solve(
        &g,
        inst.generator,
        target,
        inst.r,
        inst.cofactor,
        fb,
        seed,
        budget,
        targets,
        cfg.restart_pool(),
        |ops, ctr, point| decompose_binary(inst, fb, oracle, ops, ctr, point),
    );
    let mut v = assemble_variant(
        name,
        oracle.name(),
        oracle.summands(),
        targets,
        &fb.cost,
        fb.points.len() as u64,
        fb.abscissae as u64,
        fb.columns as u64,
        fb.dimension,
        oracle.table_cost(),
        exact,
        outcome,
        inst.r,
        space,
        calib,
        rho_s,
        floor_s,
        table_fold,
    );
    v.verified &= v.recovered == Some(d);
    v
}

/// Whether a two-summand row is worth running on a binary base: the
/// count is admissible by the cofactor classes and its exact trials
/// floor is within `max_trials / m2_floor_divisor`, so a run that finds
/// its relations at the ceiling's rate finishes well inside the budget.
fn two_summand_row_fits(
    cfg: &BoundaryConfig,
    fb: &FactorBase<FastPoint>,
    space: f64,
    exact_m2: ExactCeiling,
) -> bool {
    let p = exact_m2
        .map(|e| e.1)
        .unwrap_or_else(|| decomposition_probability_ceiling(fb.points.len() as u64, 2, space));
    p > 0.0
        && (fb.columns as f64 + 1.0) / p
            <= cfg.max_trials as f64 / cfg.m2_floor_divisor.max(1) as f64
}

// ── The binary regimes ─────────────────────────────────────────────

/// The binary-regime conversion factors for one instance: addition,
/// doubling, Artin–Schreier solve, Frobenius map, row operation, word
/// XOR.  The lookup and `S₄` factors are added by the callers that
/// build the table and the oracle.
pub fn calibrate_binary_instance(inst: &BinaryInstance) -> Calibration {
    let mut c = Calibration::default();
    calibrate_binary(inst, &mut c);
    c
}

fn calibrate_binary(inst: &BinaryInstance, calib: &mut Calibration) {
    let g = BinaryGroup(&inst.fast);
    let mut rng = StdRng::seed_from_u64(inst.r ^ 0xB1);
    let mut ops = GroupOps::default();
    let pts: Vec<FastPoint> = (0..64)
        .map(|_| g.mul(&mut ops, inst.generator, rng.gen_range(1..inst.r)))
        .collect();
    calibrate_group(&g, &pts, calib);
    calibrate_row_ops(inst.r, calib);
    let samples = 200_000u64;
    let cs: Vec<u64> = (0..1024).map(|_| rng.gen::<u64>() & inst.gf.mask).collect();
    let start = Instant::now();
    let mut acc = 0u64;
    for i in 0..samples {
        acc ^= inst
            .artin_schreier
            .solve(cs[(i % 1024) as usize])
            .unwrap_or(1);
    }
    calib.ns_per_as_solve = Some(start.elapsed().as_nanos() as f64 / samples as f64);
    std::hint::black_box(acc);
    let start = Instant::now();
    let mut acc = pts[0];
    for _ in 0..samples {
        acc = inst.fast.frobenius_k(acc, 1);
    }
    calib.ns_per_frobenius = Some(start.elapsed().as_nanos() as f64 / samples as f64);
    std::hint::black_box(acc);
    calib.ns_per_word_xor = Some(calibrate_word_xor());
}

/// Nanoseconds per pair of the `S₄` pairs-and-solve loop, measured on
/// random targets of this instance.
pub fn calibrate_s4(inst: &BinaryInstance, oracle: &SubspaceOracle, calib: &mut Calibration) {
    let mut rng = StdRng::seed_from_u64(inst.r ^ 0x54);
    let mut pairs = 0u64;
    let start = Instant::now();
    let mut tries = 0;
    while tries < 3 || (pairs < 200_000 && tries < 64) {
        let xr = rng.gen::<u64>() & inst.gf.mask;
        let (_, p) = oracle.decompose(xr, &inst.gf);
        pairs += p;
        tries += 1;
    }
    calib.ns_per_s4_pair = Some(start.elapsed().as_nanos() as f64 / pairs.max(1) as f64);
}

/// The Koblitz base for degree `n`: the Frobenius-invariant subspace
/// whose dimension is nearest `⌈n/3⌉` (at most 12), or, where none
/// exists, the Frobenius closure of a random seed space sized to about
/// `2^{⌈n/3⌉}` abscissae — capped by the pair-table budget.
pub fn choose_koblitz_base(
    inst: &BinaryInstance,
    seed: u64,
    max_points: usize,
) -> Option<(FrobeniusFactorBase, String)> {
    let kc = inst.koblitz.as_ref()?;
    let n = inst.n;
    let target = n.div_ceil(3).max(3);
    let max_dim = 12u32.min((max_points as f64 / 2.0).log2().floor() as u32 + 1);
    let usable_dims: Vec<u32> = available_subspace_dimensions(n)
        .into_iter()
        .filter(|&d| d >= 2 && d < n && d <= max_dim && (d as i64 - target as i64).abs() <= 2)
        .collect();
    if !usable_dims.is_empty() {
        // Every divisor of x^n − 1 whose degree is a usable dimension,
        // nearest the target first.  A Frobenius-invariant subspace can
        // hold almost no curve abscissae (the dimension-5 subspace of
        // K_0/F_2^15 holds three points), so a candidate is kept only
        // when it carries at least a quarter of the points a random set
        // of its size would.
        let factors = all_factors_of_x_n_minus_1(n);
        let degs: Vec<u32> = factors.iter().map(|&f| 63 - f.leading_zeros()).collect();
        let count = factors.len().min(16);
        let mut candidates: Vec<(i64, u32, Vec<usize>)> = Vec::new();
        for mask in 1u32..(1u32 << count) {
            let idx: Vec<usize> = (0..count).filter(|&i| (mask >> i) & 1 == 1).collect();
            let total: u32 = idx.iter().map(|&i| degs[i]).sum();
            if usable_dims.contains(&total) {
                candidates.push(((total as i64 - target as i64).abs(), total, idx));
            }
        }
        candidates.sort();
        let mut best: Option<(FrobeniusFactorBase, String)> = None;
        for (_, dim, idx) in candidates {
            if let Some(fb) = build_frobenius_factor_base_from_divisor(kc, &idx) {
                // A subspace that is a subfield F_{2^d} carries the whole
                // point group E(F_{2^d}), a subgroup that meets the target
                // subgroup only at O: no relation exists at any cost.
                let is_subfield = n.is_multiple_of(dim)
                    && fb
                        .subspace_basis
                        .iter()
                        .all(|v| v.square_k_times(dim, &kc.curve.irreducible) == *v);
                let healthy = !is_subfield
                    && fb.points.len() >= (1usize << dim) / 4
                    && fb.points.len() <= max_points;
                if healthy {
                    let better = best
                        .as_ref()
                        .is_none_or(|(b, _)| b.points.len() < fb.points.len() && b.ell == dim);
                    if better {
                        best = Some((
                            fb,
                            format!("invariant subspace, divisor {idx:?}, dimension {dim}"),
                        ));
                    }
                    if best.as_ref().is_some_and(|(b, _)| b.ell != dim) {
                        break;
                    }
                }
            }
        }
        if let Some(found) = best {
            return Some(found);
        }
    }
    // Orbit union of a random seed space, sized like the subspaces: about
    // `2^{⌈n/3⌉+1}` abscissae (`n · 2^s`), within the table budget.
    let mut rng = StdRng::seed_from_u64(seed ^ (n as u64));
    let log2_n = 63 - (n as u64).leading_zeros();
    let mut s = (target + 1).saturating_sub(log2_n).clamp(1, 12);
    while s > 1 && (n as usize) * (1usize << s) > max_points {
        s -= 1;
    }
    for _ in 0..64 {
        let basis: Vec<_> = (0..s)
            .map(|_| {
                let bits: Vec<u32> = (0..n).filter(|_| rng.gen::<bool>()).collect();
                crate::binary_ecc::F2mElement::from_bit_positions(&bits, n)
            })
            .collect();
        if let Some(fb) = build_frobenius_union_factor_base(kc, &basis) {
            if fb.points.len() <= max_points && fb.points.len() >= 8 {
                return Some((
                    fb,
                    format!("Frobenius orbit union of a seed space of dimension {s}"),
                ));
            }
        }
    }
    None
}

/// **A Koblitz base sized to the folded table**, for the balanced rows:
/// the Frobenius orbit union of a random seed space with about
/// `1.2·(4#E)^{1/3}` signed points — the size at which a folded table of
/// `|F|²/(4n)` entries balances a two-summand walk's `#E/(n|F|)` trials
/// — within `max_folded_table_pairs`.  `None` when that is not at least
/// half again the first-round base, so the rows are only run where the
/// full table's budget had actually bitten (`n ≥ 37` on the default
/// ladder).
pub fn choose_koblitz_balanced_base(
    inst: &BinaryInstance,
    cfg: &BoundaryConfig,
    first_round_points: usize,
) -> Option<(FrobeniusFactorBase, String)> {
    let kc = inst.koblitz.as_ref()?;
    let n = inst.n;
    let by_balance = 1.2 * (4.0 * inst.group_order as f64).cbrt();
    let by_table = (4.0 * n as f64 * cfg.max_folded_table_pairs as f64).sqrt();
    let target_points = by_balance.min(by_table);
    if target_points < 1.5 * first_round_points as f64 {
        return None;
    }
    // A seed space of dimension s gives n·2^s abscissae, about half of
    // which carry two points each: about n·2^s signed points.
    let s = ((target_points / n as f64).log2().round() as i64).clamp(1, 14) as u32;
    let mut rng = StdRng::seed_from_u64(cfg.seed ^ (n as u64) ^ 0xBA1A_4CED);
    for _ in 0..64 {
        let basis: Vec<_> = (0..s)
            .map(|_| {
                let bits: Vec<u32> = (0..n).filter(|_| rng.gen::<bool>()).collect();
                crate::binary_ecc::F2mElement::from_bit_positions(&bits, n)
            })
            .collect();
        if let Some(fb) = build_frobenius_union_factor_base(kc, &basis) {
            let f = fb.points.len();
            let pairs = (f as u64) * (f as u64) / (4 * n as u64);
            if f as f64 >= 1.5 * first_round_points as f64 && pairs <= cfg.max_folded_table_pairs {
                return Some((
                    fb,
                    format!(
                        "Frobenius orbit union of a seed space of dimension {s}, sized to the folded table (target {target_points:.0} signed points)"
                    ),
                ));
            }
        }
    }
    None
}

fn binary_regime_shell(inst: &BinaryInstance, regime: &str, automorphisms: u32) -> RegimeInstance {
    RegimeInstance {
        regime: regime.into(),
        curve: inst.describe(),
        r: inst.r,
        log2_r: (inst.r as f64).log2(),
        group_order: inst.group_order as f64,
        cofactor: inst.cofactor,
        automorphisms_generic: automorphisms,
        floor_s: generic_floor_s(automorphisms as f64),
        floor_ops: generic_floor_ops(inst.r as f64, automorphisms as f64),
        calibration: Calibration::default(),
        calibration_measured: Calibration::default(),
        calibration_pinned: PinOutcome::default(),
        rho: Vec::new(),
        rho_s_mean: 0.0,
        rho_verified_all: true,
        variants: Vec::new(),
        seeds: Vec::new(),
        targets: Vec::new(),
    }
}

/// Run every generic-binary variant on one instance: `S₄`
/// pairs-and-solve and meet in the middle over the low-order subspace
/// of dimension `⌈n/3⌉`, columns by abscissa.  `None` when no summand
/// count in `{2, 3}` can reach the subgroup from this base.
pub fn run_char2_instance(inst: &BinaryInstance, cfg: &BoundaryConfig) -> Option<RegimeInstance> {
    let g = BinaryGroup(&inst.fast);
    let r = inst.r;
    let mut calib = Calibration::default();
    calibrate_binary(inst, &mut calib);
    let l = inst.n.div_ceil(3);
    let basis: Vec<u64> = (0..l).map(|i| 1u64 << i).collect();
    let mut fb = binary_subspace_factor_base(inst, &basis);
    // Round 3: the subspace dimension the family's shape law asks for.
    // About half the subspace's elements carry points and each carries
    // two, so a dimension `l` base holds about `2^l` signed points and
    // the model optimum `#E^{1/3}` wants `l* = log2(#E^{1/3})`.  The
    // measurements put the real optimum at or a little below `l*` — the
    // model's `c = 1` per target is right but its `K/2` relations is
    // pessimistic, and the gap grows as the base shrinks — so the ladder
    // brackets it, running `l*` and `l* − 1` wherever they differ from
    // the `⌈n/3⌉` rule.
    let l_star = (family_optimum_base(inst.group_order as f64, 1.0, 1.0)
        .log2()
        .round() as i64)
        .clamp(2, (inst.n as i64 - 1).min(20)) as u32;
    let l_bal = if l_star == l {
        l_star.saturating_sub(1).max(2)
    } else {
        l_star
    };
    let fb_bal = (l_bal != l).then(|| {
        binary_subspace_factor_base(inst, &(0..l_bal).map(|i| 1u64 << i).collect::<Vec<u64>>())
    });
    let mut class_ops = GroupOps::default();
    let admissible: Vec<u32> = [3u32, 2]
        .into_iter()
        .filter(|&m| summands_admissible(&g, &mut class_ops, &fb.points, r, m))
        .collect();
    fb.cost.group_ops.merge(class_ops);
    fb.cost
        .count("admissibility_scalar_mults", class_ops.scalar_mults);
    let table = PairTable::build(&g, &fb);
    let table_neg = PairTable::build_negation_folded(&g, &fb);
    let table_bal = fb_bal
        .as_ref()
        .map(|f| PairTable::build_negation_folded(&g, f));
    let exact_bal_m2 = fb_bal
        .as_ref()
        .and_then(|f| exact_decomposition_ceiling(&g, &f.points, r, 2));
    calib.ns_per_lookup = table.calibrate_lookup(1_000_000);
    let census: Vec<(u32, usize)> = admissible
        .iter()
        .map(|&m| {
            (
                m,
                census_hits(inst, &fb, &Oracle::Mitm { table: &table, m }, 64, cfg.seed),
            )
        })
        .collect();
    let m_used = census.iter().find(|(_, hits)| *hits > 0).map(|(m, _)| *m)?;
    let s4 = (m_used == 3).then(|| SubspaceOracle::new(&basis, inst.b, &inst.gf));
    if let Some(o) = &s4 {
        calibrate_s4(inst, o, &mut calib);
    }
    let space = inst.group_order as f64;
    let exact_m2 = exact_decomposition_ceiling(&g, &fb.points, r, 2);
    let exact_m3 = exact_decomposition_ceiling(&g, &fb.points, r, 3);
    let _exact_of = |m: u32| if m == 2 { exact_m2 } else { exact_m3 };
    // The two-summand row, where the census of 64 was too small to see
    // it but the exact floor says it is within reach.
    let m2_row =
        m_used == 3 && admissible.contains(&2) && two_summand_row_fits(cfg, &fb, space, exact_m2);

    let mut out = binary_regime_shell(inst, "char2", 2);
    // Price with the repository's ratios, keep the host's as the note.
    let instance_name = out.curve["name"].as_str().unwrap_or_default().to_string();
    out.calibration_measured = calib.clone();
    out.calibration_pinned = calib.pin("char2", &instance_name);
    out.calibration = calib.clone();
    out.curve["factor_base"] = serde_json::json!({
        "description": fb.description,
        "dimension": l,
        "signed_points": fb.points.len(),
        "abscissae": fb.abscissae,
        "columns": fb.columns,
        "summands_admissible": admissible,
        "census_hits_of_64": census,
        "summands_used": m_used,
        "two_summand_row": m2_row,
        "full_table_entries": table.entries,
        "negation_folded_table_entries": table_neg.entries,
        "cofactor_classes": exact_m2.map(|e| e.0),
        "ceiling_uniform_m2": decomposition_probability_ceiling(fb.points.len() as u64, 2, space),
        "ceiling_exact_m2": exact_m2.map(|e| e.1),
        "ceiling_uniform_m3": decomposition_probability_ceiling(fb.points.len() as u64, 3, space),
        "ceiling_exact_m3": exact_m3.map(|e| e.1),
        "family_optimum_base_signed_points": family_optimum_base(space, 1.0, 1.0),
        "family_optimum_s": family_optimum_s(space, r as f64, 1.0, 1.0),
    });
    if let (Some(f), Some(t)) = (&fb_bal, &table_bal) {
        out.curve["factor_base_balanced"] = serde_json::json!({
            "description": f.description,
            "dimension": l_bal,
            "signed_points": f.points.len(),
            "abscissae": f.abscissae,
            "columns": f.columns,
            "negation_folded_table_entries": t.entries,
            "ceiling_exact_m2": exact_bal_m2.map(|e| e.1),
        });
    }
    let mut rng = StdRng::seed_from_u64(cfg.seed ^ r ^ 0xC2);
    let mut ops = GroupOps::default();
    for rep in 0..cfg.repeats {
        let seed = cfg.seed.wrapping_add(rep as u64 * 0x9E37);
        let d = rng.gen_range(1..r);
        let target = g.mul(&mut ops, inst.generator, d);
        out.seeds.push(seed);
        out.targets.push(d);
        let mut rho_s = 0.0;
        for k in 0..cfg.rho_repeats.max(1) {
            // The matched reference (negation, `A = 2`), then the plain
            // walk kept as the before mark, as in the prime regime.
            let rho_seed = seed ^ (k as u64 * 0x5EED);
            let cap = rho_cap(r, cfg.rho_cap_multiple);
            let matched = rho_reference_negation(&g, inst.generator, target, r, rho_seed, cap);
            out.rho_verified_all &= matched.verified && matched.recovered == Some(d);
            rho_s += matched.s / cfg.rho_repeats.max(1) as f64;
            out.rho.push(matched);
            let plain = rho_reference(&g, inst.generator, target, r, rho_seed, cap);
            out.rho_verified_all &= plain.verified && plain.recovered == Some(d);
            out.rho.push(plain);
        }

        let random = cfg.random_source();
        let walk = cfg.walk_source();
        let mut variants: Vec<(String, Oracle, TargetSource)> = vec![(
            format!("mitm_m{m_used}"),
            Oracle::Mitm {
                table: &table,
                m: m_used,
            },
            random,
        )];
        if let Some(o) = &s4 {
            if inst.n <= cfg.s4_max_degree {
                variants.push((
                    "semaev_s4_pairs_and_solve_m3".into(),
                    Oracle::SemaevS4 { oracle: o },
                    random,
                ));
            }
        }
        // Round 2: the negation-folded table, walk targets, and the
        // two-summand row where it fits.
        variants.push((
            format!("mitm_m{m_used}_negfold"),
            Oracle::Mitm {
                table: &table_neg,
                m: m_used,
            },
            random,
        ));
        variants.push((
            format!("mitm_m{m_used}_negfold_walk"),
            Oracle::Mitm {
                table: &table_neg,
                m: m_used,
            },
            walk,
        ));
        if m2_row {
            variants.push((
                "mitm_m2_negfold".into(),
                Oracle::Mitm {
                    table: &table_neg,
                    m: 2,
                },
                random,
            ));
            variants.push((
                "mitm_m2_negfold_walk".into(),
                Oracle::Mitm {
                    table: &table_neg,
                    m: 2,
                },
                walk,
            ));
        }
        if let Some(t) = &table_bal {
            variants.push((
                "mitm_m2_negfold_walk_balanced".into(),
                Oracle::Mitm { table: t, m: 2 },
                walk,
            ));
        }
        for (name, oracle, targets) in variants {
            let base = if name.ends_with("_balanced") {
                fb_bal.as_ref().unwrap_or(&fb)
            } else {
                &fb
            };
            let exact_of = |m: u32| match (name.ends_with("_balanced"), m) {
                (true, 2) => exact_bal_m2,
                (_, 2) => exact_m2,
                _ => exact_m3,
            };
            let v = run_binary_variant(
                inst,
                &name,
                base,
                &oracle,
                targets,
                exact_of(oracle.summands()),
                target,
                d,
                seed,
                cfg,
                &calib,
                rho_s,
                out.floor_s,
                1.0,
            );
            out.variants.push(v);
        }
    }
    out.rho_s_mean = matched_rho_s_mean(&out);
    Some(out)
}

/// Run every Koblitz variant on one instance: meet in the middle over
/// signed-orbit columns, the same without the fold (the `char2` pipeline
/// on the Koblitz curve), and `S₄` pairs-and-solve on the invariant
/// subspace when the base is one.  The reference is the signed-Frobenius
/// rho (`A = 2n`); the plain walk is run too, for the comparison with
/// the other regimes.
pub fn run_koblitz_instance(inst: &BinaryInstance, cfg: &BoundaryConfig) -> Option<RegimeInstance> {
    let kc = inst.koblitz.as_ref()?;
    let g = BinaryGroup(&inst.fast);
    let r = inst.r;
    let n = inst.n;
    let mut calib = Calibration::default();
    calibrate_binary(inst, &mut calib);
    let (mut frob, mut description) = choose_koblitz_base(inst, cfg.seed, cfg.max_table_points)?;
    // Which summand counts actually reach the subgroup from this base?
    // The cofactor-class test is the cheap necessary filter; the census
    // on the built pair table is the real one.  When neither count
    // yields, the two-torsion saturation `B ∪ (B + T)` changes the
    // cofactor classes without adding projected points.
    let admissible_of = |fb: &FrobeniusFactorBase| -> Vec<u32> {
        [3u32, 2]
            .into_iter()
            .filter(|&m| fb.m_can_decompose(kc, m as usize))
            .collect()
    };
    let mut admissible = admissible_of(&frob);
    let mut folded = koblitz_factor_base(
        inst,
        &frob,
        ColumnFold::SignedFrobeniusOrbit,
        description.clone(),
    )?;
    let mut table = PairTable::build(&g, &folded);
    let census_of =
        |fb: &FactorBase<FastPoint>, table: &PairTable, adm: &[u32]| -> Vec<(u32, usize)> {
            adm.iter()
                .map(|&m| {
                    (
                        m,
                        census_hits(inst, fb, &Oracle::Mitm { table, m }, 64, cfg.seed),
                    )
                })
                .collect()
        };
    let mut census = census_of(&folded, &table, &admissible);
    if !census.iter().any(|(_, hits)| *hits > 0) {
        let saturated = saturate_factor_base_two_torsion(kc, &frob)?;
        if saturated.points.len() > cfg.max_table_points {
            return None;
        }
        admissible = admissible_of(&saturated);
        frob = saturated;
        description.push_str(" + two-torsion saturation");
        folded = koblitz_factor_base(
            inst,
            &frob,
            ColumnFold::SignedFrobeniusOrbit,
            description.clone(),
        )?;
        table = PairTable::build(&g, &folded);
        census = census_of(&folded, &table, &admissible);
    }
    let m_used = census.iter().find(|(_, hits)| *hits > 0).map(|(m, _)| *m)?;
    let unfolded = koblitz_factor_base(inst, &frob, ColumnFold::Abscissa, description.clone())?;
    calib.ns_per_lookup = table.calibrate_lookup(1_000_000);
    let s4 = folded
        .subspace_basis
        .as_ref()
        .filter(|_| n <= cfg.s4_max_degree && m_used == 3)
        .map(|basis| SubspaceOracle::new(basis, 1, &inst.gf));
    if let Some(o) = &s4 {
        calibrate_s4(inst, o, &mut calib);
    }
    let space = inst.group_order as f64;

    // Round 2 on the same base: the negation-folded table, the
    // Frobenius-folded table, the exact ceilings, the two-summand row.
    let table_neg = PairTable::build_negation_folded(&g, &folded);
    let table_frob = FrobeniusPairTable::build(inst, &folded);
    calib.ns_per_canon = table_frob.as_ref().map(|t| t.calibrate_canon(1_000_000));
    let exact_m2 = exact_decomposition_ceiling(&g, &folded.points, r, 2);
    let exact_m3 = exact_decomposition_ceiling(&g, &folded.points, r, 3);
    let exact_of = |m: u32| if m == 2 { exact_m2 } else { exact_m3 };
    let m2_row = table_frob.is_some()
        && m_used == 3
        && admissible.contains(&2)
        && two_summand_row_fits(cfg, &folded, space, exact_m2);

    // Round 2 on a base sized to the folded table (n ≥ 37 on the default
    // ladder): its own rows, its own floor.
    let balanced =
        choose_koblitz_balanced_base(inst, cfg, folded.points.len()).and_then(|(fbb, desc)| {
            let fb = koblitz_factor_base(inst, &fbb, ColumnFold::SignedFrobeniusOrbit, desc)?;
            let table = FrobeniusPairTable::build(inst, &fb)?;
            let adm: Vec<u32> = [3u32, 2]
                .into_iter()
                .filter(|&m| fbb.m_can_decompose(kc, m as usize))
                .collect();
            let census_m3 = adm.contains(&3).then(|| {
                census_hits(
                    inst,
                    &fb,
                    &Oracle::MitmFrobenius {
                        table: &table,
                        m: 3,
                    },
                    64,
                    cfg.seed,
                )
            });
            let exact_m2 = exact_decomposition_ceiling(&g, &fb.points, r, 2);
            let exact_m3 = exact_decomposition_ceiling(&g, &fb.points, r, 3);
            let m3_row = census_m3.is_some_and(|hits| hits > 0);
            let m2_row = adm.contains(&2) && two_summand_row_fits(cfg, &fb, space, exact_m2);
            if !m3_row && !m2_row {
                return None;
            }
            Some((
                fbb, fb, table, adm, census_m3, exact_m2, exact_m3, m3_row, m2_row,
            ))
        });

    let mut out = binary_regime_shell(inst, "koblitz", 2 * n);
    // Price with the repository's ratios, keep the host's as the note.
    let instance_name = out.curve["name"].as_str().unwrap_or_default().to_string();
    out.calibration_measured = calib.clone();
    out.calibration_pinned = calib.pin("koblitz", &instance_name);
    out.calibration = calib.clone();
    out.curve["factor_base"] = serde_json::json!({
        "description": description,
        "domain": format!("{:?}", frob.domain),
        "signed_points": folded.points.len(),
        "abscissae": folded.abscissae,
        "signed_orbits": folded.columns,
        "dimension": folded.dimension,
        "lambda": kc.lambda.to_string(),
        "summands_admissible": admissible,
        "census_hits_of_64": census,
        "summands_used": m_used,
        "two_summand_row": m2_row,
        "full_table_entries": table.entries,
        "negation_folded_table_entries": table_neg.entries,
        "frobenius_folded_table_entries": table_frob.as_ref().map(|t| t.entries),
        "frobenius_folded_table_representatives": table_frob.as_ref().map(|t| t.representatives),
        "cofactor_classes": exact_m2.map(|e| e.0),
        "ceiling_uniform_m2": decomposition_probability_ceiling(folded.points.len() as u64, 2, space),
        "ceiling_exact_m2": exact_m2.map(|e| e.1),
        "ceiling_uniform_m3": decomposition_probability_ceiling(folded.points.len() as u64, 3, space),
        "ceiling_exact_m3": exact_m3.map(|e| e.1),
    });
    if let Some((fbb, fb, table, adm, census_m3, exact_m2, exact_m3, m3_row, m2_row)) = &balanced {
        out.curve["factor_base_balanced"] = serde_json::json!({
            "description": fb.description,
            "domain": format!("{:?}", fbb.domain),
            "signed_points": fb.points.len(),
            "abscissae": fb.abscissae,
            "signed_orbits": fb.columns,
            "summands_admissible": adm,
            "census_hits_of_64_m3": census_m3,
            "three_summand_row": m3_row,
            "two_summand_row": m2_row,
            "frobenius_folded_table_entries": table.entries,
            "frobenius_folded_table_representatives": table.representatives,
            "cofactor_classes": exact_m2.map(|e| e.0),
            "ceiling_uniform_m2": decomposition_probability_ceiling(fb.points.len() as u64, 2, space),
            "ceiling_exact_m2": exact_m2.map(|e| e.1),
            "ceiling_uniform_m3": decomposition_probability_ceiling(fb.points.len() as u64, 3, space),
            "ceiling_exact_m3": exact_m3.map(|e| e.1),
        });
    }
    let mut rng = StdRng::seed_from_u64(cfg.seed ^ r ^ 0x4B);
    let mut ops = GroupOps::default();
    for rep in 0..cfg.repeats {
        let seed = cfg.seed.wrapping_add(rep as u64 * 0x9E37);
        let d = rng.gen_range(1..r);
        let target = g.mul(&mut ops, inst.generator, d);
        out.seeds.push(seed);
        out.targets.push(d);

        // Signed-Frobenius rho: the reference on this curve.
        let mut rho_s = 0.0;
        for k in 0..cfg.rho_repeats.max(1) {
            let signed = signed_frobenius_rho(inst, target, d, seed ^ (k as u64 * 0x5EED))
                .expect("a Koblitz instance carries its curve");
            out.rho_verified_all &= signed.verified;
            rho_s += signed.s / cfg.rho_repeats.max(1) as f64;
            out.rho.push(signed);
            // The plain walk, for the cross-regime comparison.
            let plain = rho_reference(
                &g,
                inst.generator,
                target,
                r,
                seed ^ (k as u64 * 0x5EED),
                rho_cap(r, cfg.rho_cap_multiple),
            );
            out.rho.push(plain);
        }

        let random = cfg.random_source();
        let walk = cfg.walk_source();
        let mut variants: Vec<(
            String,
            &FactorBase<FastPoint>,
            Oracle,
            TargetSource,
            ExactCeiling,
        )> = vec![(
            format!("mitm_m{m_used}_signed_orbit_columns"),
            &folded,
            Oracle::Mitm {
                table: &table,
                m: m_used,
            },
            random,
            exact_of(m_used),
        )];
        if n <= cfg.koblitz_no_fold_max_degree {
            variants.push((
                format!("mitm_m{m_used}_abscissa_columns_control"),
                &unfolded,
                Oracle::Mitm {
                    table: &table,
                    m: m_used,
                },
                random,
                exact_of(m_used),
            ));
        }
        if let Some(o) = &s4 {
            variants.push((
                "semaev_s4_pairs_and_solve_m3_signed_orbit_columns".into(),
                &folded,
                Oracle::SemaevS4 { oracle: o },
                random,
                exact_m3,
            ));
        }
        // Round 2, cumulative: fold the negation out of the table, then
        // the Frobenius, then draw the targets by a walk; the
        // two-summand row on the folded table where it fits.
        variants.push((
            format!("mitm_m{m_used}_signed_orbit_columns_negfold"),
            &folded,
            Oracle::Mitm {
                table: &table_neg,
                m: m_used,
            },
            random,
            exact_of(m_used),
        ));
        if let Some(tf) = &table_frob {
            variants.push((
                format!("mitm_m{m_used}_signed_orbit_columns_frobfold"),
                &folded,
                Oracle::MitmFrobenius {
                    table: tf,
                    m: m_used,
                },
                random,
                exact_of(m_used),
            ));
            variants.push((
                format!("mitm_m{m_used}_signed_orbit_columns_frobfold_walk"),
                &folded,
                Oracle::MitmFrobenius {
                    table: tf,
                    m: m_used,
                },
                walk,
                exact_of(m_used),
            ));
            if m2_row {
                variants.push((
                    "mitm_m2_signed_orbit_columns_frobfold_walk".into(),
                    &folded,
                    Oracle::MitmFrobenius { table: tf, m: 2 },
                    walk,
                    exact_m2,
                ));
            }
        }
        if let Some((_, fb, tf, _, _, exact_m2_b, exact_m3_b, m3_row, m2_row_b)) = &balanced {
            if *m3_row {
                variants.push((
                    "mitm_m3_signed_orbit_columns_frobfold_walk_balanced".into(),
                    fb,
                    Oracle::MitmFrobenius { table: tf, m: 3 },
                    walk,
                    *exact_m3_b,
                ));
            }
            if *m2_row_b {
                variants.push((
                    "mitm_m2_signed_orbit_columns_frobfold_walk_balanced".into(),
                    fb,
                    Oracle::MitmFrobenius { table: tf, m: 2 },
                    walk,
                    *exact_m2_b,
                ));
            }
        }
        for (name, fb, oracle, targets, exact) in variants {
            // The table fold the family optimum is measured against: the
            // Frobenius-folded table holds one entry per `⟨σ, −1⟩`-orbit
            // of pairs, so its build is `|F|²/4n` rather than `|F|²/4`.
            let table_fold = if matches!(oracle, Oracle::MitmFrobenius { .. }) {
                n as f64
            } else {
                1.0
            };
            let v = run_binary_variant(
                inst,
                &name,
                fb,
                &oracle,
                targets,
                exact,
                target,
                d,
                seed,
                cfg,
                &calib,
                rho_s,
                out.floor_s,
                table_fold,
            );
            out.variants.push(v);
        }
    }
    // Mean over the signed reference only.
    let signed: Vec<f64> = out
        .rho
        .iter()
        .filter(|x| x.automorphisms > 1)
        .map(|x| x.s)
        .collect();
    out.rho_s_mean = signed.iter().sum::<f64>() / signed.len().max(1) as f64;
    Some(out)
}

