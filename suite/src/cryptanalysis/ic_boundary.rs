/// What building a table cost, folded into the factor-base phase of
/// every variant that probes it.
#[derive(Clone, Debug, Default)]
pub struct TableCost {
    pub kind: &'static str,
    pub entries: u64,
    pub group_ops: GroupOps,
    pub wall_ns: u64,
    /// Native counters of the build besides additions.
    pub native: Vec<(&'static str, u64)>,
}

/// A table of all pair sums of a base, keyed by the sum's abscissa so
/// `S` and `−S` share one entry; the probe checks which it found.
pub struct PairTable {
    map: FastMap<(u32, u32)>,
    /// `full` (every `i ≤ j`) or `negation_folded` (one pair per orbit
    /// under negation).
    pub kind: &'static str,
    pub entries: u64,
    pub build_ops: GroupOps,
    pub build_wall_ns: u64,
}

impl PairTable {
    pub fn build<G: CountedGroup>(g: &G, fb: &FactorBase<G::Elt>) -> Self {
        let start = Instant::now();
        let n = fb.points.len();
        let mut ops = GroupOps::default();
        let mut map: FastMap<(u32, u32)> = fast_map(n * (n + 1) / 4 + 1);
        for i in 0..n {
            for j in i..n {
                let s = g.add(&mut ops, fb.points[i], fb.points[j]);
                if g.is_identity(&s) {
                    continue;
                }
                map.entry(g.key(&s) >> 1).or_insert((i as u32, j as u32));
            }
        }
        Self {
            kind: "full",
            entries: map.len() as u64,
            map,
            build_ops: ops,
            build_wall_ns: start.elapsed().as_nanos() as u64,
        }
    }

    /// **The same table with the negation folded out of the build.**  The
    /// key is the abscissa of the sum, which `{P, Q}` and `{−P, −Q}` share,
    /// so half of the full build's additions made entries the map already
    /// held.  One pair per orbit under negation: the first point above
    /// each abscissa against every signed point above a later abscissa,
    /// plus its own double.  About `|F|²/4` additions instead of
    /// `|F|²/2`; the probe is unchanged.
    pub fn build_negation_folded<G: CountedGroup>(g: &G, fb: &FactorBase<G::Elt>) -> Self {
        let start = Instant::now();
        let mut ops = GroupOps::default();
        let groups: Vec<&Vec<usize>> = fb
            .abscissa_list
            .iter()
            .map(|x| fb.x_index.get(x).expect("every listed abscissa is indexed"))
            .collect();
        let a = groups.len();
        let mut map: FastMap<(u32, u32)> = fast_map(a * a + 1);
        for ai in 0..a {
            let i = groups[ai][0];
            for group in groups.iter().skip(ai) {
                for &j in group.iter() {
                    let s = g.add(&mut ops, fb.points[i], fb.points[j]);
                    if g.is_identity(&s) {
                        continue;
                    }
                    map.entry(g.key(&s) >> 1).or_insert((i as u32, j as u32));
                }
            }
        }
        Self {
            kind: "negation_folded",
            entries: map.len() as u64,
            map,
            build_ops: ops,
            build_wall_ns: start.elapsed().as_nanos() as u64,
        }
    }

    pub fn cost(&self) -> TableCost {
        TableCost {
            kind: self.kind,
            entries: self.entries,
            group_ops: self.build_ops,
            wall_ns: self.build_wall_ns,
            native: Vec::new(),
        }
    }

    /// Indices `(i, j)` with `P_i + P_j = target`, if the table holds a
    /// pair summing to `±target`; one probe, at most one addition.
    pub fn probe<G: CountedGroup>(
        &self,
        g: &G,
        fb: &FactorBase<G::Elt>,
        ops: &mut GroupOps,
        lookups: &mut u64,
        target: G::Elt,
    ) -> Option<(usize, usize)> {
        *lookups += 1;
        let &(i, j) = self.map.get(&(g.key(&target) >> 1))?;
        let (i, j) = (i as usize, j as usize);
        let s = g.add(ops, fb.points[i], fb.points[j]);
        if s == target {
            Some((i, j))
        } else if s == g.neg(target) {
            Some((fb.neg_index[i], fb.neg_index[j]))
        } else {
            None
        }
    }

    pub fn calibrate_lookup(&self, samples: u64) -> f64 {
        let mut rng = StdRng::seed_from_u64(7);
        let keys: Vec<u64> = (0..1024).map(|_| rng.gen::<u64>() >> 1).collect();
        let start = Instant::now();
        let mut hits = 0u64;
        for i in 0..samples {
            if self.map.contains_key(&keys[(i % 1024) as usize]) {
                hits += 1;
            }
        }
        let ns = start.elapsed().as_nanos() as f64 / samples as f64;
        std::hint::black_box(hits);
        ns
    }
}

/// Bits of a table entry that hold the second index; the rotation that
/// canonicalised the entry's sum sits above them.
const FROB_INDEX_BITS: u32 = 26;

/// **A pair table folded by the Frobenius as well as by negation**
/// (Koblitz).  One entry per pair `{P, Q}` up to the group generated by
/// `σ` and `−1`, keyed by the normal-basis canonical form of the sum's
/// abscissa ([`FrobeniusCanon`]): `σ^t(P) + σ^t(Q) = σ^t(P + Q)` for
/// every `t`, and `±` share an abscissa, so all `2n` images of a pair
/// share one entry.  About `|F|²/(4n)` additions and entries instead of
/// the full table's `|F|²/2`.
///
/// A probe canonicalises the target's abscissa once; the entry's shift
/// and the target's give the rotation `t` outright; the summands
/// `σ^t(P)`, `σ^t(Q)` are read from a per-point orbit index built once;
/// one addition confirms `±R`.  The canonicalisations are counted in
/// their own unit and converted at a measured factor, like every other
/// non-addition.
pub struct FrobeniusPairTable {
    map: FastMap<(u32, u32)>,
    canon: FrobeniusCanon,
    /// `member_of[i·n + t]`: the base index of `σ^t(P_i)`.
    member_of: Vec<u32>,
    n: u32,
    pub entries: u64,
    pub representatives: u64,
    pub build_ops: GroupOps,
    pub build_wall_ns: u64,
    pub build_canonicalisations: u64,
    pub build_frobenius_maps: u64,
    pub build_lookups: u64,
}

impl FrobeniusPairTable {
    /// `None` when the base is not closed under the Frobenius, has more
    /// than `2^26` points, or the field yields no normal basis.
    pub fn build(inst: &BinaryInstance, fb: &FactorBase<FastPoint>) -> Option<Self> {
        let start = Instant::now();
        let g = BinaryGroup(&inst.fast);
        let n = inst.n as usize;
        let f = fb.points.len();
        if f >= (1usize << FROB_INDEX_BITS) {
            return None;
        }
        let canon = FrobeniusCanon::new(&inst.gf, inst.n)?;
        let mut member_of = vec![0u32; f * n];
        let (mut frob, mut lookups) = (0u64, 0u64);
        for i in 0..f {
            let mut p = fb.points[i];
            member_of[i * n] = i as u32;
            for t in 1..n {
                p = inst.fast.frobenius_k(p, 1);
                frob += 1;
                lookups += 1;
                let idx = *fb.point_index.get(&p.pack())?;
                member_of[i * n + t] = idx as u32;
            }
        }
        // One representative per column, the first point of it: any
        // member of a signed orbit serves, the orbit being its own
        // ⟨σ, −1⟩-image.
        let mut rep_of_col = vec![usize::MAX; fb.columns];
        for i in 0..f {
            let c = fb.col_of[i];
            if rep_of_col[c] == usize::MAX {
                rep_of_col[c] = i;
            }
        }
        let mut ops = GroupOps::default();
        let mut canons = 0u64;
        let mut map: FastMap<(u32, u32)> = fast_map(f * f / (4 * n) + 1);
        for (col, &rep) in rep_of_col.iter().enumerate() {
            if rep == usize::MAX {
                continue;
            }
            for j in 0..f {
                if fb.col_of[j] < col {
                    continue;
                }
                let u = g.add(&mut ops, fb.points[rep], fb.points[j]);
                if g.is_identity(&u) {
                    continue;
                }
                canons += 1;
                let (key, t_u) = canon.canon_with_shift(u.x);
                map.entry(key)
                    .or_insert((rep as u32, (j as u32) | (t_u << FROB_INDEX_BITS)));
            }
        }
        Some(Self {
            entries: map.len() as u64,
            representatives: rep_of_col.iter().filter(|&&r| r != usize::MAX).count() as u64,
            map,
            canon,
            member_of,
            n: inst.n,
            build_ops: ops,
            build_wall_ns: start.elapsed().as_nanos() as u64,
            build_canonicalisations: canons,
            build_frobenius_maps: frob,
            build_lookups: lookups,
        })
    }

    /// Indices `(i, j)` with `P_i + P_j = target`, if some `⟨σ, −1⟩`-image
    /// of a stored pair sums to `±target`: one canonicalisation, one
    /// probe, one addition.
    pub fn probe(
        &self,
        g: &BinaryGroup,
        fb: &FactorBase<FastPoint>,
        ops: &mut GroupOps,
        ctr: &mut OracleCounters,
        target: FastPoint,
    ) -> Option<(usize, usize)> {
        ctr.canonicalisations += 1;
        let (key, t_r) = self.canon.canon_with_shift(target.x);
        ctr.lookups += 1;
        let &(i, packed) = self.map.get(&key)?;
        let n = self.n;
        let j = (packed & ((1u32 << FROB_INDEX_BITS) - 1)) as usize;
        let t_u = packed >> FROB_INDEX_BITS;
        // canon = rotl^{t_u}(coords(x_u)) = rotl^{t_r}(coords(x_R)) and the
        // Frobenius is rotl by one, so x_R = σ^t(x_u) with t = t_u − t_r.
        let t = ((t_u + n - t_r) % n) as usize;
        let i2 = self.member_of[i as usize * n as usize + t] as usize;
        let j2 = self.member_of[j * n as usize + t] as usize;
        let s = g.add(ops, fb.points[i2], fb.points[j2]);
        if s == target {
            Some((i2, j2))
        } else if s == g.neg(target) {
            Some((fb.neg_index[i2], fb.neg_index[j2]))
        } else {
            ctr.frobfold_mismatches += 1;
            None
        }
    }

    pub fn calibrate_lookup(&self, samples: u64) -> f64 {
        let mut rng = StdRng::seed_from_u64(7);
        let mask = (1u64 << self.n) - 1;
        let keys: Vec<u64> = (0..1024).map(|_| rng.gen::<u64>() & mask).collect();
        let start = Instant::now();
        let mut hits = 0u64;
        for i in 0..samples {
            if self.map.contains_key(&keys[(i % 1024) as usize]) {
                hits += 1;
            }
        }
        let ns = start.elapsed().as_nanos() as f64 / samples as f64;
        std::hint::black_box(hits);
        ns
    }

    /// Nanoseconds per canonicalisation with shift, on random abscissae.
    pub fn calibrate_canon(&self, samples: u64) -> f64 {
        let mut rng = StdRng::seed_from_u64(9);
        let mask = (1u64 << self.n) - 1;
        let xs: Vec<u64> = (0..1024).map(|_| rng.gen::<u64>() & mask).collect();
        let start = Instant::now();
        let mut acc = 0u64;
        for i in 0..samples {
            let (c, t) = self.canon.canon_with_shift(xs[(i % 1024) as usize]);
            acc ^= c.wrapping_add(t as u64);
        }
        let ns = start.elapsed().as_nanos() as f64 / samples as f64;
        std::hint::black_box(acc);
        ns
    }

    pub fn cost(&self) -> TableCost {
        TableCost {
            kind: "frobenius_folded",
            entries: self.entries,
            group_ops: self.build_ops,
            wall_ns: self.build_wall_ns,
            native: vec![
                ("canonicalisations", self.build_canonicalisations),
                ("frobenius_maps", self.build_frobenius_maps),
                ("lookups", self.build_lookups),
                ("pair_table_representatives", self.representatives),
            ],
        }
    }
}

/// Which decomposition oracle a variant uses.
pub enum Oracle<'a> {
    /// Semaev `S₃` as a quadratic in the second abscissa: one square
    /// root per base abscissa per target (`m = 2`, prime).
    SemaevS3Roots,
    /// `R − P_i ∈ F` for every signed base point (`m = 2`).
    Subtract,
    /// Meet in the middle: a pair table probed once per target (`m = 2`)
    /// or once per `R − P_i` (`m = 3`).
    Mitm { table: &'a PairTable, m: u32 },
    /// Meet in the middle on the Frobenius-folded table (Koblitz).
    MitmFrobenius {
        table: &'a FrobeniusPairTable,
        m: u32,
    },
    /// Semaev `S₄` pairs-and-solve over a subspace (`m = 3`, binary).
    SemaevS4 { oracle: &'a SubspaceOracle },
}

impl Oracle<'_> {
    pub fn name(&self) -> String {
        match self {
            Oracle::SemaevS3Roots => "semaev_s3_roots".into(),
            Oracle::Subtract => "direct_subtraction".into(),
            Oracle::Mitm { m, .. } => format!("meet_in_the_middle_m{m}"),
            Oracle::MitmFrobenius { m, .. } => format!("meet_in_the_middle_m{m}_frobenius_folded"),
            Oracle::SemaevS4 { .. } => "semaev_s4_pairs_and_solve".into(),
        }
    }
    pub fn summands(&self) -> u32 {
        match self {
            Oracle::SemaevS3Roots | Oracle::Subtract => 2,
            Oracle::Mitm { m, .. } | Oracle::MitmFrobenius { m, .. } => *m,
            Oracle::SemaevS4 { .. } => 3,
        }
    }
    /// The table this oracle probes, as a cost to fold into the
    /// factor-base phase.
    pub fn table_cost(&self) -> Option<TableCost> {
        match self {
            Oracle::Mitm { table, .. } => Some(table.cost()),
            Oracle::MitmFrobenius { table, .. } => Some(table.cost()),
            _ => None,
        }
    }
}

/// Native counters of the oracle, per phase.
#[derive(Clone, Copy, Debug, Default)]
pub struct OracleCounters {
    pub lookups: u64,
    pub sqrt_solves: u64,
    pub inversions: u64,
    pub s4_pairs: u64,
    pub s4_hits: u64,
    pub lift_failures: u64,
    /// Algebraic systems the solver decided satisfiable none of whose
    /// solutions lifted to a relation over the base — twist solutions,
    /// which a summation polynomial cannot tell from curve points.
    /// Counted apart from `lift_failures`, which is per solution.
    pub unliftable_systems: u64,
    /// Frobenius-orbit canonicalisations of a target abscissa.
    pub canonicalisations: u64,
    /// Folded-table hits whose recovered pair summed to neither `±R`;
    /// a rotation-direction bug would show here, so it must stay zero.
    pub frobfold_mismatches: u64,
}

/// Resolve the signs of a witness of abscissae: which points above them
/// sum to the target.  Costs at most `2·2^m` additions.  `None` when no
/// choice of signs sums to the target, or when an abscissa has no point
/// in the base: the witness does not lift, and a pipeline must not turn
/// it into a relation.
pub(crate) fn lift_abscissae<G: CountedGroup>(
    g: &G,
    fb: &FactorBase<G::Elt>,
    ops: &mut GroupOps,
    xs: &[u64],
    target: G::Elt,
) -> Option<Vec<usize>> {
    let mut choices: Vec<&Vec<usize>> = Vec::with_capacity(xs.len());
    for x in xs {
        choices.push(fb.x_index.get(x)?);
    }
    let mut current = vec![0usize; xs.len()];
    loop {
        let mut acc = g.identity();
        for (k, &c) in current.iter().enumerate() {
            acc = g.add(ops, acc, fb.points[choices[k][c]]);
        }
        if acc == target {
            return Some(
                current
                    .iter()
                    .enumerate()
                    .map(|(k, &c)| choices[k][c])
                    .collect(),
            );
        }
        // Next combination.
        let mut k = 0;
        loop {
            if k == current.len() {
                return None;
            }
            current[k] += 1;
            if current[k] < choices[k].len() {
                break;
            }
            current[k] = 0;
            k += 1;
        }
    }
}

/// Run one oracle on one target: indices of a decomposition, or `None`.
fn decompose_prime(
    curve: &PrimeCurve,
    fb: &FactorBase<PrimePoint>,
    oracle: &Oracle,
    ops: &mut GroupOps,
    ctr: &mut OracleCounters,
    target: PrimePoint,
) -> Option<Vec<usize>> {
    match oracle {
        Oracle::SemaevS3Roots => {
            let p = curve.p;
            let xr = target.x;
            for &xi in &fb.abscissa_list {
                let (qa, qb, qc) = semaev_s3_quadratic(curve, xr, xi);
                let mut candidates: [u64; 2] = [u64::MAX; 2];
                if qa == 0 {
                    if qb == 0 {
                        continue;
                    }
                    ctr.inversions += 1;
                    let Some(inv) = invmod(qb, p) else {
                        continue;
                    };
                    candidates[0] = mulmod(submod(0, qc, p), inv, p);
                } else {
                    let disc = submod(mulmod(qb, qb, p), mulmod(4, mulmod(qa, qc, p), p), p);
                    ctr.sqrt_solves += 1;
                    let Some(s) = curve.sqrt(disc) else {
                        continue;
                    };
                    ctr.inversions += 1;
                    let Some(inv) = invmod(mulmod(2, qa, p), p) else {
                        continue;
                    };
                    candidates[0] = mulmod(addmod(submod(0, qb, p), s, p), inv, p);
                    candidates[1] = mulmod(submod(submod(0, qb, p), s, p), inv, p);
                }
                for xj in candidates {
                    if xj == u64::MAX {
                        continue;
                    }
                    if !fb.x_index.contains_key(&xj) {
                        continue;
                    }
                    ctr.lookups += 1;
                    if let Some(w) = lift_abscissae(curve, fb, ops, &[xi, xj], target) {
                        return Some(w);
                    }
                    ctr.lift_failures += 1;
                }
            }
            None
        }
        Oracle::Subtract => {
            for i in 0..fb.points.len() {
                let s = curve.add(ops, target, curve.neg(fb.points[i]));
                ctr.lookups += 1;
                if let Some(&j) = fb.point_index.get(&curve.key(&s)) {
                    return Some(vec![i, j]);
                }
            }
            None
        }
        Oracle::Mitm { table, m } => decompose_mitm(curve, fb, table, *m, ops, ctr, target),
        Oracle::MitmFrobenius { .. } | Oracle::SemaevS4 { .. } => None,
    }
}

/// Meet in the middle on a built pair table: one probe for `m = 2`,
/// one `R − P_i` and probe per signed base point for `m = 3`.
pub fn decompose_mitm<G: CountedGroup>(
    g: &G,
    fb: &FactorBase<G::Elt>,
    table: &PairTable,
    m: u32,
    ops: &mut GroupOps,
    ctr: &mut OracleCounters,
    target: G::Elt,
) -> Option<Vec<usize>> {
    match m {
        2 => table
            .probe(g, fb, ops, &mut ctr.lookups, target)
            .map(|(i, j)| vec![i, j]),
        3 => {
            for i in 0..fb.points.len() {
                let s = g.add(ops, target, g.neg(fb.points[i]));
                if g.is_identity(&s) {
                    continue;
                }
                if let Some((j, k)) = table.probe(g, fb, ops, &mut ctr.lookups, s) {
                    return Some(vec![i, j, k]);
                }
            }
            None
        }
        _ => None,
    }
}

/// Meet in the middle on the Frobenius-folded table: the same loop as
/// [`decompose_mitm`] with the folded probe.
pub fn decompose_mitm_frobenius(
    g: &BinaryGroup,
    fb: &FactorBase<FastPoint>,
    table: &FrobeniusPairTable,
    m: u32,
    ops: &mut GroupOps,
    ctr: &mut OracleCounters,
    target: FastPoint,
) -> Option<Vec<usize>> {
    match m {
        2 => table
            .probe(g, fb, ops, ctr, target)
            .map(|(i, j)| vec![i, j]),
        3 => {
            for i in 0..fb.points.len() {
                let s = g.add(ops, target, g.neg(fb.points[i]));
                if g.is_identity(&s) {
                    continue;
                }
                if let Some((j, k)) = table.probe(g, fb, ops, ctr, s) {
                    return Some(vec![i, j, k]);
                }
            }
            None
        }
        _ => None,
    }
}

fn decompose_binary(
    inst: &BinaryInstance,
    fb: &FactorBase<FastPoint>,
    oracle: &Oracle,
    ops: &mut GroupOps,
    ctr: &mut OracleCounters,
    target: FastPoint,
) -> Option<Vec<usize>> {
    let g = BinaryGroup(&inst.fast);
    match oracle {
        Oracle::Mitm { table, m } => decompose_mitm(&g, fb, table, *m, ops, ctr, target),
        Oracle::MitmFrobenius { table, m } => {
            decompose_mitm_frobenius(&g, fb, table, *m, ops, ctr, target)
        }
        Oracle::Subtract => {
            for i in 0..fb.points.len() {
                let s = g.add(ops, target, g.neg(fb.points[i]));
                ctr.lookups += 1;
                if let Some(&j) = fb.point_index.get(&s.pack()) {
                    return Some(vec![i, j]);
                }
            }
            None
        }
        Oracle::SemaevS4 { oracle } => {
            let (witness, pairs) = oracle.decompose(target.x, &inst.gf);
            ctr.s4_pairs += pairs;
            let xs = witness?;
            ctr.s4_hits += 1;
            match lift_abscissae(&g, fb, ops, &xs, target) {
                Some(w) => Some(w),
                None => {
                    ctr.lift_failures += 1;
                    None
                }
            }
        }
        Oracle::SemaevS3Roots => None,
    }
}

