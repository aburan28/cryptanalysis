/// The unit's conversion ratios, pinned in the repository.
///
/// Through Round 3 every factor above was measured on the host at the
/// start of each run, and the *ratios* to `ns_per_add` then drifted by a
/// median of `1.08` and up to `3.70` between runs on one machine.  That
/// repriced rows which had done identical native work by up to eight per
/// cent and put a floor under every cross-run comparison: 111 of 166
/// rows in the Round-3 comparison moved without an operation changing.
///
/// `AGENTS.md` §6 says operation counts are the metric "because they
/// survive hardware".  A conversion re-measured per run does not, so the
/// ratios now come from `docs/ic/calibration.json`, compiled in here.
/// The measured factors are still taken and still reported — they are
/// the wall-clock practicality note, and they say whether the host has
/// changed — but they no longer price anything.
const PINNED_CALIBRATION: &str = include_str!("../../docs/ic/calibration.json");

/// Ratios for one instance, and which units had none.
#[derive(Clone, Debug, Default, Serialize)]
pub struct PinOutcome {
    /// Units priced at a ratio from the repository.
    pub pinned: Vec<String>,
    /// Units with no entry, left at the host's measured ratio.
    pub measured: Vec<String>,
}

/// The pinned ratios for `regime/instance`, or `None` when the table has
/// no entry for it — a new size or a freshly generated curve.
fn pinned_ratios(
    regime: &str,
    instance: &str,
) -> Option<serde_json::Map<String, serde_json::Value>> {
    let doc: serde_json::Value = serde_json::from_str(PINNED_CALIBRATION).ok()?;
    let row = doc.get("instances")?.get(format!("{regime}/{instance}"))?;
    Some(row.as_object()?.clone())
}

impl Calibration {
    /// Group-addition equivalents of `count` native units at
    /// `ns_per_unit`.
    pub fn gae(&self, count: u64, ns_per_unit: f64) -> f64 {
        if self.ns_per_add <= 0.0 {
            return count as f64;
        }
        count as f64 * ns_per_unit / self.ns_per_add
    }

    /// Replace the measured factors with the repository's pinned ratios.
    ///
    /// Every factor is stored as nanoseconds, and [`Calibration::gae`]
    /// divides by `ns_per_add`, so writing `ratio · ns_per_add` makes the
    /// conversion exactly the pinned ratio whatever the host measured.
    /// A unit the table does not carry keeps its measured value and is
    /// named in the outcome, so a row priced the old way says so.
    pub fn pin(&mut self, regime: &str, instance: &str) -> PinOutcome {
        let mut out = PinOutcome::default();
        let table = pinned_ratios(regime, instance);
        let add = self.ns_per_add;
        let apply = |name: &str, slot: &mut Option<f64>, out: &mut PinOutcome| match table
            .as_ref()
            .and_then(|t| t.get(name))
            .and_then(serde_json::Value::as_f64)
        {
            Some(ratio) => {
                *slot = Some(ratio * add);
                out.pinned.push(name.to_string());
            }
            None => {
                if slot.is_some() {
                    out.measured.push(name.to_string());
                }
            }
        };
        let mut double = Some(self.ns_per_double);
        apply("ns_per_double", &mut double, &mut out);
        self.ns_per_double = double.unwrap_or(self.ns_per_double);
        let mut lookup = Some(self.ns_per_lookup);
        apply("ns_per_lookup", &mut lookup, &mut out);
        self.ns_per_lookup = lookup.unwrap_or(self.ns_per_lookup);
        let mut row_op = Some(self.ns_per_row_op);
        apply("ns_per_row_op", &mut row_op, &mut out);
        self.ns_per_row_op = row_op.unwrap_or(self.ns_per_row_op);
        for (name, slot) in [
            ("ns_per_sqrt", &mut self.ns_per_sqrt),
            ("ns_per_as_solve", &mut self.ns_per_as_solve),
            ("ns_per_s4_pair", &mut self.ns_per_s4_pair),
            ("ns_per_word_xor", &mut self.ns_per_word_xor),
            ("ns_per_legendre", &mut self.ns_per_legendre),
            ("ns_per_inversion", &mut self.ns_per_inversion),
            ("ns_per_frobenius", &mut self.ns_per_frobenius),
            ("ns_per_canon", &mut self.ns_per_canon),
        ] {
            apply(name, slot, &mut out);
        }
        self.pinned_units = out.pinned.clone();
        out
    }

    /// Whether `unit` (a field name such as `ns_per_word_xor`) carries
    /// the repository's pinned ratio rather than this host's
    /// measurement.
    pub fn is_pinned(&self, unit: &str) -> bool {
        self.pinned_units.iter().any(|u| u == unit)
    }
}

/// `√(πr/2A)`: expected operations of a generic collision search on a
/// group of order `r` with `A` usable automorphisms.
pub fn generic_floor_ops(r: f64, automorphisms: f64) -> f64 {
    (std::f64::consts::PI * r / (2.0 * automorphisms)).sqrt()
}

/// The same floor in the unit: `√(π/2A)`.
pub fn generic_floor_s(automorphisms: f64) -> f64 {
    (std::f64::consts::PI / (2.0 * automorphisms)).sqrt()
}

/// `C(n, k)` as a float, for the counting ceiling.
fn binomial_f64(n: f64, k: u32) -> f64 {
    let mut acc = 1.0f64;
    for i in 0..k {
        acc *= (n - i as f64) / (i as f64 + 1.0);
    }
    acc.max(0.0)
}

/// Upper bound on the probability that a uniform target of a space of
/// size `space` is an `m`-sum of `signed_points` base points:
/// `min(1, C(F + m − 1, m) / space)`.
pub fn decomposition_probability_ceiling(signed_points: u64, m: u32, space: f64) -> f64 {
    let sums = binomial_f64(signed_points as f64 + m as f64 - 1.0, m);
    (sums / space).min(1.0)
}

/// Fewest targets that can yield `columns + 1` relations under the
/// counting ceiling.
pub fn trials_floor(columns: u64, signed_points: u64, m: u32, space: f64) -> f64 {
    (columns as f64 + 1.0) / decomposition_probability_ceiling(signed_points, m, space)
}

/// **The shape law of the pair-table family**: what the best member of
/// it costs, and at which base size.
///
/// Every two-summand row on this ledger pays the same two things.  The
/// table is one entry per pair up to the fold, `F²/4a` additions with
/// `a = 1` for the negation fold and `a = n` when the Frobenius folds it
/// too.  The relations are `K/2` rows — a two-summand row is an edge on
/// the `K = F/2a` columns, and a random multigraph acquires its first
/// cycle at about half as many edges as vertices, which is what closes
/// the elimination — at `1/p` targets each, `p = C(F+1,2)/#E ≈ F²/2#E`,
/// and at least one group operation per target.  So
///
/// ```text
///     ops(F) = F²/(4t) + c·#E/(2kF),   minimal at F = (c·#E·t/k)^{1/3}
///     ops    = 0.75·(c·#E·t/k)^{2/3} / t
/// ```
///
/// with `c` the group operations a fresh target costs (`c = 1` for a
/// walk step, `c ≈ 2·1.5·log₂ r` for `[a]G + [b]Q`), `t` the **table
/// fold** (one entry per pair up to negation is `t = 1`; up to `⟨σ, −1⟩`
/// is `t = n`) and `k` the **column fold** (one column per abscissa is
/// `k = 1`, one per signed Frobenius orbit is `k = n`, so `K = F/2k`).
/// The two are independent: a Koblitz row can fold its columns and not
/// its table.  In the unit, with `c = 1`:
///
/// ```text
///     S_family = 0.75 · (#E·t/k)^{2/3} / (t · √r)
/// ```
///
/// which is `Θ(r^{1/6})` on a prime-order curve: no choice of base size
/// escapes it, and every constant this repository can tune lives inside
/// the `0.75`.  It is a model of the family, not a theorem about the
/// problem — the relation count is an expectation over the cycle
/// structure, so an individual row can land under it — and the note
/// reports it as such next to the generic floor, which is a bound.
pub fn family_optimum_s(group_order: f64, r: f64, table_fold: f64, column_fold: f64) -> f64 {
    0.75 * (group_order * table_fold / column_fold).powf(2.0 / 3.0) / (table_fold * r.sqrt())
}

/// The base size that attains [`family_optimum_s`]: `(#E·t/k)^{1/3}`
/// signed points.
pub fn family_optimum_base(group_order: f64, table_fold: f64, column_fold: f64) -> f64 {
    (group_order * table_fold / column_fold).cbrt()
}

/// **The exact counting ceiling, from the base's cofactor classes.**
///
/// With `#E = h·r` and `gcd(h, r) = 1`, a point lies in the order-`r`
/// subgroup exactly when `[r]P = O`, and `[r]` is a homomorphism, so a
/// sum of base points lands in the subgroup exactly when its summands'
/// classes `[r]P_i` cancel.  The subgroup's `m`-sums are therefore at
/// most the `m`-multisets of base points with class-sum zero, `N₀`, and a
/// uniform target of the subgroup decomposes with probability at most
/// `min(1, N₀/r)`.  On a base whose classes are spread evenly that is the
/// uniform `C(F+m−1, m)/#E`; on a base confined to a proper subgroup it
/// is larger by the index, which the uniform bound cannot see.
///
/// Returns the number of distinct classes and the ceiling; `None` when
/// the classes are too many to enumerate (`m = 3` walks class pairs) or
/// `m ∉ {2, 3}`.  The scalar multiplications are a bound's cost, not the
/// method's, and are not charged to any phase.
pub fn exact_decomposition_ceiling<G: CountedGroup>(
    g: &G,
    points: &[G::Elt],
    r: u64,
    m: u32,
) -> Option<(u64, f64)> {
    let mut ops = GroupOps::default();
    let mut index: FastMap<usize> = fast_map(64);
    let mut classes: Vec<G::Elt> = Vec::new();
    let mut counts: Vec<f64> = Vec::new();
    for &p in points {
        let c = g.mul(&mut ops, p, r);
        let next = classes.len();
        let idx = *index.entry(g.key(&c)).or_insert(next);
        if idx == next {
            classes.push(c);
            counts.push(0.0);
        }
        counts[idx] += 1.0;
        if classes.len() > 65_536 {
            return None;
        }
    }
    let cc = classes.len();
    let find = |q: &G::Elt| index.get(&g.key(q)).copied();
    let n0 = match m {
        2 => {
            let mut acc = 0.0;
            for c1 in 0..cc {
                let Some(c2) = find(&g.neg(classes[c1])) else {
                    continue;
                };
                if c2 < c1 {
                    continue;
                }
                acc += if c1 == c2 {
                    binomial_f64(counts[c1] + 1.0, 2)
                } else {
                    counts[c1] * counts[c2]
                };
            }
            acc
        }
        3 => {
            if cc > 4096 {
                return None;
            }
            let mut acc = 0.0;
            for c1 in 0..cc {
                for c2 in c1..cc {
                    let s = g.add(&mut ops, classes[c1], classes[c2]);
                    let Some(c3) = find(&g.neg(s)) else {
                        continue;
                    };
                    if c3 < c2 {
                        continue;
                    }
                    acc += if c1 == c2 && c2 == c3 {
                        binomial_f64(counts[c1] + 2.0, 3)
                    } else if c1 == c2 {
                        binomial_f64(counts[c1] + 1.0, 2) * counts[c3]
                    } else if c2 == c3 {
                        counts[c1] * binomial_f64(counts[c2] + 1.0, 2)
                    } else {
                        counts[c1] * counts[c2] * counts[c3]
                    };
                }
            }
            acc
        }
        _ => return None,
    };
    Some((cc as u64, (n0 / r as f64).min(1.0)))
}

/// Cost of one phase: what it did (exact), what it took (wall) and what
/// it comes to in the unit (converted).
#[derive(Clone, Debug, Default, Serialize)]
pub struct PhaseCost {
    pub wall_ns: u64,
    pub group_ops: GroupOps,
    /// Native counters by name: `sqrt_solves`, `as_solves`, `s4_pairs`,
    /// `lookups`, `row_ops`, `abscissae_scanned`, `trials`, …
    pub native: std::collections::BTreeMap<String, u64>,
    /// Group-addition equivalents after conversion.
    pub gae: f64,
}

impl PhaseCost {
    /// Add `by` to the native counter `name`, creating it at zero.
    pub fn count(&mut self, name: &str, by: u64) {
        *self.native.entry(name.to_string()).or_insert(0) += by;
    }
    /// Read a native counter, zero when it was never touched.
    pub fn get(&self, name: &str) -> u64 {
        self.native.get(name).copied().unwrap_or(0)
    }
}

