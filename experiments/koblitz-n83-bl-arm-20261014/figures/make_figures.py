#!/usr/bin/env python3
"""Lay out the recorded positive-control counts as a pgfplots figure, and build every figure.

Reads smoke/control/*/control.json (recorded step counts; nothing is recomputed
except the model values the protocol freezes, read from the same records),
writes figures/positive_control.dat and positive_control.tex, then runs
pdflatex on design.tex and positive_control.tex and renders 150 dpi PNGs.
"""

import json
import subprocess
from pathlib import Path

HERE = Path(__file__).resolve().parent
EXPERIMENT = HERE.parent


def control_rows():
    rows = []
    for path in sorted((EXPERIMENT / "smoke/control").glob("*/control.json")):
        record = json.loads(path.read_text())
        plain = record["plain"]
        for entry in record["bl"]:
            rows.append({
                "label": "%s P=2e%d" % (record["id"].replace("pc", "n").replace("-", " "),
                                       entry["stop_steps"].bit_length() - 1),
                "tick": "%s $P=2^{%d}$" % (record["id"].replace("pc", "n").replace("-", " "),
                                          entry["stop_steps"].bit_length() - 1),
                "plain": plain["mean_steps"], "plain_lo": plain["ci95"][0], "plain_hi": plain["ci95"][1],
                "plain_model": plain["predicted_steps"],
                "bl": entry["mean_steps"], "bl_lo": entry["ci95"][0], "bl_hi": entry["ci95"][1],
                "bl_model": entry["predicted_steps"],
                "speedup": entry["speedup_over_plain"], "speedup_model": entry["speedup_predicted"],
            })
    return rows


def write_plot(rows):
    data = ["i label plain plainlo plainhi plainmodel bl bllo blhi blmodel speedup speedupmodel"]
    for i, row in enumerate(rows):
        data.append("%d {%s} %.1f %.1f %.1f %.1f %.1f %.1f %.1f %.1f %.4f %.4f" % (
            i, row["label"].replace(" ", "_"), row["plain"], row["plain_lo"], row["plain_hi"], row["plain_model"],
            row["bl"], row["bl_lo"], row["bl_hi"], row["bl_model"], row["speedup"], row["speedup_model"]))
    (HERE / "positive_control.dat").write_text("\n".join(data) + "\n")
    ticks = ",".join("{%s}" % row["tick"] for row in rows)
    tex = r"""%% Editable source for positive_control.pdf, generated by make_figures.py from smoke/control/*/control.json.
\documentclass[border=6pt]{standalone}
\usepackage[T1]{fontenc}
\usepackage{pgfplots}
\pgfplotsset{compat=1.17}
\begin{document}
\sffamily\footnotesize
\begin{tikzpicture}
\begin{groupplot}[group style={group size=2 by 1,horizontal sep=18mm},
  width=78mm,height=62mm,xtick={0,...,7},xticklabels={%(ticks)s},
  x tick label style={rotate=50,anchor=east,font=\sffamily\scriptsize},
  tick label style={font=\sffamily\scriptsize},legend style={font=\sffamily\scriptsize,cells={anchor=west}}]
\nextgroupplot[ymode=log,ylabel={mean online walk steps (256 targets)},ymin=1500,ymax=300000,xmin=-0.5,xmax=7.5,
  title={Steps: measured (95\%% bootstrap) and model},legend columns=2,
  legend style={at={(0.5,1.0)},anchor=north,draw=none,fill=white,fill opacity=0.8,text opacity=1}]
\addplot+[only marks,mark=*,color=gray!70!black,error bars/.cd,y dir=both,y explicit]
  table[x=i,y=plain,y error plus expr=\thisrow{plainhi}-\thisrow{plain},y error minus expr=\thisrow{plain}-\thisrow{plainlo}]{positive_control.dat};
\addlegendentry{plain rho, measured}
\addplot+[only marks,mark=o,mark size=3pt,color=gray!70!black] table[x=i,y=plainmodel]{positive_control.dat};
\addlegendentry{plain rho, model}
\addplot+[only marks,mark=square*,color=green!50!black,error bars/.cd,y dir=both,y explicit]
  table[x=i,y=bl,y error plus expr=\thisrow{blhi}-\thisrow{bl},y error minus expr=\thisrow{bl}-\thisrow{bllo}]{positive_control.dat};
\addlegendentry{BL online, measured}
\addplot+[only marks,mark=square,mark size=3pt,color=green!50!black] table[x=i,y=blmodel]{positive_control.dat};
\addlegendentry{BL online, model}
\nextgroupplot[ylabel={BL speedup over plain rho: measured / model},title={The gate: inside [0.8, 1.25] at every size},
  ymin=0.6,ymax=1.4,xmin=-0.5,xmax=7.5]
\addplot[dashed,red!70!black,domain=-0.5:7.5,samples=2] {0.8};
\addplot[dashed,red!70!black,domain=-0.5:7.5,samples=2] {1.25};
\addplot[densely dotted,gray,domain=-0.5:7.5,samples=2] {1};
\addplot+[only marks,mark=*,color=blue!70!black] table[x=i,y expr=\thisrow{speedup}/\thisrow{speedupmodel}]{positive_control.dat};
\end{groupplot}
\end{tikzpicture}
\end{document}
""" % {"ticks": ticks}
    tex = tex.replace(r"\begin{tikzpicture}", r"\usepgfplotslibrary{groupplots}" "\n" r"\begin{tikzpicture}", 1)
    (HERE / "positive_control.tex").write_text(tex)


RUN = "run_github_38689817618"


def write_result():
    """Per-target online ms of the three arms, from the run's raw rows."""
    rows = [json.loads(line) for line in (EXPERIMENT / RUN / "panel/runs.jsonl").read_text().splitlines()]
    cell = {}
    for row in rows:
        if row["status"] == "valid" and row["arm"] in ("ic", "bl", "rho"):
            label = row["point_id"] if row["panel"] == "F" else "q0b%d" % row["block"]
            cell.setdefault(label, {})[row["arm"]] = float(row["fields"]["online_ms"])
    order = ["w%02d" % w for w in range(16)] + ["q0b%d" % b for b in range(4)]
    lines = ["i label ic bl rho"]
    for i, label in enumerate(order):
        c = cell[label]
        lines.append("%d %s %.6f %.6f %.6f" % (i, label, c["ic"], c["bl"], c["rho"]))
    (HERE / "result.dat").write_text("\n".join(lines) + "\n")
    result = json.loads((EXPERIMENT / RUN / "result.json").read_text())
    F = result["F"]
    ticks = ",".join("{%s}" % label for label in order)
    tex = r"""%% Editable source for result.pdf, generated by make_figures.py from RUN/panel/runs.jsonl and result.json.
\documentclass[border=6pt]{standalone}
\usepackage[T1]{fontenc}
\usepackage{pgfplots}
\pgfplotsset{compat=1.17}
\begin{document}
\sffamily\footnotesize
\begin{tikzpicture}
\begin{axis}[width=150mm,height=72mm,ymode=log,xtick={0,...,19},xticklabels={%(ticks)s},
  x tick label style={rotate=60,anchor=east,font=\sffamily\scriptsize},ymin=0.5,ymax=20000,xmin=-0.6,xmax=19.6,
  ylabel={online interval (ms, one process per point)},
  title={Run 38689817618, rT770: IC/BL %(icbl).0f [%(icbl0).0f, %(icbl1).0f], rho/BL %(rhobl).0f [%(rhobl0).0f, %(rhobl1).0f], rho/IC %(rhoic).2f [%(rhoic0).2f, %(rhoic1).2f] (16 fresh points, mean ratios, 95\%% bootstrap)},
  title style={font=\sffamily\scriptsize},legend style={font=\sffamily\scriptsize,at={(0.5,-0.22)},anchor=north,legend columns=3}]
\addplot[draw=none,fill=gray!12,forget plot] coordinates {(15.5,0.5) (19.6,0.5) (19.6,20000) (15.5,20000)} \closedcycle;
\addplot+[only marks,mark=triangle*,mark size=2.5pt,color=orange!80!black] table[x=i,y=ic]{result.dat};
\addlegendentry{index calculus (cached logs)}
\addplot+[only marks,mark=*,color=blue!70!black] table[x=i,y=rho]{result.dat};
\addlegendentry{single-target rho (rT770)}
\addplot+[only marks,mark=square*,color=green!50!black] table[x=i,y=bl]{result.dat};
\addlegendentry{Bernstein--Lange online}
\node[font=\sffamily\scriptsize,anchor=north] at (axis cs:17.5,15000) {Q0, blocks 0--3};
\end{axis}
\end{tikzpicture}
\end{document}
""" % {"ticks": ticks, "icbl": F["ic_over_bl"]["value"], "icbl0": F["ic_over_bl"]["ci95"][0],
       "icbl1": F["ic_over_bl"]["ci95"][1], "rhobl": F["rho_over_bl"]["value"],
       "rhobl0": F["rho_over_bl"]["ci95"][0], "rhobl1": F["rho_over_bl"]["ci95"][1],
       "rhoic": F["rho_over_ic"]["value"], "rhoic0": F["rho_over_ic"]["ci95"][0],
       "rhoic1": F["rho_over_ic"]["ci95"][1]}
    (HERE / "result.tex").write_text(tex)


def build(name):
    subprocess.run(["pdflatex", "-interaction=nonstopmode", "-halt-on-error", name + ".tex"], cwd=HERE,
                   check=True, stdout=subprocess.DEVNULL)
    subprocess.run(["pdftoppm", "-png", "-r", "150", "-singlefile", name + ".pdf", name], cwd=HERE, check=True)
    for suffix in (".aux", ".log"):
        (HERE / (name + suffix)).unlink(missing_ok=True)


def main():
    write_plot(control_rows())
    write_result()
    for name in ("design", "positive_control", "result"):
        build(name)
    print("built", [p.name for p in sorted(HERE.glob("*.p*"))])


if __name__ == "__main__":
    main()
