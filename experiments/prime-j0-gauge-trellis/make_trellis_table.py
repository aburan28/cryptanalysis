#!/usr/bin/env python3
"""Generate the exact three-state unit-gauge DP transition table."""

import argparse
from pathlib import Path


HERE = Path(__file__).resolve().parent
OUTPUT = HERE.parents[1] / "src/generated/tau_gauge_trellis.h"


def local_cost(pattern):
    powers = (pattern,) if pattern < 3 else ((pattern - 3) // 3, (pattern - 3) % 3)
    return [sum((power + gauge) % 3 != 0 for power in powers)
            for gauge in range(3)]


def encode(state, pattern, first):
    prior = [(state >> (2 * gauge)) & 3 for gauge in range(3)]
    local = local_cost(pattern)
    next_cost = []
    back = []
    for gauge in range(3):
        if first:
            best, previous = 0, 0
        else:
            best, previous = min((prior[p] + (p != gauge), p) for p in range(3))
        next_cost.append(best + local[gauge])
        back.append(previous)
    delta = min(next_cost)
    offsets = [value - delta for value in next_cost]
    assert max(offsets) <= 3 and delta <= 7
    next_state = sum(offset << (2 * gauge) for gauge, offset in enumerate(offsets))
    back_code = sum(previous << (2 * gauge) for gauge, previous in enumerate(back))
    return next_state | (delta << 6) | (back_code << 9)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="verify the checked-in table")
    args = parser.parse_args()
    starts = [encode(0, pattern, True) for pattern in range(12)]
    steps = [[encode(state, pattern, False) for pattern in range(12)]
             for state in range(64)]
    lines = [
        "/* Generated by experiments/prime-j0-gauge-trellis/make_trellis_table.py. */",
        "#ifndef CA_TAU_GAUGE_TRELLIS_H",
        "#define CA_TAU_GAUGE_TRELLIS_H",
        "#include <stdint.h>",
        "/* bits 0..5: next normalized costs; 6..8: minimum increment;",
        " * bits 9..14: predecessor gauge for each next gauge. */",
        "static const uint16_t ca_tau_gauge_start[12] = {",
        "    " + ", ".join(f"0x{value:04x}" for value in starts),
        "};",
        "static const uint16_t ca_tau_gauge_step[64][12] = {",
    ]
    for row in steps:
        lines.append("    {" + ", ".join(f"0x{value:04x}" for value in row) + "},")
    lines.extend(["};", "#endif /* CA_TAU_GAUGE_TRELLIS_H */", ""])
    output = "\n".join(lines)
    if args.check:
        if OUTPUT.read_text() != output:
            raise SystemExit("generated trellis table differs")
        print(f"verified {OUTPUT}")
    else:
        OUTPUT.write_text(output)
        print(OUTPUT)


if __name__ == "__main__":
    main()
