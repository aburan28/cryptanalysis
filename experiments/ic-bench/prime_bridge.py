def normalize(r,host=None,run_number=1):
    require(r); curve_id,curve=curve_record(r); wid,wrec=workload(r,curve_id); cid,man=candidate(r,curve)
    l=r["logs"]; ds=r["descent"]["per_target"]; q=r["configuration"]
    order=int(r["instance"]["subgroup_order"]); w=int(r["factor_base"]["automorphism_order"])
    shared=int(l["oracle_ops"])+int(l["probe_ops"]); per=[int(d["ops"]) for d in ds]
    target=sum(per); total=shared+target if r["status"]=="complete" else None
    ops={p:0 for p in PHASES}; ops["precompute"]=shared; ops["target_descent"]=target
    walls={p:0 for p in PHASES}; walls["precompute"]=round(float(l["seconds"])*1e9)
    walls["target_descent"]=round(sum(float(d["seconds"]) for d in ds)*1e9)
    wall=max(round(float(r["elapsed_seconds"])*1e9),sum(walls.values()))
    rho=round(float(r["rho"]["expected_steps"])+float(r["rho"]["mean_setup_ops"]))
    floor=round(float(r["rho"]["expected_steps_folded"])+float(r["rho"]["mean_setup_ops"]))
    ps=[]; cum=0; wanted=set(prefixes(len(per)))
    for i,x in enumerate(per,1):
        cum+=x
        if i in wanted:
            ic=shared+cum; br=batch_rho(order,w,i,False); bf=batch_rho(order,w,i,True)
            ps.append({"targets":i,"ic_operations":ic,"shared_operations":shared,
              "target_operations":cum,"mean_target_operations":cum/i,
              "amortized_operations_per_target":ic/i,"independent_rho_operations":i*rho,
              "batch_rho_operations":br,"folded_batch_rho_operations":bf,
              "ic_over_independent_rho":ic/(i*rho),"ic_over_batch_rho":ic/br,
              "ic_over_folded_batch_rho":ic/bf,"shared_fraction":shared/ic})
    env={"max_ops":q["max_ops"],"max_descent_ops":q["max_descent_ops"],
         "rho_max_steps":q["rho_max_steps"],"processes_per_run":1}
    run_id=f"{cid}W{wid}R{run_number}"; status="complete" if r["status"]=="complete" else "error"
    rank=int(l.get("rank",0)); src=sha({"binary_blake3":r["software"].get("binary_blake3"),
                                       "git_commit":r["software"].get("git_commit")})
    receipt={"schema_version":1,"kind":"full_dlp","status":status,"candidate_id":cid,"proposal_id":None,
      "run_id":run_id,"workload_id":wid,
      "workload_series_id":"ICBW1h"+sha({"curve_id":curve_id,"seed":q["seed"],
                                          "target_law":wrec["target_law"]})[:12],
      "pair_block_id":f"W{wid}","source_curve_ref":curve_id,
      "profile_id":f"prime-{r['curve_type']}-b{r['instance']['field_bits']}-t{len(ds)}-s{q['seed']}",
      "isogeny_route_ref":"none","subgroup_order":str(order),
      "counts":{"ordinary_queries":int(l["trials"]),"solved_queries":0,
        "verified_decompositions":int(l["relations"]),"verified_relations":int(l["relations"]),
        "novel_rows":rank,"effective_columns":int(r["factor_base"]["orbits"]),"final_rank":rank,
        "pdp_attempts":0,"pdp_verified":0,"pdp_proved_unsat":0,"pdp_timeout":0,
        "pdp_budget":0,"pdp_error":0,"pdp_lift_rejected":0,"targets":len(ds),
        "targets_verified":sum(bool(d["verified"]) for d in ds),
        "descent_attempts":sum(int(d["trials"]) for d in ds)},
      "phase_operations":ops,"phase_wall_ns":walls,
      "phase_counters":{"precompute":{"prime_oracle_op":int(l["oracle_ops"]),"prime_probe_op":int(l["probe_ops"])},
        "target_descent":{"prime_oracle_op":sum(int(d["oracle_ops"]) for d in ds),
                          "prime_probe_op":sum(int(d["probe_ops"]) for d in ds)}},
      "total_operations":total,"operation_unit":"prime_group_operation",
      "rho_operations":rho,"rho_floor_operations":floor,
      "rho_batch":{"independent_operations":len(ds)*rho,
        "shared_dp_expected_operations":batch_rho(order,w,len(ds),False),
        "folded_shared_dp_expected_operations":batch_rho(order,w,len(ds),True),
        "model":"Kuhn-Struik shared-DP expectation with ca-ic seeding and jump-table charges"},
      "ratio_to_rho":total/rho if total else None,"ratio_to_floor":total/floor if total else None,
      "ratio_to_independent_rho_batch":total/(len(ds)*rho) if total else None,
      "ratio_to_batch_rho":total/batch_rho(order,w,len(ds),False) if total else None,
      "ratio_to_batch_floor":total/batch_rho(order,w,len(ds),True) if total else None,
      "warm":{"k":len(ds),"per_target_operations":per,"target_operations":target,
        "mean_target_operations":target/len(ds),"shared_operations":shared,
        "amortized_operations_per_target":total/len(ds) if total else None,
        "independent_rho_operations":len(ds)*rho,
        "batch_rho_operations":batch_rho(order,w,len(ds),False),
        "folded_batch_rho_operations":batch_rho(order,w,len(ds),True),
        "ic_over_independent_rho":total/(len(ds)*rho) if total else None,
        "ic_over_batch_rho":total/batch_rho(order,w,len(ds),False) if total else None,
        "ic_over_folded_batch_rho":total/batch_rho(order,w,len(ds),True) if total else None,
        "prefixes":ps,"shared":"prime logarithm database precomputation"},
      "verified_scalar":status=="complete","scalar_certificate_ref":f"{run_id}#prime-descents" if status=="complete" else None,
      "descents":[{"expected":d["expected"],"recovered":d["recovered"],"verified":d["verified"],
                   "target":d["target"],"attempts":d["trials"]} for d in ds],
      "wall_ns":wall,"peak_rss_bytes":int(r.get("resources",{}).get("peak_rss_bytes") or 0),
      "provenance":{"workload_fixture_sha256":sha(wrec),"source_sha256":src,
        "host_id":host or platform.node() or "unknown","resource_envelope_id":"ENV1h"+sha(env)[:12],
        "calibration_id":CAL,"binary_blake3":r["software"].get("binary_blake3"),
        "git_commit":r["software"].get("git_commit")},
      "resource_envelope":env,"native_prime_report":r}
    return {"receipt":receipt,"manifest":(cid,man),"workload":(wid,wrec),"curve":(curve_id,curve)}

def write(out_dir,items):
    out_dir.mkdir(parents=True,exist_ok=True)
    with (out_dir/"prime.jsonl").open("w") as fh:
        for x in items: fh.write(canon(x["receipt"])+"\\n")
    for sub,key in (("candidates","manifest"),("workloads","workload"),("curves","curve")):
        d=out_dir/sub; d.mkdir(exist_ok=True)
        for x in items:
            ident,rec=x[key]; p=d/f"{ident}.json"; txt=json.dumps(rec,indent=1,sort_keys=True)+"\\n"
            if p.exists() and p.read_text()!=txt: raise ValueError(f"{p} identity collision")
            p.write_text(txt)
    native=out_dir/"native"; native.mkdir(exist_ok=True)
    for x in items:
        r=x["receipt"]; p=native/f"{r['run_id']}.json"
        p.write_text(json.dumps(r["native_prime_report"],indent=1,sort_keys=True)+"\\n")

def run_cell(binary,cell):
    cmd=[str(binary),"prime","--type",cell["curve_type"],"--bits",str(cell["bits"]),
         "--targets",str(cell["targets"]),"--seed",str(cell["seed"]),"--json"]
    p=subprocess.run(cmd,cwd=ROOT,text=True,capture_output=True)
    if p.returncode: raise RuntimeError(f"{' '.join(cmd)}\\n{p.stderr}\\n{p.stdout}")
    return json.loads(p.stdout)

def main():
    ap=argparse.ArgumentParser(description=__doc__); sub=ap.add_subparsers(dest="cmd",required=True)
    a=sub.add_parser("adapt"); a.add_argument("raw",type=Path); a.add_argument("--out-dir",type=Path,required=True)
    x=sub.add_parser("run"); x.add_argument("--suite",choices=SUITES,default="ci"); x.add_argument("--binary",type=Path,default=BINARY); x.add_argument("--out-dir",type=Path,required=True); x.add_argument("--jobs",type=int,default=1)
    args=ap.parse_args()
    if args.cmd=="adapt":
        raw=json.loads(args.raw.read_text()); items=[normalize(raw)]
    else:
        if args.jobs < 1: raise ValueError("--jobs must be positive")
        cells=SUITES[args.suite]
        with ThreadPoolExecutor(max_workers=args.jobs) as pool:
            raws=list(pool.map(lambda cell: run_cell(args.binary,cell),cells))
        items=[normalize(raw) for raw in raws]
        for item in items:
            rr=item["receipt"]; print(f"{rr['profile_id']}: {rr['status']} total={rr['total_operations']} IC/folded-batch-rho={rr['ratio_to_batch_floor']:.4g}")
    write(args.out_dir,items)
    print(f"wrote {len(items)} normalized prime-field receipt(s) to {args.out_dir}")

if __name__=="__main__": main()
