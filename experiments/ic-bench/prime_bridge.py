def canon(x): return json.dumps(x,sort_keys=True,separators=(",",":"),ensure_ascii=False)
def sha(x): return hashlib.sha256(canon(x).encode()).hexdigest()
def dec(x): return None if x is None else format(x,".17g")
def frozen(x):
    if isinstance(x,float): return dec(x)
    if isinstance(x,list): return [frozen(v) for v in x]
    if isinstance(x,dict): return {k:frozen(v) for k,v in x.items()}
    return x

def batch_rho(r,w,t,folded):
    n=r/w if folded else r; term=1.; series=0.
    for k in range(t):
        series+=term; term*= (2*k+1)/(2*k+2)
    scalar=(3*r.bit_length()+1)//2
    return round(math.sqrt(math.pi*n/2)*series+t*(2*scalar+1)+32*scalar)

def prefixes(k):
    out=[]; n=1
    while n<=k: out.append(n); n*=2
    if k and out[-1]!=k: out.append(k)
    return out

def require(r):
    if r.get("operation")!="prime" or r.get("solver")!="orbit":
        raise ValueError("only ca-ic prime --solver orbit enters the common operation ledger")
    for k in ("instance","configuration","factor_base","logs","descent","software"):
        if not isinstance(r.get(k),dict): raise ValueError(f"prime report missing {k}")
    if not r["descent"].get("per_target"): raise ValueError("prime report has no descents")
    if r.get("rho") is None: raise ValueError("normalized runs require the rho control")

def curve_record(r):
    i=r["instance"]; tag={"generic":"gen","j0":"j0","j1728":"j1728"}[r["curve_type"]]
    rec={"field":{"characteristic":i["p"],"degree":1,"representation":"prime field",
                  "element_encoding":"unsigned decimal integer"},
         "curve":{"model":"short_weierstrass","a":i["a"],"b":i["b"],
                  "group_order":i["group_order"],"subgroup_order":i["subgroup_order"],
                  "cofactor":i["cofactor"],"generator":i["generator"],
                  "target_group":"prime-order subgroup generated by G",
                  "order_certificate":i["order_certificate"]}}
    cid=f"EC1P{i['field_bits']}C{tag}h{sha(rec)[:12]}"
    return cid,{**rec,"curve_id":cid}

def workload(r,cid):
    ds=r["descent"]["per_target"]
    rec={"schema":"ic-bench-prime-workload/1","curve_id":cid,
         "subgroup_order":r["instance"]["subgroup_order"],
         "target_law":"ca-ic GeneratedInstance::targets; deterministic from scaled instance and seed",
         "targets":[{"scalar":d["expected"],"point":d["target"]} for d in ds],
         "target_count":len(ds),"seed":r["configuration"]["seed"],
         "cache_state":"one shared logarithm database; ordered descents may learn"}
    return sha(rec)[:12],rec

