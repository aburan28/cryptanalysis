def candidate_id(params: dict, report: dict, arm: str, fb_digest: str | None) -> str:
    n = params["field"]["degree"]
    b = report["factor_base"]["points"]
    rec = candidate_record(params, report, arm, fb_digest)
    return (f"IC1N{n}Cka{int(params['a'])}fb{b}PDP2f4RCsampleLAgaussTDdirectISO0"
            f"h{sha(rec)[:12]}")


def workload_record(params: dict, report: dict) -> dict:
    return {
        "curve_id": curve_id(params),
        "subgroup_order": params["subgroup_order"],
        "targets": [{"known_log": params["fixture"]["known_log"],
                     "point": params["point"]}],
        "input_law": "synthetic known-answer target [k]G",
        "query_seed": str(params["fixture"]["seed"]),
        "target_count": 1,
        "cache": "cold: fresh process, algebra cache off",
        "max_trials": report["arguments"]["max_trials"],
        "threads": 1,
    }


def run_record(report: dict, arm: str, block: int, fb_digest: str | None) -> dict:
    params = report["parameters"]
    cid = candidate_id(params, report, arm, fb_digest)
    wrec = workload_record(params, report)
    wid = sha(wrec)[:12]
    counts = report["counts"]
    disp = report.get("attempt_dispositions", {})
    stages = {s["stage"] + ":" + s["status"]: s for s in report["stages"]}
    ns = lambda key: int(stages[key]["elapsed_seconds"] * 1e9) if key in stages else None
    wall = int(report["elapsed_seconds"] * 1e9)
    la = int(report["timing_seconds"]["linear_algebra"] * 1e9)
    collection = int(report["timing_seconds"]["relation_collection"] * 1e9)
    fb_ns = ns("factor_base:complete")
    check_ns = ns("verification:pass") or 0
    phase_wall = {k: None for k in analyze.CONTRACT["phase_operations"]}
    phase_wall.update({"isogeny": 0, "precompute": 0, "target_descent": 0,
                       "factor_base": fb_ns, "pdp": collection, "relation_la": la,
                       "recovery_check": check_ns})
    phase_wall["setup"] = max(0, wall - sum(v for v in phase_wall.values() if v))
    return {
        "schema_version": 1,
        "kind": "stage",
        "status": "complete" if report["status"] == "complete" else "error",
        "run_id": f"{cid}W{wid}R{block}",
        "workload_id": wid,
        "pair_block_id": f"block{block}",
        "source_curve_ref": curve_id(params),
        "profile_id": "f4-gpu-20260925",
        "isogeny_route_ref": "none",
        "candidate_id": cid,
        "proposal_id": None,
        "provenance": {
            "workload_fixture_sha256": sha(wrec),
            "source_sha256": sha({p: file_sha(p) for p in SOURCES}),
            "host_id": "cursor-cloud-vm: Intel Xeon (KVM), 4 vCPU, 15 GiB",
            "resource_envelope_id": "taskset -c 0, batch 1, one process at a time",
            "calibration_id": "none: wall-clock nanoseconds only; no calibrated operation unit",
            "binary_blake3": report["software"]["binary_blake3"],
        },
        "counts": {
            "ordinary_queries": counts["trials"],
            "solved_queries": disp.get("RelationFound", 0),
            "verified_decompositions": disp.get("RelationFound", 0),
            "verified_relations": counts["relations"],
            "novel_rows": counts["independent_relations"],
            "effective_columns": counts["columns"] + 1,
            "final_rank": counts["independent_relations"],
            "pdp_attempts": counts["trials"],
            "pdp_verified": disp.get("RelationFound", 0),
            "pdp_proved_unsat": disp.get("Refuted", 0),
            "pdp_timeout": 0,
            "pdp_budget": disp.get("Unknown", 0),
            "pdp_error": disp.get("InvalidModel", 0),
            "pdp_lift_rejected": 0,
            "f4_reductions": counts["f4_reductions"],
            "f4_word_ops": counts["f4_word_ops"],
        },
        "phase_operations": {k: None for k in analyze.CONTRACT["phase_operations"]},
        "phase_wall_ns": phase_wall,
        "phase_notes": "pdp wall includes query generation and relation checks, which "
        "the report does not split out (queries and relation_check are null); relation_la "
        "includes matrix construction (matrix_build is null)",
        "peak_rss_bytes": report["resources"]["peak_rss_bytes"],
        "wall_ns": wall,
        "subgroup_order": params["subgroup_order"],
        "total_operations": None,
        "rho_operations": None,
        "verified_scalar": None,
        "stage_scope": "PDP internal Macaulay kernel inside complete runs",
        "scalar_check": {"expected": report["result"]["expected"],
                         "recovered": report["result"]["recovered"],
                         "verified_by_pipeline": report["result"]["verified"]},
    }


def bootstrap_ratio(ref: list[float], fast: list[float], seed: str) -> dict:
    ratios = [a / b for a, b in zip(ref, fast)]
    logs = [math.log(r) for r in ratios]
    out = {"pairs": len(ratios), "geomean": math.exp(statistics.mean(logs)),
           "ratios": ratios, "ci95": None}
    if len(logs) >= 3:
        rng = random.Random(int(hashlib.sha256(seed.encode()).hexdigest()[:16], 16))
        draws = sorted(math.exp(statistics.mean(rng.choices(logs, k=len(logs))))
                       for _ in range(10000))
        out["ci95"] = [draws[249], draws[9749]]
    return out


def main() -> None:
    receipts = HERE / "receipts"
    digests = {}
    for path in sorted((receipts / "batch").glob("*/f4_batch.json")):
        doc = json.loads(path.read_text())
        digests[doc["curve"]] = doc.get("factor_base_sha256")
    manifests = HERE / "manifests"
    manifests.mkdir(exist_ok=True)
    runs, pairs = [], {}
    for path in sorted((receipts / "e2e").glob("*.json")):
        name = path.stem  # k{a}-n{n}-{arm}-block{b}
        curve, n, arm, block = name.split("-")
        report = json.loads(path.read_text())
        params = report["parameters"]
        digest = digests.get(f"K_{params['a']}/2^{params['field']['degree']}")
        rec = analyze.validate_run(run_record(report, arm, int(block[5:]), digest))
        runs.append(rec)
        pairs.setdefault(curve + n, {}).setdefault(arm, {})[int(block[5:])] = rec
        (manifests / f"{curve_id(params)}.json").write_text(
            json.dumps(curve_record(params), indent=2, sort_keys=True) + "\n")
        (manifests / f"{rec['candidate_id']}.json").write_text(
            json.dumps(candidate_record(params, report, arm, digest), indent=2,
                       sort_keys=True) + "\n")
        (manifests / f"W{rec['workload_id']}.json").write_text(
            json.dumps(workload_record(params, report), indent=2, sort_keys=True) + "\n")
    ids = [r["run_id"] for r in runs]
    assert len(set(ids)) == len(ids), "duplicate run IDs"
    (HERE / "runs.jsonl").write_text("".join(json.dumps(r, sort_keys=True) + "\n" for r in runs))

    summary = {"workloads": {}}
    for key, arms in sorted(pairs.items()):
        blocks = sorted(set(arms.get("reference", {})) & set(arms.get("fast", {})))
        ref = [arms["reference"][b] for b in blocks]
        fast = [arms["fast"][b] for b in blocks]
        same = all(
            r["counts"][c] == f["counts"][c]
            for r, f in zip(ref, fast)
            for c in ("ordinary_queries", "verified_relations", "novel_rows", "pdp_verified",
                      "pdp_proved_unsat", "pdp_budget", "f4_reductions")
        ) and all(r["scalar_check"] == f["scalar_check"] for r, f in zip(ref, fast))
        summary["workloads"][key] = {
            "workload_id": ref[0]["workload_id"] if ref else None,
            "baseline_candidate": ref[0]["candidate_id"] if ref else None,
            "candidate": fast[0]["candidate_id"] if fast else None,
            "identical_counts_and_scalar": same,
            "pdp_wall_ratio": bootstrap_ratio(
                [r["phase_wall_ns"]["pdp"] for r in ref],
                [f["phase_wall_ns"]["pdp"] for f in fast], key + "pdp"),
            "whole_run_wall_ratio": bootstrap_ratio(
                [r["wall_ns"] for r in ref], [f["wall_ns"] for f in fast], key + "wall"),
            "f4_word_ops": {"reference": ref[0]["counts"]["f4_word_ops"] if ref else None,
                            "fast": fast[0]["counts"]["f4_word_ops"] if fast else None},
            "end_to_end_calibrated_speedup": None,
            "S": None,
            "rho_ratio": None,
        }
    stage = {}
    for rep_dir in sorted((receipts / "stage").glob("*-rep*")):
        arm, rep = rep_dir.name.split("-rep")
        for row in json.loads((rep_dir / "stage.json").read_text())["rows"]:
            stage.setdefault(row["curve"] + f" m={row['m']}", {}).setdefault(arm, {})[int(rep)] = row
    summary["stage_ladder"] = {}
    for inst, arms in stage.items():
        reps = sorted(set(arms.get("reference", {})) & set(arms.get("fast", {})))
        keys = ("verdict_digest", "reductions", "infeasible_branches", "propagations",
                "splits", "oversize", "matrix_rows", "matrix_cols", "f4_calls")
        summary["stage_ladder"][inst] = {
            "identical_logical_work": all(arms["reference"][r][k] == arms["fast"][r][k]
                                          for r in reps for k in keys),
            "wall_ratio": bootstrap_ratio([arms["reference"][r]["wall_ns"] for r in reps],
                                          [arms["fast"][r]["wall_ns"] for r in reps], inst),
        }
    summary["validation"] = "every record passed analyze.validate_run"
    summary["source_commit"] = SOURCE_COMMIT
    (HERE / "summary.json").write_text(json.dumps(summary, indent=2, sort_keys=True) + "\n")
    print(json.dumps(summary, indent=2, sort_keys=True))


if __name__ == "__main__":
    main()
