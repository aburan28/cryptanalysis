#!/usr/bin/env python3
"""Candidate IDs, run records and the paired summary for RESULT.md.

Reads the raw reports under receipts/, writes manifests/ (canonical curve,
candidate and workload records), runs.jsonl (one contract record per run,
validated by ../ic-candidate-catalog/analyze.py) and summary.json.

Both candidates are the same `ca-ic run --solver groebner` pipeline built
from one binary; they differ only in the PDP stage's internal Macaulay
kernel (F4_F2_RREF=reference versus the default f4_gf2 kernel with F5), so
the comparison is a PDP-stage comparison embedded in complete, verified
runs.  The pipeline prices no phase in a calibrated operation unit, so the
records are `kind: "stage"` with every operation count and the end-to-end
total `null`, as AGENTS.md requires of an unpriced total.
"""

