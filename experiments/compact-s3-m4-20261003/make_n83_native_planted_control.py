#!/usr/bin/env python3
"""Freeze a four-leaf N83 control inside Q1328's sampled native index.

The target is deliberately planted from two indexed pair states. The native
solver receives only the public target and its exact full-base manifest; it
does not receive leaf coordinates or index positions. This is a correctness
control, not an ordinary-query relation-yield measurement.
"""

from __future__ import annotations

import argparse
import hashlib
import json
from pathlib import Path

from derive_onb_poly_bridge import xor_images
from run_probe import HERE, curves, field, sha

N = 83
INDEX_POSITIONS = (0, 1)


def sampled_state(position, k):
    total = k * k * N
    origin = 0x7E5218AC20261003 % total
    step = 0x9E3779B97F4A7C15 % total
    if not step:
        step = 1
    from math import gcd
    while gcd(step, total) != 1:
        step += 1
    state_id = (origin + position * step) % total
    relative = state_id % N
    pair = state_id // N
    return {"position": position, "state_id": state_id,
            "left_column": pair // k, "right_column": pair % k,
            "relative_frobenius_shift": relative,
            "origin": origin, "step": step}


def freeze():
    ordinary_path = HERE / "native_inputs/n83_manifest.json"
    ordinary = json.loads(ordinary_path.read_text())
    bridge_path = HERE / "field_bridges/n83_onb_poly.json"
    bridge = json.loads(bridge_path.read_text())
    reps_path = HERE / "native_inputs/n83_x_representatives.bin"
    packed = reps_path.read_bytes()
    assert sha(reps_path) == ordinary["representatives_file_sha256"]
    assert len(packed) == 16 * ordinary["representative_count_K"]
    reps_poly = [int.from_bytes(packed[i:i + 16], "little")
                 for i in range(0, len(packed), 16)]
    assert ordinary["proposal_id"] == "Q1328"
    assert ordinary["parent_factor_base_proposal_id"] == "Q1325"
    assert ordinary["curve_id"] == bridge["curve_id"]
    assert ordinary["pair_state_cap"] == 2_000_000
    assert sha(bridge_path) == ordinary["bridge_sha256"]
    inverse = bridge["poly_to_onb_basis_images"]
    onb = field.Onb(N)
    curve = curves.Curve(onb)
    subgroup_order = int(bridge["subgroup_order"])
    states = [sampled_state(position, len(reps_poly))
              for position in INDEX_POSITIONS]
    assert all(row["position"] < ordinary["pair_state_cap"]
               for row in states)

    def point_for(column, shift):
        x_coords = xor_images(reps_poly[column], inverse)
        x = onb.fromCoords(x_coords)
        for _ in range(shift):
            x = onb.sqr(x)
        point = curve.pointFromX(x)
        assert point is not None
        assert curve.mul(point, subgroup_order) is None
        return point

    points = []
    for state in states:
        points.append(point_for(state["left_column"], 0))
        points.append(point_for(state["right_column"],
                                state["relative_frobenius_shift"]))
    target = None
    for point in points:
        target = curve.add(target, point)
    assert target is not None and curve.mul(target, subgroup_order) is None
    forward = bridge["onb_to_poly_basis_images"]
    target_poly = [xor_images(onb.toCoords(value), forward)
                   for value in target]
    workload = {
        "schema_version": 1,
        "field_degree": N,
        "curve_id": ordinary["curve_id"],
        "subgroup_order": subgroup_order,
        "target_group": "subgroup generated by frozen curve generator",
        "target_points_onb": [list(map(int, target))],
        "input_law": "fixed four-leaf planted correctness control from sampled index positions zero and one",
        "target_generation_seed": None,
        "target_count": 1,
        "cache_policy": "warm target-independent index",
        "planted_index_positions": list(INDEX_POSITIONS),
    }
    workload_canonical = json.dumps(workload, sort_keys=True,
                                    separators=(",", ":"),
                                    ensure_ascii=False).encode()
    workload_id = hashlib.sha256(workload_canonical).hexdigest()[:12]
    fixture = {
        "kind": "known_satisfiable_native_n83_four_leaf_control",
        "proposal_id": "Q1329",
        "parent_solver_proposal_id": "Q1328",
        "parent_factor_base_proposal_id": "Q1325",
        "candidate_id": None,
        "run_id": None,
        "curve_id": ordinary["curve_id"],
        "isogeny": "none",
        "workload_id": workload_id,
        "workload_record": workload,
        "workload_canonical_sha256": hashlib.sha256(
            workload_canonical).hexdigest(),
        "point_decomposition_stage_code": "PDP4root",
        "factor_base_actual_B": ordinary["actual_usable_points_B"],
        "factor_base_folded_columns_K": len(reps_poly),
        "factor_base_enumerated_set_sha256": ordinary[
            "factor_base_enumerated_set_sha256"],
        "pair_state_cap": ordinary["pair_state_cap"],
        "peak_rss_cap_mib": ordinary["peak_rss_cap_mib"],
        "target_orientations_per_state": N,
        "planted_target_onb": list(map(int, target)),
        "planted_target_poly_decimal": [str(value) for value in target_poly],
        "oracle_witness_points_onb": [list(map(int, point)) for point in points],
        "selected_index_states": states,
        "solver_receives_witness_or_index_positions": False,
        "is_natural_yield_measurement": False,
        "ordinary_input_manifest_sha256": sha(ordinary_path),
        "representatives_file_sha256": sha(reps_path),
        "bridge_sha256": sha(bridge_path),
        "source_sha256": sha(Path(__file__)),
    }
    fixture_content = json.dumps(fixture, indent=2) + "\n"
    fixture_path = HERE / "runs/n83_q1329_planted_fixture.json"
    control_manifest = dict(ordinary)
    control_manifest.update({
        "kind": "exact_native_s3_root_planted_control_input",
        "proposal_id": "Q1329",
        "parent_solver_proposal_id": "Q1328",
        "workload_id": workload_id,
        "target_poly_xy": [str(value) for value in target_poly],
        "orientations_per_state": N,
        "target_source_receipt_sha256": hashlib.sha256(
            fixture_content.encode()).hexdigest(),
        "stage_protocol_sha256": hashlib.sha256(
            fixture_content.encode()).hexdigest(),
        "source_sha256": sha(Path(__file__)),
    })
    manifest_content = json.dumps(control_manifest, indent=2) + "\n"
    manifest_path = HERE / "native_inputs/n83_planted_control_manifest.json"
    return (fixture_path, manifest_path, fixture_content, manifest_content)


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    fixture_path, manifest_path, fixture, manifest = freeze()
    if args.check:
        assert fixture_path.read_text() == fixture
        assert manifest_path.read_text() == manifest
    else:
        assert not fixture_path.exists() and not manifest_path.exists()
        fixture_path.write_text(fixture)
        manifest_path.write_text(manifest)
    row = json.loads(fixture)
    print(json.dumps({"proposal_id": "Q1329",
                      "workload_id": row["workload_id"],
                      "target_onb": row["planted_target_onb"]}))


if __name__ == "__main__":
    main()
