"""G6 step (6) runner.

1. Runs the unfinished audit script verify/pairing-transfer/C3-audit/t1.gp as-is (read-only;
   output captured in t1_run.log) to record what it does.
2. Writes pairing_c3_inputs.gp (b_int, j_int of E0, A000, B000 from ground_truth.json),
   runs pairing_c3_check.gp with gp, logs to pairing_c3_check.log and parses the RES lines
   into pairing_c3_check.json.
Run: export TMPDIR=/Volumes/SSD990/ecdlp-hardness-work/tmp; timeout 2400 python3 run_pairing_c3.py
"""
import json, os, subprocess, time, hashlib
HERE = os.path.dirname(os.path.abspath(__file__))
W = "/Volumes/SSD990/ecdlp-hardness-work"
T1 = os.path.join(W, "verify/pairing-transfer/C3-audit/t1.gp")
env = dict(os.environ, TMPDIR=os.path.join(W, "tmp"))

def run(cmd, log):
    t0 = time.time()
    p = subprocess.run(cmd, cwd=HERE, stdin=subprocess.DEVNULL, stdout=subprocess.PIPE,
                       stderr=subprocess.STDOUT, env=env, text=True)
    open(os.path.join(HERE, log), "w").write(p.stdout)
    return p.returncode, round(time.time() - t0, 1), p.stdout

res = {"script": "run_pairing_c3.py"}
rc, sec, out = run(["timeout", "2400", "gp", "-q", T1], "t1_run.log")
res["t1_gp"] = {"path": "verify/pairing-transfer/C3-audit/t1.gp",
                "sha256": hashlib.sha256(open(T1, "rb").read()).hexdigest(),
                "returncode": rc, "seconds": sec, "stdout_lines": out.strip().splitlines(),
                "assessment": "incomplete: builds F_{2^262}, embeds F_q, point-counts one unrelated curve "
                              "[1,0,0,0,w^5+1] and E0 over F_{q^2} and prints E0's ellgroup; it never "
                              "evaluates a Tate pairing, so it cannot test t_263(P,Q_N) = 1"}

gt = json.load(open(os.path.join(W, "ground_truth/ground_truth.json")))
rec = {c["label"]: c for c in gt["curves"]}
labs = ["E0", "A000", "B000"]
with open(os.path.join(HERE, "pairing_c3_inputs.gp"), "w") as fh:
    fh.write("\\\\ generated by run_pairing_c3.py from ground_truth/ground_truth.json\n")
    fh.write("LABS = [%s];\n" % ", ".join('"%s"' % l for l in labs))
    fh.write("BINT = [%s];\n" % ", ".join(rec[l]["b_int"] for l in labs))
    fh.write("JINT = [%s];\n" % ", ".join(rec[l]["j_int"] for l in labs))
rc, sec, out = run(["timeout", "2400", "gp", "-q", "pairing_c3_check.gp"], "pairing_c3_check.log")
parsed = {}
for line in out.splitlines():
    if line.startswith("RES "):
        parts = line.split(None, 3)
        if len(parts) == 4:
            _, lab, key, val = parts
            val = val.strip()
            if val in ("0", "1") and key not in ("v263_CL", "gcd_N_263", "seconds"):
                val = bool(int(val))
            else:
                try:
                    val = float(val) if "." in val else int(val)
                except ValueError:
                    pass
            parsed.setdefault(lab, {})[key] = val
res["pairing_c3_check_gp"] = {"returncode": rc, "seconds": sec, "results": parsed}
ok = rc == 0 and all(parsed.get(l, {}).get(k) is True for l in labs for k in
                     ("j_matches_ground_truth", "card_L_equals_(q+1-t)(q+1+t)", "QN_order_N", "P_order_263",
                      "tate_P_QN_all_1", "tate_P_T_ne_1", "shift_invariant_T_plus_QN", "bilinear_second_slot",
                      "bilinear_first_slot", "frobenius_acts_as_minus1_on_P"))
res["verdict"] = ("CONFIRMED: t_263(P, Q_N) = 1 on E0, A000, B000 (PARI, own embedding), with non-degenerate, "
                  "shift-invariant, bilinear controls" if ok else "NOT CONFIRMED - see results")
res["all_checks_pass"] = ok
json.dump(res, open(os.path.join(HERE, "pairing_c3_check.json"), "w"), indent=1)
print(json.dumps(res, indent=1)[:4000])
