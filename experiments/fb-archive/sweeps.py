# ------------------------------------------------------------------ manifest, store, verify
def manifest(name, experiment, field, curves, families, ks, curve_note, family_note, recorded, cells_note):
    """ks: the dimensions measured for every family, unless a family carries its own `dimensions`."""
    labels = [c["label"] for c in curves]
    if len(set(labels)) != len(labels):
        raise ValueError("duplicate curve labels")
    for f in families.values():
        if gf2_rank(f["basis"]) != len(f["basis"]):
            raise ValueError("dependent basis")
        f.setdefault("dimensions", ks)
    return {
        "schema": SCHEMA,
        "name": name,
        "experiment": experiment,
        "field": field,
        "curve_model": "y^2 + x*y = x^3 + a6 (a2 = 0); full records: fb-archive/sweeps.py curve_record",
        "curves": curves,
        "curve_note": curve_note,
        "families": families,
        "family_note": family_note,
        "factor_base": {
            "construction": "nested F_2-subspaces V_k = span(basis[:k]) of x-coordinates",
            "cell_rule": CELL_RULE,
            "subgroup_policy": "none",
            "dimensions": "per family (families[name].dimensions)",
            "enumerated_set_sha256": None,
            "actual_usable_point_count": None,
            "effective_columns": None,
        },
        "cells": {"count": len(curves) * sum(len(f["dimensions"]) for f in families.values()), "note": cells_note},
        "recorded": [{**r, "sha256": file_sha256(r["path"])} for r in recorded],
        "points": None,
    }


BUILDERS = {"volcano-m83": (build_m83, m83_recorded), "ecc2k130-isogeny-class": (build_iso, iso_recorded),
            "volcano-ic": (build_vic, vic_recorded)}


def read_index() -> list[dict]:
    if not INDEX.exists():
        return []
    with INDEX.open(newline="") as fh:
        return list(csv.DictReader(fh))


def store(doc: dict) -> dict:
    content = canonical(doc).encode()
    blob = gzip.compress(content, compresslevel=9, mtime=0)
    rel = Path("sweeps") / f"{doc['name']}.json.gz"
    (HERE / rel).parent.mkdir(exist_ok=True)
    (HERE / rel).write_bytes(blob)
    row = {"name": doc["name"], "experiment": doc["experiment"], "n": doc["field"]["degree"],
           "curves": len(doc["curves"]), "families": len(doc["families"]), "cells": doc["cells"]["count"],
           "path": str(rel), "bytes": len(blob), "file_sha256": hashlib.sha256(blob).hexdigest(),
           "content_sha256": hashlib.sha256(content).hexdigest()}
    rows = sorted([r for r in read_index() if r["name"] != row["name"]] + [row], key=lambda r: r["name"])
    with INDEX.open("w", newline="") as fh:
        w = csv.DictWriter(fh, fieldnames=INDEX_FIELDS, lineterminator="\n")
        w.writeheader()
        w.writerows(rows)
    return row


def load(name: str) -> dict:
    return json.loads(gzip.decompress((DIR / f"{name}.json.gz").read_bytes()))


def recount(doc: dict, keys) -> dict:
    n = doc["field"]["degree"]
    mod = sum(1 << e for e in doc["field"]["modulus_exponents"])
    ctr = Counter(n, mod)
    b_of = {c["label"]: c["b"] for c in doc["curves"]}
    wanted: dict[tuple, list] = {}
    for label, fam, k in keys:
        wanted.setdefault((label, fam), []).append(k)
    out = {}
    for (label, fam), ks in wanted.items():
        for k, v in ctr.counts(b_of[label], doc["families"][fam]["basis"], ks).items():
            out[(label, fam, k)] = v
    return out


def verify_sweep(row: dict, cells: int | None, seed: int = 1) -> list[str]:
    errors = []
    path = HERE / row["path"]
    blob = path.read_bytes()
    if hashlib.sha256(blob).hexdigest() != row["file_sha256"]:
        errors.append(f"{row['path']}: file SHA-256 differs from sweeps.csv")
    content = gzip.decompress(blob)
    if hashlib.sha256(content).hexdigest() != row["content_sha256"]:
        errors.append(f"{row['path']}: content SHA-256 differs from sweeps.csv")
    doc = json.loads(content)
    build, recorded = BUILDERS[row["name"]]
    if canonical(build()).encode() != content:
        errors.append(f"{row['path']}: rebuilding from the experiment's inputs gives different content "
                      "(an input or a recorded file changed)")
    rec = recorded()
    keys = sorted(rec)
    if cells is not None and cells < len(keys):
        keys = sorted(random.Random(f"{row['name']}|{seed}").sample(keys, cells))
    got = recount(doc, keys)
    bad = [k for k in keys if got[k] != rec[k]]
    for k in bad[:10]:
        errors.append(f"{row['name']}: cell {k} recounts to {got[k]}, recorded {rec[k]}")
    if len(bad) > 10:
        errors.append(f"{row['name']}: {len(bad) - 10} more cells differ")
    print(f"{row['name']}: {len(doc['curves'])} curves, {doc['cells']['count']} cells, "
          f"{len(keys)} of {len(rec)} recorded cells recounted, {len(bad)} differ")
    return errors


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    sub = ap.add_subparsers(dest="cmd", required=True)
    e = sub.add_parser("export")
    e.add_argument("names", nargs="*")
    v = sub.add_parser("verify")
    v.add_argument("--cells", type=int, default=40, help="recorded cells recounted per sweep")
    v.add_argument("--all-cells", metavar="NAME", help="recount every recorded cell of this sweep")
    args = ap.parse_args()
    if args.cmd == "export":
        for name in args.names or list(BUILDERS):
            row = store(BUILDERS[name][0]())
            print(f"{row['path']}: {row['curves']} curves, {row['families']} families, {row['cells']} cells, "
                  f"{row['bytes']} bytes")
        return 0
    index = read_index()
    rows = [r for r in index if r["name"] == args.all_cells] if args.all_cells else index
    if args.all_cells and not rows:
        ap.error(f"no sweep named {args.all_cells}")
    errors = [err for r in rows for err in verify_sweep(r, None if args.all_cells else args.cells)]
    on_disk = {str(p.relative_to(HERE)) for p in DIR.glob("*.json.gz")} if DIR.exists() else set()
    errors += [f"{p}: not in sweeps.csv" for p in sorted(on_disk - {r["path"] for r in index})]
    for err in errors:
        print(err)
    print(f"{len(rows)} sweeps, {len(errors)} problems")
    return 1 if errors else 0


