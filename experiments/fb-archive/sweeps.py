#!/usr/bin/env python3
"""Recipe-only archives of large factor-base sweeps: every curve and basis, no point lists.

    python3 sweeps.py export [NAME ...]           # write sweeps/<name>.json.gz and sweeps.csv rows
    python3 sweeps.py verify [--cells N]          # rebuild, check sources, recount N sampled cells per sweep
    python3 sweeps.py verify --all-cells NAME     # recount every recorded cell of one sweep

A sweep measures one factor-base rule on many curves: thousands of curves times several
nested subspaces times several dimensions. Storing each base's points is out of the
question (volcano-m83 alone has 1,243,200 cells), and the bases are cheap to rebuild,
so a sweep archive (schema `ic-factor-base-sweep/1`) stores the recipe instead:

  field     the field record of fbarchive (purepy.PyKoblitz format)
  curves    every curve: label, a6 = b, generator (null where the experiment never fixed
            one), and its EC1 curve ID hashed from the full field and curve record
  families  every nested basis by name, with the recipe that regenerates it (seed, rule)
            and the 16 or 10 vectors themselves
  cells     curves x families x dimensions k; the base of cell (curve, family, k) is
            {x in span(basis[:k]) : x = 0 or Tr(x + b/x^2) = 0}, the abscissae of
            E_b: y^2 + xy = x^3 + b over that subspace (both signs of y)
  recorded  the experiment's committed files holding per-cell counts, with SHA-256, and
            which count they hold (with or without x = 0)

`B`, the point digest and the column count stay null, as for any recipe-only archive.
`verify` rebuilds each manifest from the experiment's own committed inputs, checks that
the recorded files are unchanged, and recounts sampled cells against them.
"""

