"""Pure-Python Koblitz curves for fields beyond pdpkernel.c's 63-bit limit (ECC2K-130).

`PyField` duck-types the parts of kernel.Field that factor_base.family_basis uses (mul,
sqr, pow, inv, frob, trace, half_trace, sqrt), so every subspace family is built by the
same code at n = 131 as on the toy curves.  `PyKoblitz` carries the same AGENTS.md
`field` / `curve` records as toycurve.ToyCurve, so curve IDs are comparable.
"""

from __future__ import annotations

import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE.parent / "pdp-scaling"))
sys.path.insert(0, str(HERE.parent / "pdp-degree-heuristics"))

import gf2n  # noqa: E402
from toycurve import factor, koblitz_order, sha256_hex  # noqa: E402

# ECC2K-130 challenge parameters, polynomial basis (ecc2k130/runner/codegen/gen.py)
ECC2K130 = {
    "n": 131,
    "px": 0x051C99BFA6F18DE467C80C23B98C7994AA,
    "py": 0x042EA2D112ECEC71FCF7E000D7EFC978BD,
    "r": 680564733841876926932320129493409985129,
}


class PyField:
    def __init__(self, n: int, mod: int | None = None):
        self.n = n
        self.mod = mod if mod is not None else gf2n.modulus(n)
        self._top = 1 << n
        self.trace_mask = sum(self._trace_slow(1 << i) << i for i in range(n))

    def mul(self, a: int, b: int) -> int:
        r, top, mod = 0, self._top, self.mod
        if a.bit_count() < b.bit_count():
            a, b = b, a
        while b:
            if b & 1:
                r ^= a
            b >>= 1
            a <<= 1
            if a & top:
                a ^= mod
        return r

    def sqr(self, a: int) -> int:
        return self.mul(a, a)

    def pow(self, a: int, e: int) -> int:
        r = 1
        while e:
            if e & 1:
                r = self.mul(r, a)
            a = self.sqr(a)
            e >>= 1
        return r

    def inv(self, a: int) -> int:
        if a == 0:
            raise ZeroDivisionError
        u, v, g1, g2 = a, self.mod, 1, 0
        while u != 1:
            j = u.bit_length() - v.bit_length()
            if j < 0:
                u, v, g1, g2 = v, u, g2, g1
                j = -j
            u ^= v << j
            g1 ^= g2 << j
        return g1

    def frob(self, a: int, k: int) -> int:
        for _ in range(k % self.n):
            a = self.sqr(a)
        return a

    def _trace_slow(self, a: int) -> int:
        t, x = 0, a
        for _ in range(self.n):
            t ^= x
            x = self.sqr(x)
        assert t in (0, 1)
        return t

    def trace(self, a: int) -> int:
        return (a & self.trace_mask).bit_count() & 1

    def half_trace(self, a: int) -> int:
        assert self.n % 2 == 1
        h, x = 0, a
        for _ in range((self.n + 1) // 2):
            h ^= x
            x = self.sqr(self.sqr(x))
        return h

    def sqrt(self, a: int) -> int:
        return self.frob(a, self.n - 1)


INF = None


class PyKoblitz:
    """y^2 + xy = x^3 + a2 x^2 + 1 over F_2^n with an explicit generator G of prime order r."""

    def __init__(self, n: int, a2: int, G: tuple[int, int], r: int, mod: int | None = None):
        self.n, self.a2, self.b = n, a2, 1
        self.K = PyField(n, mod)
        self.mod = self.K.mod
        self.order = koblitz_order(n, a2)
        self.trace = 2**n + 1 - self.order
        if self.order % r:
            raise ValueError("r does not divide #E")
        self.r, self.h = r, self.order // r
        self.G = G
        assert self.on_curve(G) and self.smul(G, r) is INF, "G is not a point of order r"
        self._torsion: list | None = None

    @classmethod
    def ecc2k130(cls) -> "PyKoblitz":
        return cls(ECC2K130["n"], 0, (ECC2K130["px"], ECC2K130["py"]), ECC2K130["r"])

    # --- identity (same records as toycurve.ToyCurve) ---------------------------
    @property
    def tag(self) -> str:
        return "kb1" if self.a2 == 0 else "ka1"

    def field_record(self) -> dict:
        return {
            "characteristic": 2,
            "degree": self.n,
            "representation": "polynomial_basis",
            "modulus_exponents": [i for i in range(self.n, -1, -1) if (self.mod >> i) & 1],
            "element_encoding": "unsigned integer; bit i is the coefficient of z^i",
        }

    def curve_record(self) -> dict:
        return {
            "model": "y^2 + x*y = x^3 + a2*x^2 + a6",
            "a2": self.a2,
            "a6": self.b,
            "order": self.order,
            "trace": self.trace,
            "subgroup_order": self.r,
            "cofactor": self.h,
            "generator": [self.G[0], self.G[1]],
            "target_group": "prime-order subgroup generated by G",
        }

    @property
    def curve_id(self) -> str:
        digest = sha256_hex({"field": self.field_record(), "curve": self.curve_record()})
        return f"EC1N{self.n}C{self.tag}h{digest[:12]}"

    # --- group law ----------------------------------------------------------------
    def on_curve(self, P) -> bool:
        if P is INF:
            return True
        K, (x, y) = self.K, P
        return K.sqr(y) ^ K.mul(x, y) == K.mul(K.sqr(x), x) ^ K.mul(self.a2, K.sqr(x)) ^ self.b

    def neg(self, P):
        return P if P is INF else (P[0], P[0] ^ P[1])

    def add(self, P, Q):
        if P is INF:
            return Q
        if Q is INF:
            return P
        K = self.K
        (x1, y1), (x2, y2) = P, Q
        if x1 == x2:
            if y1 != y2 or x1 == 0:
                return INF
            lam = x1 ^ K.mul(y1, K.inv(x1))
            x3 = K.sqr(lam) ^ lam ^ self.a2
            return x3, K.sqr(x1) ^ K.mul(lam ^ 1, x3)
        lam = K.mul(y1 ^ y2, K.inv(x1 ^ x2))
        x3 = K.sqr(lam) ^ lam ^ x1 ^ x2 ^ self.a2
        return x3, K.mul(lam, x1 ^ x3) ^ x3 ^ y1

    def smul(self, P, k: int):
        R = INF
        for bit in bin(k)[2:] if k > 0 else "":
            R = self.add(R, R)
            if bit == "1":
                R = self.add(R, P)
        return R

    def lift(self, x: int):
        K = self.K
        if x == 0:
            return 0, K.sqrt(self.b)
        c = x ^ self.a2 ^ K.mul(self.b, K.inv(K.sqr(x)))
        if K.trace(c):
            return None
        return x, K.mul(x, K.half_trace(c))

    def cofactor_torsion(self) -> list:
        """E(F_2^n)[h]: the points [r]Q, collected until h distinct ones appear."""
        if self._torsion is None:
            import random

            rng = random.Random(f"torsion|{self.curve_id}")
            pts = {INF}
            while len(pts) < self.h:
                Q = self.lift(rng.getrandbits(self.n))
                if Q is not None:
                    pts.add(self.smul(Q, self.r))
            assert len(pts) == self.h
            self._torsion = sorted(pts, key=lambda P: (-1, -1) if P is INF else P)
        return self._torsion

    def summary(self) -> dict:
        return {"curve_id": self.curve_id, "n": self.n, "order": self.order,
                "factorization": {str(p): e for p, e in factor(self.order // self.r).items()} | {str(self.r): 1},
                "subgroup_order": self.r, "subgroup_bits": self.r.bit_length(), "cofactor": self.h}
