#!/usr/bin/env python3
"""Generate the offline canonical-vs-oracle decision for every bounded tail."""

import argparse
import hashlib
from pathlib import Path

from make_tau_tail_oracle import BOUND, PHASES, SIDE, UNREACHABLE, generate, index
from run import recode


def canonical_cost(a, b, phase):
    digits = recode(a, b)
    nonzero = [(i, digit) for i, digit in enumerate(digits) if digit is not None]
    if not nonzero:
        return 0
    triples = max(i // 2 for i, _digit in nonzero)
    rotations = sum((digit[3] + phase + i // 2) % 3 != 0
                    for i, digit in nonzero)
    return 10 * triples + 16 * len(nonzero) + rotations


def generate_gate():
    costs, actions = generate()
    bits = bytearray((len(actions) + 7) // 8)
    improved = missing = worse_or_tied = 0
    for phase in range(PHASES):
        for a in range(-BOUND, BOUND + 1):
            for b in range(-BOUND, BOUND + 1):
                pos = index(a, b, phase)
                if actions[pos] == UNREACHABLE:
                    missing += 1
                    continue
                base = canonical_cost(a, b, phase)
                if costs[pos] < base:
                    bits[pos >> 3] |= 1 << (pos & 7)
                    improved += 1
                else:
                    worse_or_tied += 1
    assert improved + missing + worse_or_tied == PHASES * SIDE * SIDE
    assert all(not (bits[pos >> 3] & (1 << (pos & 7)))
               for pos, action in enumerate(actions) if action == UNREACHABLE)
    return bytes(bits), improved, missing, worse_or_tied


def render(bits):
    source_hash = hashlib.sha256(Path(__file__).read_bytes()).hexdigest()
    lines = ["/* Generated by make_tau_tail_gate.py; do not edit.",
             f" * Generator SHA-256: {source_hash}",
             " * Bit i is set only when the bounded oracle's exact weighted",
             " * evaluation cost is strictly less than canonical recoding.",
             " */", "#ifndef CA_TAU_TAIL_GATE_H", "#define CA_TAU_TAIL_GATE_H",
             "#include <stdint.h>",
             f"static const uint8_t ca_tau_tail_gate[{len(bits)}] = {{"]
    for offset in range(0, len(bits), 16):
        lines.append("    " + ", ".join(str(value) for value in bits[offset:offset + 16]) + ",")
    lines.extend(["};", "#endif", ""])
    return "\n".join(lines)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output", type=Path, default=Path(__file__).resolve().parents[2] /
                        "src/generated/tau_tail_gate.h")
    args = parser.parse_args()
    bits, improved, missing, worse_or_tied = generate_gate()
    data = render(bits)
    if args.output.exists() and args.output.read_text() != data:
        raise SystemExit(f"generated gate changed: {args.output}")
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(data)
    print(f"gate_bytes={len(bits)} improved_states={improved} "
          f"unreachable_states={missing} tied_or_worse_states={worse_or_tied} "
          f"table_sha256={hashlib.sha256(data.encode()).hexdigest()}")


if __name__ == "__main__":
    main()
