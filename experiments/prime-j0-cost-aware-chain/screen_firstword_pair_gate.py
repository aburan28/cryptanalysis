#!/usr/bin/env python3
"""Train a one-pass periodic pair gate on old point-0 scalars only."""

import csv
import hashlib
import json
from pathlib import Path
import struct

from make_tau_pair_fused import catalog
from run import representatives
from screen_global_pair_search import lattice_norm, score, tail_oracle
from screen_periodic_pair_atlas import periodic_plan, reference_plan
from screen_tau_tail_double import ENDO_LAMBDA


ROOT = Path(__file__).resolve().parent
REPO = ROOT.parents[1]
HEADER = REPO / "src/generated/tau_pair_firstword_gate.h"
RAW = ROOT / "firstword-pair-gate-raw.csv"
SUMMARY = ROOT / "firstword-pair-gate-screen.json"
MIN_SUPPORT = 2


def sha256(path):
    return hashlib.sha256(path.read_bytes()).hexdigest()


def main():
    fixture_path = ROOT / "tail-pair-fused-inputs.json"
    fixture = json.loads(fixture_path.read_text())
    reps, _, words_by_point, _, _ = catalog()
    options = sorted(((a, b, word) for (a, b), word in words_by_point.items()),
                     key=lambda item: (lattice_norm(item[0], item[1]), item[2]))
    _, actions = tail_oracle(options)
    assert sum(action is not None for action in actions) == 15043

    rows = []
    scalar_paths = []
    for case_index in (0, 1, 4, 5):
        case = fixture["cases"][case_index]
        assert case["point_index"] == case_index % 4
        scalar_path = ROOT / case["scalar_file"]
        raw = scalar_path.read_bytes()
        assert sha256(scalar_path) == case["scalar_file_sha256"]
        scalar_paths.append(scalar_path)
        scalars = struct.unpack(f"<{len(raw)//8}Q", raw)
        assert len(scalars) == 4096
        curve = case["curve"]["name"]
        order = case["curve"]["order"]
        omega_lambda = order - ENDO_LAMBDA[curve]
        for scalar_index, scalar in enumerate(scalars):
            _, a, b = min(representatives(order, omega_lambda, scalar),
                          key=lambda row: row[0])
            reference = reference_plan((a, b), words_by_point, actions, reps)
            periodic, lookups, misses = periodic_plan((a, b), 27,
                                                      words_by_point, actions, reps)
            assert periodic is not None and misses == 0 and periodic
            rows.append({"curve": curve, "point_index": case["point_index"],
                         "scalar_index": scalar_index, "scalar": scalar,
                         "first_word": periodic[0], "reference_score": score(reference),
                         "periodic_score": score(periodic),
                         "periodic_lookups": lookups})

    training = [row for row in rows if row["point_index"] == 0]
    validation = [row for row in rows if row["point_index"] == 1]
    assert len(training) == len(validation) == 8192
    stats = {}
    for row in training:
        word = row["first_word"]
        support, gain = stats.get(word, (0, 0))
        stats[word] = (support + 1,
                       gain + row["reference_score"] - row["periodic_score"])
    selected = {word for word, (support, gain) in stats.items()
                if support >= MIN_SUPPORT and gain > 0}
    assert len(selected) == 269
    bitset = bytearray(128)
    for word in selected:
        assert 0 <= word < 1024
        bitset[word >> 3] |= 1 << (word & 7)
    lines = ["/* Generated by screen_firstword_pair_gate.py; do not edit. */",
             "#ifndef CA_TAU_PAIR_FIRSTWORD_GATE_H",
             "#define CA_TAU_PAIR_FIRSTWORD_GATE_H",
             "#include <stdint.h>",
             "static const uint8_t ca_tau_pair_firstword_gate[128] = {"]
    for offset in range(0, len(bitset), 16):
        lines.append("    " + ", ".join(str(value) for value in bitset[offset:offset + 16]) + ",")
    lines.extend(["};", "#endif", ""])
    HEADER.write_text("\n".join(lines))

    for row in rows:
        row["selected"] = row["first_word"] in selected
        row["chosen_score"] = (row["periodic_score"] if row["selected"] else
                               row["reference_score"])
    with RAW.open("w", newline="") as stream:
        writer = csv.DictWriter(stream, fieldnames=tuple(rows[0]), lineterminator="\n")
        writer.writeheader()
        writer.writerows(rows)

    cases = []
    for curve in ("glv-j0-32", "j0-56"):
        for point_index in (0, 1):
            selected_rows = [row for row in rows if row["curve"] == curve and
                             row["point_index"] == point_index]
            reference_total = sum(row["reference_score"] for row in selected_rows)
            periodic_total = sum(row["periodic_score"] for row in selected_rows)
            chosen_total = sum(row["chosen_score"] for row in selected_rows)
            cases.append({"curve": curve, "point_index": point_index,
                          "count": len(selected_rows),
                          "reference_score": reference_total,
                          "direct_periodic_score": periodic_total,
                          "chosen_score": chosen_total,
                          "saved_score": reference_total - chosen_total,
                          "saving_percent": 100 * (reference_total - chosen_total) /
                          reference_total,
                          "selected_scalars": sum(row["selected"] for row in selected_rows)})
    assert [(case["saved_score"], case["selected_scalars"]) for case in cases
            if case["point_index"] == 1] == [(9546, 1486), (8582, 1500)]
    sources = [Path(__file__), ROOT / "screen_periodic_pair_atlas.py",
               ROOT / "screen_global_pair_search.py", ROOT / "make_tau_pair_fused.py",
               ROOT / "run.py", ROOT / "screen_tau_tail_double.py", fixture_path] + scalar_paths
    result = {"schema": 1, "status": "retrospective_firstword_gate_design_screen",
              "claim_boundary": "old scalar design and validation data; no CPU or novelty claim",
              "training": "point0 on both curves, 4096 scalars per curve",
              "validation": "point1 on both curves, 4096 scalars per curve",
              "selector": "select the periodic schedule iff its first word has training support >= 2 and positive aggregate score gain",
              "selected_word_count": len(selected), "selected_words": sorted(selected),
              "gate_bytes": len(bitset), "gate_sha256": sha256(HEADER),
              "raw_csv": RAW.name, "raw_csv_sha256": sha256(RAW),
              "source_sha256": {str(path.relative_to(REPO)): sha256(path) for path in sources},
              "cases": cases}
    SUMMARY.write_text(json.dumps(result, indent=2, sort_keys=True) + "\n")
    print(json.dumps({"status": result["status"], "selected_words": len(selected),
                      "cases": cases}, sort_keys=True))


if __name__ == "__main__":
    main()
