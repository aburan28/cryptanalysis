#!/usr/bin/env python3
"""Generate and screen the complete width-3, six-step unit-orbit table."""

import argparse
import hashlib
import json
from pathlib import Path
import struct

from run import representatives


ROOT = Path(__file__).resolve().parent
SEEDS = ((1, 0), (2, 0), (1, 1))
ZERO_PATTERN = 0
UNREACHABLE = 65535


def omega(a, b):
    return a + 3 * b, -a - 2 * b


def tau(a, b):
    return -3 * b, a + 3 * b


def unit(a, b, code):
    for _ in range(code % 3):
        a, b = omega(a, b)
    return (-a, -b) if code >= 3 else (a, b)


def digits():
    return [unit(*seed, code) for seed in SEEDS for code in range(6)]


def build():
    digit = digits()
    assert len(digit) == len(set(digit)) == 18
    residue = [0] * 27
    for digit_id, (a, b) in enumerate(digit, 1):
        key = 3 * (a % 9) + b % 3
        assert a % 3 and residue[key] == 0
        residue[key] = digit_id
    assert sum(bool(x) for x in residue) == 18
    assert all(residue[3 * a + b] != 0 for a in range(9) for b in range(3)
               if a % 3)
    pattern = [(0, 0)] + [(position, digit_id)
                          for position in range(3) for digit_id in range(1, 19)]
    assert len(pattern) == 55
    pattern_ids = {entry: i for i, entry in enumerate(pattern)}
    digit_ids = {entry: i for i, entry in enumerate(digit, 1)}
    unit_pattern = []
    for code in range(6):
        mapping = [0]
        for position, digit_id in pattern[1:]:
            moved = digit_ids[unit(*digit[digit_id - 1], code)]
            mapping.append(pattern_ids[(position, moved)])
        unit_pattern.append(mapping)
    valid_pairs = []
    reps = set()
    for u in range(55):
        for v in range(55):
            valid = not u or not v or pattern[v][0] >= pattern[u][0]
            if not valid:
                continue
            valid_pairs.append((u, v))
            orbit = {(mapping[u], mapping[v]) for mapping in unit_pattern}
            assert len(orbit) == (1 if u == v == 0 else 6)
            reps.add(min(orbit))
    assert len(valid_pairs) == 2053
    reps = sorted(reps)
    assert len(reps) == 343 and reps[0] == (0, 0)
    rep_ids = {entry: i for i, entry in enumerate(reps)}
    orbit_id = [UNREACHABLE] * (55 * 55)
    orbit_unit = [255] * (55 * 55)
    for u, v in valid_pairs:
        orbit = {(mapping[u], mapping[v]) for mapping in unit_pattern}
        rep = min(orbit)
        index = 55 * u + v
        orbit_id[index] = rep_ids[rep]
        orbit_unit[index] = next(code for code, mapping in enumerate(unit_pattern)
                                 if (mapping[rep[0]], mapping[rep[1]]) == (u, v))
    assert sum(value != UNREACHABLE for value in orbit_id) == 2053
    assert sum(bool(u and v) for u, v in reps) == 324
    return digit, residue, pattern, orbit_id, orbit_unit, reps


def recode(a, b, digit, residue):
    out = []
    original = (a, b)
    while a or b:
        if len(out) >= 128:
            raise ValueError(f"width-3 expansion failed to terminate: {original}")
        digit_id = residue[3 * (a % 9) + b % 3]
        if digit_id:
            da, db = digit[digit_id - 1]
            a -= da
            b -= db
        out.append(digit_id)
        if a % 3:
            raise AssertionError("digit did not make tau division exact")
        a, b = a + b, -a // 3
    for i, digit_id in enumerate(out):
        if digit_id and any(out[i + 1:i + 3]):
            raise AssertionError("width-3 spacing failed")
    x = y = 0
    for digit_id in reversed(out):
        x, y = tau(x, y)
        if digit_id:
            da, db = digit[digit_id - 1]
            x += da
            y += db
    if (x, y) != original:
        raise AssertionError("width-3 reconstruction failed")
    return out


def block_pattern(sequence):
    active = [(position, value) for position, value in enumerate(sequence) if value]
    if len(active) > 1:
        raise AssertionError("multiple width-3 digits in one three-step block")
    return 0 if not active else 1 + 18 * active[0][0] + active[0][1] - 1


def blocks_for_order(order):
    count = 1  # one spare block; overflow uses the generic fallback in C
    n = order - 1
    while n:
        count += 1
        n //= 729
    return count


def render(data):
    digit, residue, pattern, orbit_id, orbit_unit, reps = data
    lines = ["/* Generated by make_tau3_fused.py; do not hand-edit. */",
             "#ifndef CA_TAU3_FUSED_H", "#define CA_TAU3_FUSED_H", "",
             "#include <stdint.h>", "", "#define CA_TAU3_FUSED_ORBITS 343", ""]
    arrays = (
        ("ca_tau3_digit_a", "int8_t", [0] + [a for a, _ in digit], 18),
        ("ca_tau3_digit_b", "int8_t", [0] + [b for _, b in digit], 18),
        ("ca_tau3_residue", "uint8_t", residue, 27),
        ("ca_tau3_orbit_id", "uint16_t", orbit_id, 18),
        ("ca_tau3_orbit_unit", "uint8_t", orbit_unit, 27),
        ("ca_tau3_rep_u", "uint8_t", [u for u, _ in reps], 27),
        ("ca_tau3_rep_v", "uint8_t", [v for _, v in reps], 27),
    )
    for name, ctype, values, width in arrays:
        lines.append(f"static const {ctype} {name}[{len(values)}] = {{")
        for start in range(0, len(values), width):
            lines.append("  " + ", ".join(str(v) for v in values[start:start + width]) + ",")
        lines += ["};", ""]
    lines += ["#endif", ""]
    return "\n".join(lines)


def screen(data, header_path, output):
    digit, residue, _, orbit_id, orbit_unit, _ = data
    fixture = json.loads((ROOT / "compact-pos-inputs.json").read_text())
    panel = json.loads((ROOT / "compact-pos-panel.json").read_text())
    old_rows = {(row["case_id"], row["mode"]): row for row in panel["rows"]}
    rows = []
    for case in fixture["cases"]:
        old = old_rows[(case["id"], "pos-compact")]["fields"]
        order = case["curve"]["order"]
        # ec_tau.c builds its lattice with r - g->endo_lambda. The bench field
        # is the curve automorphism eigenvalue, not the lattice eigenvalue.
        eigenvalue = (order - int(old["endo_lambda"])) % order
        content = (ROOT / case["scalar_file"]).read_bytes()
        counts = [0, 0, 0]
        rotations = 0
        max_length = 0
        for (k,) in struct.iter_unpack("<Q", content):
            _, a, b = min(representatives(order, eigenvalue, k), key=lambda r: r[0])
            sequence = recode(a, b, digit, residue)
            max_length = max(max_length, len(sequence))
            if (len(sequence) + 5) // 6 > blocks_for_order(order):
                raise AssertionError("design scalar would exceed prepared blocks")
            for offset in range(0, len(sequence), 6):
                padded = (sequence[offset:offset + 6] + [0] * 6)[:6]
                u = block_pattern(padded[:3])
                v = block_pattern(padded[3:])
                index = 55 * u + v
                if orbit_id[index] == UNREACHABLE:
                    raise AssertionError("natural width-3 recode reached invalid pair")
                counts[(u != 0) + (v != 0)] += 1
                if u or v:
                    rotations += orbit_unit[index] % 3 != 0
        new_adds = counts[1] + counts[2]
        old_adds = int(old["adds"])
        rows.append({"case_id": case["id"], "curve": case["curve"]["name"],
                     "scalar_file_sha256": case["scalar_file_sha256"],
                     "max_tau_length": max_length, "prepared_blocks": blocks_for_order(order),
                     "zero_blocks": counts[0], "single_digit_blocks": counts[1],
                     "two_digit_blocks": counts[2],
                     "old_compact_pos_adds": old_adds,
                     "predicted_tau3_fused_adds": new_adds,
                     "predicted_rotations": rotations,
                     "predicted_add_saving": f"{(old_adds - new_adds) / old_adds:.6f}"})
    report = {"schema": 1, "status": "retrospective_design_screen",
              "cpu_timing_claim": None, "fixture_sha256": hashlib.sha256(
                  (ROOT / "compact-pos-inputs.json").read_bytes()).hexdigest(),
              "prior_panel_sha256": hashlib.sha256(
                  (ROOT / "compact-pos-panel.json").read_bytes()).hexdigest(),
              "header_sha256": hashlib.sha256(header_path.read_bytes()).hexdigest(),
              "source_sha256": hashlib.sha256(Path(__file__).read_bytes()).hexdigest(),
              "point_entries_by_curve": {name: 343 * blocks_for_order(order)
                                         for name, order in (("glv-j0-32", 23729779),
                                                             ("j0-56", 53624256071278747))},
              "rows": rows}
    output.write_text(json.dumps(report, indent=2, sort_keys=True) + "\n")
    print(json.dumps({"status": report["status"],
                      "add_saving": [row["predicted_add_saving"] for row in rows]},
                     sort_keys=True))


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output", type=Path, required=True)
    parser.add_argument("--screen", type=Path)
    args = parser.parse_args()
    data = build()
    content = render(data)
    args.output.parent.mkdir(parents=True, exist_ok=True)
    if args.output.exists() and args.output.read_text() != content:
        raise ValueError("generated tau3 header differs from frozen file")
    args.output.write_text(content)
    if args.screen:
        screen(data, args.output, args.screen)
    print(json.dumps({"orbits": 343,
                      "header_sha256": hashlib.sha256(content.encode()).hexdigest()},
                     sort_keys=True))


if __name__ == "__main__":
    main()
