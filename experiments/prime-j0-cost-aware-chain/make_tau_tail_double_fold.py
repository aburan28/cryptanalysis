#!/usr/bin/env python3
"""Fold the exact two-digit tau-tail policy by sign and pack action indices."""

import argparse
import hashlib
from pathlib import Path

from make_tau_tail_double import BOUND, DIGITS, NONE, PHASES, gate_bits, generate, index, step

SIDE = 2 * BOUND + 1
HALF = (SIDE * SIDE + 1) // 2
UNREACHABLE = (254, 254)


def representative(a, b):
    negative = a < 0 or (a == 0 and b < 0)
    return (-a, -b, True) if negative else (a, b, False)


def half_index(a, b):
    assert a > 0 or (a == 0 and b >= 0)
    return b if a == 0 else BOUND + 1 + (a - 1) * SIDE + b + BOUND


def build(costs, actions, gate):
    digit_by_coordinate = {(digit[0], digit[1]): slot for slot, digit in DIGITS}
    negate = [NONE] * 81
    for slot, digit in DIGITS:
        negate[slot] = digit_by_coordinate[-digit[0], -digit[1]]
    assert all(negate[negate[slot]] == slot for slot, _digit in DIGITS)

    dictionaries = []
    codes = []
    folded_gate = bytearray((PHASES * HALF + 7) // 8)
    for phase in range(PHASES):
        phase_actions = [None] * HALF
        for a in range(BOUND + 1):
            for b in range(-BOUND if a else 0, BOUND + 1):
                k = half_index(a, b)
                phase_actions[k] = actions[index(a, b, phase)]
                full = index(a, b, phase)
                mirrored = index(-a, -b, phase)
                assert costs[full] == costs[mirrored]
                selected = bool(gate[full >> 3] & (1 << (full & 7)))
                assert selected == bool(gate[mirrored >> 3] & (1 << (mirrored & 7)))
                if selected:
                    pos = phase * HALF + k
                    folded_gate[pos >> 3] |= 1 << (pos & 7)
        dictionary = sorted({action or UNREACHABLE for action in phase_actions})
        assert len(dictionary) <= 1024
        action_to_code = {action: code for code, action in enumerate(dictionary)}
        dictionaries.append(dictionary)
        codes.extend(action_to_code[action or UNREACHABLE] for action in phase_actions)

    packed = bytearray((10 * len(codes) + 7) // 8 + 2)
    for pos, code in enumerate(codes):
        bit = 10 * pos
        word = code << (bit & 7)
        byte = bit >> 3
        packed[byte] |= word & 255
        packed[byte + 1] |= (word >> 8) & 255
        packed[byte + 2] |= (word >> 16) & 255
    assert ((10 * (len(codes) - 1)) >> 3) + 2 < len(packed)

    # Check every original state, including mirrored actions with different
    # equal-cost tie choices. The folded successor must remain on an exact
    # shortest path and the statewise gate must be unchanged.
    different_actions = 0
    for phase in range(PHASES):
        for a in range(-BOUND, BOUND + 1):
            for b in range(-BOUND, BOUND + 1):
                ra, rb, negative = representative(a, b)
                pos = phase * HALF + half_index(ra, rb)
                bit = 10 * pos
                byte = bit >> 3
                code = ((packed[byte] | packed[byte + 1] << 8 | packed[byte + 2] << 16)
                        >> (bit & 7)) & 1023
                even, odd = dictionaries[phase][code]
                if negative and even != 254:
                    even = negate[even] if even != NONE else NONE
                    odd = negate[odd] if odd != NONE else NONE
                old = actions[index(a, b, phase)]
                different_actions += (even, odd) != (old or UNREACHABLE)
                selected = bool(folded_gate[pos >> 3] & (1 << (pos & 7)))
                full = index(a, b, phase)
                assert selected == bool(gate[full >> 3] & (1 << (full & 7)))
                if (even, odd) == UNREACHABLE:
                    assert old is None
                    continue
                if (a, b) == (0, 0):
                    assert (even, odd) == (NONE, NONE)
                    continue
                qa, qb, edge = step(a, b, phase, even, odd)
                assert -BOUND <= qa <= BOUND and -BOUND <= qb <= BOUND
                next_cost = costs[index(qa, qb, (phase + 1) % PHASES)]
                assert costs[full] == edge + next_cost and next_cost < costs[full]
    return dictionaries, bytes(packed), bytes(folded_gate), negate, different_actions


def render(dictionaries, packed, gate, negate):
    source_hash = hashlib.sha256(Path(__file__).read_bytes()).hexdigest()
    lines = ["/* Generated by make_tau_tail_double_fold.py; do not edit.",
             f" * Generator SHA-256: {source_hash}",
             " * Representative: a > 0 or a == 0 and b >= 0.",
             " * Ten-bit phase-local action indices; 254/254 = unreachable.",
             " */", "#ifndef CA_TAU_TAIL_DOUBLE_FOLD_H",
             "#define CA_TAU_TAIL_DOUBLE_FOLD_H", "#include <stdint.h>",
             f"#define CA_TAU_DOUBLE_HALF {HALF}",
             f"#define CA_TAU_DOUBLE_FOLD_BYTES {len(packed)}",
             f"#define CA_TAU_DOUBLE_FOLD_GATE_BYTES {len(gate)}",
             f"#define CA_TAU_DOUBLE_FOLD_DICT_WIDTH {max(map(len, dictionaries))}"]
    for name, values in (("code", packed), ("gate", gate), ("negate", negate)):
        lines.append(f"static const uint8_t ca_tau_double_fold_{name}[{len(values)}] = {{")
        for offset in range(0, len(values), 20):
            lines.append("    " + ", ".join(map(str, values[offset:offset + 20])) + ",")
        lines.append("};")
    lines.append("static const uint16_t ca_tau_double_fold_dictionary"
                 f"[{PHASES}][{max(map(len, dictionaries))}] = {{")
    for dictionary in dictionaries:
        lines.append("    {")
        words = [(even << 8) | odd for even, odd in dictionary]
        for offset in range(0, len(words), 16):
            lines.append("        " + ", ".join(map(str, words[offset:offset + 16])) + ",")
        lines.append("    },")
    lines.extend(["};", "#endif", ""])
    return "\n".join(lines)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output", type=Path, default=Path(__file__).resolve().parents[2] /
                        "src/generated/tau_tail_double_fold.h")
    args = parser.parse_args()
    costs, actions = generate()
    gate, _ = gate_bits(costs, actions)
    dictionaries, packed, folded_gate, negate, different = build(costs, actions, gate)
    header = render(dictionaries, packed, folded_gate, negate)
    if args.output.exists() and args.output.read_text() != header:
        raise SystemExit(f"generated folded policy changed: {args.output}")
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(header)
    print(f"half_states={PHASES * HALF} dictionary_sizes={[len(x) for x in dictionaries]} "
          f"different_tie_actions={different} static_bytes={len(packed) + len(folded_gate) + len(negate) + PHASES * max(map(len, dictionaries)) * 2} "
          f"header_sha256={hashlib.sha256(header.encode()).hexdigest()}")


if __name__ == "__main__":
    main()
