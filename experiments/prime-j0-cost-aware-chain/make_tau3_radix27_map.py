#!/usr/bin/env python3
"""Generate the 729-residue action pool for exact radix-minus-27 recoding."""

import argparse
import hashlib
import json
from pathlib import Path

from screen_tau3_radix27 import action_pool


ROOT = Path(__file__).resolve().parent


def sha256(data):
    return hashlib.sha256(data).hexdigest()


def build_arrays():
    pool, _ = action_pool()
    offsets = [0]
    entries = []
    for a in range(27):
        for b in range(27):
            options = sorted(pool[(a, b)], key=lambda item: (item[1], item[0]))
            assert 1 <= len(options) <= 9
            for (ca, cb), action in options:
                assert (ca % 27, cb % 27) == (a, b)
                assert -128 <= ca <= 127 and -128 <= cb <= 127
                assert 0 <= action < 343 * 8
                entries.append((ca, cb, action))
            offsets.append(len(entries))
    assert len(offsets) == 730 and len(entries) == 2053
    return offsets, entries


def render(offsets, entries):
    lines = ["/* Generated by make_tau3_radix27_map.py; do not hand-edit. */",
             "#ifndef CA_TAU3_RADIX27_H", "#define CA_TAU3_RADIX27_H", "",
             "#include <stdint.h>", "",
             "#define CA_TAU3_RADIX27_SIDE 27",
             "#define CA_TAU3_RADIX27_OPTIONS 2053", "",
             "typedef struct { int8_t a, b; uint16_t action; } ca_tau3_radix27_option;",
             "static const uint16_t ca_tau3_radix27_offsets[730] = {"]
    for start in range(0, len(offsets), 16):
        lines.append("  " + ", ".join(str(v) for v in offsets[start:start + 16]) + ",")
    lines += ["};", "", "static const ca_tau3_radix27_option ca_tau3_radix27_options[2053] = {"]
    for start in range(0, len(entries), 8):
        lines.append("  " + ", ".join("{%d, %d, %d}" % entry
                                       for entry in entries[start:start + 8]) + ",")
    lines += ["};", "", "#endif", ""]
    return "\n".join(lines)


def report(offsets, entries, content):
    return {"schema": 1, "status": "frozen_radix27_action_pool",
            "residues": 729, "options": 2053,
            "option_multiplicity": {"1": 397, "3": 222, "9": 110},
            "coefficient_max_abs": {"a": max(abs(row[0]) for row in entries),
                                    "b": max(abs(row[1]) for row in entries)},
            "compiled_map_bytes": 2 * len(offsets) + 4 * len(entries),
            "generator_sha256": sha256(Path(__file__).read_bytes()),
            "action_pool_source_sha256": sha256((ROOT / "screen_tau3_radix27.py").read_bytes()),
            "header_sha256": sha256(content.encode())}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output", type=Path, required=True)
    parser.add_argument("--report", type=Path, required=True)
    args = parser.parse_args()
    offsets, entries = build_arrays()
    content = render(offsets, entries)
    summary = json.dumps(report(offsets, entries, content), indent=2, sort_keys=True) + "\n"
    for path, value in ((args.output, content), (args.report, summary)):
        path.parent.mkdir(parents=True, exist_ok=True)
        if path.exists() and path.read_text() != value:
            raise ValueError(f"frozen map differs at {path}")
        path.write_text(value)
    print(json.dumps({"header": str(args.output), "report": str(args.report),
                      "options": len(entries), "map_bytes": 2 * len(offsets) + 4 * len(entries)}))


if __name__ == "__main__":
    main()
