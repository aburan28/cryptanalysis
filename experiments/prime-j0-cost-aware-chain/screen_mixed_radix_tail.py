#!/usr/bin/env python3
"""Exact bounded-tail shortest paths using tau^2, tau, and binary steps."""

import argparse
import csv
import hashlib
import json
from heapq import heappop, heappush
from pathlib import Path
import struct

from make_tau_pair_fused import ZERO, catalog, decode
from make_tau_tail_double import tau2
from run import representatives
from screen_global_pair_search import (BOUND, SIDE, bounded, canonical_step, index,
                                       lattice_norm, quotient, reconstruct, score, tail_oracle)
from screen_periodic_pair_atlas import periodic_plan, reference_plan
from screen_tau_tail_double import ENDO_LAMBDA


ROOT = Path(__file__).resolve().parent
REPO = ROOT.parents[1]
HEADER = REPO / "src/generated/tau_pair_mixed_radix_tail.h"
RAW = ROOT / "mixed-radix-tail-raw.csv"
SUMMARY = ROOT / "mixed-radix-tail-screen.json"
FIXTURE = ROOT / "tail-pair-fused-inputs.json"
KIND_PAIR = 0
KIND_TAU = 1
KIND_DOUBLE = 2
KIND_NAMES = ("tau2", "tau", "double")
STEP_COSTS = (10, 6, 8)
INF = 1 << 30


def sha256(path):
    return hashlib.sha256(path.read_bytes()).hexdigest()


def tau(a, b):
    return -3 * b, a + 3 * b


def inverse(state, action, points):
    a, b = state
    kind, word = action
    da, db = points[word]
    ax, by = a - da, b - db
    if kind == KIND_PAIR:
        return quotient(a, b, da, db)
    if kind == KIND_TAU:
        assert ax % 3 == 0
        return by + ax, -ax // 3
    assert kind == KIND_DOUBLE and ax % 2 == by % 2 == 0
    return ax // 2, by // 2


def forward(state, action, points):
    a, b = state
    kind, word = action
    if kind == KIND_PAIR:
        a, b = tau2(a, b)
    elif kind == KIND_TAU:
        a, b = tau(a, b)
    else:
        assert kind == KIND_DOUBLE
        a, b = 2 * a, 2 * b
    da, db = points[word]
    return a + da, b + db


def cost(path):
    total = 0
    started = False
    for kind, word in reversed(path):
        if started:
            total += STEP_COSTS[kind]
        if word != ZERO:
            total += 16
            started = True
    return total


def reconstruct_mixed(path, points):
    state = (0, 0)
    for action in reversed(path):
        state = forward(state, action, points)
    return state


def build_atlas(options, words_by_point):
    units = ((0, 0), (1, 0), (-1, 0), (1, -1), (-1, 1), (-2, 1), (2, -1))
    unit_options = [(a, b, words_by_point[(a, b)]) for a, b in units]
    total = SIDE * SIDE
    costs = [INF] * total
    actions = [None] * total
    origin = index(0, 0)
    costs[origin] = 0
    actions[origin] = (KIND_PAIR, ZERO)
    heap = [(0, 0, 0)]
    edges = 0
    while heap:
        current_cost, qa, qb = heappop(heap)
        if current_cost != costs[index(qa, qb)]:
            continue
        for kind, base, candidates in ((KIND_PAIR, tau2(qa, qb), options),
                                       (KIND_TAU, tau(qa, qb), unit_options),
                                       (KIND_DOUBLE, (2 * qa, 2 * qb), unit_options)):
            for da, db, word in candidates:
                a, b = base[0] + da, base[1] + db
                if not bounded(a, b) or (a, b) == (0, 0):
                    continue
                edges += 1
                next_cost = (current_cost + (STEP_COSTS[kind] if (qa, qb) != (0, 0) else 0)
                             + (16 if word != ZERO else 0))
                pos = index(a, b)
                action = (kind, word)
                if next_cost < costs[pos]:
                    costs[pos], actions[pos] = next_cost, action
                    heappush(heap, (next_cost, a, b))
                elif next_cost == costs[pos] and (actions[pos] is None or action < actions[pos]):
                    actions[pos] = action
    assert all(action is not None for action in actions)
    return costs, actions, edges


def path_from(start, actions, points):
    state = start
    path = []
    while state != (0, 0):
        assert bounded(*state) and len(path) <= 64
        action = actions[index(*state)]
        assert action is not None
        state = inverse(state, action, points)
        path.append(action)
    assert reconstruct_mixed(path, points) == start
    return tuple(path)


def header_text(actions):
    encoded = [(kind << 10) | word for kind, word in actions]
    assert len(encoded) == SIDE * SIDE and max(encoded) < 1 << 12
    lines = ["/* Generated by screen_mixed_radix_tail.py; do not edit. */",
             "#ifndef CA_TAU_PAIR_MIXED_RADIX_TAIL_H",
             "#define CA_TAU_PAIR_MIXED_RADIX_TAIL_H",
             "#include <stdint.h>",
             f"#define CA_TAU_PAIR_MIXED_BOUND {BOUND}",
             f"#define CA_TAU_PAIR_MIXED_SIDE {SIDE}",
             "static const uint16_t ca_tau_pair_mixed_action[16641] = {"]
    for offset in range(0, len(encoded), 12):
        lines.append("    " + ", ".join(str(value) for value in encoded[offset:offset + 12]) + ",")
    lines += ["};", "#endif", ""]
    return "\n".join(lines)


def main(samples):
    reps, _, words_by_point, _, _ = catalog()
    points = {word: (a, b) for (a, b), word in words_by_point.items()}
    options = sorted(((a, b, word) for (a, b), word in words_by_point.items()),
                     key=lambda item: (lattice_norm(item[0], item[1]), item[2]))
    pure_costs, pure_actions = tail_oracle(options)
    mixed_costs, mixed_actions, edges = build_atlas(options, words_by_point)
    assert all(mixed_costs[pos] <= pure_costs[pos] for pos in range(SIDE * SIDE))
    for a in range(-BOUND, BOUND + 1):
        for b in range(-BOUND, BOUND + 1):
            path = path_from((a, b), mixed_actions, points)
            assert cost(path) == mixed_costs[index(a, b)]
    HEADER.write_text(header_text(mixed_actions))

    fixture = json.loads(FIXTURE.read_text())
    selected = set(json.loads((ROOT / "firstword-pair-gate-screen.json").read_text())
                   ["selected_words"])
    rows = []
    inputs = []
    for case_index in (0, 1, 4, 5):
        case = fixture["cases"][case_index]
        scalar_path = ROOT / case["scalar_file"]
        raw = scalar_path.read_bytes()
        assert sha256(scalar_path) == case["scalar_file_sha256"]
        inputs.append(scalar_path)
        assert 1 <= samples <= len(raw) // 8
        scalars = struct.unpack(f"<{samples}Q", raw[:8 * samples])
        curve = case["curve"]["name"]
        order = case["curve"]["order"]
        omega_lambda = order - ENDO_LAMBDA[curve]
        for scalar_index, scalar in enumerate(scalars):
            _, a, b = min(representatives(order, omega_lambda, scalar),
                          key=lambda row: row[0])
            start = (a, b)
            high = []
            state = start
            while state != (0, 0) and (not bounded(*state) or
                                         pure_actions[index(*state)] is None):
                state, word = canonical_step(*state, words_by_point)
                high.append((KIND_PAIR, word))
                assert len(high) < 128
            mixed_tail = path_from(state, mixed_actions, points)
            mixed = tuple(high) + mixed_tail
            assert reconstruct_mixed(mixed, points) == start
            reference = reference_plan(start, words_by_point, pure_actions, reps)
            assert reconstruct(reference, reps) == start
            pure_score = score(reference)
            assert pure_score == cost(tuple((KIND_PAIR, word) for word in reference))
            periodic, _, misses = periodic_plan(start, 27, words_by_point,
                                                pure_actions, reps)
            assert periodic is not None and not misses
            firstword_score = score(periodic if periodic[0] in selected else reference)
            rows.append({"case_id": case["id"], "curve": curve,
                         "point_index": case["point_index"],
                         "scalar_index": scalar_index, "scalar": scalar,
                         "canonical_score": pure_score,
                         "firstword_score": firstword_score,
                         "mixed_score": cost(mixed),
                         "tail_pure_score": pure_costs[index(*state)] if state != (0, 0) else 0,
                         "tail_mixed_score": mixed_costs[index(*state)] if state != (0, 0) else 0,
                         "high_pairs": len(high),
                         "mixed_pairs": sum(kind == KIND_PAIR for kind, _ in mixed),
                         "mixed_tau_steps": sum(kind == KIND_TAU for kind, _ in mixed),
                         "mixed_doubles": sum(kind == KIND_DOUBLE for kind, _ in mixed),
                         "mixed_adds": sum(word != ZERO for _, word in mixed)})
    with RAW.open("w", newline="") as stream:
        writer = csv.DictWriter(stream, fieldnames=tuple(rows[0]), lineterminator="\n")
        writer.writeheader()
        writer.writerows(rows)
    summaries = []
    for case_index in (0, 1, 4, 5):
        case = fixture["cases"][case_index]
        group = [row for row in rows if row["case_id"] == case["id"]]
        baseline = sum(row["canonical_score"] for row in group)
        mixed = sum(row["mixed_score"] for row in group)
        firstword = sum(row["firstword_score"] for row in group)
        summaries.append({"case_id": case["id"], "count": len(group),
                          "canonical_score": baseline, "firstword_score": firstword,
                          "mixed_score": mixed, "saving_vs_canonical_percent":
                          100 * (baseline - mixed) / baseline,
                          "saving_vs_firstword_percent":
                          100 * (firstword - mixed) / firstword,
                          "mixed_tau_steps": sum(row["mixed_tau_steps"] for row in group),
                          "mixed_doubles": sum(row["mixed_doubles"] for row in group),
                          "mixed_adds": sum(row["mixed_adds"] for row in group)})
    sources = [Path(__file__), ROOT / "make_tau_pair_fused.py",
               ROOT / "make_tau_tail_double.py", ROOT / "run.py",
               ROOT / "screen_global_pair_search.py",
               ROOT / "screen_periodic_pair_atlas.py",
               ROOT / "screen_firstword_pair_gate.py",
               ROOT / "firstword-pair-gate-screen.json",
               ROOT / "screen_tau_tail_double.py", FIXTURE] + inputs
    result = {"schema": 1,
              "status": "retrospective_exact_mixed_radix_tail_screen",
              "claim_boundary": "old design and validation scalars; model only, no native/CPU/novelty claim",
              "samples_per_case": samples, "bounded_states": SIDE * SIDE,
              "pure_reached_states": sum(action is not None for action in pure_actions),
              "mixed_reached_states": sum(action is not None for action in mixed_actions),
              "better_bounded_states": sum(mixed_costs[i] < pure_costs[i] and
                                            pure_actions[i] is not None
                                            for i in range(SIDE * SIDE)),
              "graph_edges_examined": edges,
              "radix_step_model": {"tau2": 10, "tau": 6, "double": 8,
                                   "nonzero_digit": 16},
              "unit_digits": 6, "pair_digits": len(words_by_point),
              "encoded_action_bytes": 2 * SIDE * SIDE,
              "header_sha256": sha256(HEADER), "raw_csv": RAW.name,
              "raw_csv_sha256": sha256(RAW),
              "source_sha256": {str(path.relative_to(REPO)): sha256(path)
                                for path in sources},
              "summaries": summaries}
    SUMMARY.write_text(json.dumps(result, indent=2, sort_keys=True) + "\n")
    print(json.dumps({"status": result["status"], "summaries": summaries},
                     sort_keys=True))


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--samples", type=int, default=4096)
    args = parser.parse_args()
    main(args.samples)
