#!/usr/bin/env python3
"""Render the frozen scattered-pair selection as a compact C lookup table."""
import argparse
import hashlib
import json
from pathlib import Path

from make_tau3_fused import build, unit


def render(path):
    design = json.loads(path.read_text())
    assert design['status'] == 'frozen_retrospective_design'
    digits = build()[0]
    ids = {pair: i for i, pair in enumerate(digits, 1)}
    maps = [[0] + [18 * ((p-1)//18) + ids[unit(*digits[(p-1)%18], c)]
                   for p in range(1, 55)] for c in range(6)]
    lines = ['/* Generated by make_tau3_scatter_map.py; do not hand-edit. */',
             '#ifndef CA_TAU3_SCATTER_H', '#define CA_TAU3_SCATTER_H', '',
             '#include <stdint.h>', '',
             'static const uint8_t ca_tau3_scatter_unit_map[6][55] = {']
    for mapping in maps:
        lines.append('    {' + ', '.join(map(str, mapping)) + '},')
    lines += ['};', '']
    for label, record in zip(('small', 'large'), design['records']):
        assert len(record['entries']) == record['extra_point_entries']
        lines += [f'#define CA_TAU3_SCATTER_{label.upper()}_COUNT {len(record["entries"])}',
                  f'static const ca_tau3_scatter_entry ca_tau3_scatter_{label}'
                  f'[CA_TAU3_SCATTER_{label.upper()}_COUNT] = {{']
        for i,j,u,v in record['entries']:
            assert 0 <= i < j < 32 and i//2 != j//2 and 1 <= u <= 54 and 1 <= v <= 54
            assert (u,v) == min((m[u],m[v]) for m in maps)
            lines.append(f'    {{{i}, {j}, {u}, {v}}},')
        lines += ['};', '']
    lines += ['#endif', '']
    return '\n'.join(lines)


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('design', type=Path)
    parser.add_argument('output', type=Path)
    args = parser.parse_args()
    content = render(args.design)
    if args.output.exists() and args.output.read_text() != content:
        raise ValueError('frozen map changed')
    args.output.write_text(content)
    print(json.dumps({'header_sha256': hashlib.sha256(content.encode()).hexdigest()}, sort_keys=True))
