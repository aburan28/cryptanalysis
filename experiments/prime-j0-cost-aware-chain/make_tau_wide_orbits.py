#!/usr/bin/env python3
"""Build complete even-width tau residue tables modulo the six cheap units."""

import argparse
import hashlib
import json
from pathlib import Path

from make_tau8_orbits import unit_action
from run import expand, recode


ID_BITS = 17
MAX_ID = 1 << ID_BITS
WIDTHS = (8, 10, 12)


def residue_key(a, b, modulus):
    return modulus * (a % modulus) + b % modulus


def build(width):
    if width not in WIDTHS:
        raise ValueError("unsupported tau width")
    modulus = 3 ** (width // 2)
    size = modulus * modulus
    representatives = set()
    for key in range(size):
        a, b = divmod(key, modulus)
        representatives.add(min(residue_key(*unit_action(a, b, code), modulus)
                                for code in range(6)))
    reps = sorted(representatives)
    if len(reps) >= MAX_ID or reps[0] != 0:
        raise AssertionError("orbit IDs exceed packed-map width")
    packed = [None] * size
    corrections = []
    orbit_sizes = {}
    for orbit_id, rep in enumerate(reps):
        a, b = divmod(rep, modulus)
        centered_a = a if a <= modulus // 2 else a - modulus
        centered_b = b if b <= modulus // 2 else b - modulus
        correction = expand(recode(centered_a, centered_b)[:width])
        if residue_key(*correction, modulus) != rep:
            raise AssertionError("tau prefix changed the residue class")
        if max(map(abs, correction)) > 32767:
            raise AssertionError("correction exceeds signed 16-bit encoding")
        corrections.append(correction)
        members = set()
        for code in range(6):
            member = residue_key(*unit_action(a, b, code), modulus)
            members.add(member)
            if packed[member] is None:
                packed[member] = orbit_id | (code << ID_BITS)
        orbit_sizes[len(members)] = orbit_sizes.get(len(members), 0) + 1
    if any(value is None for value in packed):
        raise AssertionError("residue orbit map is incomplete")
    for key, entry in enumerate(packed):
        orbit_id = entry & (MAX_ID - 1)
        code = entry >> ID_BITS
        if orbit_id >= len(reps) or code > 5:
            raise AssertionError("invalid packed orbit entry")
        if residue_key(*unit_action(*corrections[orbit_id], code), modulus) != key:
            raise AssertionError("orbit point and correction disagree")
    if corrections[0] != (0, 0):
        raise AssertionError("zero orbit must have zero correction")
    return {"width": width, "modulus": modulus, "reps": reps,
            "corrections": corrections, "packed": packed,
            "orbit_sizes": orbit_sizes}


def render(atlases):
    lines = ["/* Generated by make_tau_wide_orbits.py; do not hand-edit. */",
             "#ifndef CA_TAU_WIDE_ORBITS_H", "#define CA_TAU_WIDE_ORBITS_H", "",
             "#include <stdint.h>", "",
             f"#define CA_TAU_WIDE_ID_BITS {ID_BITS}", "",
             "typedef struct { int16_t a, b; } ca_tau_wide_correction;", ""]
    for width in WIDTHS:
        atlas = atlases[width]
        lines += [f"#define CA_TAU_WIDE{width}_MODULUS {atlas['modulus']}",
                  f"#define CA_TAU_WIDE{width}_ORBIT_COUNT {len(atlas['reps'])}", "",
                  f"static const ca_tau_wide_correction ca_tau_wide{width}_correction"
                  f"[{len(atlas['reps'])}] = {{"]
        for a, b in atlas["corrections"]:
            lines.append(f"  {{{a}, {b}}},")
        lines += ["};", "",
                  f"static const uint32_t ca_tau_wide{width}_index[{len(atlas['packed'])}] = {{"]
        for start in range(0, len(atlas["packed"]), 12):
            lines.append("  " + ", ".join(str(x) for x in
                                        atlas["packed"][start:start + 12]) + ",")
        lines += ["};", ""]
    lines += ["#endif", ""]
    return "\n".join(lines)


def main(output):
    atlases = {width: build(width) for width in WIDTHS}
    content = render(atlases)
    output.parent.mkdir(parents=True, exist_ok=True)
    if output.exists() and output.read_text() != content:
        raise ValueError(f"generated map differs from frozen file: {output}")
    output.write_text(content)
    print(json.dumps({
        "status": "generated_complete_tau_residue_orbits",
        "widths": {width: {"modulus": atlas["modulus"],
                           "orbits": len(atlas["reps"]),
                           "orbit_sizes": atlas["orbit_sizes"]}
                   for width, atlas in atlases.items()},
        "sha256": hashlib.sha256(content.encode()).hexdigest(),
    }, sort_keys=True))


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output", type=Path, required=True)
    args = parser.parse_args()
    main(args.output)
