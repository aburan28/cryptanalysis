#!/usr/bin/env python3
"""Generate the fixed 2,048-entry budgeted orbit index."""

import argparse
import hashlib
import json
from pathlib import Path

from make_tau8_orbits import build_orbits


def make_hot(screen_path):
    screen = json.loads(screen_path.read_text())
    selected = screen["selected_orbit_ids"]
    encoded = json.dumps(selected, separators=(",", ":")).encode()
    if (screen["candidate_budget"] != 2048 or len(selected) != 2048 or
            len(set(selected)) != 2048 or
            hashlib.sha256(encoded).hexdigest() != screen[
                "selected_orbit_ids_sha256"]):
        raise ValueError("hot orbit selection changed")
    _, _, representatives = build_orbits()
    index = [65535] * len(representatives)
    for dense, orbit_id in enumerate(selected):
        if not (0 <= orbit_id < len(representatives)):
            raise ValueError("orbit ID outside map")
        u, v = representatives[orbit_id]
        if not (u and v):
            raise ValueError("hot entry must have two nonzero patterns")
        index[orbit_id] = dense
    return index, [representatives[i][0] for i in selected], [
        representatives[i][1] for i in selected]


def render(index, first, second):
    lines = ["/* Generated by make_tau8_hot.py; do not hand-edit. */",
             "#ifndef CA_TAU8_HOT_MAP_H", "#define CA_TAU8_HOT_MAP_H", "",
             "#include <stdint.h>", "", "#define CA_TAU8_HOT_COUNT 2048", ""]
    for name, ctype, values, width in (
        ("ca_tau8_hot_id", "uint16_t", index, 18),
        ("ca_tau8_hot_rep_u", "uint8_t", first, 27),
        ("ca_tau8_hot_rep_v", "uint8_t", second, 27),
    ):
        lines.append(f"static const {ctype} {name}[{len(values)}] = {{")
        for start in range(0, len(values), width):
            lines.append("  " + ", ".join(str(x) for x in
                                      values[start:start + width]) + ",")
        lines += ["};", ""]
    lines += ["#endif", ""]
    return "\n".join(lines)


def main(output, screen_path):
    content = render(*make_hot(screen_path))
    output.parent.mkdir(parents=True, exist_ok=True)
    if output.exists() and output.read_text() != content:
        raise ValueError(f"generated map differs from frozen file: {output}")
    output.write_text(content)
    print({"status": "generated_hot_orbit_map", "entries": 2048,
           "sha256": hashlib.sha256(content.encode()).hexdigest()})


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output", type=Path, required=True)
    parser.add_argument("--screen", type=Path, default=Path(__file__).with_name(
        "hot-orbit-screen.json"))
    args = parser.parse_args()
    main(args.output, args.screen)
