#!/usr/bin/env python3
"""Freeze hot pair-orbit maps from old tau3 traces, with a cold two-half path."""

import argparse
from collections import Counter
import gzip
import hashlib
import json
from pathlib import Path

from make_tau3_fused import build


ROOT = Path(__file__).resolve().parent
BUDGET = {"glv-j0-32": (4, 396), "j0-56": (7, 756)}
UNUSED = 65535


def sha256(data):
    return hashlib.sha256(data).hexdigest()


def candidate(curve, blocks, budget, pair_ids, compact_panel, verified_traces):
    traces = sorted((ROOT / "tau3-fused-design-traces").glob(f"{curve}-point*.txt.gz"))
    assert len(traces) == 4
    frequency = Counter()
    full_adds = pair_events = scalars = 0
    trace_hashes = []
    for path in traces:
        compressed = path.read_bytes()
        relative = str(path.relative_to(ROOT))
        assert verified_traces[relative] == sha256(compressed)
        trace_hashes.append({"file": relative, "sha256": sha256(compressed)})
        for line in gzip.decompress(compressed).decode().splitlines():
            pieces = line.split(":")
            assert pieces[0].startswith("tau3_actions=")
            actions = [int(value) for value in pieces[2:]]
            assert len(actions) == int(pieces[1]) and len(actions) <= blocks
            scalars += 1
            for block, action in enumerate(actions):
                orbit_id, unit = action >> 3, action & 7
                assert 0 <= orbit_id < 343 and unit < 6
                full_adds += orbit_id != 0
                if orbit_id in pair_ids:
                    frequency[(block, orbit_id)] += 1
                    pair_events += 1
    assert scalars == 16384
    half_slots = 18 * blocks
    hot_budget = budget - half_slots
    assert 0 < hot_budget <= len(frequency)
    chosen = sorted(frequency, key=lambda key: (-frequency[key], key[0], key[1]))[:hot_budget]
    hot_by_block = [sorted(orbit_id for block, orbit_id in chosen if block == i)
                    for i in range(blocks)]
    assert sum(map(len, hot_by_block)) == hot_budget
    hot_offsets = [0]
    for entries in hot_by_block:
        hot_offsets.append(hot_offsets[-1] + len(entries))
    flat_hot = [orbit_id for entries in hot_by_block for orbit_id in entries]
    hot_slots = [UNUSED] * (blocks * 343)
    for block, entries in enumerate(hot_by_block):
        for slot, orbit_id in enumerate(entries):
            assert orbit_id in pair_ids
            hot_slots[343 * block + orbit_id] = slot
    saved = sum(frequency[key] for key in chosen)
    compact_adds = sum(int(row["fields"]["adds"]) for row in compact_panel["rows"]
                       if row["mode"] == "pos-compact" and row["fields"]["curve"] == curve)
    assert compact_adds > 0
    record = {"curve": curve, "blocks": blocks, "point_entries": budget,
              "point_bytes": budget * 32, "half_entries": half_slots,
              "hot_entries": hot_budget, "hot_counts_by_block": list(map(len, hot_by_block)),
              "scalars": scalars, "full_fused_adds": full_adds,
              "pair_events": pair_events, "hot_pair_hits": saved,
              "predicted_sparse_adds": full_adds + pair_events - saved,
              "compact_pos_adds": compact_adds,
              "trace_files": trace_hashes}
    return record, hot_offsets, flat_hot, hot_slots


def build_candidate():
    reps = build()[-1]
    pair_ids = {i for i, (u, v) in enumerate(reps) if u and v}
    single_ids = {i for i, (u, v) in enumerate(reps) if (u == 0) != (v == 0)}
    assert len(pair_ids) == 324 and len(single_ids) == 18
    assert pair_ids | single_ids | {0} == set(range(343))
    prior_path = ROOT / "compact-pos-panel.json"
    compact_panel = json.loads(prior_path.read_text())
    native_path = ROOT / "tau3-fused-native-design.json"
    native = json.loads(native_path.read_text())
    assert native["status"] == "old_data_exact_native_action_match"
    verified_traces = {row["trace_file"]: row["trace_gzip_sha256"]
                       for row in native["rows"]}
    assert len(verified_traces) == 8
    records, arrays = [], {}
    for curve, (blocks, budget) in BUDGET.items():
        record, *maps = candidate(curve, blocks, budget, pair_ids,
                                  compact_panel, verified_traces)
        records.append(record)
        arrays[curve] = maps
    return records, arrays, sha256(prior_path.read_bytes()), sha256(native_path.read_bytes())


def render_array(name, ctype, values, width):
    lines = [f"static const {ctype} {name}[{len(values)}] = {{"]
    for start in range(0, len(values), width):
        lines.append("  " + ", ".join(str(v) for v in values[start:start + width]) + ",")
    lines += ["};", ""]
    return lines


def render_header(records, arrays):
    lines = ["/* Generated by make_tau3_sparse.py; do not hand-edit. */",
             "#ifndef CA_TAU3_SPARSE_H", "#define CA_TAU3_SPARSE_H", "",
             "#include <stdint.h>", ""]
    for label, record in zip(("small", "large"), records):
        offsets, ids, slots = arrays[record["curve"]]
        lines += [f"#define CA_TAU3_SPARSE_{label.upper()}_BLOCKS {record['blocks']}",
                  f"#define CA_TAU3_SPARSE_{label.upper()}_ENTRIES {record['point_entries']}", ""]
        lines += render_array(f"ca_tau3_sparse_{label}_hot_offsets", "uint16_t", offsets, 16)
        lines += render_array(f"ca_tau3_sparse_{label}_hot_ids", "uint16_t", ids, 16)
        lines += render_array(f"ca_tau3_sparse_{label}_hot_slots", "uint16_t", slots, 16)
    lines += ["#endif", ""]
    return "\n".join(lines)


def render_report(records, prior_hash, native_hash, header, source):
    report = {"schema": 1, "status": "retrospective_sparse_hot_pair_screen",
              "cpu_timing_claim": None, "budget_policy": "two times compact positional point slots",
              "selection_rule": "pair orbits only; descending old-trace frequency, ties by block then orbit ID",
              "cold_path": "two prepared one-digit half points, each with exact unit action",
              "prior_panel_sha256": prior_hash,
              "native_trace_receipt_sha256": native_hash,
              "source_sha256": sha256(source), "header_sha256": sha256(header.encode()),
              "records": records}
    return json.dumps(report, indent=2, sort_keys=True) + "\n"


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output", type=Path, required=True)
    parser.add_argument("--screen", type=Path, required=True)
    args = parser.parse_args()
    records, arrays, prior_hash, native_hash = build_candidate()
    header = render_header(records, arrays)
    report = render_report(records, prior_hash, native_hash, header,
                           Path(__file__).read_bytes())
    for path, content in ((args.output, header), (args.screen, report)):
        path.parent.mkdir(parents=True, exist_ok=True)
        if path.exists() and path.read_text() != content:
            raise ValueError(f"frozen output changed: {path}")
        path.write_text(content)
    print(json.dumps({"status": "retrospective_sparse_hot_pair_screen",
                      "records": [{key: row[key] for key in
                                   ("curve", "point_entries", "predicted_sparse_adds",
                                    "compact_pos_adds")} for row in records]}, sort_keys=True))


if __name__ == "__main__":
    main()
