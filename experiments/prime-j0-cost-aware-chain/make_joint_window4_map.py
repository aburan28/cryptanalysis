#!/usr/bin/env python3
"""Generate a compact six-unit action map for balanced radix-16 pairs."""

import hashlib
import json
from pathlib import Path
import sys


def actions(x, y):
    answer = []
    for sign in (1, -1):
        a, b = sign * x, sign * y
        for _ in range(3):
            answer.append((a, b))
            a, b = -b, a - b
    return answer


def build():
    raw = [(x, y) for x in range(-8, 8) for y in range(-8, 8)]
    reps = sorted({min(actions(*pair)) for pair in raw if pair != (0, 0)})
    if len(reps) != 71 or any(not -128 <= z <= 127 for pair in reps for z in pair):
        raise AssertionError("unexpected joint-window orbit set")
    rank = {rep: i for i, rep in enumerate(reps)}
    code = []
    for pair in raw:
        if pair == (0, 0):
            code.append(127)
            continue
        rep = min(actions(*pair))
        matches = [i for i, moved in enumerate(actions(*rep)) if moved == pair]
        if len(matches) != 1:
            raise AssertionError("nonunique unit action")
        code.append(rank[rep] | (matches[0] << 7))
    assert len(code) == 256
    return reps, code


def array(name, ctype, values, width=12):
    rows = [", ".join(str(value) for value in values[i:i + width])
            for i in range(0, len(values), width)]
    return (f"static const {ctype} {name}[{len(values)}] = {{\n" +
            ",\n".join("    " + row for row in rows) + "\n};\n")


def render(reps, code):
    return ("/* Generated by make_joint_window4_map.py; do not edit by hand. */\n"
            "#ifndef CA_JOINT_WINDOW4_H\n#define CA_JOINT_WINDOW4_H\n"
            "#include <stdint.h>\n"
            "#define CA_JOINT_WINDOW4_ORBITS 71\n"
            "#define CA_JOINT_WINDOW4_ZERO 127\n"
            + array("ca_joint_window4_rep_x", "int8_t", [x for x, _ in reps])
            + array("ca_joint_window4_rep_y", "int8_t", [y for _, y in reps])
            + array("ca_joint_window4_action", "uint16_t", code)
            + "#endif\n")


def main(design_path, output):
    design = json.loads(design_path.read_text())
    if design.get("status") != "frozen_retrospective_design" or \
            design.get("orbit_count") != 71 or design.get("window_width") != 4:
        raise ValueError("joint-window design is not frozen")
    reps, code = build()
    content = render(reps, code).encode()
    if output.exists() and output.read_bytes() != content:
        raise ValueError("generated joint-window map changed")
    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_bytes(content)
    print(json.dumps({"orbits": len(reps), "raw_pairs": len(code),
                      "header_sha256": hashlib.sha256(content).hexdigest()}, sort_keys=True))


if __name__ == "__main__":
    if len(sys.argv) != 3:
        raise SystemExit("usage: make_joint_window4_map.py DESIGN HEADER")
    main(Path(sys.argv[1]), Path(sys.argv[2]))
