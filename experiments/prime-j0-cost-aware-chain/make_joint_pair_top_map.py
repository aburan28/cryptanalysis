#!/usr/bin/env python3
"""Generate complete upper-pair orbit tables from a lattice-coordinate bound."""

import argparse
import hashlib
import json
from pathlib import Path

from make_joint_pair_map import build, unit_actions


ROOT = Path(__file__).resolve().parent


def top_sets():
    pair_design = json.loads((ROOT / "joint-pair-design.json").read_text())
    zero_design = json.loads((ROOT / "joint-window4-zero-design.json").read_text())
    zero_records = {row["curve"]: row for row in zero_design["records"]}
    preferred, reps, _ = build()
    rank = {rep: index for index, rep in enumerate(reps)}
    result = {}
    for record in pair_design["records"]:
        curve = record["curve"]
        v1, v2 = zero_records[curve]["lattice_basis"]
        coordinate_bound = (sum(abs(value) for value in (*v1, *v2)) + 1) // 2
        bounds = [coordinate_bound]
        for _ in range(record["hex_digit_positions"] - 2):
            bounds.append((bounds[-1] + 10) // 16)
        top_bound = bounds[-1]
        top = set()
        for x0 in range(-top_bound, top_bound + 1):
            for y0 in range(-top_bound, top_bound + 1):
                x, y = x0, y0
                for _ in range(2):
                    dx, dy = preferred[(x % 16, y % 16)]
                    x, y = (x - dx) // 16, (y - dy) // 16
                if x or y:
                    raise AssertionError("upper-pair coordinate exceeds two hex digits")
                if x0 or y0:
                    top.add(rank[min(unit_actions(x0, y0))])
        orbits = sorted(top)
        max_coord = max(max(abs(value) for value in reps[index]) for index in orbits)
        result[curve] = {"babai_l1_coordinate_bound": coordinate_bound,
                         "bounds_after_each_digit": bounds,
                         "top_coordinate_bound": top_bound,
                         "top_orbits": orbits,
                         "top_max_representative_coordinate": max_coord,
                         "exhaustive_top_coordinate_pairs": (2 * top_bound + 1)**2}
    if len(result["glv-j0-32"]["top_orbits"]) != 756 or \
            len(result["j0-56"]["top_orbits"]) != 210:
        raise AssertionError("unexpected bounded upper-pair atlas")
    return result


def array(name, values, width=16):
    rows = [", ".join(str(value) for value in values[i:i + width])
            for i in range(0, len(values), width)]
    return (f"static const uint16_t {name}[{len(values)}] = {{\n" +
            ",\n".join("    " + row for row in rows) + "\n};\n")


def render(result):
    small = result["glv-j0-32"]
    large = result["j0-56"]
    small_rank = [65535] * 11061
    large_rank = [65535] * 11061
    for index, orbit in enumerate(small["top_orbits"]):
        small_rank[orbit] = index
    for index, orbit in enumerate(large["top_orbits"]):
        large_rank[orbit] = index
    return ("/* Generated by make_joint_pair_top_map.py; do not edit by hand. */\n"
            "#ifndef CA_JOINT_PAIR_TOP_MAP_H\n#define CA_JOINT_PAIR_TOP_MAP_H\n"
            "#include <stdint.h>\n"
            "#define CA_JOINT_PAIR_TOP_SMALL_ORBITS 756\n"
            "#define CA_JOINT_PAIR_TOP_LARGE_ORBITS 210\n"
            "#define CA_JOINT_PAIR_TOP_MISSING 65535\n"
            + array("ca_joint_pair_top_small_orbit", small["top_orbits"])
            + array("ca_joint_pair_top_large_orbit", large["top_orbits"])
            + array("ca_joint_pair_top_small_rank", small_rank)
            + array("ca_joint_pair_top_large_rank", large_rank)
            + "#endif\n")


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("output", type=Path)
    args = parser.parse_args()
    result = top_sets()
    content = render(result).encode()
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_bytes(content)
    print(json.dumps({"header_sha256": hashlib.sha256(content).hexdigest(),
                      "small_orbits": len(result["glv-j0-32"]["top_orbits"]),
                      "large_orbits": len(result["j0-56"]["top_orbits"]),
                      "static_bytes": 2 * (11061 * 2 + 756 + 210)}, sort_keys=True))


if __name__ == "__main__":
    main()
