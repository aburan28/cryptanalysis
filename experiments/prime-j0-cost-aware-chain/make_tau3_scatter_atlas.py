#!/usr/bin/env python3
"""Render a dense orbit-indexed lookup for the frozen scattered-pair table."""

import argparse
import hashlib
import json
from pathlib import Path

from make_tau3_fused import build, unit
from make_tau3_scatter_design import unit_maps


ORBIT_COUNT = 505
PAIR_KEY_COUNT = 400
ABSENT_PAIR = 255
ABSENT_SLOT = 65535


def render(layout_path, table_path):
    layout_blob = layout_path.read_bytes()
    table_blob = table_path.read_bytes()
    layout, table = json.loads(layout_blob), json.loads(table_blob)
    if layout["status"] != "frozen_retrospective_layout":
        raise ValueError("atlas layout is not frozen")
    if layout["table_design_sha256"] != hashlib.sha256(table_blob).hexdigest():
        raise ValueError("scattered point table changed")

    maps = unit_maps(build()[0], unit)
    canonical = [min((mapping[u], mapping[v]) for mapping in maps)
                 for u in range(55) for v in range(55)]
    representatives = sorted(set(canonical))
    if len(representatives) != ORBIT_COUNT:
        raise ValueError("canonical pair-orbit count changed")
    rank = {rep: index for index, rep in enumerate(representatives)}
    packed = []
    for u in range(55):
        for v in range(55):
            rep = canonical[55 * u + v]
            code = next(code for code, mapping in enumerate(maps)
                        if (mapping[rep[0]], mapping[rep[1]]) == (u, v))
            packed.append(rank[rep] | (code << 9))

    lines = ["/* Generated by make_tau3_scatter_atlas.py; do not hand-edit. */",
             "#ifndef CA_TAU3_SCATTER_ATLAS_H", "#define CA_TAU3_SCATTER_ATLAS_H", "",
             "#include <stdint.h>", "",
             "#define CA_TAU3_SCATTER_ATLAS_ORBITS 505", "",
             "static const uint16_t ca_tau3_scatter_atlas_rep[505] = {"]
    rep_words = [55 * u + v for u, v in representatives]
    for start in range(0, len(rep_words), 16):
        lines.append("    " + ", ".join(map(str, rep_words[start:start + 16])) + ",")
    lines += ["};", "", "static const uint16_t ca_tau3_scatter_atlas_code[3025] = {"]
    for start in range(0, len(packed), 16):
        lines.append("    " + ", ".join(map(str, packed[start:start + 16])) + ",")
    lines += ["};", ""]

    if len(table["records"]) != 2:
        raise ValueError("expected exactly two frozen curve records")
    for label, curve, record in zip(("small", "large"), ("glv-j0-32", "j0-56"),
                                    table["records"]):
        if record["curve"] != curve:
            raise ValueError("curve order changed in scattered design")
        entries = record["entries"]
        pair_keys = sorted({20 * i + j for i, j, _, _ in entries})
        if len(pair_keys) != layout["position_pair_counts"][record["curve"]]:
            raise ValueError("position-pair count changed")
        if len(pair_keys) >= ABSENT_PAIR:
            raise ValueError("position-pair index no longer fits uint8_t")
        pair_id = {key: index for index, key in enumerate(pair_keys)}
        pair_map = [pair_id.get(key, ABSENT_PAIR) for key in range(PAIR_KEY_COUNT)]
        slots = [ABSENT_SLOT] * (len(pair_keys) * ORBIT_COUNT)
        for slot, (i, j, u, v) in enumerate(entries):
            if not (0 <= i < j < 20 and i // 2 != j // 2):
                raise ValueError("invalid position pair")
            rep = canonical[55 * u + v]
            if rep != (u, v):
                raise ValueError("entry is not canonical")
            index = pair_id[20 * i + j] * ORBIT_COUNT + rank[rep]
            if slots[index] != ABSENT_SLOT:
                raise ValueError("duplicate orbit in one position pair")
            slots[index] = slot
        lines += [f"#define CA_TAU3_SCATTER_ATLAS_{label.upper()}_PAIRS {len(pair_keys)}",
                  f"static const uint8_t ca_tau3_scatter_atlas_{label}_pair[400] = {{"]
        for start in range(0, len(pair_map), 20):
            lines.append("    " + ", ".join(map(str, pair_map[start:start + 20])) + ",")
        lines += ["};", "",
                  f"static const uint16_t ca_tau3_scatter_atlas_{label}_slot"
                  f"[{len(pair_keys)} * CA_TAU3_SCATTER_ATLAS_ORBITS] = {{"]
        for start in range(0, len(slots), 16):
            lines.append("    " + ", ".join(map(str, slots[start:start + 16])) + ",")
        lines += ["};", ""]
    lines += ["#endif", ""]
    return "\n".join(lines)


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("layout", type=Path)
    parser.add_argument("table", type=Path)
    parser.add_argument("output", type=Path)
    args = parser.parse_args()
    content = render(args.layout, args.table)
    if args.output.exists() and args.output.read_text() != content:
        raise ValueError("frozen atlas header changed")
    args.output.write_text(content)
    print(json.dumps({"header_sha256": hashlib.sha256(content.encode()).hexdigest()},
                     sort_keys=True))
