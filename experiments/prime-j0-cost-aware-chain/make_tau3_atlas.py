#!/usr/bin/env python3
"""Generate the six-step quotient/correction atlas for frozen width-three tau."""

import argparse
import hashlib
import json
from pathlib import Path

from make_tau3_fused import UNREACHABLE, block_pattern, build, recode, tau


ROOT = Path(__file__).resolve().parent
SIDE = 81
BLOCK_RADIX = -27  # tau^6


def correction(sequence, digits):
    a = b = 0
    for digit_id in reversed(sequence):
        a, b = tau(a, b)
        if digit_id:
            da, db = digits[digit_id - 1]
            a += da
            b += db
    return a, b


def build_atlas():
    digits, residue, _, orbit_id, orbit_unit, _ = build()
    entries = []
    for a in range(SIDE):
        for b in range(SIDE):
            sequence = (recode(a, b, digits, residue) + [0] * 6)[:6]
            ca, cb = correction(sequence, digits)
            if (a - ca) % 27 or (b - cb) % 27:
                raise AssertionError("six-step correction is not divisible by tau^6")
            if not (-128 <= ca <= 127 and -128 <= cb <= 127):
                raise AssertionError("correction does not fit signed byte")
            u = block_pattern(sequence[:3])
            v = block_pattern(sequence[3:])
            slot = 55 * u + v
            identity = orbit_id[slot]
            unit = orbit_unit[slot]
            if identity == UNREACHABLE or unit >= 6:
                raise AssertionError("invalid width-three block action")
            entries.append((ca, cb, (identity << 3) | unit))
    assert len(entries) == SIDE * SIDE
    return entries


def render(entries):
    lines = ["/* Generated by make_tau3_atlas.py; do not hand-edit. */",
             "#ifndef CA_TAU3_ATLAS_H", "#define CA_TAU3_ATLAS_H", "",
             "#include <stdint.h>", "",
             "typedef struct { int8_t a, b; uint16_t action; } ca_tau3_atlas_entry;",
             "static const ca_tau3_atlas_entry ca_tau3_atlas[6561] = {"]
    for start in range(0, len(entries), 8):
        lines.append("  " + ", ".join("{%d, %d, %d}" % e for e in entries[start:start + 8]) + ",")
    lines += ["};", "", "#endif", ""]
    return "\n".join(lines)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output", type=Path, required=True)
    args = parser.parse_args()
    entries = build_atlas()
    content = render(entries)
    args.output.parent.mkdir(parents=True, exist_ok=True)
    if args.output.exists() and args.output.read_text() != content:
        raise ValueError("generated atlas differs from frozen header")
    args.output.write_text(content)
    print(json.dumps({"entries": len(entries), "element_bytes": 4,
                      "header_sha256": hashlib.sha256(content.encode()).hexdigest(),
                      "source_sha256": hashlib.sha256(Path(__file__).read_bytes()).hexdigest()},
                     sort_keys=True))


if __name__ == "__main__":
    main()
