#!/usr/bin/env python3
"""Generate the frozen bounded and modulus-27 pair action tables for C."""

import hashlib
from pathlib import Path

from make_tau_pair_fused import UNREACHABLE, catalog, decode
from screen_global_pair_search import SIDE, index, lattice_norm, tail_oracle


ROOT = Path(__file__).resolve().parents[2]
HEADER = ROOT / "src/generated/tau_pair_periodic.h"
MODULUS = 27


def generate():
    reps, _, words_by_point, _, _ = catalog()
    options = [(a, b, word) for (a, b), word in words_by_point.items()]
    assert len(options) == 727
    assert all(decode(word, reps) == (a, b) for a, b, word in options)
    options.sort(key=lambda item: (lattice_norm(item[0], item[1]), item[2]))
    _, actions = tail_oracle(options)
    assert sum(action is not None for action in actions) == 15043
    periodic = [actions[index(a, b)] for a in range(-13, 14) for b in range(-13, 14)]
    assert len(periodic) == MODULUS * MODULUS and all(word is not None for word in periodic)
    lines = ["/* Generated by make_periodic_pair_native.py; do not edit. */",
             "#ifndef CA_TAU_PAIR_PERIODIC_H",
             "#define CA_TAU_PAIR_PERIODIC_H",
             "#include <stdint.h>",
             "#define CA_TAU_PAIR_PERIODIC_BOUND 64",
             f"#define CA_TAU_PAIR_PERIODIC_SIDE {SIDE}",
             f"#define CA_TAU_PAIR_PERIODIC_MODULUS {MODULUS}",
             f"static const uint16_t ca_tau_pair_periodic_tail[{SIDE * SIDE}] = {{"]
    encoded = [UNREACHABLE if word is None else word for word in actions]
    for offset in range(0, len(encoded), 16):
        lines.append("    " + ", ".join(str(word) for word in encoded[offset:offset + 16]) + ",")
    lines.append("};")
    lines.append(f"static const uint16_t ca_tau_pair_periodic_atlas[{MODULUS * MODULUS}] = {{")
    for offset in range(0, len(periodic), 16):
        lines.append("    " + ", ".join(str(word) for word in periodic[offset:offset + 16]) + ",")
    lines.extend(["};", "#endif", ""])
    content = "\n".join(lines).encode()
    HEADER.write_bytes(content)
    print(f"{HEADER.relative_to(ROOT)} sha256={hashlib.sha256(content).hexdigest()} "
          "tail_reached=15043 periodic_reached=729")


if __name__ == "__main__":
    generate()
