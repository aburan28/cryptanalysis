#!/usr/bin/env python3
"""Generate the unit-closed radix-16 digit and two-window orbit atlas."""

import argparse
import hashlib
import json
from collections import defaultdict
from pathlib import Path


RADIX = 16
ORBIT_BITS = 14


def unit_actions(x, y):
    answer = []
    for sign in (1, -1):
        a, b = sign * x, sign * y
        for _ in range(3):
            answer.append((a, b))
            a, b = -b, a - b
    return answer


def eisenstein_norm(x, y):
    return x * x - x * y + y * y


def digits():
    residue_orbit = {}
    remaining = {(x, y) for x in range(RADIX) for y in range(RADIX)}
    while remaining:
        canonical = min(remaining)
        members = {(x % RADIX, y % RADIX) for x, y in unit_actions(*canonical)}
        for member in members:
            residue_orbit[member] = canonical
        remaining.difference_update(members)
    closed = {(0, 0)}
    for canonical in sorted(set(residue_orbit.values())):
        if canonical == (0, 0):
            continue
        _, x, y = min((eisenstein_norm(x, y), x, y)
                      for x in range(-RADIX, RADIX + 1)
                      for y in range(-RADIX, RADIX + 1)
                      if residue_orbit[(x % RADIX, y % RADIX)] == canonical)
        closed.update(unit_actions(x, y))
    choices = defaultdict(list)
    for digit in sorted(closed):
        choices[(digit[0] % RADIX, digit[1] % RADIX)].append(digit)
    preferred = {residue: min(options, key=lambda digit:
                 (eisenstein_norm(*digit), sum(map(abs, digit)), digit))
                 for residue, options in choices.items()}
    if len(residue_orbit) != 256 or len(set(residue_orbit.values())) != 44 or \
            len(closed) != 259 or len(preferred) != 256 or \
            sorted(len(options) for options in choices.values()).count(2) != 3:
        raise AssertionError("unexpected unit-closed radix-16 alphabet")
    return closed, preferred


def build():
    closed, preferred = digits()
    coefficients = {(a + RADIX * c, b + RADIX * d)
                    for a, b in closed for c, d in closed}
    all_reps = sorted({min(unit_actions(*pair)) for pair in coefficients})
    if len(coefficients) != 66367 or len(all_reps) != 11062 or all_reps.count((0, 0)) != 1:
        raise AssertionError("unexpected two-window coefficient quotient")
    reps = [pair for pair in all_reps if pair != (0, 0)]
    rank = {rep: index for index, rep in enumerate(reps)}
    action = []
    for first in range(256):
        x0, y0 = preferred[(first >> 4, first & 15)]
        for second in range(256):
            x1, y1 = preferred[(second >> 4, second & 15)]
            coefficient = (x0 + RADIX * x1, y0 + RADIX * y1)
            if coefficient == (0, 0):
                action.append((1 << ORBIT_BITS) - 1)
                continue
            rep = min(unit_actions(*coefficient))
            matches = [code for code, moved in enumerate(unit_actions(*rep))
                       if moved == coefficient]
            if len(matches) != 1:
                raise AssertionError("nonunique unit action")
            action.append(rank[rep] | (matches[0] << ORBIT_BITS))
    if len(action) != 65536 or len(reps) != 11061 or \
            max(max(map(abs, rep)) for rep in reps) != 170:
        raise AssertionError("unexpected generated atlas shape")
    return preferred, reps, action


def array(name, ctype, values, width=12):
    rows = [", ".join(str(value) for value in values[i:i + width])
            for i in range(0, len(values), width)]
    return (f"static const {ctype} {name}[{len(values)}] = {{\n" +
            ",\n".join("    " + row for row in rows) + "\n};\n")


def render(preferred, reps, action):
    ordered_digits = [preferred[(index >> 4, index & 15)] for index in range(256)]
    return ("/* Generated by make_joint_pair_map.py; do not edit by hand. */\n"
            "#ifndef CA_JOINT_PAIR_MAP_H\n#define CA_JOINT_PAIR_MAP_H\n"
            "#include <stdint.h>\n"
            "#define CA_JOINT_PAIR_ORBITS 11061\n"
            "#define CA_JOINT_PAIR_ORBIT_BITS 14\n"
            "#define CA_JOINT_PAIR_ZERO 16383\n"
            + array("ca_joint_pair_digit_x", "int8_t", [x for x, _ in ordered_digits])
            + array("ca_joint_pair_digit_y", "int8_t", [y for _, y in ordered_digits])
            + array("ca_joint_pair_rep_x", "int16_t", [x for x, _ in reps])
            + array("ca_joint_pair_rep_y", "int16_t", [y for _, y in reps])
            + array("ca_joint_pair_action", "uint32_t", action)
            + "#endif\n")


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("output", type=Path)
    args = parser.parse_args()
    preferred, reps, action = build()
    content = render(preferred, reps, action).encode()
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_bytes(content)
    print(json.dumps({"header_sha256": hashlib.sha256(content).hexdigest(),
                      "orbit_representatives": len(reps), "residue_pairs": len(action),
                      "static_bytes": 2 * 256 + 2 * 2 * len(reps) + 4 * len(action)},
                     sort_keys=True))


if __name__ == "__main__":
    main()
