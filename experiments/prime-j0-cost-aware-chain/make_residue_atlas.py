#!/usr/bin/env python3
"""Generate the exact four-step tau residue atlas used by ec_tau.c."""

import argparse
import hashlib
from pathlib import Path

from run import TABLE, expand


MODULUS = 81
SLOTS = {9 * x + y: digit for (x, y), digit in TABLE.items()}


def prefix4(a, b):
    slots = []
    for _ in range(4):
        slot = 255
        if a % 3:
            slot = 9 * (a % 9) + b % 9
            digit = SLOTS[slot]
            a -= digit[0]
            b -= digit[1]
        slots.append(slot)
        if a % 3:
            raise AssertionError("tau digit left a nondivisible coefficient")
        a, b = a + b, -a // 3
    return tuple(slots), (a, b)


def build():
    patterns = [(255, 255, 0, 0)]
    for position in range(4):
        for slot in sorted(SLOTS):
            digits = [None] * 4
            digits[position] = SLOTS[slot]
            ca, cb = expand(digits)
            if not (-128 <= ca <= 127 and -128 <= cb <= 127):
                raise AssertionError("correction exceeds signed-byte range")
            patterns.append((slot, position, ca, cb))
    if len(patterns) != 217:
        raise AssertionError("unexpected pattern count")
    pattern_id = {(position, slot): index
                  for index, (slot, position, _, _) in enumerate(patterns)}
    indexes = []
    counts = [0] * len(patterns)
    for a in range(MODULUS):
        for b in range(MODULUS):
            slots, quotient = prefix4(a, b)
            selected = [(position, slot) for position, slot in enumerate(slots)
                        if slot != 255]
            if len(selected) > 1:
                raise AssertionError("width-four block had multiple digits")
            key = selected[0] if selected else (255, 255)
            index = pattern_id[key]
            slot, position, ca, cb = patterns[index]
            if slot != 255 and slots[position] != slot:
                raise AssertionError("pattern slot mismatch")
            da, db = a - ca, b - cb
            if (da + 3 * db) % 9 or (-da - 2 * db) % 9:
                raise AssertionError("nonintegral tau-four quotient")
            if quotient != ((da + 3 * db) // 9, (-da - 2 * db) // 9):
                raise AssertionError("quotient formula mismatch")
            indexes.append(index)
            counts[index] += 1
    if len(indexes) != 6561 or sorted(counts) != sorted(
            [3] * 54 + [9] * 54 + [27] * 54 + [81] * 55):
        raise AssertionError("atlas coverage mismatch")
    return indexes, patterns


def render(indexes, patterns):
    lines = ["/* Generated by make_residue_atlas.py; do not hand-edit. */",
             "#ifndef CA_TAU4_RESIDUE_ATLAS_H",
             "#define CA_TAU4_RESIDUE_ATLAS_H", "", "#include <stdint.h>",
             "", "typedef struct ca_tau4_atlas_pattern {",
             "  uint8_t slot, position;", "  int8_t correction_a, correction_b;",
             "} ca_tau4_atlas_pattern;", "",
             "static const uint8_t ca_tau4_atlas_index[6561] = {"]
    for start in range(0, len(indexes), 27):
        lines.append("  " + ", ".join(str(x) for x in indexes[start:start + 27]) + ",")
    lines += ["};", "", "static const ca_tau4_atlas_pattern "
              "ca_tau4_atlas_patterns[217] = {"]
    for slot, position, ca, cb in patterns:
        lines.append(f"  {{{slot}, {position}, {ca}, {cb}}},")
    lines += ["};", "", "#endif", ""]
    return "\n".join(lines)


def main(output):
    indexes, patterns = build()
    content = render(indexes, patterns)
    output.parent.mkdir(parents=True, exist_ok=True)
    if output.exists() and output.read_text() != content:
        raise ValueError(f"generated atlas differs from frozen file: {output}")
    output.write_text(content)
    print({"status": "generated_tau4_residue_atlas", "indexes": len(indexes),
           "patterns": len(patterns), "sha256": hashlib.sha256(
               content.encode()).hexdigest()})


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output", type=Path, required=True)
    args = parser.parse_args()
    main(args.output)
