#!/usr/bin/env python3
"""Generate the exact six-unit quotient of valid eight-digit tau pairs."""

import argparse
import hashlib
from pathlib import Path

from make_residue_atlas import SLOTS, build
from make_tau8_pairs import make_map


def omega(a, b):
    return a + 3 * b, -a - 2 * b


def unit_action(a, b, code):
    for _ in range(code % 3):
        a, b = omega(a, b)
    if code >= 3:
        a, b = -a, -b
    return a, b


def build_orbits():
    _, patterns = build()
    valid = make_map()
    by_slot_position = {(slot, position): index
                        for index, (slot, position, _, _) in enumerate(patterns)}
    actions = []
    for code in range(6):
        transformed = []
        for slot, position, _, _ in patterns:
            if slot == 255:
                transformed.append(0)
                continue
            x, y = unit_action(*SLOTS[slot][:2], code)
            new_slot = 9 * (x % 9) + y % 9
            if SLOTS[new_slot][:2] != (x, y):
                raise AssertionError("digit set not closed under units")
            transformed.append(by_slot_position[(new_slot, position)])
        actions.append(transformed)

    representatives = set()
    for index, old_id in enumerate(valid):
        if old_id == 65535:
            continue
        u, v = divmod(index, 217)
        orbit = {(actions[code][u], actions[code][v])
                 for code in range(6)}
        if len(orbit) != (1 if u == v == 0 else 6):
            raise AssertionError("unexpected unit orbit size")
        representatives.add(min(orbit))
    reps = sorted(representatives)
    if len(reps) != 4933:
        raise AssertionError("unexpected representative count")
    rep_ids = {pair: index for index, pair in enumerate(reps)}
    ids = []
    units = []
    counts = [0, 0, 0]
    for index, old_id in enumerate(valid):
        if old_id == 65535:
            ids.append(65535)
            units.append(255)
            continue
        u, v = divmod(index, 217)
        orbit = [(actions[code][u], actions[code][v]) for code in range(6)]
        rep = min(orbit)
        code = next(code for code in range(6)
                    if (actions[code][rep[0]], actions[code][rep[1]]) ==
                    (u, v))
        if valid[217 * rep[0] + rep[1]] == 65535:
            raise AssertionError("invalid orbit representative")
        ids.append(rep_ids[rep])
        units.append(code)
        counts[(u != 0) + (v != 0)] += 1
    if counts != [1, 432, 29160] or max(ids) != 65535:
        raise AssertionError((counts, max(ids)))
    rep_counts = [0, 0, 0]
    for u, v in reps:
        rep_counts[(u != 0) + (v != 0)] += 1
    if rep_counts != [1, 72, 4860]:
        raise AssertionError(rep_counts)
    return ids, units, reps


def render(ids, units, reps):
    lines = ["/* Generated by make_tau8_orbits.py; do not hand-edit. */",
             "#ifndef CA_TAU8_ORBIT_MAP_H", "#define CA_TAU8_ORBIT_MAP_H", "",
             "#include <stdint.h>", "", "#define CA_TAU8_ORBIT_COUNT 4933", ""]
    for name, ctype, values, width in (
        ("ca_tau8_orbit_id", "uint16_t", ids, 18),
        ("ca_tau8_orbit_unit", "uint8_t", units, 27),
        ("ca_tau8_orbit_rep_u", "uint8_t", [u for u, _ in reps], 27),
        ("ca_tau8_orbit_rep_v", "uint8_t", [v for _, v in reps], 27),
    ):
        lines.append(f"static const {ctype} {name}[{len(values)}] = {{")
        for start in range(0, len(values), width):
            lines.append("  " + ", ".join(str(x) for x in
                                          values[start:start + width]) + ",")
        lines += ["};", ""]
    lines += ["#endif", ""]
    return "\n".join(lines)


def main(output):
    content = render(*build_orbits())
    output.parent.mkdir(parents=True, exist_ok=True)
    if output.exists() and output.read_text() != content:
        raise ValueError(f"generated orbit map differs from frozen file: {output}")
    output.write_text(content)
    print({"status": "generated_tau8_orbit_map", "entries": 47089,
           "representatives": 4933,
           "sha256": hashlib.sha256(content.encode()).hexdigest()})


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output", type=Path, required=True)
    args = parser.parse_args()
    main(args.output)
