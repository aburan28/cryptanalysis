#!/usr/bin/env python3
"""Generate the exact compact index for two four-step tau atlas patterns."""

import argparse
import hashlib
from pathlib import Path

from make_residue_atlas import SLOTS, build
from run import expand, recode


def make_map():
    _, patterns = build()
    if len(patterns) != 217:
        raise AssertionError("unexpected four-step pattern count")
    output = []
    counts = [0, 0, 0]
    for slot0, pos0, _, _ in patterns:
        for slot1, pos1, _, _ in patterns:
            valid = (slot0 == 255 or slot1 == 255 or pos1 >= pos0)
            first = [None] * 4
            second = [None] * 4
            if slot0 != 255:
                first[pos0] = SLOTS[slot0]
            if slot1 != 255:
                second[pos1] = SLOTS[slot1]
            digits = first + second
            a, b = expand(digits)
            got = recode(a, b)
            exact = (got + [None] * (8 - len(got)))[:8] == digits
            if valid != exact:
                raise AssertionError((slot0, pos0, slot1, pos1))
            if valid:
                counts[(slot0 != 255) + (slot1 != 255)] += 1
                output.append(sum(counts) - 1)
            else:
                output.append(65535)
    if counts != [1, 432, 29160] or len(output) != 47089:
        raise AssertionError((counts, len(output)))
    return output


def render(values):
    lines = ["/* Generated by make_tau8_pairs.py; do not hand-edit. */",
             "#ifndef CA_TAU8_PAIR_MAP_H", "#define CA_TAU8_PAIR_MAP_H", "",
             "#include <stdint.h>", "", "#define CA_TAU8_PAIR_COUNT 29593", "",
             "static const uint16_t ca_tau8_pair_map[47089] = {"]
    for start in range(0, len(values), 18):
        lines.append("  " + ", ".join(str(x) for x in values[start:start + 18]) + ",")
    lines += ["};", "", "#endif", ""]
    return "\n".join(lines)


def main(output):
    content = render(make_map())
    output.parent.mkdir(parents=True, exist_ok=True)
    if output.exists() and output.read_text() != content:
        raise ValueError(f"generated pair map differs from frozen file: {output}")
    output.write_text(content)
    print({"status": "generated_tau8_pair_map", "entries": 47089,
           "valid": 29593,
           "sha256": hashlib.sha256(content.encode()).hexdigest()})


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output", type=Path, required=True)
    args = parser.parse_args()
    main(args.output)
