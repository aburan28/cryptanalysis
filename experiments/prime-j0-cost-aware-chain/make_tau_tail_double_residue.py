#!/usr/bin/env python3
"""Encode the sign-folded two-digit tau-tail policy with residue-local bytes."""

import argparse
import hashlib
from pathlib import Path

from make_tau_tail_double import BOUND, DIGITS, NONE, PHASES, gate_bits, generate, index, step
from make_tau_tail_double_fold import HALF, UNREACHABLE, half_index, representative


def build(costs, actions, gate):
    digit_by_coordinate = {(digit[0], digit[1]): slot for slot, digit in DIGITS}
    negate = [NONE] * 81
    for slot, digit in DIGITS:
        negate[slot] = digit_by_coordinate[-digit[0], -digit[1]]
    assert all(negate[negate[slot]] == slot for slot, _digit in DIGITS)

    local = [[set() for _ in range(9)] for _ in range(PHASES)]
    for phase in range(PHASES):
        for a in range(BOUND + 1):
            for b in range(-BOUND if a else 0, BOUND + 1):
                residue = (a % 3) * 3 + b % 3
                local[phase][residue].add(actions[index(a, b, phase)] or UNREACHABLE)

    dictionary, offsets, lengths, encoders = [], [], [], []
    for phase in range(PHASES):
        phase_offsets, phase_lengths, phase_encoders = [], [], []
        for residue in range(9):
            group = sorted(local[phase][residue])
            assert len(group) <= 255
            phase_offsets.append(len(dictionary))
            phase_lengths.append(len(group))
            phase_encoders.append({action: code for code, action in enumerate(group)})
            dictionary.extend(group)
        offsets.append(phase_offsets)
        lengths.append(phase_lengths)
        encoders.append(phase_encoders)

    codes = bytearray(PHASES * HALF)
    folded_gate = bytearray((len(codes) + 7) // 8)
    for phase in range(PHASES):
        for a in range(BOUND + 1):
            for b in range(-BOUND if a else 0, BOUND + 1):
                pos = phase * HALF + half_index(a, b)
                residue = (a % 3) * 3 + b % 3
                full, mirror = index(a, b, phase), index(-a, -b, phase)
                assert costs[full] == costs[mirror]
                selected = bool(gate[full >> 3] & (1 << (full & 7)))
                assert selected == bool(gate[mirror >> 3] & (1 << (mirror & 7)))
                if selected:
                    folded_gate[pos >> 3] |= 1 << (pos & 7)
                codes[pos] = encoders[phase][residue][actions[full] or UNREACHABLE]

    changed_ties = 0
    for phase in range(PHASES):
        for a in range(-BOUND, BOUND + 1):
            for b in range(-BOUND, BOUND + 1):
                ra, rb, negative = representative(a, b)
                pos = phase * HALF + half_index(ra, rb)
                residue = (ra % 3) * 3 + rb % 3
                code = codes[pos]
                assert code < lengths[phase][residue]
                even, odd = dictionary[offsets[phase][residue] + code]
                if negative and even != 254:
                    even = negate[even] if even != NONE else NONE
                    odd = negate[odd] if odd != NONE else NONE
                full = index(a, b, phase)
                changed_ties += (even, odd) != (actions[full] or UNREACHABLE)
                assert bool(folded_gate[pos >> 3] & (1 << (pos & 7))) == bool(
                    gate[full >> 3] & (1 << (full & 7)))
                if (even, odd) == UNREACHABLE:
                    assert actions[full] is None
                    continue
                if (a, b) == (0, 0):
                    assert (even, odd) == (NONE, NONE)
                    continue
                qa, qb, edge = step(a, b, phase, even, odd)
                assert -BOUND <= qa <= BOUND and -BOUND <= qb <= BOUND
                next_cost = costs[index(qa, qb, (phase + 1) % PHASES)]
                assert costs[full] == edge + next_cost and next_cost < costs[full]
    return bytes(codes), bytes(folded_gate), negate, offsets, lengths, dictionary, changed_ties


def render(codes, gate, negate, offsets, lengths, dictionary):
    source_hash = hashlib.sha256(Path(__file__).read_bytes()).hexdigest()
    lines = ["/* Generated by make_tau_tail_double_residue.py; do not edit.",
             f" * Generator SHA-256: {source_hash}",
             " * One byte per sign-folded state, indexed by phase and residue class.",
             " */", "#ifndef CA_TAU_TAIL_DOUBLE_RESIDUE_H",
             "#define CA_TAU_TAIL_DOUBLE_RESIDUE_H", "#include <stdint.h>",
             f"#define CA_TAU_DOUBLE_RESIDUE_ACTIONS {len(dictionary)}"]
    for name, values in (("code", codes), ("gate", gate), ("negate", negate)):
        lines.append(f"static const uint8_t ca_tau_double_residue_{name}[{len(values)}] = {{")
        for offset in range(0, len(values), 20):
            lines.append("    " + ", ".join(map(str, values[offset:offset + 20])) + ",")
        lines.append("};")
    for name, values, ctype in (("offset", offsets, "uint16_t"),
                                ("length", lengths, "uint8_t")):
        lines.append(f"static const {ctype} ca_tau_double_residue_{name}[{PHASES}][9] = {{")
        for phase in values:
            lines.append("    {" + ", ".join(map(str, phase)) + "},")
        lines.append("};")
    words = [(even << 8) | odd for even, odd in dictionary]
    lines.append(f"static const uint16_t ca_tau_double_residue_dictionary[{len(words)}] = {{")
    for offset in range(0, len(words), 16):
        lines.append("    " + ", ".join(map(str, words[offset:offset + 16])) + ",")
    lines.extend(["};", "#endif", ""])
    return "\n".join(lines)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output", type=Path, default=Path(__file__).resolve().parents[2] /
                        "src/generated/tau_tail_double_residue.h")
    args = parser.parse_args()
    costs, actions = generate()
    gate, _ = gate_bits(costs, actions)
    codes, folded_gate, negate, offsets, lengths, dictionary, changed = build(costs, actions, gate)
    header = render(codes, folded_gate, negate, offsets, lengths, dictionary)
    if args.output.exists() and args.output.read_text() != header:
        raise SystemExit(f"generated residue policy changed: {args.output}")
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(header)
    static_bytes = len(codes) + len(folded_gate) + len(negate) + 2 * len(dictionary) + 3 * 9 * 3
    print(f"states={len(codes)} dictionary_entries={len(dictionary)} "
          f"max_residue_dictionary={max(map(max, lengths))} "
          f"changed_ties={changed} static_bytes={static_bytes} "
          f"header_sha256={hashlib.sha256(header.encode()).hexdigest()}")


if __name__ == "__main__":
    main()
