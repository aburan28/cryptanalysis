#!/usr/bin/env python3
"""Generate one low-cost valid tau-eight pair per residue class."""

import argparse
import hashlib
import json
from pathlib import Path

from make_residue_atlas import build as build_atlas
from make_tau8_orbits import build_orbits
from make_tau8_pairs import make_map


MODULUS = 81
RESIDUES = MODULUS * MODULUS
ABSENT = 65535


def correction(patterns, u, v):
    _, _, a0, b0 = patterns[u]
    _, _, a1, b1 = patterns[v]
    return a0 - 18 * a1 - 27 * b1, b0 + 9 * a1 + 9 * b1


def build_map(screen_path):
    screen = json.loads(screen_path.read_text())
    hot = set(screen["selected_orbit_ids"])
    if screen["candidate_budget"] != 2048 or len(hot) != 2048:
        raise ValueError("unexpected hot-orbit selection")
    _, patterns = build_atlas()
    valid = make_map()
    orbit_ids, _, _ = build_orbits()
    best = [None] * RESIDUES
    for pair, dense_id in enumerate(valid):
        if dense_id == ABSENT:
            continue
        u, v = divmod(pair, 217)
        ca, cb = correction(patterns, u, v)
        key = MODULUS * (ca % MODULUS) + cb % MODULUS
        orbit = orbit_ids[pair]
        if orbit == ABSENT:
            raise AssertionError("valid pair has no orbit")
        cost = 0 if u == v == 0 else (
            1 if u == 0 or v == 0 or orbit in hot else 2)
        rank = (cost, abs(ca) + abs(cb), pair)
        if best[key] is None or rank < best[key][0]:
            best[key] = (rank, pair)
    if any(row is None for row in best):
        raise AssertionError("residue class has no valid pair")
    selected = [row[1] if row[0][0] < 2 else ABSENT for row in best]
    if sum(pair != ABSENT for pair in selected) != 6225:
        raise AssertionError("unexpected one-addition residue coverage")
    for key, pair in enumerate(selected):
        if pair == ABSENT:
            continue
        if valid[pair] == ABSENT:
            raise AssertionError("selected pair is invalid")
        ca, cb = correction(patterns, *divmod(pair, 217))
        if MODULUS * (ca % MODULUS) + cb % MODULUS != key:
            raise AssertionError("selected pair changed its residue")
    return selected


def render(selected):
    lines = ["/* Generated by make_tau8_steer.py; do not hand-edit. */",
             "#ifndef CA_TAU8_STEER_MAP_H",
             "#define CA_TAU8_STEER_MAP_H", "",
             "#include <stdint.h>", "",
             "#define CA_TAU8_STEER_RESIDUES 6561", "",
             "static const uint16_t ca_tau8_steer_pair[6561] = {"]
    for start in range(0, len(selected), 18):
        lines.append("  " + ", ".join(str(value) for value in
                                    selected[start:start + 18]) + ",")
    lines += ["};", "", "#endif", ""]
    return "\n".join(lines)


def main(output, screen):
    content = render(build_map(screen))
    output.parent.mkdir(parents=True, exist_ok=True)
    if output.exists() and output.read_text() != content:
        raise ValueError(f"generated steer map differs from frozen file: {output}")
    output.write_text(content)
    print(json.dumps({
        "status": "generated_tau8_steer_map",
        "residues": RESIDUES, "covered": 6225,
        "static_bytes": RESIDUES * 2,
        "sha256": hashlib.sha256(content.encode()).hexdigest(),
    }, sort_keys=True))


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output", type=Path, required=True)
    parser.add_argument("--screen", type=Path, default=Path(__file__).with_name(
        "hot-orbit-screen.json"))
    args = parser.parse_args()
    main(args.output, args.screen)
