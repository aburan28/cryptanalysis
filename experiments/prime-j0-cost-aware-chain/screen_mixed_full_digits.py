#!/usr/bin/env python3
"""Screen a mixed-radix tail using every prepared digit for every radix."""

import argparse
import csv
import hashlib
from heapq import heappop, heappush
import json
from pathlib import Path
import re
import struct

from make_tau_pair_fused import ZERO, catalog
from make_tau_tail_double import tau2
from run import representatives
from screen_global_pair_search import (BOUND, SIDE, bounded, canonical_step, index,
                                       lattice_norm, tail_oracle)
from screen_mixed_radix_tail import (KIND_DOUBLE, KIND_PAIR, KIND_TAU, STEP_COSTS,
                                     cost, path_from, reconstruct_mixed, tau)
from screen_tau_tail_double import ENDO_LAMBDA


ROOT = Path(__file__).resolve().parent
REPO = ROOT.parents[1]
HEADER = REPO / "src/generated/tau_pair_mixed_full_digits.h"
OLD_HEADER = REPO / "src/generated/tau_pair_mixed_radix_tail.h"
RAW = ROOT / "mixed-full-digits-raw.csv"
SUMMARY = ROOT / "mixed-full-digits-screen.json"
FIXTURE = ROOT / "tail-pair-fused-inputs.json"
INF = 1 << 30


def sha256(path):
    return hashlib.sha256(path.read_bytes()).hexdigest()


def read_actions(path, symbol):
    body = path.read_text().split(f"{symbol}[16641] = {{", 1)[1].split("};", 1)[0]
    codes = [int(value) for value in re.findall(r"\d+", body)]
    assert len(codes) == SIDE * SIDE
    return [(code >> 10, code & 1023) for code in codes]


def build_atlas(options):
    costs = [INF] * (SIDE * SIDE)
    actions = [None] * (SIDE * SIDE)
    costs[index(0, 0)] = 0
    actions[index(0, 0)] = (KIND_PAIR, ZERO)
    heap = [(0, 0, 0)]
    edges = 0
    while heap:
        current_cost, qa, qb = heappop(heap)
        if current_cost != costs[index(qa, qb)]:
            continue
        for kind, base in ((KIND_PAIR, tau2(qa, qb)),
                           (KIND_TAU, tau(qa, qb)),
                           (KIND_DOUBLE, (2 * qa, 2 * qb))):
            step_cost = STEP_COSTS[kind] if (qa, qb) != (0, 0) else 0
            for da, db, word in options:
                a, b = base[0] + da, base[1] + db
                if not bounded(a, b) or (a, b) == (0, 0):
                    continue
                edges += 1
                new_cost = current_cost + step_cost + (16 if word != ZERO else 0)
                pos = index(a, b)
                action = (kind, word)
                if new_cost < costs[pos]:
                    costs[pos], actions[pos] = new_cost, action
                    heappush(heap, (new_cost, a, b))
                elif new_cost == costs[pos] and action < actions[pos]:
                    actions[pos] = action
    assert all(action is not None for action in actions)
    return costs, actions, edges


def header_text(actions):
    encoded = [(kind << 10) | word for kind, word in actions]
    assert len(encoded) == SIDE * SIDE and max(encoded) < 1 << 12
    lines = ["/* Generated by screen_mixed_full_digits.py; do not edit. */",
             "#ifndef CA_TAU_PAIR_MIXED_FULL_DIGITS_H",
             "#define CA_TAU_PAIR_MIXED_FULL_DIGITS_H",
             "#include <stdint.h>",
             f"#define CA_TAU_PAIR_MIXED_FULL_BOUND {BOUND}",
             f"#define CA_TAU_PAIR_MIXED_FULL_SIDE {SIDE}",
             "static const uint16_t ca_tau_pair_mixed_full_action[16641] = {"]
    for offset in range(0, len(encoded), 12):
        lines.append("    " + ", ".join(str(value) for value in encoded[offset:offset + 12]) + ",")
    return "\n".join(lines + ["};", "#endif", ""])


def main(samples):
    reps, _, words_by_point, _, _ = catalog()
    points = {word: point for point, word in words_by_point.items()}
    options = sorted(((a, b, word) for (a, b), word in words_by_point.items()),
                     key=lambda row: (lattice_norm(row[0], row[1]), row[2]))
    assert len(options) == 727
    _, pure_actions = tail_oracle(options)
    old_actions = read_actions(OLD_HEADER, "ca_tau_pair_mixed_action")
    full_costs, full_actions, edges = build_atlas(options)
    assert all(cost(path_from((a, b), old_actions, points)) >= full_costs[index(a, b)]
               for a in range(-BOUND, BOUND + 1) for b in range(-BOUND, BOUND + 1))
    for a in range(-BOUND, BOUND + 1):
        for b in range(-BOUND, BOUND + 1):
            path = path_from((a, b), full_actions, points)
            assert reconstruct_mixed(path, points) == (a, b)
            assert cost(path) == full_costs[index(a, b)]
    HEADER.write_text(header_text(full_actions))

    fixture = json.loads(FIXTURE.read_text())
    rows = []
    scalar_paths = []
    for case_index in (0, 1, 4, 5):
        case = fixture["cases"][case_index]
        scalar_path = ROOT / case["scalar_file"]
        raw = scalar_path.read_bytes()
        assert sha256(scalar_path) == case["scalar_file_sha256"]
        scalar_paths.append(scalar_path)
        assert 1 <= samples <= len(raw) // 8
        scalars = struct.unpack(f"<{samples}Q", raw[:8 * samples])
        curve = case["curve"]["name"]
        order = case["curve"]["order"]
        omega_lambda = order - ENDO_LAMBDA[curve]
        for scalar_index, scalar in enumerate(scalars):
            _, a, b = min(representatives(order, omega_lambda, scalar),
                          key=lambda item: item[0])
            start = (a, b)
            high = []
            state = start
            while state != (0, 0) and (not bounded(*state) or
                                         pure_actions[index(*state)] is None):
                state, word = canonical_step(*state, words_by_point)
                high.append((KIND_PAIR, word))
                assert len(high) < 128
            old = tuple(high) + path_from(state, old_actions, points)
            full = tuple(high) + path_from(state, full_actions, points)
            assert reconstruct_mixed(old, points) == start
            assert reconstruct_mixed(full, points) == start
            old_score, full_score = cost(old), cost(full)
            assert full_score <= old_score
            rows.append({"case_id": case["id"], "curve": curve,
                         "point_index": case["point_index"],
                         "scalar_index": scalar_index, "scalar": scalar,
                         "mixed_score": old_score, "full_digit_score": full_score,
                         "high_pairs": len(high),
                         "full_pairs": sum(kind == KIND_PAIR for kind, _ in full),
                         "full_tau_steps": sum(kind == KIND_TAU for kind, _ in full),
                         "full_doubles": sum(kind == KIND_DOUBLE for kind, _ in full),
                         "full_adds": sum(word != ZERO for _, word in full)})
    with RAW.open("w", newline="") as stream:
        writer = csv.DictWriter(stream, fieldnames=tuple(rows[0]), lineterminator="\n")
        writer.writeheader()
        writer.writerows(rows)
    summaries = []
    for case_index in (0, 1, 4, 5):
        case = fixture["cases"][case_index]
        group = [row for row in rows if row["case_id"] == case["id"]]
        old = sum(row["mixed_score"] for row in group)
        full = sum(row["full_digit_score"] for row in group)
        summaries.append({"case_id": case["id"], "count": len(group),
                          "mixed_score": old, "full_digit_score": full,
                          "saved_score": old - full,
                          "saving_percent": 100 * (old - full) / old,
                          "improved_scalars": sum(row["full_digit_score"] < row["mixed_score"]
                                                  for row in group),
                          "full_pairs": sum(row["full_pairs"] for row in group),
                          "full_tau_steps": sum(row["full_tau_steps"] for row in group),
                          "full_doubles": sum(row["full_doubles"] for row in group),
                          "full_adds": sum(row["full_adds"] for row in group)})
    sources = [Path(__file__), ROOT / "screen_mixed_radix_tail.py",
               ROOT / "screen_global_pair_search.py", ROOT / "make_tau_pair_fused.py",
               ROOT / "make_tau_tail_double.py", ROOT / "run.py",
               ROOT / "screen_tau_tail_double.py", FIXTURE, OLD_HEADER] + scalar_paths
    summary = {"schema": 1, "status": "retrospective_exact_full_digit_mixed_screen",
               "claim_boundary": "old scalar design/validation data; group-operation model only",
               "samples_per_case": samples, "bounded_states": SIDE * SIDE,
               "digit_count_per_radix": len(options), "encoded_action_bytes": 2 * SIDE * SIDE,
               "graph_edges_examined": edges,
               "radix_step_model": {"tau2": 10, "tau": 6, "double": 8,
                                    "nonzero_digit": 16},
               "strictly_better_states": sum(full_costs[pos] <
                                             cost(path_from((pos // SIDE - BOUND,
                                                             pos % SIDE - BOUND),
                                                            old_actions, points))
                                             for pos in range(SIDE * SIDE)),
               "header_sha256": sha256(HEADER), "old_header_sha256": sha256(OLD_HEADER),
               "raw_csv": RAW.name, "raw_csv_sha256": sha256(RAW),
               "source_sha256": {str(path.relative_to(REPO)): sha256(path)
                                 for path in sources},
               "summaries": summaries}
    SUMMARY.write_text(json.dumps(summary, indent=2, sort_keys=True) + "\n")
    print(json.dumps({"status": summary["status"], "summaries": summaries,
                      "strictly_better_states": summary["strictly_better_states"]},
                     sort_keys=True))


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--samples", type=int, default=4096)
    args = parser.parse_args()
    main(args.samples)
