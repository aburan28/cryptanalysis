#!/usr/bin/env python3
"""Generate exact per-curve six-unit maps from the frozen hot design."""

import hashlib
import json
from pathlib import Path
import sys

from make_joint_window4_map import actions, build


CURVES = ("glv-j0-32", "j0-56")


def sha256(path):
    return hashlib.sha256(path.read_bytes()).hexdigest()


def array(name, ctype, rows, width=12):
    lines = [f"static const {ctype} {name}[2][{len(rows[0])}] = {{"]
    for row in rows:
        lines.append("    {")
        for start in range(0, len(row), width):
            lines.append("        " + ", ".join(map(str, row[start:start + width])) + ",")
        lines.append("    },")
    lines.append("};")
    return "\n".join(lines) + "\n"


def make(design_path, output):
    design = json.loads(design_path.read_text())
    if design.get("status") != "frozen_retrospective_design":
        raise ValueError("hot design is not frozen")
    root = Path(__file__).resolve().parents[2]
    if design["baseline_design_sha256"] != sha256(design_path.parent / "joint-window4-design.json"):
        raise ValueError("baseline design changed")
    if design["baseline_map_header_sha256"] != sha256(root / "src/generated/joint_window4.h"):
        raise ValueError("baseline map changed")
    if design["source_sha256"] != sha256(design_path.parent / "make_joint_window4_hot_design.py"):
        raise ValueError("selection source changed")
    canonical, baseline_codes = build()
    records = {row["curve"]: row for row in design["records"]}
    if set(records) != set(CURVES):
        raise ValueError("unexpected curve records")
    reps_x, reps_y, maps = [], [], []
    for curve in CURVES:
        selected = [tuple(pair) for pair in records[curve]["selected_representatives"]]
        if len(selected) != len(canonical):
            raise ValueError("orbit count changed")
        for index, rep in enumerate(selected):
            if min(actions(*rep)) != canonical[index]:
                raise ValueError("selected representative left its orbit")
            if max(map(abs, rep)) > 15:
                raise ValueError("selected representative exceeds preparation table")
        codes = []
        for index, (x, y) in enumerate((x, y) for x in range(-8, 8)
                                      for y in range(-8, 8)):
            orbit = baseline_codes[index] & 127
            if orbit == 127:
                codes.append(127)
                continue
            matches = [code for code, pair in enumerate(actions(*selected[orbit]))
                       if pair == (x, y)]
            if len(matches) != 1:
                raise ValueError("selected action is not unique")
            codes.append(orbit | (matches[0] << 7))
        reps_x.append([x for x, _ in selected])
        reps_y.append([y for _, y in selected])
        maps.append(codes)
    content = ("/* Generated by make_joint_window4_hot_map.py from the frozen design. */\n"
               "#ifndef CA_JOINT_WINDOW4_HOT_H\n#define CA_JOINT_WINDOW4_HOT_H\n"
               "#include <stdint.h>\n"
               + array("ca_joint_window4_hot_rep_x", "int8_t", reps_x)
               + array("ca_joint_window4_hot_rep_y", "int8_t", reps_y)
               + array("ca_joint_window4_hot_action", "uint16_t", maps)
               + "#endif\n").encode()
    if output.exists() and output.read_bytes() != content:
        raise ValueError("generated hot map changed")
    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_bytes(content)
    print(json.dumps({"header_sha256": hashlib.sha256(content).hexdigest(),
                      "orbits_per_curve": len(canonical), "curves": CURVES}, sort_keys=True))


if __name__ == "__main__":
    if len(sys.argv) != 3:
        raise SystemExit("usage: make_joint_window4_hot_map.py DESIGN HEADER")
    make(Path(sys.argv[1]), Path(sys.argv[2]))
