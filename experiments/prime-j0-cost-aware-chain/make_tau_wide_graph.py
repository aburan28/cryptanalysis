#!/usr/bin/env python3
"""Generate exact unit-folded predecessor recipes for wide tau orbit points."""

import argparse
import hashlib
import json
from pathlib import Path

from make_tau8_orbits import unit_action
from make_tau_wide_orbits import ID_BITS, MAX_ID, WIDTHS, build, residue_key
from run import TABLE, expand, recode


def recipes(atlas):
    width = atlas["width"]
    modulus = atlas["modulus"]
    corrections = atlas["corrections"]
    counts = [sum(digit is not None for digit in recode(a, b))
              for a, b in corrections]
    if max(counts) > 3 or counts[0] != 0:
        raise AssertionError("unexpected tau correction depth")
    output = []
    for orbit_id, ((a, b), depth) in enumerate(zip(corrections, counts)):
        if depth == 0:
            output.append((0, 255, 0, 0))
            continue
        digits = recode(a, b)
        position = max(j for j, digit in enumerate(digits) if digit is not None)
        digit = digits[position]
        slot = (digit[0] % 9) * 9 + digit[1] % 9
        if TABLE[(digit[0] % 9, digit[1] % 9)] != digit or slot >= 81:
            raise AssertionError("digit table slot changed")
        parent = expand(digits[:position])
        packed = atlas["packed"][residue_key(*parent, modulus)]
        parent_id = packed & (MAX_ID - 1)
        unit = packed >> ID_BITS
        actual_parent = unit_action(*corrections[parent_id], unit)
        if (actual_parent != parent or counts[parent_id] != depth - 1 or
                orbit_id == parent_id or position >= width or unit > 5):
            raise AssertionError((width, orbit_id, parent, packed, depth))
        term = expand([None] * position + [digit])
        if (a, b) != (actual_parent[0] + term[0],
                      actual_parent[1] + term[1]):
            raise AssertionError("graph edge changed the correction")
        output.append((packed, slot, position, depth))
    return output


def render(all_recipes):
    lines = ["/* Generated by make_tau_wide_graph.py; do not hand-edit. */",
             "#ifndef CA_TAU_WIDE_GRAPH_H", "#define CA_TAU_WIDE_GRAPH_H", "",
             "#include <stdint.h>", "",
             "typedef struct {", "    uint32_t parent_packed;",
             "    uint8_t digit_slot, position, depth, reserved;",
             "} ca_tau_wide_recipe;", ""]
    for width in WIDTHS:
        graph = all_recipes[width]
        lines.append(f"static const ca_tau_wide_recipe ca_tau_wide{width}_recipe[{len(graph)}] = {{")
        lines += [f"    {{{parent}, {slot}, {position}, {depth}, 0}},"
                  for parent, slot, position, depth in graph]
        lines += ["};", ""]
    lines += ["#endif", ""]
    return "\n".join(lines)


def main(output, report_path=None):
    atlases = {width: build(width) for width in WIDTHS}
    graphs = {width: recipes(atlas) for width, atlas in atlases.items()}
    content = render(graphs)
    output.parent.mkdir(parents=True, exist_ok=True)
    if output.exists() and output.read_text() != content:
        raise ValueError(f"generated graph differs from frozen file: {output}")
    output.write_text(content)
    summary = {str(width): {
        "orbits": len(graphs[width]),
        "depth_counts": {str(depth): sum(row[3] == depth for row in graphs[width])
                         for depth in range(4)},
        "direct_prep_adds": sum(max(row[3] - 1, 0) for row in graphs[width]),
        "graph_prep_adds": sum(row[3] >= 2 for row in graphs[width]),
        "recipe_bytes_at_8_bytes_each": 8 * len(graphs[width]),
    } for width in WIDTHS}
    report = {"schema": 1, "status": "verified_unit_folded_orbit_graph",
              "widths": summary,
              "generated_header_sha256": hashlib.sha256(content.encode()).hexdigest(),
              "source_sha256": {
                  "make_tau_wide_graph.py": hashlib.sha256(Path(__file__).read_bytes()).hexdigest(),
                  "make_tau_wide_orbits.py": hashlib.sha256(
                      Path(__file__).with_name("make_tau_wide_orbits.py").read_bytes()).hexdigest(),
                  "tau_wide_orbits.h": hashlib.sha256(
                      output.with_name("tau_wide_orbits.h").read_bytes()).hexdigest()}}
    if report_path is not None:
        report_path.write_text(json.dumps(report, indent=2, sort_keys=True) + "\n")
    print(json.dumps(report, sort_keys=True))


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output", type=Path, required=True)
    parser.add_argument("--report", type=Path)
    args = parser.parse_args()
    main(args.output, args.report)
