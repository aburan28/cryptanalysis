#!/usr/bin/env python3
"""Generate the frozen exact-pair tail and 32-choice native tables."""

import hashlib
from pathlib import Path

from make_tau_pair_fused import UNREACHABLE, catalog, decode
from screen_global_pair_search import BOUND, SIDE, lattice_norm, tail_oracle


ROOT = Path(__file__).resolve().parents[2]
HEADER = ROOT / "src/generated/tau_pair_global.h"


def generate():
    representatives, _, words_by_point, _, _ = catalog()
    options = [(a, b, word) for (a, b), word in words_by_point.items()]
    assert len(options) == 727
    assert all(decode(word, representatives) == (a, b) for a, b, word in options)
    options.sort(key=lambda item: (lattice_norm(item[0], item[1]), item[2]))
    costs, actions = tail_oracle(options)
    assert len(actions) == SIDE * SIDE
    assert sum(action is not None for action in actions) == 15043
    grouped = [[(a, b, word) for a, b, word in options
                if a % 3 == ra and b % 3 == rb][:32]
               for ra in range(3) for rb in range(3)]
    assert [len(row) for row in grouped] == [1, 27, 27, 32, 32, 32, 32, 32, 32]
    assert max(abs(value) for a, b, _ in options for value in (a, b)) <= 127
    lines = ["/* Generated by make_global_pair_native.py; do not edit. */",
             "#ifndef CA_TAU_PAIR_GLOBAL_H",
             "#define CA_TAU_PAIR_GLOBAL_H",
             "#include <stdint.h>",
             f"#define CA_TAU_PAIR_GLOBAL_BOUND {BOUND}",
             f"#define CA_TAU_PAIR_GLOBAL_SIDE {SIDE}",
             "#define CA_TAU_PAIR_GLOBAL_OPTIONS 32",
             "typedef struct { int8_t a, b; uint16_t word; } ca_tau_pair_global_option;",
             f"static const uint16_t ca_tau_pair_global_action[{SIDE * SIDE}] = {{"]
    encoded = [UNREACHABLE if action is None else action for action in actions]
    for offset in range(0, len(encoded), 16):
        lines.append("    " + ", ".join(str(value) for value in encoded[offset:offset + 16]) + ",")
    lines.extend(["};",
                  "static const uint8_t ca_tau_pair_global_count[9] = {" +
                  ", ".join(str(len(row)) for row in grouped) + "};",
                  "static const ca_tau_pair_global_option "
                  "ca_tau_pair_global_option_set[9][CA_TAU_PAIR_GLOBAL_OPTIONS] = {"])
    for row in grouped:
        padded = row + [(0, 0, UNREACHABLE)] * (32 - len(row))
        lines.append("    {" + ", ".join(f"{{{a}, {b}, {word}}}" for a, b, word in padded) + "},")
    lines.extend(["};", "#endif", ""])
    content = "\n".join(lines).encode()
    HEADER.write_bytes(content)
    print(f"{HEADER.relative_to(ROOT)} sha256={hashlib.sha256(content).hexdigest()} "
          f"reached={sum(action is not None for action in actions)}")


if __name__ == "__main__":
    generate()
