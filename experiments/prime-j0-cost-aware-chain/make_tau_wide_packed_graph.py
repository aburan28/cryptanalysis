#!/usr/bin/env python3
"""Pack exact unit-folded orbit graph recipes into one uint32 per orbit."""

import argparse
import hashlib
import json
from pathlib import Path

from make_tau_wide_graph import recipes
from make_tau_wide_orbits import ID_BITS, MAX_ID, WIDTHS, build
from run import TABLE


SLOTS = sorted(9 * a + b for a, b in TABLE)
SLOT_ID = {slot: index for index, slot in enumerate(SLOTS)}


def pack(graph):
    if len(SLOTS) != 54 or len(SLOT_ID) != 54:
        raise AssertionError("digit slot vocabulary changed")
    output = []
    for parent, slot, position, depth in graph:
        if depth == 0:
            if (parent, slot, position) != (0, 255, 0):
                raise AssertionError("zero recipe changed")
            output.append(0)
            continue
        parent_id = parent & (MAX_ID - 1)
        unit = parent >> ID_BITS
        digit_id = SLOT_ID[slot]
        if parent_id >= MAX_ID or unit > 5 or digit_id >= 54 or position >= 16 or depth > 3:
            raise AssertionError("recipe exceeded 32-bit layout")
        word = (parent_id | unit << 17 | digit_id << 20 |
                position << 26 | depth << 30)
        unpacked = (word & (MAX_ID - 1), (word >> 17) & 7,
                    SLOTS[(word >> 20) & 63], (word >> 26) & 15,
                    word >> 30)
        if unpacked != (parent_id, unit, slot, position, depth):
            raise AssertionError("packed recipe did not round-trip")
        output.append(word)
    return output


def render(packed):
    lines = ["/* Generated by make_tau_wide_packed_graph.py; do not hand-edit. */",
             "#ifndef CA_TAU_WIDE_PACKED_GRAPH_H",
             "#define CA_TAU_WIDE_PACKED_GRAPH_H", "", "#include <stdint.h>", "",
             f"static const uint8_t ca_tau_wide_packed_slot[{len(SLOTS)}] = {{"]
    for start in range(0, len(SLOTS), 12):
        lines.append("    " + ", ".join(str(slot) for slot in SLOTS[start:start + 12]) + ",")
    lines += ["};", ""]
    for width in WIDTHS:
        words = packed[width]
        lines.append(f"static const uint32_t ca_tau_wide{width}_packed_recipe[{len(words)}] = {{")
        for start in range(0, len(words), 12):
            lines.append("    " + ", ".join(str(word) for word in words[start:start + 12]) + ",")
        lines += ["};", ""]
    lines += ["#endif", ""]
    return "\n".join(lines)


def main(output, report_path):
    output = output.resolve()
    report_path = report_path.resolve()
    root = Path(__file__).resolve().parent
    graphs = {width: recipes(build(width)) for width in WIDTHS}
    packed = {width: pack(graphs[width]) for width in WIDTHS}
    content = render(packed)
    output.parent.mkdir(parents=True, exist_ok=True)
    if output.exists() and output.read_text() != content:
        raise ValueError(f"generated packed graph changed: {output}")
    output.write_text(content)
    rows = {str(width): {"orbits": len(packed[width]),
                         "recipe_roundtrips": len(packed[width]),
                         "unpacked_bytes": 8 * len(packed[width]),
                         "packed_bytes": 4 * len(packed[width])}
            for width in WIDTHS}
    report = {"schema": 1, "status": "verified_packed_orbit_graph",
              "digit_slot_count": len(SLOTS), "digit_slot_bytes": len(SLOTS),
              "widths": rows,
              "schedule_recipe_bytes": {
                  "glv-j0-32": 4 * len(packed[10]) + len(SLOTS),
                  "j0-56": 4 * (len(packed[12]) + len(packed[8])) + len(SLOTS)},
              "generated_header_sha256": hashlib.sha256(content.encode()).hexdigest(),
              "source_sha256": {str(path.relative_to(root.parents[1])):
                                hashlib.sha256(path.read_bytes()).hexdigest()
                                for path in (Path(__file__), root / "make_tau_wide_graph.py",
                                             root / "PACKED_ORBIT_GRAPH.md",
                                             output.with_name("tau_wide_graph.h"))}}
    report_path.write_text(json.dumps(report, indent=2, sort_keys=True) + "\n")
    print(json.dumps({"status": report["status"],
                      "schedule_recipe_bytes": report["schedule_recipe_bytes"],
                      "header_sha256": report["generated_header_sha256"]}, sort_keys=True))


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output", type=Path, required=True)
    parser.add_argument("--report", type=Path, required=True)
    args = parser.parse_args()
    main(args.output, args.report)
