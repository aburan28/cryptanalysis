#!/usr/bin/env python3
"""Generate and exhaustively check the bounded shortest-path tau-pair oracle.

This is an offline generator. The resulting table is only used by an opt-in
public-scalar recoder; the ordinary width-four path remains the fallback.
"""

import argparse
import hashlib
from heapq import heappop, heappush
from pathlib import Path

from run import TABLE


BOUND = 64
SIDE = 2 * BOUND + 1
PHASES = 3
UNREACHABLE = 254
ZERO = 255
INF = 1 << 30


def index(a, b, phase):
    return (phase * SIDE + a + BOUND) * SIDE + b + BOUND


def tau2(a, b):
    return -3 * a - 9 * b, 3 * a + 6 * b


def choices():
    result = [(ZERO, 0, 0, 0, 0)]
    for (x, y), (a, b, _seed, power, _sign) in sorted(TABLE.items()):
        slot = 9 * x + y
        result.append((slot, a, b, power, 0))
        result.append((128 + slot, -3 * b, a + 3 * b, power, 1))
    return result


CHOICES = {row[0]: row[1:] for row in choices()}


def forward(a, b, phase, action):
    da, db, power, kind = CHOICES[action]
    x, y = a - da, b - db
    if x % 3 or y % 3:
        raise AssertionError("nonintegral tau-pair quotient")
    qa, qb = 2 * (x // 3) + y, -(x + y) // 3
    if kind and qa % 3:
        raise AssertionError("odd digit violates frozen choice restriction")
    edge = (10 if (qa, qb) != (0, 0) else 0)
    if action != ZERO:
        edge += 16 + int((power + phase) % 3 != 0)
    return qa, qb, edge


def generate():
    count = PHASES * SIDE * SIDE
    costs = [INF] * count
    actions = [UNREACHABLE] * count
    heap = []
    for phase in range(PHASES):
        costs[index(0, 0, phase)] = 0
        actions[index(0, 0, phase)] = ZERO
        heappush(heap, (0, 0, 0, phase))
    while heap:
        cost, qa, qb, next_phase = heappop(heap)
        if cost != costs[index(qa, qb, next_phase)]:
            continue
        phase = (next_phase - 1) % PHASES
        base_a, base_b = tau2(qa, qb)
        for action, da, db, power, kind in choices():
            # This restriction fixes the exact choice set tested in the
            # exploratory screen, including the odd-position candidates.
            if kind and qa % 3:
                continue
            a, b = base_a + da, base_b + db
            if not (-BOUND <= a <= BOUND and -BOUND <= b <= BOUND):
                continue
            if (a, b) == (0, 0):
                continue
            edge = (10 if (qa, qb) != (0, 0) else 0)
            if action != ZERO:
                edge += 16 + int((power + phase) % 3 != 0)
            new = cost + edge
            pos = index(a, b, phase)
            if new < costs[pos] or (new == costs[pos] and action < actions[pos]):
                costs[pos], actions[pos] = new, action
                heappush(heap, (new, a, b, phase))
    return costs, actions


def validate(costs, actions):
    reachable = missing = max_steps = 0
    for phase in range(PHASES):
        for a in range(-BOUND, BOUND + 1):
            for b in range(-BOUND, BOUND + 1):
                pos = index(a, b, phase)
                if actions[pos] == UNREACHABLE:
                    assert costs[pos] == INF
                    missing += 1
                    continue
                reachable += 1
                if (a, b) == (0, 0):
                    assert actions[pos] == ZERO and costs[pos] == 0
                    continue
                x, y, p = a, b, phase
                steps = 0
                while (x, y) != (0, 0):
                    old = index(x, y, p)
                    action = actions[old]
                    assert action != UNREACHABLE
                    qx, qy, edge = forward(x, y, p, action)
                    assert -BOUND <= qx <= BOUND and -BOUND <= qy <= BOUND
                    new = index(qx, qy, (p + 1) % PHASES)
                    assert costs[old] == edge + costs[new]
                    assert costs[new] < costs[old]
                    x, y, p = qx, qy, (p + 1) % PHASES
                    steps += 1
                    assert steps <= 256
                max_steps = max(max_steps, steps)
    return reachable, missing, max_steps


def render(actions):
    source_hash = hashlib.sha256(Path(__file__).read_bytes()).hexdigest()
    lines = ["/* Generated by make_tau_tail_oracle.py; do not edit.",
             f" * Generator SHA-256: {source_hash}",
             " * 254 = unreachable; 255 = zero; 0..80 = even slot;",
             " * 128..208 = odd slot (slot = action - 128).",
             " */", "#ifndef CA_TAU_TAIL_ORACLE_H", "#define CA_TAU_TAIL_ORACLE_H",
             "#include <stdint.h>",
             "#define CA_TAU_TAIL_BOUND 64",
             "#define CA_TAU_TAIL_SIDE 129",
             "static const uint8_t ca_tau_tail_action[3][129][129] = {"]
    for phase in range(PHASES):
        lines.append("    {")
        for a in range(-BOUND, BOUND + 1):
            row = actions[index(a, -BOUND, phase):index(a, BOUND, phase) + 1]
            lines.append("        {" + ", ".join(str(value) for value in row) + "},")
        lines.append("    },")
    lines.extend(["};", "#endif", ""])
    return "\n".join(lines)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output", type=Path, default=Path(__file__).resolve().parents[2] /
                        "src/generated/tau_tail_oracle.h")
    args = parser.parse_args()
    costs, actions = generate()
    reachable, missing, max_steps = validate(costs, actions)
    data = render(actions)
    if args.output.exists() and args.output.read_text() != data:
        raise SystemExit(f"generated oracle changed: {args.output}")
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(data)
    print(f"reachable={reachable} missing={missing} max_steps={max_steps} "
          f"table_sha256={hashlib.sha256(data.encode()).hexdigest()}")


if __name__ == "__main__":
    main()
