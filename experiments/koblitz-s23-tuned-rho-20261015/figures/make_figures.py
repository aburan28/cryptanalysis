#!/usr/bin/env python3
"""Render figures/gap.tex (pgfplots) from a receipt's result.json, then gap.pdf and gap.png.

    python3 figures/make_figures.py [--result run_github_38777903922/panel/result.json]

Plots IC / reference (gap > 1: the IC costs more; < 1: cheaper), online and cold,
with the 95% paired-bootstrap interval over the 64 targets (verify_receipt.py's
statistics). Online gaps are the reciprocal of the receipt's rho/IC ratio, with
the interval endpoints inverted.
"""
import argparse
import json
import subprocess
from pathlib import Path

HERE = Path(__file__).resolve().parent.parent  # the experiment directory
REFS = [("parallel", "ParallelRho (in-process)", "blue", "square*"),
        ("strong", "strong (32 lanes, DP 4, one-word)", "orange", "triangle*"),
        ("strong_wide", "strong\\_wide (rA770)", "red", "diamond*"),
        ("tuned", "tuned (rT770 config)", "teal", "*")]


def series(res, ref, kind):
    rows = []
    for s in sorted(res["sizes"], key=lambda s: s["n"]):
        r = s["references"][ref]
        if kind == "online":
            v, lo, hi = (1 / r["online_rho_over_ic"]["value"], 1 / r["online_rho_over_ic"]["ci95"][1],
                         1 / r["online_rho_over_ic"]["ci95"][0])
        else:
            v, (lo, hi) = r["cold_ic_over_rho"]["value"], r["cold_ic_over_rho"]["ci95"]
        rows.append((s["n"], v, v - lo, hi - v))
    return rows


def plot(res, kind, title, ylabel, ymin, ymax):
    out = [f"\\nextgroupplot[title={{{title}}}, ymode=log, ymin={ymin}, ymax={ymax}, xmin=39, xmax=64, "
           f"xtick={{41,47,53,57,59,61}}, xlabel={{$n$ (field of $2^n$ elements)}}, ylabel={{{ylabel}}}, "
           "ymajorgrids, grid style={gray!25}]"]
    out.append("\\addplot[black, dashed, forget plot] coordinates {(39,1) (64,1)};")
    for ref, label, colour, mark in REFS:
        pts = " ".join(f"({n},{v:.5g}) += (0,{up:.5g}) -= (0,{dn:.5g})"
                       for n, v, dn, up in series(res, ref, kind))
        out.append(f"\\addplot[{colour}, mark={mark}, error bars/.cd, y dir=both, y explicit] coordinates {{{pts}}};")
        out.append(f"\\addlegendentry{{{label}}}" if kind == "online" else "")
    return "\n".join(out)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--result", type=Path, default=HERE / "run_github_38777903922/panel/result.json")
    args = ap.parse_args()
    res = json.loads(args.result.read_text())
    tex = ("% Generated by make_figures.py from run_github_38777903922/panel/result.json. Data: 64 targets a size, 95% paired bootstrap.\n"
           "\\documentclass[border=6pt]{standalone}\n\\usepackage{pgfplots}\\usepgfplotslibrary{groupplots}\\pgfplotsset{compat=1.16}\n"
           "\\begin{document}\n\\begin{tikzpicture}\n"
           "\\begin{groupplot}[group style={group size=2 by 1, horizontal sep=2.2cm}, width=8.2cm, height=6.5cm, "
           "legend style={font=\\scriptsize, at={(1.05,-0.35)}, anchor=north, legend columns=2}, tick label style={font=\\scriptsize}, "
           "label style={font=\\small}, title style={font=\\small}]\n"
           + plot(res, "online", "Online: IC / reference (below 1: IC faster)", "IC online / reference online", "0.01", "1")
           + "\n" + plot(res, "cold", "Cold: IC / reference (above 1: rho faster)", "IC (setup+online) / reference", "1", "40")
           + "\n\\end{groupplot}\n\\end{tikzpicture}\n\\end{document}\n")
    fig = HERE / "figures"
    (fig / "gap.tex").write_text(tex)
    subprocess.run(["pdflatex", "-interaction=nonstopmode", "-halt-on-error", "gap.tex"], cwd=fig, check=True, stdout=subprocess.DEVNULL)
    subprocess.run(["pdftoppm", "-png", "-r", "160", "-singlefile", "gap.pdf", "gap"], cwd=fig, check=True)
    for ext in ("aux", "log"):
        (fig / f"gap.{ext}").unlink(missing_ok=True)


if __name__ == "__main__":
    main()
