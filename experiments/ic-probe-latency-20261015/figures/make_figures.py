#!/usr/bin/env python3
"""Render figures/ratio.tex (pgfplots), ratio.pdf and ratio.png from a receipt's result.json.

    python3 figures/make_figures.py [RESULT_JSON]

Left: dependent-load latency by buffer size and page policy (median over two
rounds). Right: 4k/thp ratio for the pointer chase over 4 GiB, the IC ns/probe
and the tuned rho ns/step, with the frozen 1.5x threshold and 95% t intervals.
"""
import json
import statistics as st
import subprocess
import sys
from pathlib import Path

EXP = Path(__file__).resolve().parent.parent
res_path = Path(sys.argv[1]) if len(sys.argv) > 1 else EXP / "run_github_38779143540/panel/result.json"
r = json.loads(res_path.read_text())
sweep = r["pointer_chase_sweep"]
null4g = [p["pchase_ns_4k"] / p["pchase_ns_thp"] for p in r["ic"]["pairs"]]
null_gm = st.geometric_mean(null4g)
bars = [("pointer chase 4 GiB", null_gm, None), ("IC ns/probe", r["ic"]["R_4k_over_thp"], r["ic"]["ci95_t"]),
        ("tuned rho ns/step", r["rho"]["R_4k_over_thp"], r["rho"]["ci95_t"])]
cols = {"4k": "red", "default": "blue", "hugetlb": "green!60!black", "thp": "orange"}
marks = {"4k": "square*", "default": "triangle*", "hugetlb": "diamond*", "thp": "*"}
lines = []
for mode in ("4k", "default", "thp", "hugetlb"):
    pts = " ".join(f"({s['size_bytes'] / 2**20:g},{s['ns_per_access']:.4g})" for s in sweep if s["mode"] == mode)
    lines.append(f"\\addplot[{cols[mode]}, mark={marks[mode]}] coordinates {{{pts}}}; \\addlegendentry{{{mode.replace('_', ' ')}}}")
errs = " ".join(
    f"({i},{v:.5g}) += (0,{(c[1] - v) if c else 0:.5g}) -= (0,{(v - c[0]) if c else 0:.5g})" for i, (_, v, c) in enumerate(bars))
tex = f"""% Generated by figures/make_figures.py from run_github_38779143540/panel/result.json.
\\documentclass[border=6pt]{{standalone}}
\\usepackage{{pgfplots}}\\usepgfplotslibrary{{groupplots}}\\pgfplotsset{{compat=1.16}}
\\begin{{document}}\\begin{{tikzpicture}}
\\begin{{groupplot}}[group style={{group size=2 by 1, horizontal sep=2.2cm}}, width=8.2cm, height=6.5cm,
  tick label style={{font=\\scriptsize}}, label style={{font=\\small}}, title style={{font=\\small}}]
\\nextgroupplot[title={{Dependent-load latency by buffer size}}, xmode=log, ymode=log, xlabel={{buffer (MiB)}}, ylabel={{ns per access}},
  ymajorgrids, grid style={{gray!25}}, legend style={{font=\\scriptsize, at={{(0.03,0.97)}}, anchor=north west}}]
{chr(10).join(lines)}
\\nextgroupplot[title={{Page policy 4k over thp (above 1: THP faster)}}, ybar, bar width=0.8cm, ymin=0.9, ymax=1.6, xmin=-0.6, xmax=2.6,
  xtick={{0,1,2}}, xticklabels={{{", ".join(b[0] for b in bars)}}}, xticklabel style={{font=\\scriptsize, text width=2cm, align=center}},
  ylabel={{ratio (geometric mean of 4 blocks)}}, ymajorgrids, grid style={{gray!25}}]
\\addplot[fill=blue!40, error bars/.cd, y dir=both, y explicit] coordinates {{{errs}}};
\\draw[red, dashed] (axis cs:-0.6,1.5) -- (axis cs:2.6,1.5) node[above left, font=\\scriptsize] {{frozen threshold 1.5}};
\\draw[black, dotted] (axis cs:-0.6,1) -- (axis cs:2.6,1);
\\end{{groupplot}}\\end{{tikzpicture}}\\end{{document}}
"""
fig = EXP / "figures"
(fig / "ratio.tex").write_text(tex)
subprocess.run(["pdflatex", "-interaction=nonstopmode", "-halt-on-error", "ratio.tex"], cwd=fig, check=True, stdout=subprocess.DEVNULL)
subprocess.run(["pdftoppm", "-png", "-r", "160", "-singlefile", "ratio.pdf", "ratio"], cwd=fig, check=True)
for ext in ("aux", "log"):
    (fig / f"ratio.{ext}").unlink(missing_ok=True)
print(f"pointer chase 4 GiB 4k/thp geometric mean {null_gm:.4f}")
