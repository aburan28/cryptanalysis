#!/usr/bin/env python3
"""Freeze an exact, tiny degree-131 ordinary-target stage workload."""

import hashlib
import json
import random
from pathlib import Path

import curves
from perf_probe import base_prefix, build_prefix, frozen_json, sha

HERE = Path(__file__).resolve().parent
DEGREE = 131
COFACTOR = 4
SEED = 260926


def main():
    order = curves.curveOrder(DEGREE)
    subgroup_order = order // COFACTOR
    assert order == COFACTOR * subgroup_order
    assert curves.isPrimeBig(subgroup_order)
    _, curve, base, reps, base_info = base_prefix(
        DEGREE, COFACTOR, subgroup_order, 2)
    rng = random.Random(SEED)
    generator = curve.randomPointOfOrder(subgroup_order, COFACTOR, rng)
    scalar = rng.randrange(1, subgroup_order)
    target = curve.mul(generator, scalar)
    assert target is not None and curve.mul(generator, scalar) == target
    index, index_info = build_prefix(curve, base, reps, DEGREE,
                                     len(reps) * len(base))
    assert len(index) == index_info["index_keys_in_prefix"]
    identity = {
        "field": {
            "p": 2, "n": DEGREE, "basis": "type_ii_optimal_normal",
            "defining_modulus": f"symmetric subalgebra of F2[z]/(z^{2 * DEGREE + 1}-1), modulo sum(z^i, i=0..{2 * DEGREE})",
            "basis_coordinates": "bit i-1 is coefficient of gamma_i=zeta^i+zeta^-i, i=1..n",
            "element_encoding": "nonnegative integer native ONB symmetric bit vector, normalized bit zero",
        },
        "curve": {
            "model": "y^2 + x*y = x^3 + 1", "a1": 1, "a2": 0,
            "a3": 0, "a4": 0, "a6": 1,
            "order": order, "subgroup_order": subgroup_order,
            "cofactor": COFACTOR, "generator": generator,
            "target_group": "subgroup generated by generator",
        },
    }
    curve_id = "EC1N131Ckb1h" + hashlib.sha256(frozen_json(identity)).hexdigest()[:12]
    workload = {"curve_id": curve_id, "target": target, "seed": SEED,
                "target_count": 1,
                "input_law": "uniform nonzero scalar times fixed subgroup generator"}
    report = {
        "kind": "tiny_degree131_quotient_pair_stage_reference",
        "claim_boundary": "exact two-orbit selected base and ordinary target; no coverage, relation, or DLP claim",
        "candidate_id": None, "proposal_id": None,
        "curve_id": curve_id, "curve_identity_record": identity,
        "workload_id": hashlib.sha256(frozen_json(workload)).hexdigest()[:12],
        "workload": workload, "field_degree": DEGREE,
        "cofactor": COFACTOR, "subgroup_order": str(subgroup_order),
        "base_policy": "first two rational normal-weight-two x orbits, cofactor projected, both signs",
        "base": base_info, "index_prefix": index_info,
        "target_fixture_scalar": scalar,
        "target_fixture_scalar_replay_verified": True,
        "source_sha256": sha(Path(__file__)),
        "dependency_sha256": {name: sha(HERE / name) for name in (
            "perf_probe.py", "quotient_pair_probe.py", "field.py", "curves.py")},
    }
    output = HERE / "runs" / "n131_stage_reference.json"
    output.write_text(json.dumps(report, indent=2) + "\n")
    print(json.dumps({"curve_id": curve_id, "actual_B": len(base),
                      "index_keys": len(index),
                      "workload_id": report["workload_id"]}))


if __name__ == "__main__":
    main()
